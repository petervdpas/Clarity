/// The program of the project: the desktop program, or with the web target
/// alone the web application (manual/stacks.csharp.md). With both targets the desktop
/// program; `clarity_gen_core::programs` asks for each target on its own.
pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    if settings.stack.ui != clarity_project::Ui::Clarity {
        return Err(vec!["C# draws with Clarity.UI only".to_string()]);
    }
    if settings.stack.has(clarity_project::Target::Desktop) || !settings.stack.has(clarity_project::Target::Web) {
        return generate_desktop(project, settings, DESKTOP_PACKAGE);
    }
    // The windows as the desktop program has them, on Clarity.UI without the desktop's own.
    let windows = generate_desktop(project, settings, web::APP_PACKAGE)?;
    web::generate(&clarity_gen_core::with_secret_settings(project, &clarity_gen_core::settings_program(settings)), settings, windows)
}

/// The desktop program, its windows drawn by the package `ui`.
fn generate_desktop(project: &Project, settings: &Settings, ui: &str) -> Result<Vec<OutFile>, Vec<String>> {
    let project = &clarity_gen_core::with_secret_settings(project, &clarity_gen_core::settings_program(settings));
    // What the parts' code lacks of Clarity's files, read without building it (manual/design.custom-parts.md).
    let mismatches = parts::code_mismatches(project);
    if !mismatches.is_empty() {
        return Err(mismatches);
    }
    let (databases, owned) = clarity_gen_core::databases(project, settings)?;
    let databases = clarity_gen_core::with_secret_locations(databases, &clarity_gen_core::settings_program(settings));
    if main_window(project).is_none() {
        return Err(vec!["the project has no window to start with".to_string()]);
    }
    let name = project_name(settings);
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let texts = texts::Texts::of(project);
    let drivers: Vec<&Driver> = DRIVERS
        .iter()
        // A data source that is a file is kept in an in-memory SQLite table.
        .filter(|s| databases.iter().any(|(_, sql, _)| *sql == s.sql) || (s.sql == clarity_gen_core::ddl::Sql::Sqlite && !clarity_gen_core::file_sources(project, settings).unwrap_or_default().is_empty()))
        .collect();
    let engines = !clarity_gen_core::engines(project).is_empty();
    // Engines beside the screen run in the application's process too, through the same package.
    let screen_engines = !clarity_gen_core::screen_engines(project).is_empty();
    // The empty database in memory the windows work on while the databases do not open is SQLite's (manual/data.settings.md).
    let mut packaged = drivers.clone();
    if clarity_gen_core::unconnected(project).is_some() && !packaged.iter().any(|d| d.sql == Sql::Sqlite) {
        packaged.push(&DRIVERS[0]);
    }
    // Songs play through Clarity.Audio on the desktop; a browser plays them itself.
    let songs = ui == DESKTOP_PACKAGE && clarity_spec::resources::carries_audio(project);
    let videos = ui == DESKTOP_PACKAGE && clarity_spec::resources::plays_videos(project);
    let pictures = clarity_gen_core::uses_picture_functions(project);
    // The commands agents call while the app runs, and `<program> mcp` (docs/ledger/app-mcp.md).
    let agents = ui == DESKTOP_PACKAGE && clarity_gen_core::agent_tools::offers_agents(project);
    let media: Vec<&str> = [(songs, AUDIO_PACKAGE), (videos, VIDEO_PACKAGE), (pictures, IMAGE_PACKAGE), (project.uses_pdf(), PDF_PACKAGE), (clarity_gen_core::carries_formats(project, settings), FORMATS_PACKAGE), (clarity_gen_core::carries_auth(project), AUTH_PACKAGE), (agents, APP_MCP_PACKAGE)].into_iter().filter(|(on, _)| *on).map(|(_, p)| p).collect();
    let mut files = vec![text(&format!("{name}.csproj"), csproj(&name, ui, &media, &packaged, project.resources.as_ref().is_some_and(|r| !r.files.is_empty() || !r.markdown.is_empty()), engines || screen_engines, parts::references(project) + &library_references(project)))];
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        // The settings read and keep JSON, numbers and dates written the same everywhere.
        let settings_usings = if file.entities.iter().any(|e| e.settings) { "using System.Globalization;\nusing System.Text.Json.Nodes;\n" } else { "" };
        let mut code = format!("{HEADER}\n{settings_usings}using Clarity.Runtime;\nusing CommunityToolkit.Mvvm.ComponentModel;\n\nnamespace {name};\n\n");
        code.push_str(&model::emit(project, file, &name, &clarity_gen_core::settings_program(settings), &texts, false));
        match logic::emit(project, file, &file_types) {
            Ok(methods) => code.push_str(&methods),
            Err(mut problems) => errors.append(&mut problems),
        }
        if agents {
            match logic::emit_commands(project, file, &file_types) {
                Ok(commands) => code.push_str(&commands),
                Err(mut problems) => errors.append(&mut problems),
            }
        }
        files.push(text(&format!("Modules/{}.cs", pascal(&module.name)), code.trim_end().to_string() + "\n"));
        for page in &file.pages {
            match windows::emit(project, page, &file_types, &name, &texts) {
                Ok(mut window) => files.append(&mut window),
                Err(mut problems) => errors.append(&mut problems),
            }
        }
    }
    // The app's `on unconnected` (manual/data.settings.md) runs on a window of its own that
    // is never shown, made of the app's frame and code: its ViewModel alone.
    if let Some((app, handler)) = clarity_gen_core::unconnected(project).and_then(|u| u.handler)
        && let Some(file) = project.files.iter().find(|f| f.apps.iter().any(|a| a.name.name == app))
    {
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let host = unconnected_host(project);
        match windows::emit(project, &host, &file_types, &name, &texts) {
            Ok(window) => files.extend(window),
            Err(mut problems) => errors.append(&mut problems),
        }
        let reason = if clarity_gen_core::unconnected_takes_reason(project, &app, &handler) { "reason" } else { "" };
        files.push(text(
            &format!("Windows/{}Run.cs", host.name.name),
            format!(
                "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\npublic sealed partial class {}ViewModel\n{{\n    /// <summary>Runs the app's <c>on unconnected</c>, with why the databases did not open.</summary>\n    public void Unconnected(Unconnecting unconnecting) => RunUnconnected(unconnecting, reason => {}({reason}));\n}}\n",
                host.name.name,
                names::on(&handler)
            ),
        ));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("Schema.cs", schema_cs(project, &name, &owned)?));
    files.push(text("Program.cs", program_cs(project, &name, &databases, &drivers, settings, engines)));
    if agents {
        files.push(text("AgentCommands.cs", cli::agents_desktop(project, settings, &name)));
    }
    if engines {
        files.extend(clarity_gen_core::engine_files(project, "Engines"));
        files.push(text("Engines.cs", engines_cs(project, &name)));
    }
    if screen_engines {
        files.extend(clarity_gen_core::screen_engine_files(project, "Engines"));
        files.push(text("ScreenEngines.cs", screen_engines_cs(project, &name)));
    }
    // The custom parts, Clarity.UI's custom controls: each adapter, and the half generated from its declaration (manual/start.how-it-works.md).
    files.extend(parts::files(project));
    // The libraries: each adapter, and the half generated from its declaration (manual/code.libraries.md).
    for library in clarity_gen_core::libraries::libraries(project) {
        let n = &library.name.name;
        let own = clarity_gen_core::libraries::own_file(library, false);
        files.extend(clarity_gen_core::libraries::adapter_files(project, n, &own));
        files.push(text(&format!("{}/{own}", clarity_gen_core::libraries::folder(n)), clarity_gen_core::libraries::csharp_half(project, library)));
    }
    // The windows and the app frames as markup, which Clarity.UI draws (manual/start.how-it-works.md).
    for file in clarity_gen_core::web_windows::window_files(project).into_iter().chain(clarity_gen_core::web_windows::app_files(project)) {
        let path = file.path.replace("ui/windows/", "Windows/").replace("ui/apps/", "Apps/");
        files.push(OutFile { path, ..file });
    }
    files.push(text("Labels.cs", labels_cs(project, &name)));
    files.push(text("Fields.cs", fields_cs(project, &name)));
    // The model as JSON, which Clarity.UI reads on the desktop and in the browser: the
    // windows' facts, the fields', the translations, the themes and the keys (manual/start.how-it-works.md).
    files.push(text("model.json", clarity_gen_core::web::model_json(project)));
    if !clarity_spec::icons::used(project).is_empty() {
        files.push(text("Icons.cs", icons_cs(project, &name)));
    }
    // The default language's texts, and each other language's.
    files.push(text("Texts.cs", texts.class(project, &name)));
    files.push(text("Texts.resx", texts.base_resx(project)));
    let default = clarity_spec::translations::default_language(project);
    for (language, values) in project.translations.iter().filter(|(l, _)| **l != default) {
        files.push(text(&format!("Texts.{language}.resx"), texts.language_resx(values)));
    }
    // The themes offered, as Clarity resolves them for light and dark mode (manual/start.how-it-works.md).
    files.extend(themes::theme_files(project, &name));
    files.extend(clarity_gen_core::web::resource_files(project, "resources"));
    // The program file's icon on Windows, as C# takes it.
    if let Some(ico) = clarity_gen_core::windows_resources::ico_file(project) {
        files.push(ico);
        if let Some(csproj) = files.first_mut() {
            csproj.text = csproj.text.replacen("    <OutputType>WinExe</OutputType>\n", &format!("    <OutputType>WinExe</OutputType>\n    <ApplicationIcon>{}</ApplicationIcon>\n", clarity_gen_core::windows_resources::ICO_PATH.replace('/', "\\")), 1);
        }
    }
    Ok(files)
}

fn text(path: &str, body: String) -> OutFile {
    OutFile {
        path: path.to_string(),
        text: body,
        bytes: None,
    }
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project
        .apps()
        .find_map(|a| a.main.as_ref().map(|m| m.name.clone()))
        .or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

/// The project file. It references the runtime's packages: `ui` (Clarity.Ui)
/// and the driver of each kind of database the data sources are. With the
/// property `ClarityRuntime` (or the environment variable CLARITY_RUNTIME) set
/// to the runtime's folder (runtimes/csharp in Clarity's repository), it
/// references the runtime's own projects there instead, for working on them.
#[allow(clippy::too_many_arguments)]
fn csproj(name: &str, ui: &str, media: &[&str], drivers: &[&Driver], carried: bool, engines: bool, dotnet: String) -> String {
    let version = runtime_version();
    // Engines need Wasmtime, which only an application with an engine carries.
    let packages: Vec<&str> = std::iter::once(ui).chain(media.iter().copied()).chain(drivers.iter().map(|s| s.package)).chain(engines.then_some(ENGINES_PACKAGE)).collect();
    let references: String = packages.iter().map(|p| format!("    <PackageReference Include=\"{p}\" Version=\"{version}\" />\n")).collect();
    let projects: String = packages.iter().map(|p| format!("    <ProjectReference Include=\"$(ClarityRuntime)/{p}/{p}.csproj\" />\n")).collect();
    // The files of the project's resources folder, embedded.
    let mut resources = if carried { "  <ItemGroup>\n    <EmbeddedResource Include=\"resources/**\" LogicalName=\"resources/%(RecursiveDir)%(Filename)%(Extension)\" />\n  </ItemGroup>\n".to_string() } else { String::new() };
    // The engines' files, embedded under their names.
    if engines {
        resources.push_str("  <ItemGroup>\n    <EmbeddedResource Include=\"Engines/*.wasm\" LogicalName=\"Engines/%(Filename)%(Extension)\" />\n  </ItemGroup>\n");
    }
    // The libraries' packages and assemblies.
    resources.push_str(&dotnet);
    format!(
        "<!-- Generated by Clarity. Do not edit: change the project in Clarity instead. -->
<Project Sdk=\"Microsoft.NET.Sdk\">
  <PropertyGroup>
    <OutputType>WinExe</OutputType>
    <TargetFramework>{TARGET_FRAMEWORK}</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <RootNamespace>{name}</RootNamespace>
    <AssemblyName>{name}</AssemblyName>
    <!-- Where Clarity's runtime projects are, to build on them instead of its
         packages: dotnet build -p:ClarityRuntime=<folder>, or the environment
         variable CLARITY_RUNTIME. Empty: the packages. -->
    <ClarityRuntime Condition=\"'$(ClarityRuntime)' == ''\">$(CLARITY_RUNTIME)</ClarityRuntime>
  </PropertyGroup>
  <ItemGroup>
    <!-- The windows and app frames as markup, and the themes, which Clarity.UI draws (manual/start.how-it-works.md). -->
    <EmbeddedResource Include=\"Windows/*.cxaml\" LogicalName=\"Windows/%(Filename)%(Extension)\" />
    <EmbeddedResource Include=\"Apps/*.cxaml\" LogicalName=\"Apps/%(Filename)%(Extension)\" />
    <EmbeddedResource Include=\"Themes/*.json\" LogicalName=\"Themes/%(Filename)%(Extension)\" />
    <EmbeddedResource Include=\"model.json\" LogicalName=\"model.json\" Condition=\"Exists('model.json')\" />
  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' == ''\">
{references}  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' != ''\">
{projects}  </ItemGroup>
{resources}</Project>
"
    )
}

/// The libraries' packages and assemblies, in an item group (manual/code.libraries.md).
fn library_references(project: &Project) -> String {
    let lines = clarity_gen_core::libraries::csharp_references(project);
    if lines.is_empty() { lines } else { format!("  <ItemGroup>\n{lines}  </ItemGroup>\n") }
}

/// The runtime's name for a database kind.
fn dialect(sql: Sql) -> &'static str {
    match sql {
        Sql::Sqlite => "Dialect.Sqlite",
        Sql::Postgres => "Dialect.Postgres",
        Sql::Mysql => "Dialect.Mysql",
        Sql::Mssql => "Dialect.Mssql",
    }
}

/// How many migration steps every database Clarity owns was made with: the
/// program checks its databases against these at start and does not migrate
/// (docs/ledger/migrations.md); clarity-migrate applies the steps.
fn schema_cs(project: &Project, name: &str, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut out = format!(
        "{HEADER}
namespace {name};

public static class Schema
{{
    /// <summary>
    /// How many migration steps each data source's database was made with. The
    /// program checks its database has as many when it starts, and does not
    /// migrate: clarity-migrate does (docs/ledger/migrations.md).
    /// </summary>
    public static readonly (string Source, int Steps)[] Sources =
    [
"
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        match schema::steps(project, source, *sql) {
            Ok(steps) => out.push_str(&format!("        ({}, {}),\n", string(source), steps.len())),
            Err(mut problems) => errors.append(&mut problems),
        }
    }
    out.push_str("    ];\n}\n");
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}

/// The program: it opens the database of every data source, brings Clarity's
/// own up to date, and starts the windows; `--check` stops after the databases.
/// The package that hosts engines (manual/code.engines.md).
const ENGINES_PACKAGE: &str = "Clarity.Runtime.Engines";

/// The engines of the application (manual/code.engines.md): each loaded once from its
/// embedded file, and every one checked when the application starts.
fn engines_cs(project: &Project, name: &str) -> String {
    let mut members = String::new();
    let mut checks = String::new();
    for engine in clarity_gen_core::engines(project) {
        let member = pascal(&engine.name.name);
        let functions: Vec<String> = engine.functions.iter().map(|f| string(&f.name.name)).collect();
        members.push_str(&format!(
            "    static readonly Lazy<Engine> {field} = new(() => Engine.Load({}, Read({}), new EngineDeclaration([{}], [{}], new EngineLimits({}, {}), {}, {})));\n\n    /// <summary>Engine {}, from {}.</summary>\n    public static Engine {member} => {field}.Value;\n\n",
            string(&engine.name.name),
            string(&engine.file),
            functions.join(", "),
            engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            engine.seconds(),
            engine.megabytes(),
            match engine.state {
                clarity_spec::code::EngineState::None => "EngineState.None",
                clarity_spec::code::EngineState::App => "EngineState.PerApp",
                clarity_spec::code::EngineState::Window => "EngineState.PerWindow",
            },
            engine.opens,
            engine.name.name,
            engine.file,
            field = format!("_{}", camel(&engine.name.name)),
        ));
        checks.push_str(&format!("        _ = {member};\n"));
    }
    // An engine that says how far a long call is (manual/code.engines.md): Clarity.UI runs the
    // handlers off the screen's thread, so the window shows the bar with Stop.
    let watches = clarity_gen_core::engines(project).iter().any(|e| e.uses.iter().any(|u| u.name == clarity_spec::code::check::PROGRESS));
    format!(
        "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n/// <summary>The engines of the application: each loaded once from its file, every one checked when the application starts.</summary>\npublic static class Engines\n{{\n    /// <summary>Whether an engine says how far a long call is: the screen then shows the bar with Stop.</summary>\n    public const bool Watches = {watches};\n\n{members}    /// <summary>Loads every engine, so one whose file does not fit stops the application at start.</summary>\n    public static void Check()\n    {{\n{checks}    }}\n\n    static byte[] Read(string file)\n    {{\n        using var stream = typeof(Engines).Assembly.GetManifestResourceStream(\"Engines/\" + file) ?? throw new EngineException($\"the engine file {{file}} is missing\");\n        using var bytes = new MemoryStream();\n        stream.CopyTo(bytes);\n        return bytes.ToArray();\n    }}\n}}\n"
    )
}

/// The engines beside the screen (manual/code.engines.md): for each, what makes a new
/// instance for a canvas that runs it, from its embedded file.
fn screen_engines_cs(project: &Project, name: &str) -> String {
    let mut members = String::new();
    for engine in clarity_gen_core::screen_engines(project) {
        members.push_str(&format!(
            "    /// <summary>Engine {engine_name} beside the screen, from {file}: a new instance for each canvas that runs it.</summary>\n    public static readonly Func<IFrames> {member} = () =>\n        ScreenEngine.Load({name}, Read({file_text}), [{uses}], {opens}, new EngineLimits({seconds}, {megabytes}));\n\n",
            name = string(&engine.name.name),
            file_text = string(&engine.file),
            uses = engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            opens = engine.opens,
            seconds = engine.seconds(),
            megabytes = engine.megabytes(),
            engine_name = engine.name.name,
            file = engine.file,
            member = pascal(&engine.name.name),
        ));
    }
    format!(
        "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n/// <summary>The engines beside the screen, which the canvases that run them draw with.</summary>\npublic static class ScreenEngines\n{{\n{members}    static byte[] Read(string file)\n    {{\n        using var stream = typeof(ScreenEngines).Assembly.GetManifestResourceStream(\"Engines/\" + file) ?? throw new EngineException($\"the engine file {{file}} is missing\");\n        using var bytes = new MemoryStream();\n        stream.CopyTo(bytes);\n        return bytes.ToArray();\n    }}\n}}\n"
    )
}

/// An engine whose file does not fit its declaration stops the application at start.
fn check_engines(engines: bool) -> &'static str {
    if engines {
        "        try\n        {\n            Engines.Check();\n        }\n        catch (EngineException e)\n        {\n            Console.Error.WriteLine(e.Message);\n            return 1;\n        }\n"
    } else {
        ""
    }
}

/// The databases of the data sources and the file stores, and `method`, which opens them.
fn opening(project: &Project, databases: &[(String, Sql, String)], drivers: &[&Driver], settings: &Settings, method: &str) -> String {
    // Each kind of database, turned on by its package before the databases open.
    let turned_on: String = drivers.iter().map(|s| format!("        {}.Use();\n", s.class)).collect();
    let stores = clarity_gen_core::fixed_stores(settings).iter().map(|s| format!("({}, {})", string(&s.name), string(&s.location))).collect::<Vec<_>>().join(", ");
    // A store whose folder is a folder setting follows the person's settings.
    let program_name = clarity_gen_core::settings_program(settings);
    let folder_stores: String = clarity_gen_core::folder_stores(project, settings)
        .iter()
        .map(|(name, setting, default)| format!("        db.AddStoreSetting({}, {}, {}, {});\n", string(name), string(&program_name), string(setting), string(default)))
        .chain(clarity_gen_core::file_sources(project, settings).unwrap_or_default().iter().map(|f| format!("        Clarity.Formats.FileSources.AddFile(db, new Clarity.Formats.FileSource({}, {}, {}, {}, {}, {}, {}, {}));\n", string(&f.name), string(&f.format), string(&f.path), string(&f.options), string(&f.table), string(&f.key), string(&f.fields), f.readonly)))
        .chain(add_signin(project, settings))
        .collect();
    let databases = databases
        .iter()
        .map(|(source, sql, at)| format!("({}, {}, {})", string(source), dialect(*sql), string(at)))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "    /// <summary>The database of each data source: its name, its kind and where it is.</summary>
    static readonly (string, Dialect, string)[] Sources = [{databases}];

    /// <summary>The folder of each file store, which keeps the pictures of image fields kept as files.</summary>
    static readonly (string, string)[] Stores = [{stores}];

    /// <summary>Opens every database and checks it has the migration steps the program was made with.</summary>
    public static Db {method}()
    {{
{turned_on}        var db = Db.Connect(Sources);
        foreach (var (source, steps) in Schema.Sources)
        {{
            try
            {{
                db.CheckSteps(source, steps);
            }}
            catch (Clarity.Runtime.StepsException e)
            {{
                // The program does not migrate (docs/ledger/migrations.md): behind or ahead, it stops with this line, in English.
                Console.Error.WriteLine(e.Message);
                Environment.Exit(1);
            }}
        }}
        foreach (var (name, at) in Stores)
            db.AddStore(name, at);
{folder_stores}        return db;
    }}
"
    )
}

/// `read`, which hands records of `entity` out (a list or one record), checked by
/// the entity's `readable when` (step 4) on `db`: refused with notYours. As it is
/// for an entity without the line.
pub fn readable(project: &Project, entity: &str, db: &str, read: String) -> String {
    if project.entity(entity).is_some_and(|e| e.readable.is_some()) { format!("{entity}.Readable_({db}, {read})") } else { read }
}

/// The people of the program and how they sign in, named to the database
/// handle once its databases are open (docs/ledger/signin.md);
/// none without a `signin` block.
pub fn add_signin(project: &Project, settings: &Settings) -> Option<String> {
    let plan = clarity_gen_core::signin::signin_plan(project)?;
    let list = |items: &[String]| items.iter().map(|i| string(i)).collect::<Vec<_>>().join(", ");
    // How long the desktop remembers a sign-in, only with `remember N days`.
    let mut remember = plan.remember_seconds.map(|s| format!(", RememberSeconds = {s}")).unwrap_or_default();
    // `when asked`: remembered only when the sign-in part's box is ticked; left out otherwise.
    if plan.remember_asks {
        remember.push_str(", RememberAsks = true");
    }
    // A provider's settings for Clarity.Auth; left out for a strategy without them.
    let options = |name: &str| plan.options.get(name).map(|o| format!(" {{ Options = [{}] }}", o.iter().map(|(k, v)| format!("({}, {})", string(k), string(v))).collect::<Vec<_>>().join(", "))).unwrap_or_default();
    let strategies = plan.strategies.iter().map(|(name, columns)| format!("new Clarity.Auth.SigninStrategy({}, [{}]){}", string(name), list(columns), options(name))).collect::<Vec<_>>().join(", ");
    Some(format!(
        "        Clarity.Auth.Signins.AddSignin(db, new Clarity.Auth.SigninSource({}, {}) {{ Source = {}, Key = {}, Targets = [{}], Strategies = [{strategies}], SessionSeconds = {}, Tries = {}, TriesSeconds = {}, Program = {}{remember} }});\n",
        string(&plan.table),
        string(&plan.page),
        string(&plan.source),
        string(&plan.key),
        list(&plan.targets),
        plan.session_seconds,
        plan.tries,
        plan.tries_seconds,
        // The program's name, which the protected store keeps a remembered sign-in under, as its secret settings.
        string(&clarity_gen_core::settings_program(settings)),
    ))
}

fn program_cs(project: &Project, name: &str, databases: &[(String, Sql, String)], drivers: &[&Driver], settings: &Settings, engines: bool) -> String {
    // Commands for agents (docs/ledger/app-mcp.md): Clarity.UI serves them while the window runs; `mcp` without one.
    let agents = settings.stack.has(clarity_project::Target::Desktop) && settings.stack.ui == clarity_project::Ui::Clarity && clarity_gen_core::agent_tools::offers_agents(project);
    let (agents_mcp, agents_install) = if agents {
        (
            "        // `mcp` as the only word: agents call the commands without a window (docs/ledger/app-mcp.md).\n        if (args is [\"mcp\"])\n        {\n            using var mcpDatabases = OpenDatabases();\n            return AgentCommands.Mcp(mcpDatabases, args);\n        }\n",
            "        AgentCommands.Install(databases);\n",
        )
    } else {
        ("", "")
    };
    let check_engines = check_engines(engines);
    let opening = opening(project, databases, drivers, settings, "OpenDatabases");
    let main_window = main_window(project).unwrap_or_default();
    // Engines ask for the language the person picked.
    let engines_language = if engines { "        Clarity.Runtime.Engine.Language = () => Locale.Language?.Name;\n" } else { "" };
    let currency = project.locale.currency.as_deref().map_or_else(|| "null".to_string(), string);
    // The person's settings, after the language and theme they may name (manual/data.settings.md).
    let settings_start = if project.entities().any(|e| e.settings) { "        Settings.Start();\n" } else { "" };
    // The person's keys and the keys window's commands (manual/app.keys.md).
    let keys_start = if project.keys_editable {
        format!("        PersonKeys.Start({});\n", string(&clarity_gen_core::settings_program(settings)))
    } else {
        String::new()
    };
    let unconnected = unconnected_start(project, &main_window);
    // Songs play through Clarity.Audio, handed to Clarity.UI before the first window.
    let mut audio = if clarity_spec::resources::carries_audio(project) { "        Clarity.Audio.ClarityAudio.Use();\n".to_string() } else { String::new() };
    if clarity_spec::resources::plays_videos(project) {
        audio.push_str("        Clarity.Video.ClarityVideo.Use();\n");
    }
    // DesktopWindow is Clarity.Ui's.
    let ui_using = "using Clarity.Ui;\n";
    format!(
        "{HEADER}
using Clarity.Runtime;
{ui_using}
namespace {name};

public static class Program
{{
{opening}
    [STAThread]
    public static int Main(string[] args)
    {{
{check_engines}        // `--check` opens and migrates the databases without windows, for builds and scripts.
        if (args.Contains(\"--check\"))
        {{
            using var db = OpenDatabases();
            Console.WriteLine({ready});
            return 0;
        }}
        // The language and theme kept from the last run, or the system's.
        Remembered.Use({application});
        Locale.Start(Texts.BaseLanguage, Texts.Languages, {currency}, Texts.In, Labels.Named);
{engines_language}        AppThemes.Start();
{settings_start}{keys_start}{agents_mcp}        Db opened;
        try
        {{
            opened = OpenDatabases();
        }}
        catch (Exception e)
        {{
{unconnected}        }}
        using var databases = opened;
{agents_install}{audio}        DesktopWindow.Run(new {main_window}ViewModel(databases));
        return 0;
    }}
}}
",
        application = string(name),
        ready = string(&format!("{name}: the databases are ready."))
    )
}

/// What Program.cs does when the databases did not open (manual/data.settings.md): with a
/// window that keeps the connection or the app's `on unconnected`, Clarity.UI's
/// unconnected flow shows what keeps the connection first, on an empty
/// database in memory; without either, the program says why and stops.
fn unconnected_start(project: &Project, main_window: &str) -> String {
    let Some(unconnected) = clarity_gen_core::unconnected(project) else {
        return "            // The databases did not open and nothing keeps the connection: the program says why.\n            Console.Error.WriteLine(Locale.Show(Unconnecting.Why(e)));\n            return 1;\n".to_string();
    };
    let window = unconnected.window.map(|w| format!("                Window = db => new {w}ViewModel(db),\n")).unwrap_or_default();
    let handler = if unconnected.handler.is_some() {
        format!("                Handler = (db, unconnecting) => new {}ViewModel(db).Unconnected(unconnecting),\n", unconnected_host(project).name.name)
    } else {
        String::new()
    };
    let settings = if project.entities().any(|e| e.settings) { "                Settings = Settings.Current,\n" } else { "" };
    format!(
        "            // The databases did not open (manual/data.settings.md): what keeps the connection shows first.\n            DesktopWindow.Run(new Unconnected\n            {{\n                Connect = OpenDatabases,\n                Empty = Sqlite.Memory,\n                Main = db => new {main_window}ViewModel(db),\n{window}{handler}{settings}            }}, Unconnected.Reason(e));\n            return 0;\n"
    )
}

/// The window the app's `on unconnected` runs on: empty, with the app's frame,
/// never shown (manual/data.settings.md).
fn unconnected_host(project: &Project) -> clarity_spec::model::Page {
    use clarity_spec::model::{Frame, Ident, Page, PageKind};
    let taken = |n: &str| project.pages().any(|p| p.name.name == n);
    let name = if taken("AppUnconnected") { "AppUnconnectedStart" } else { "AppUnconnected" };
    Page {
        name: Ident { name: name.to_string(), span: Default::default() },
        kind: PageKind::Window,
        title: None,
        size: None,
        style: None,
        cell: None,
        data: Vec::new(),
        columns: 12,
        widgets: Vec::new(),
        frame: Frame::default(),
        handlers: Vec::new(),
        gives: None,
        tells: Vec::new(),
        allow: None,
        allow_condition: None,
        span: Default::default(),
    }
}

