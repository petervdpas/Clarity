/// The build of a C# program, as a debug or (with `release`) a release
/// program; none with a UI other than Clarity.UI, which is not generated.
pub fn toolchain(settings: &clarity_project::Settings, release: bool) -> Option<clarity_gen_core::Toolchain> {
    if settings.stack.ui != clarity_project::Ui::Clarity {
        return None;
    }
    let configuration = if release { "Release" } else { "Debug" };
    // The web application is built as its server, which builds the application it serves (manual/stacks.csharp.md).
    let web = clarity_gen_core::windowed_target(settings) == clarity_project::Target::Web;
    let (project, folder, program) = if web {
        (vec!["Server".to_string()], "Server/", format!("{}.Server", project_name(settings)))
    } else {
        (vec![], "", project_name(settings))
    };
    Some(clarity_gen_core::Toolchain {
        tool: "dotnet",
        // `-tl:off`: plain lines, not the terminal logger.
        args: ["build".to_string()].into_iter().chain(project).chain(["--nologo", "-tl:off", "-c", configuration].map(String::from)).collect(),
        env: vec![("DOTNET_CLI_TELEMETRY_OPTOUT", "1".into()), ("DOTNET_NOLOGO", "1".into())],
        program: exe(format!("{folder}bin/{configuration}/{}/{program}", TARGET_FRAMEWORK)),
        missing: "is the .NET SDK installed?",
    })
}

/// The build of the command-line program, named as it is typed; C# has no
/// web renderer to need, so its console program builds the same way on either UI.
pub fn cli_toolchain(settings: &clarity_project::Settings, release: bool) -> Option<clarity_gen_core::Toolchain> {
    let configuration = if release { "Release" } else { "Debug" };
    let program = clarity_gen_core::commands::program_name(settings);
    Some(clarity_gen_core::Toolchain {
        tool: "dotnet",
        args: ["build", "--nologo", "-tl:off", "-c", configuration].map(String::from).to_vec(),
        env: vec![("DOTNET_CLI_TELEMETRY_OPTOUT", "1".into()), ("DOTNET_NOLOGO", "1".into())],
        program: exe(format!("bin/{configuration}/{}/{program}", TARGET_FRAMEWORK)),
        missing: "is the .NET SDK installed?",
    })
}

fn exe(path: String) -> std::path::PathBuf {
    std::path::PathBuf::from(if cfg!(windows) { format!("{path}.exe") } else { path })
}
