//! The README.md this stack writes for a project (P3): what it needs, how to
//! build and run it without Clarity (clarity_gen_core::readme and its own sections).

use clarity_project::{Backend, Settings, Ui, starter};
use clarity_spec::load_converted;
use clarity_gen_rust::program as generate;

const SHOP: &str = "module shop

entity Customer
    name: text(80)

page Card: window
    title \"Customer card\"
    data customer: Customer
";

fn readme(settings: &Settings) -> String {
    let project = load_converted([("shop.clarity", SHOP)]);
    let files = generate(&project, settings).unwrap_or_else(|e| panic!("{e:#?}"));
    files.into_iter().find(|f| f.path == "README.md").expect("a README.md").text
}

fn has(text: &str, expected: &str) {
    assert!(text.contains(expected), "expected\n{expected}\nin\n{text}");
}

#[test]
fn a_rust_project_says_what_it_needs_and_how_to_build_it() {
    let text = readme(&starter("Shop", "shop"));
    assert!(text.starts_with("# Shop\n"), "{text}");
    has(&text, "Generated by Clarity from the project Shop");
    has(&text, "Rust with Clarity.UI");
    // The same words as Clarity's own check (clarity tools); Clarity.UI needs no webview.
    has(&text, "- Rust with cargo, from https://rustup.rs\n");
    assert!(!text.contains("WebKitGTK"), "{text}");
    has(&text, "    cargo build --release\n");
    has(&text, "    cargo run\n");
    has(&text, "target/release/shop");
    has(&text, "data/shop.db");
    // Clarity.UI's ready-made library from the folder CLARITY_UI names; the runtime from crates.io, or from Clarity's repository while working on it.
    has(&text, "The desktop program draws with Clarity.UI's ready-made library");
    has(&text, "`build.rs` takes it from the folder the environment variable `CLARITY_UI` names");
    has(&text, &format!("Clarity's runtime comes as the crate clarity-runtime ({})", clarity_gen_rust::runtime_version()));
    has(&text, "    [patch.crates-io]\n    clarity-runtime = { path = \"<Clarity>/runtimes/rust\" }\n");
    has(&text, "set the environment variable `CLARITY_RUNTIME` to `<Clarity>/runtimes/rust`");
    assert!(!text.contains("clarity-ui = "), "{text}");
    // A run by hand or in the IDE chooses its data without editing the program.
    has(&text, "Set the environment variable `CLARITY_DATA` to a folder to open it there instead, under its own file name.");
}

#[test]
fn a_rust_program_with_custom_parts_says_its_debug_build_optimizes_their_dependencies() {
    let source = "module game\n\npart Gauge\n    crate \"parts/Gauge\"\n    binds integer\n    size 8 x 6\n\npage Game: window\n    title \"Game\"\n    data best: integer\n    Gauge name gauge at 1,1 span 8 rows 6 bind best\n";
    let mut project = clarity_spec::keyed::load_keyed([("game.clarity", source)], &[], "en");
    assert!(project.diagnostics.is_empty(), "{:#?}", project.diagnostics);
    let files = clarity_gen_rust::parts::ui_starter(&project.files[0].parts[0]).into_iter().map(|(path, text)| clarity_spec::native::PartFile { part: "Gauge".into(), path, bytes: text.into_bytes() }).collect();
    clarity_spec::native::attach(&mut project, files);
    let mut settings = starter("Game", "game");
    settings.stack.backend = Backend::Rust;
    settings.stack.ui = Ui::Clarity;
    let readme_of = |project: &clarity_spec::Project| generate(project, &settings).unwrap_or_else(|e| panic!("{e:#?}")).into_iter().find(|f| f.path == "README.md").expect("a README.md").text;
    has(&readme_of(&project), "[profile.dev.package.\"*\"]");
    let plain = clarity_spec::keyed::load_keyed([("game.clarity", "module game\n\npage Game: window\n    title \"Game\"\n")], &[], "en");
    assert!(!readme_of(&plain).contains("[profile.dev.package"));
}
