fn said(text: &Option<Said>) -> String {
    match text {
        Some(Said::Key(key)) => format!("clarity_text_show(clarity_key_text({}))", string(key)),
        Some(Said::Plain(text)) => string(text),
        None => "NULL".to_string(),
    }
}

fn kind(word: &str) -> &'static str {
    match word {
        "integer" => "CLARITY_CLI_INTEGER",
        "decimal" => "CLARITY_CLI_DECIMAL",
        "money" => "CLARITY_CLI_MONEY",
        "date" => "CLARITY_CLI_DATE",
        "datetime" => "CLARITY_CLI_DATETIME",
        "duration" => "CLARITY_CLI_DURATION",
        "enum" => "CLARITY_CLI_ENUM",
        "bool" => "CLARITY_CLI_BOOL",
        _ => "CLARITY_CLI_TEXT",
    }
}

fn some(text: &Option<String>) -> String {
    text.as_ref().map_or("NULL".to_string(), |t| string(t))
}

/// A parameter as a compound literal, its enum values in an array of their own.
fn param(p: &ParamSpec, values_name: &str, out: &mut String) -> String {
    let values = if p.values.is_empty() {
        ".values = NULL, .value_count = 0".to_string()
    } else {
        let _ = writeln!(out, "    static const char* const {values_name}[] = {{{}}};", p.values.iter().map(|v| string(v)).collect::<Vec<_>>().join(", "));
        format!(".values = {values_name}, .value_count = {}", p.values.len())
    };
    format!(
        "(ClarityCliParam){{.name = {}, .kind = {}, {values}, .fallback = {}, .min = {}, .max = {}, .required = {}, .help = {}}}",
        string(&p.name),
        kind(p.kind),
        some(&p.default),
        some(&p.min),
        some(&p.max),
        p.required,
        said(&p.help)
    )
}

fn command(i: usize, c: &CommandSpec, out: &mut String) {
    let line: Vec<String> = c.line.iter().map(|w| string(w)).collect();
    let _ = writeln!(out, "    static const char* const line{i}[] = {{{}}};", line.join(", "));
    let params = |list: &[ParamSpec], which: &str, out: &mut String| -> String {
        if list.is_empty() {
            return "NULL".to_string();
        }
        let name = format!("{which}{i}");
        let mut items = Vec::new();
        for (at, p) in list.iter().enumerate() {
            items.push(param(p, &format!("{which}{i}_{at}_values"), out));
        }
        let _ = writeln!(out, "    ClarityCliParam* {name} = CLARITY_NEW(ClarityCliParam, {});", list.len());
        for (at, item) in items.iter().enumerate() {
            let _ = writeln!(out, "    {name}[{at}] = {item};");
        }
        name
    };
    let arguments = params(&c.arguments, "arguments", out);
    let options = params(&c.options, "options", out);
    let _ = writeln!(
        out,
        "    commands[{i}] = (ClarityCliCommand){{.line = line{i}, .words = {}, .help = {}, .arguments = {arguments}, .argument_count = {}, .options = {options}, .option_count = {}}};",
        c.line.len(),
        said(&c.help),
        c.arguments.len(),
        c.options.len()
    );
}

/// A value of the command line as the type code holds it.
fn typed(p: &ParamSpec, at: usize) -> String {
    let value = format!("parsed.values[{at}]");
    match &p.ty {
        TypeInfo::Integer | TypeInfo::Duration => format!("clarity_cli_integer({value})"),
        TypeInfo::Decimal | TypeInfo::Money => format!("clarity_cli_decimal({value})"),
        TypeInfo::Date => format!("clarity_cli_date({value})"),
        TypeInfo::DateTime => format!("clarity_cli_date_time({value})"),
        TypeInfo::Bool => format!("clarity_cli_bool({value})"),
        TypeInfo::Enum(name) => format!("{}_from(clarity_cli_text({value}))", prefix(name)),
        _ => format!("clarity_cli_text({value})"),
    }
}

fn cmake_lists(program: &str, engines: bool, http: bool, secrets: bool) -> String {
    let engine = if engines { " clarity_engine" } else { "" };
    let http = if http { " clarity_http" } else { "" };
    // Secret settings (DESIGN 5.27): the system's protected store.
    let http = if secrets { format!("{http} clarity_secrets") } else { http.to_string() };
    format!(
        "# Generated by Clarity. Do not edit: change the project in Clarity instead.
#
# Configure and build with one command (CMake 3.25 or newer):
#   cmake --workflow --preset debug      (or release)
# The program is then build/debug/{program}. See README.md for what to install.
cmake_minimum_required(VERSION 3.25)
project({target} LANGUAGES C)

set(CMAKE_C_STANDARD 17)
set(CMAKE_C_STANDARD_REQUIRED ON)

include(clarity-runtime/clarity.cmake)

file(GLOB PROGRAM_SOURCES CONFIGURE_DEPENDS src/*.c src/modules/*.c)
add_executable({target} ${{PROGRAM_SOURCES}})
set_target_properties({target} PROPERTIES OUTPUT_NAME {program})
target_include_directories({target} PRIVATE src)
target_link_libraries({target} PRIVATE clarity{engine}{http})
",
        target = snake(program),
    )
}

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let project = &crate::with_secret_settings(project, &crate::settings_program(settings));
    let (databases, owned) = crate::databases(project, settings)?;
    let databases = crate::with_secret_locations(databases, &crate::settings_program(settings));
    if let Some((name, _, _)) = databases.iter().find(|(_, sql, _)| *sql != Sql::Sqlite) {
        return Err(vec![format!("data source '{name}' is a server database; the C backend stores records in SQLite for now")]);
    }
    let program = crate::commands::program_name(settings);
    let types = check::types(&project.files);
    let engines = !crate::engines(project).is_empty();
    let mut files = vec![text("CMakeLists.txt", cmake_lists(&program, engines, project.calls_out(), !project.secret_settings().is_empty())), text("CMakePresets.json", PRESETS.to_string())];
    // The runtime without the shell: no window, no webview.
    let engine_files = ENGINE_FILES.iter().chain(&WASM3_FILES).filter(|_| engines);
    let http_files = super::HTTP_FILES.iter().filter(|_| project.calls_out());
    let secret_files = super::SECRET_FILES.iter().filter(|_| !project.secret_settings().is_empty());
    for (path, body) in RUNTIME_FILES.iter().chain(engine_files).chain(http_files).chain(secret_files) {
        files.push(text(&format!("clarity-runtime/{path}"), body.to_string()));
    }
    let (records_h, records_c) = model::emit(project);
    files.push(text("src/records.h", format!("{HEADER}\n#pragma once\n\n#include <stddef.h>\n\n#include \"clarity/code.h\"\n#include \"clarity/list_fields.h\"\n{}\n{}", if project.calls_out() { "#include \"http/http.h\"\n" } else { "" }, records_h.trim_end().to_string() + "\n")));
    files.push(text("src/records.c", format!("{HEADER}\n#include <stdlib.h>\n#include <string.h>\n\n#include \"app.h\"\n\n{}", records_c.trim_end().to_string() + "\n")));

    let mut errors = Vec::new();
    let mut declarations = String::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        for decl in file.functions.iter().chain(&logic::events(file)) {
            let _ = writeln!(declarations, "{};", logic::signature(project, decl));
        }
        for command in &file.commands {
            let _ = writeln!(declarations, "{};", logic::command_signature(project, command));
        }
        let mut body = String::new();
        match logic::emit(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_commands(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        let includes = "#include \"../app.h\"\n";
        files.push(text(&format!("src/modules/{}.c", snake(&m.name)), format!("{HEADER}\n{includes}\n{}", body.trim_end().to_string() + "\n")));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    // What every command has as data of its own: the settings (DESIGN 5.17).
    let kept = project.files.iter().flat_map(|f| &f.entities).find(|e| e.settings);
    let data = match kept {
        Some(entity) => format!("/// What every command has as data of its own: the settings.\ntypedef struct {{\n    {} settings;\n}} CommandData;\n", entity.name.name),
        None => "/// What every command has as data of its own.\ntypedef struct {\n    int unused;\n} CommandData;\n".to_string(),
    };
    let engines_include = if engines { "#include \"engines.h\"\n" } else { "" };
    files.push(text(
        "src/app.h",
        format!("{HEADER}\n#pragma once\n\n#include <string.h>\n\n#include \"clarity/cli.h\"\n#include \"clarity/code.h\"\n#include \"records.h\"\n{engines_include}\n{data}\n{}", declarations.trim_end().to_string() + "\n"),
    ));
    if engines {
        let (header, source) = super::engines_c(project);
        files.push(text("src/engines.h", header));
        files.push(text("src/engines.c", source));
    }
    files.push(text("src/schema.h", format!("{HEADER}\n{SCHEMA_H}")));
    files.push(text("src/schema.c", super::schema_c(project, &owned)?));
    // Secret settings (DESIGN 5.27): read and kept through the system's protected store.
    let mut main = main_c(project, settings, &databases);
    let secrets = crate::secret_names(project);
    if !secrets.is_empty() {
        let list = string(&format!("[{}]", secrets.iter().map(|n| format!("{n:?}")).collect::<Vec<_>>().join(", ")));
        main = main
            .replace("clarity_read_settings(PROGRAM)", &format!("clarity_read_settings_with(PROGRAM, cJSON_Parse({list}))"))
            .replace("clarity_keep_settings(PROGRAM, after)", &format!("clarity_keep_settings_with(PROGRAM, after, cJSON_Parse({list}))"));
    }
    files.push(text("src/main.c", main));
    files.push(text(
        "README.md",
        format!(
            "# {title}: the command line\n\nGenerated by Clarity from the project {project}: the command-line program `{program}`, in C. Do not edit these files; change the project in Clarity and generate it again.\n\n## Build and run\n\nIn this folder, build the program with\n\n    cmake --workflow --preset release\n\nwhich writes `build/release/{program}`. Run `{program} --help` to see its commands.\n",
            title = clarity_project::title(settings),
            project = settings.name,
        ),
    ));
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

fn main_c(project: &Project, settings: &Settings, databases: &[(String, Sql, String)]) -> String {
    // Secret settings (DESIGN 5.27): the system's protected store, before anything reads a setting.
    let (secrets_include, use_secrets) = if project.secret_settings().is_empty() {
        (String::new(), String::new())
    } else {
        ("#include \"secrets/secrets.h\"\n\n".to_string(), "    clarity_secrets_use();\n".to_string())
    };
    let commands = crate::commands::commands(project);
    let sources: Vec<String> = databases.iter().map(|(name, _, at)| format!("    {{{}, CLARITY_SQLITE, {}}},", string(name), string(at))).collect();
    let stores: Vec<String> = settings.filestores.iter().map(|s| format!("    if (!clarity_add_store(db, {}, {})) return failed(db);", string(&s.name), string(&s.location))).collect();
    let languages: Vec<String> = project.translations.keys().map(|l| string(l)).collect();
    let base = project.locale.language.clone().unwrap_or_else(|| "en".to_string());
    let mut described = String::new();
    for (i, c) in commands.iter().enumerate() {
        command(i, c, &mut described);
    }
    let kept = project.files.iter().flat_map(|f| &f.entities).find(|e| e.settings);
    let (start, keep) = match kept {
        Some(entity) => {
            let p = prefix(&entity.name.name);
            let language = entity
                .fields
                .iter()
                .find(|f| f.ty == FieldType::Language)
                .map(|f| format!("    if (data.settings.{field} && *data.settings.{field}) clarity_set_language(data.settings.{field});\n", field = ident(&f.name.name)))
                .unwrap_or_default();
            (
                format!("    CommandData data = {{kept_settings()}};\n    const char* before = cJSON_PrintUnformatted({p}_json(&data.settings));\n{language}"),
                format!("    // A command that changed a setting keeps it, as a window does.\n    cJSON* after = {p}_json(&data.settings);\n    if (strcmp(cJSON_PrintUnformatted(after), before) != 0) {{\n        cJSON_DeleteItemFromObjectCaseSensitive(after, \"id\");\n        clarity_keep_settings(PROGRAM, after);\n    }}\n"),
            )
        }
        None => ("    CommandData data = {0};\n".to_string(), String::new()),
    };
    let kept_settings = match kept {
        Some(entity) => {
            let (name, p) = (&entity.name.name, prefix(&entity.name.name));
            format!(
                "/// The settings kept, each one that still fits; the others have their default.\nstatic {name} kept_settings(void) {{\n    {name} settings = {p}_new();\n    cJSON* values = {p}_json(&settings);\n    cJSON* kept = clarity_read_settings(PROGRAM);\n    const cJSON* item;\n    cJSON_ArrayForEach(item, kept) {{\n        if (!cJSON_GetObjectItemCaseSensitive(values, item->string)) continue;\n        cJSON* tried = cJSON_Duplicate(values, 1);\n        cJSON_ReplaceItemInObjectCaseSensitive(tried, item->string, cJSON_Duplicate(item, 1));\n        {name} check;\n        if ({p}_from_json(tried, &check)) values = tried;\n    }}\n    {p}_from_json(values, &settings);\n    return settings;\n}}\n\n"
            )
        }
        None => String::new(),
    };
    let mut dispatch = String::new();
    for (i, c) in commands.iter().enumerate() {
        let values: Vec<String> = c.arguments.iter().chain(&c.options).enumerate().map(|(at, p)| typed(p, at)).collect();
        let args: String = values.iter().map(|v| format!(", {v}")).collect();
        let _ = writeln!(dispatch, "    case {i}:\n        worked = {}(db, &data{args}, &code);\n        break;", logic::command_function(c.decl));
    }
    let settings_include = if kept.is_some() { "#include \"clarity/settings.h\"\n" } else { "" };
    let mut out = format!(
        "{HEADER}
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include \"app.h\"
#include \"clarity/db.h\"
{settings_include}#include \"schema.h\"

/// The desktop program's name, which names the folder the person's
/// settings are kept in: both programs share them.
#define PROGRAM {program}

/// The database of each data source: its name, its kind and where it is.
static const ClaritySource databases[] = {{
{sources}
}};

",
        program = string(&crate::settings_program(settings)),
        sources = sources.join("\n"),
    );
    out.push_str(&long_text("texts", &crate::commands::texts_json(project)));
    let _ = write!(
        out,
        "/// The texts the program shows, in every language the project has.
static const char* texts(void) {{
    ClarityBuffer all = {{0}};
    for (size_t i = 0; texts_parts[i]; i++) clarity_buffer_add(&all, texts_parts[i]);
    return clarity_buffer_text(&all);
}}

{kept_settings}/// The program and its commands, as the command line reads them.
static ClarityCliProgram program(void) {{
    ClarityCliCommand* commands = CLARITY_NEW(ClarityCliCommand, {count});
{described}    return (ClarityCliProgram){{.name = {name}, .help = {help}, .commands = commands, .command_count = {count}}};
}}

/// Says what went wrong, and ends the program.
static int failed(ClarityDb* db) {{
    fprintf(stderr, \"%s\\n\", clarity_error()->message);
    clarity_db_close(db);
    return 1;
}}

{secrets_include}int main(int argc, char** argv) {{
{use_secrets}
    clarity_start();
    clarity_load_translations(texts());
    const char* locale = getenv(\"LC_ALL\");
    if (!locale || !*locale) locale = getenv(\"LC_MESSAGES\");
    if (!locale || !*locale) locale = getenv(\"LANG\");
    static const char* const languages[] = {{{languages}NULL}};
    clarity_set_language(clarity_cli_pick_language(locale, languages, {language_count}, {base}));
{start}    ClarityDb* db = NULL;
    if (!clarity_db_open(databases, sizeof databases / sizeof databases[0], &db)) return failed(db);
    size_t count = 0;
    const SourceSteps* sources = schema_sources(&count);
    for (size_t i = 0; i < count; i++)
        if (!clarity_migrate(db, sources[i].source, sources[i].steps, sources[i].count, NULL)) return failed(db);
{stores}
    ClarityCliProgram described = program();
    ClarityCliParsed parsed = clarity_cli_parse(&described, (size_t)(argc - 1), (const char* const*)(argv + 1), clarity_cli_words());
    if (parsed.outcome == CLARITY_CLI_HELP) {{
        fputs(parsed.help, stdout);
        clarity_db_close(db);
        return 0;
    }}
    if (parsed.outcome == CLARITY_CLI_WRONG) {{
        fputs(parsed.said, stderr);
        clarity_db_close(db);
        return 2;
    }}
    int code = 0;
    bool worked = false;
    switch (parsed.command) {{
{dispatch}    }}
    if (!worked) {{
        clarity_cli_failed();
        code = 1;
    }}
{keep}    clarity_db_close(db);
    return code < 0 ? 0 : (code > 255 ? 255 : code);
}}
",
        count = commands.len().max(1),
        name = string(&crate::commands::program_name(settings)),
        help = said(&crate::commands::program_help(project)),
        languages = languages.iter().map(|l| format!("{l}, ")).collect::<String>(),
        language_count = languages.len(),
        base = string(&base),
        stores = stores.join("\n"),
    );
    out
}
