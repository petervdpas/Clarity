/// The name of the generated program.
pub fn program_name(settings: &Settings) -> String {
    let name = snake(&settings.name);
    if name == "clarity" { format!("{name}_app") } else { ident(&name) }
}

pub use cli::generate as generate_cli;

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let project = &crate::with_secret_settings(project, &crate::settings_program(settings));
    // What the parts' code lacks of Clarity's files, read without building it (DESIGN 5.19).
    let mismatches = parts::code_mismatches(project);
    if !mismatches.is_empty() {
        return Err(mismatches);
    }
    let (databases, owned) = crate::databases(project, settings)?;
    let databases = crate::with_secret_locations(databases, &crate::settings_program(settings));
    if let Some((name, sql, _)) = databases.iter().find(|(_, sql, _)| *sql != Sql::Sqlite) {
        return Err(vec![format!(
            "data source '{name}' is a {} database; the C backend stores records in SQLite for now",
            match sql {
                Sql::Postgres => "PostgreSQL",
                Sql::Mysql => "MySQL",
                _ => "SQL Server",
            }
        )]);
    }
    let program = program_name(settings);
    let types = check::types(&project.files);
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let engines = !crate::engines(project).is_empty();
    let desktop = settings.stack.has(clarity_project::Target::Desktop);
    let web = settings.stack.has(clarity_project::Target::Web);
    // Engines beside the screen run in the program, on the runtime's engine host (DESIGN 5.12): the web's too, asked over the wire.
    let screen_engines = (desktop || web) && !crate::screen_engines(project).is_empty();
    // The desktop's windows, app frames, themes and resources, which Clarity.UI reads (DESIGN 7.9).
    let carried = if desktop { crate::rust::clarity_files(project) } else { Vec::new() };
    let links = Links { engines: engines || screen_engines, http: project.calls_out(), secrets: !project.secret_settings().is_empty(), desktop, web };
    // Custom parts are kinds of part of Clarity.UI, built into the program (DESIGN 7.9): on the desktop only.
    let custom = if desktop { parts::parts(project) } else { Vec::new() };
    let mut files = vec![
        text("CMakeLists.txt", cmake_lists(&program, &links, &carried) + &parts::cmake_lines(&program, &custom) + &crate::libraries::cmake_lines(project, &program) + &audio_cmake_lines(project, settings, &program) + &formats_cmake_lines(project, &program)),
        text("CMakePresets.json", PRESETS.to_string()),
    ];
    if !custom.is_empty() {
        files.extend(parts::out_files(project));
        files.push(text("src/parts.h", format!("{HEADER}\n{}", parts::GLUE_H)));
        files.push(text("src/parts.c", parts::glue(&custom)));
    }
    let engine_files = ENGINE_FILES.iter().chain(&WASM3_FILES).filter(|_| engines || screen_engines).chain(SCREEN_FILES.iter().filter(|_| screen_engines));
    let http_files = HTTP_FILES.iter().filter(|_| project.calls_out());
    let picture_files = PICTURE_FILES.iter().filter(|_| crate::uses_picture_functions(project));
    let formats_files = FORMATS_FILES.iter().filter(|_| project.uses_formats());
    let secret_files = SECRET_FILES.iter().filter(|_| !project.secret_settings().is_empty());
    let desktop_files = DESKTOP_FILES.iter().filter(|_| desktop);
    for (path, body) in RUNTIME_FILES.iter().chain(&SERVICE_FILES).chain(desktop_files).chain(engine_files).chain(http_files).chain(picture_files).chain(formats_files).chain(secret_files) {
        files.push(text(&format!("clarity-runtime/{path}"), body.to_string()));
    }

    let (records_h, records_c) = model::emit(project);
    // Each library's header, so every module calls it (DESIGN 5.21).
    let library_includes: String = crate::libraries::libraries(project).iter().map(|l| format!("#include \"clarity/{}.h\"\n", l.name.name)).collect();
    // The HTTP client, for code that calls out (DESIGN 5.23).
    let http_include = if project.calls_out() { "#include \"http/http.h\"\n" } else { "" };
    // The picture functions, for code that calls one (docs/IMAGE-PLAN.md).
    let pictures_include = if crate::uses_picture_functions(project) { "#include \"pictures/pictures.h\"\n" } else { "" };
    let formats_include = if project.uses_formats() { "#include \"formats/formats.h\"\n" } else { "" };
    files.push(text("src/records.h", format!("{HEADER}\n#pragma once\n\n#include <stddef.h>\n\n#include \"clarity/code.h\"\n#include \"clarity/list_fields.h\"\n{http_include}{pictures_include}{formats_include}{library_includes}\n{}", records_h.trim_end().to_string() + "\n")));
    for library in crate::libraries::libraries(project) {
        let n = &library.name.name;
        let own = crate::libraries::own_file(library, false);
        files.extend(crate::libraries::adapter_files(project, n, &own));
        files.push(text(&format!("{}/{own}", crate::libraries::folder(n)), crate::libraries::c_header(library, false)));
    }
    files.push(text("src/records.c", format!("{HEADER}\n#include <stdlib.h>\n#include <string.h>\n\n#include \"app.h\"\n\n{}", records_c.trim_end().to_string() + "\n")));

    let mut errors = Vec::new();
    let mut declarations = String::new();
    let mut windows = String::new();
    let mut owners = Vec::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        for decl in file.functions.iter().chain(&logic::events(file)) {
            let _ = writeln!(declarations, "{};", logic::signature(project, decl));
        }
        let mut body = String::new();
        match logic::emit(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types) {
            Ok((header, code, mut found)) => {
                windows.push_str(&header);
                body.push_str(&code);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        let includes = "#include \"../app.h\"\n";
        files.push(text(&format!("src/modules/{}.c", snake(&m.name)), format!("{HEADER}\n{includes}\n{}", body.trim_end().to_string() + "\n")));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let app = format!("{declarations}\n{windows}");
    let engines_include = if engines { "#include \"engines.h\"\n" } else { "" };
    files.push(text(
        "src/app.h",
        format!("{HEADER}\n#pragma once\n\n#include <string.h>\n\n#include \"clarity/code.h\"\n#include \"records.h\"\n{engines_include}\n{}", app.trim_end().to_string() + "\n"),
    ));
    if engines {
        let (header, source) = engines_c(project);
        files.push(text("src/engines.h", header));
        files.push(text("src/engines.c", source));
    }
    if screen_engines {
        files.push(text("src/screen_engines.h", format!("{HEADER}\n{SCREEN_ENGINES_H}")));
        files.push(text("src/screen_engines.c", screen_engines_c(project)));
    }
    files.push(text("src/schema.h", format!("{HEADER}\n{SCHEMA_H}")));
    files.push(text("src/schema.c", schema_c(project, &owned)?));
    files.push(text("src/model.h", format!("{HEADER}\n{MODEL_H}")));
    files.push(text("src/model.c", model_c(project)));
    if web {
        // The page, files.json and the resources Clarity.UI in the browser reads, which the server carries (browser/).
        files.extend(crate::web_browser::site(project, settings));
    }
    if desktop || web {
        // What the parts read beside the values (DESIGN 7.9).
        files.push(text("src/facts.h", format!("{HEADER}\n{FACTS_H}")));
        files.push(text("src/facts.c", facts_c(project)));
    }
    files.extend(carried);
    files.push(text("src/main.c", main_c(project, settings, &databases, &owners, &main_window)));
    with_windows_resources(project, &clarity_project::title(settings), &program, &mut files);
    Ok(files)
}

