/// The name of the generated program.
pub fn program_name(settings: &Settings) -> String {
    let name = snake(&settings.name);
    if name == "clarity" { format!("{name}_app") } else { ident(&name) }
}

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "C")?;
    if let Some((name, sql, _)) = databases.iter().find(|(_, sql, _)| *sql != Sql::Sqlite) {
        return Err(vec![format!(
            "data source '{name}' is a {} database; the C backend stores records in SQLite for now",
            match sql {
                Sql::Postgres => "PostgreSQL",
                Sql::Mysql => "MySQL",
                _ => "SQL Server",
            }
        )]);
    }
    let program = program_name(settings);
    let types = check::types(&project.files);
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let engines = !crate::engines(project).is_empty();
    let mut files = vec![text("CMakeLists.txt", cmake_lists(&program, engines)), text("CMakePresets.json", PRESETS.to_string())];
    let engine_files = ENGINE_FILES.iter().chain(&WASM3_FILES).filter(|_| engines);
    for (path, body) in RUNTIME_FILES.iter().chain(&SHELL_FILES).chain(engine_files) {
        files.push(text(&format!("clarity-runtime/{path}"), body.to_string()));
    }

    let (records_h, records_c) = model::emit(project);
    files.push(text("src/records.h", format!("{HEADER}\n#pragma once\n\n#include <stddef.h>\n\n#include \"clarity/code.h\"\n#include \"clarity/list_fields.h\"\n\n{}", records_h.trim_end().to_string() + "\n")));
    files.push(text("src/records.c", format!("{HEADER}\n#include <stdlib.h>\n#include <string.h>\n\n#include \"app.h\"\n\n{}", records_c.trim_end().to_string() + "\n")));

    let mut errors = Vec::new();
    let mut declarations = String::new();
    let mut windows = String::new();
    let mut owners = Vec::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        for decl in file.functions.iter().chain(&logic::events(file)) {
            let _ = writeln!(declarations, "{};", logic::signature(project, decl));
        }
        declarations.push_str(&logic::engine_declarations(project, file));
        let mut body = String::new();
        match logic::emit(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types) {
            Ok((header, code, mut found)) => {
                windows.push_str(&header);
                body.push_str(&code);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        // An engine written in Clarity with state keeps each instance's values on the heap.
        let kept = file.engines.iter().any(|e| e.body.is_some() && e.state != clarity_spec::code::EngineState::None);
        let includes = if kept { "#include <stdlib.h>\n\n#include \"../app.h\"\n" } else { "#include \"../app.h\"\n" };
        files.push(text(&format!("src/modules/{}.c", snake(&m.name)), format!("{HEADER}\n{includes}\n{}", body.trim_end().to_string() + "\n")));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let app = format!("{declarations}\n{windows}");
    let engines_include = if engines { "#include \"engines.h\"\n" } else { "" };
    files.push(text(
        "src/app.h",
        format!("{HEADER}\n#pragma once\n\n#include <string.h>\n\n#include \"clarity/code.h\"\n#include \"records.h\"\n{engines_include}\n{}", app.trim_end().to_string() + "\n"),
    ));
    if engines {
        let (header, source) = engines_c(project);
        files.push(text("src/engines.h", header));
        files.push(text("src/engines.c", source));
    }
    files.push(text("src/schema.h", format!("{HEADER}\n{SCHEMA_H}")));
    files.push(text("src/schema.c", schema_c(project, &owned)?));
    files.push(text("src/page.h", format!("{HEADER}\n{PAGE_H}")));
    files.push(text("src/page.c", page_c(project)));
    files.push(text("src/main.c", main_c(project, settings, &program, &databases, &owners, &main_window)));
    Ok(files)
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project.apps().find_map(|a| a.main.as_ref().map(|m| m.name.clone())).or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

fn text(path: &str, body: String) -> OutFile {
    OutFile { path: path.to_string(), text: body, bytes: None }
}

/// The C function code calls for a function of an engine: `pricing_add`.
pub fn engine_function(engine: &str, function: &str) -> String {
    format!("{}_{}", snake(engine), snake(function))
}

/// The engines of the application (DESIGN 5.11): each file as bytes, loaded
/// once and checked at start, and a typed function for each of their
/// functions, whose values cross as JSON. Returns the header and the source.
fn engines_c(project: &Project) -> (String, String) {
    use clarity_spec::code::check::TypeInfo;
    let to_json = |ty: &TypeInfo, value: &str| -> String {
        match ty {
            TypeInfo::Text => format!("clarity_json_text({value})"),
            TypeInfo::Bytes => format!("clarity_json_bytes({value})"),
            TypeInfo::Integer | TypeInfo::Duration => format!("clarity_json_integer({value})"),
            TypeInfo::Decimal | TypeInfo::Money => format!("clarity_json_decimal({value})"),
            TypeInfo::Bool => format!("clarity_json_bool({value})"),
            TypeInfo::Date => format!("clarity_json_date({value})"),
            TypeInfo::DateTime => format!("clarity_json_date_time({value})"),
            TypeInfo::Enum(e) => format!("clarity_json_text({}_name({value}))", prefix(e)),
            TypeInfo::Record(e) => format!("{}_json({value})", prefix(e)),
            TypeInfo::List(e) => format!("{}_list_json(&{value})", prefix(e)),
            _ => "cJSON_CreateNull()".to_string(),
        }
    };
    let from_json = |ty: &TypeInfo| -> String {
        match ty {
            TypeInfo::Text => "clarity_json_get_text(box, \"value\", result)".into(),
            TypeInfo::Bytes => "clarity_json_get_bytes(box, \"value\", result)".into(),
            TypeInfo::Integer | TypeInfo::Duration => "clarity_json_get_integer(box, \"value\", result)".into(),
            TypeInfo::Decimal | TypeInfo::Money => "clarity_json_get_decimal(box, \"value\", result)".into(),
            TypeInfo::Bool => "clarity_json_get_bool(box, \"value\", result)".into(),
            TypeInfo::Date => "clarity_json_get_date(box, \"value\", result)".into(),
            TypeInfo::DateTime => "clarity_json_get_date_time(box, \"value\", result)".into(),
            TypeInfo::Enum(e) => format!("(name = NULL, clarity_json_get_text(box, \"value\", &name)) && (*result = {}_from(name), true)", prefix(e)),
            TypeInfo::Record(e) => format!("{}_from_json(value, result)", prefix(e)),
            TypeInfo::List(e) => format!("{}_list_from_json(value, result)", prefix(e)),
            _ => "false".into(),
        }
    };
    let mut header = format!("{HEADER}\n#pragma once\n\n#include \"engine/engine.h\"\n#include \"records.h\"\n\n/// Loads every engine, so one whose file does not fit stops the application at start.\nbool engines_check(void);\n");
    let mut source = format!("{HEADER}\n#include \"app.h\"\n");
    let mut checks = String::new();
    for engine in crate::engines(project) {
        let var = snake(&engine.name.name);
        let bytes = project.engines.as_deref().unwrap_or_default().iter().find(|f| f.name == engine.file).map(|f| f.bytes.as_slice()).unwrap_or_default();
        let rows: Vec<String> = bytes.chunks(16).map(|row| row.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ")).collect();
        let names: Vec<String> = engine.functions.iter().map(|f| string(&f.name.name)).collect();
        source.push_str(&format!(
            "\n/// Engine {name}, from {file}.\nstatic const uint8_t {var}_wasm[] = {{\n    {}\n}};\nstatic const char* const {var}_functions[] = {{{}}};\nstatic const char* const {var}_uses[] = {{{uses}}};\nstatic ClarityEngine* {var}_engine = NULL;\n\nstatic bool {var}_loaded(void) {{\n    return {var}_engine || clarity_engine_load({}, {var}_wasm, sizeof {var}_wasm, (ClarityEngineDeclaration){{{}, {var}_functions, {use_count}, {var}_uses, (ClarityEngineLimits){{{seconds}, {megabytes}}}, {state}, {opens}}}, &{var}_engine);\n}}\n",
            rows.join(",\n    "),
            names.join(", "),
            string(&engine.name.name),
            names.len(),
            uses = if engine.uses.is_empty() { "NULL".to_string() } else { engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", ") },
            use_count = engine.uses.len(),
            seconds = engine.seconds(),
            megabytes = engine.megabytes(),
            state = match engine.state {
                clarity_spec::code::EngineState::None => "CLARITY_ENGINE_NO_STATE",
                clarity_spec::code::EngineState::App => "CLARITY_ENGINE_PER_APP",
                clarity_spec::code::EngineState::Window => "CLARITY_ENGINE_PER_WINDOW",
            },
            opens = engine.opens,
            name = engine.name.name,
            file = engine.file,
        ));
        checks.push_str(&format!("    if (!{var}_loaded()) return false;\n"));
        // An engine with state per window is called in a window: its functions take the window's number.
        let per_window = engine.state == clarity_spec::code::EngineState::Window;
        for function in &engine.functions {
            let wrapper = engine_function(&engine.name.name, &function.name.name);
            let returns = function.returns.as_ref().map_or(TypeInfo::Unknown, |r| logic::type_ref_info(project, r));
            let window = per_window.then(|| "uint64_t window".to_string());
            let mut params: Vec<String> =
                window.into_iter().chain(function.params.iter().map(|p| format!("{} {}", names::param_type(&logic::type_ref_info(project, &p.ty)), ident(&p.name.name)))).collect();
            let call = if per_window { "clarity_engine_call_in({var}_engine, window, " } else { "clarity_engine_call({var}_engine, " }.replace("{var}", &var);
            params.push(format!("{}* result", value_type(&returns)));
            let signature = format!("bool {wrapper}({})", params.join(", "));
            header.push_str(&format!("/// {}.{} of engine {}.\n{signature};\n", engine.name.name, function.name.name, engine.name.name));
            let args: String = function
                .params
                .iter()
                .map(|p| format!("    cJSON_AddItemToArray(args, {});\n", to_json(&logic::type_ref_info(project, &p.ty), &ident(&p.name.name))))
                .collect();
            let name_local = if matches!(returns, TypeInfo::Enum(_)) { "    const char* name;\n" } else { "" };
            source.push_str(&format!(
                "\n{signature} {{\n    if (!{var}_loaded()) return false;\n    cJSON* args = cJSON_CreateArray();\n{args}    cJSON* value = NULL;\n    if (!{call}{}, args, &value)) return false;\n    cJSON* box = cJSON_CreateObject();\n    cJSON_AddItemToObject(box, \"value\", value);\n{name_local}    return {};\n}}\n",
                string(&function.name.name),
                from_json(&returns),
            ));
        }
    }
    source.push_str(&format!("\nbool engines_check(void) {{\n{checks}    return true;\n}}\n"));
    (header, source)
}

fn cmake_lists(program: &str, engines: bool) -> String {
    let engine = if engines { " clarity_engine" } else { "" };
    format!(
        "# Generated by Clarity. Do not edit: change the project in Clarity instead.
#
# Configure and build with one command (CMake 3.25 or newer):
#   cmake --workflow --preset debug      (or release)
# The program is then build/debug/{program}. See README.md for what to install.
# The program is C; the webview it shows its windows in is C++, so a C++
# compiler builds that one file.
cmake_minimum_required(VERSION 3.25)
project({program} LANGUAGES C CXX)

set(CMAKE_C_STANDARD 17)
set(CMAKE_C_STANDARD_REQUIRED ON)

include(clarity-runtime/clarity.cmake)

file(GLOB PROGRAM_SOURCES CONFIGURE_DEPENDS src/*.c src/modules/*.c)
add_executable({program} ${{PROGRAM_SOURCES}})
target_include_directories({program} PRIVATE src)
target_link_libraries({program} PRIVATE clarity clarity_shell{engine})
"
    )
}

