/// The name of the generated program.
pub fn program_name(settings: &Settings) -> String {
    let name = snake(&settings.name);
    if name == "clarity" { format!("{name}_app") } else { ident(&name) }
}

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "C")?;
    if let Some((name, sql, _)) = databases.iter().find(|(_, sql, _)| *sql != Sql::Sqlite) {
        return Err(vec![format!(
            "data source '{name}' is a {} database; the C backend stores records in SQLite for now",
            match sql {
                Sql::Postgres => "PostgreSQL",
                Sql::Mysql => "MySQL",
                _ => "SQL Server",
            }
        )]);
    }
    let program = program_name(settings);
    let types = check::types(&project.files);
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let mut files = vec![text("CMakeLists.txt", cmake_lists(&program)), text("CMakePresets.json", PRESETS.to_string())];
    for (path, body) in RUNTIME_FILES.iter().chain(&SHELL_FILES) {
        files.push(text(&format!("clarity-runtime/{path}"), body.to_string()));
    }

    let (records_h, records_c) = model::emit(project);
    files.push(text("src/records.h", format!("{HEADER}\n#pragma once\n\n#include <stddef.h>\n\n#include \"clarity/code.h\"\n\n{}", records_h.trim_end().to_string() + "\n")));
    files.push(text("src/records.c", format!("{HEADER}\n#include <string.h>\n\n#include \"app.h\"\n\n{}", records_c.trim_end().to_string() + "\n")));

    let mut errors = Vec::new();
    let mut declarations = String::new();
    let mut windows = String::new();
    let mut owners = Vec::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        for decl in file.functions.iter().chain(&logic::events(file)) {
            let _ = writeln!(declarations, "{};", logic::signature(project, decl));
        }
        let mut body = String::new();
        match logic::emit(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types) {
            Ok((header, code, mut found)) => {
                windows.push_str(&header);
                body.push_str(&code);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("src/modules/{}.c", snake(&m.name)), format!("{HEADER}\n#include \"../app.h\"\n\n{}", body.trim_end().to_string() + "\n")));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let app = format!("{declarations}\n{windows}");
    files.push(text(
        "src/app.h",
        format!("{HEADER}\n#pragma once\n\n#include <string.h>\n\n#include \"clarity/code.h\"\n#include \"records.h\"\n\n{}", app.trim_end().to_string() + "\n"),
    ));
    files.push(text("src/schema.h", format!("{HEADER}\n{SCHEMA_H}")));
    files.push(text("src/schema.c", schema_c(project, &owned)?));
    files.push(text("src/page.h", format!("{HEADER}\n{PAGE_H}")));
    files.push(text("src/page.c", page_c(project)));
    files.push(text("src/main.c", main_c(project, settings, &program, &databases, &owners, &main_window)));
    Ok(files)
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project.apps().find_map(|a| a.main.as_ref().map(|m| m.name.clone())).or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

fn text(path: &str, body: String) -> OutFile {
    OutFile { path: path.to_string(), text: body, bytes: None }
}

fn cmake_lists(program: &str) -> String {
    format!(
        "# Generated by Clarity. Do not edit: change the project in Clarity instead.
#
# Configure and build with one command (CMake 3.25 or newer):
#   cmake --workflow --preset debug      (or release)
# The program is then build/debug/{program}. See README.md for what to install.
# The program is C; the webview it shows its windows in is C++, so a C++
# compiler builds that one file.
cmake_minimum_required(VERSION 3.25)
project({program} LANGUAGES C CXX)

set(CMAKE_C_STANDARD 17)
set(CMAKE_C_STANDARD_REQUIRED ON)

include(clarity-runtime/clarity.cmake)

file(GLOB PROGRAM_SOURCES CONFIGURE_DEPENDS src/*.c src/modules/*.c)
add_executable({program} ${{PROGRAM_SOURCES}})
target_include_directories({program} PRIVATE src)
target_link_libraries({program} PRIVATE clarity clarity_shell)
"
    )
}

