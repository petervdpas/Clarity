/// The steps of each data source, as main.c applies them.
const SCHEMA_H: &str = "#pragma once\n\n#include \"clarity/store.h\"\n\n/// The migration steps of one data source, in order, each a list of\n/// statements. Each database remembers how many steps it has applied, and\n/// applies the rest when the application starts.\ntypedef struct {\n    const char* source;\n    const ClarityStep* steps;\n    size_t count;\n} SourceSteps;\n\n/// The steps of every database Clarity owns, and how many databases there are.\nconst SourceSteps* schema_sources(size_t* count);\n";

/// The steps of every database Clarity owns, as SQL per data source.
fn schema_c(project: &Project, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut body = String::new();
    let mut all = Vec::new();
    let mut errors = Vec::new();
    for (n, (source, sql)) in sources.iter().enumerate() {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        let mut list = Vec::new();
        for (i, (title, statements)) in steps.iter().enumerate() {
            let name = format!("source{}_step{}", n + 1, i + 1);
            let lines: Vec<String> = statements.iter().map(|s| format!("    {},", string(s))).collect();
            let lines = if lines.is_empty() { "    NULL,".to_string() } else { lines.join("\n") };
            let _ = write!(body, "// {}: {title}\nstatic const char* const {name}[] = {{\n{lines}\n}};\n\n", i + 1);
            list.push(format!("    {{{name}, {}}},", statements.len()));
        }
        let steps_name = format!("source{}_steps", n + 1);
        let list = if list.is_empty() { "    {NULL, 0},".to_string() } else { list.join("\n") };
        let _ = write!(body, "static const ClarityStep {steps_name}[] = {{\n{list}\n}};\n\n");
        all.push(format!("    {{{}, {steps_name}, {}}},", string(source), steps.len()));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let count = all.len();
    let all = if all.is_empty() { "    {\"\", NULL, 0},".to_string() } else { all.join("\n") };
    Ok(format!(
        "{HEADER}\n#include \"schema.h\"\n\n{body}static const SourceSteps all[] = {{\n{all}\n}};\n\nconst SourceSteps* schema_sources(size_t* count) {{\n    *count = {count};\n    return all;\n}}\n"
    ))
}

/// The renderer's page and the model it draws from, as main.c hands them to the shell.
const PAGE_H: &str = "#pragma once\n\n/// The windows, frame and data dictionary the renderer draws from, as JSON.\nconst char* page_model(void);\n/// The renderer's page, with its script, styles and pictures in it.\nconst char* page_html(void);\n";

/// Text as C source: pieces small enough for every compiler's limit on
/// one string literal, joined once when the program first asks for it.
fn long_text(name: &str, text: &str) -> String {
    let mut pieces = Vec::new();
    let mut rest = text;
    while !rest.is_empty() {
        let mut at = rest.len().min(2000);
        while !rest.is_char_boundary(at) {
            at -= 1;
        }
        pieces.push(format!("    {},", string(&rest[..at])));
        rest = &rest[at..];
    }
    format!("static const char* const {name}_parts[] = {{\n{}\n    NULL,\n}};\n\n", pieces.join("\n"))
}

fn page_c(project: &Project) -> String {
    format!(
        "{HEADER}\n#include <stdlib.h>\n#include <string.h>\n\n#include \"page.h\"\n\n/// The pieces joined, in memory that lasts as long as the program.\nstatic char* joined(const char* const* parts) {{\n    size_t length = 0;\n    for (const char* const* p = parts; *p; ++p) length += strlen(*p);\n    char* out = malloc(length + 1);\n    if (!out) return \"\";\n    out[0] = '\\0';\n    for (const char* const* p = parts; *p; ++p) strcat(out, *p);\n    return out;\n}}\n\n{}{}const char* page_model(void) {{\n    static char* text;\n    if (!text) text = joined(model_parts);\n    return text;\n}}\n\nconst char* page_html(void) {{\n    static char* text;\n    if (!text) text = joined(html_parts);\n    return text;\n}}\n",
        long_text("model", &crate::web::model_json(project)),
        long_text("html", &crate::web::single_page(project))
    )
}

fn main_c(project: &Project, settings: &Settings, program: &str, databases: &[(String, Sql, String)], owners: &[logic::Owner], main_window: &str) -> String {
    let sources: Vec<String> = databases.iter().map(|(name, _, at)| format!("    {{{}, CLARITY_SQLITE, {}}},", string(name), string(at))).collect();
    let stores: Vec<String> = settings.filestores.iter().map(|s| format!("    if (!clarity_add_store(db, {}, {})) return failed(db);", string(&s.name), string(&s.location))).collect();
    let windows: Vec<&logic::Owner> = owners.iter().filter(|o| !o.is_app).collect();
    let apps: Vec<&logic::Owner> = owners.iter().filter(|o| o.is_app).collect();

    let mut open = String::new();
    for w in &windows {
        let _ = write!(
            open,
            "    if (strcmp(window, {name}) == 0) {{\n        {s} w = {{0}};\n        if (!{p}_load(db, &w)) return false;\n        ClarityWindowState* state = clarity_opened(window, {p}_json(&w), with);\n        // Data that does not fit the window, such as a wrong `with`, is refused here.\n        if (!{p}_from_json(state->data, &w)) return false;\n        *out = state;\n        return true;\n    }}\n",
            name = string(&w.name),
            s = w.struct_name,
            p = w.prefix
        );
    }
    let mut events = String::new();
    for w in &windows {
        for (event, handler) in &w.events {
            let _ = writeln!(events, "    if (strcmp(window, {}) == 0 && strcmp(event, {}) == 0) return {};", string(&w.name), string(event), string(handler));
        }
    }
    for (event, handler) in apps.iter().flat_map(|a| &a.events) {
        let _ = writeln!(events, "    // The app's own events run whatever window is given.\n    if (strcmp(event, {}) == 0) return {};", string(event), string(handler));
    }
    // Each window that has canvases to draw.
    let mut redraws = String::new();
    for w in windows.iter().filter(|w| !w.draws.is_empty()) {
        let draws: String = w
            .draws
            .iter()
            .map(|(canvas, function)| format!("        clarity_ui_begin_drawing(ui, {});\n        if (!{function}(db, ui, &w)) return false;\n", string(canvas)))
            .collect();
        let _ = write!(
            redraws,
            "    if (strcmp(reply->state.window, {}) == 0) {{\n        {} w = {{0}};\n        if (!{}_from_json(reply->state.data, &w)) return false;\n        ClarityUi* ui = clarity_ui(&reply->state);\n{draws}        reply->state = clarity_ui_reply(ui, reply->state.window, reply->state.data)->state;\n        return true;\n    }}\n",
            string(&w.name),
            w.struct_name,
            w.prefix
        );
    }
    let mut dispatch = String::new();
    for w in windows.iter().filter(|w| !w.handlers.is_empty() || !w.calls.is_empty()) {
        let _ = write!(
            dispatch,
            "    if (strcmp(state->window, {}) == 0) {{\n        {} w = {{0}};\n        if (!{}_from_json(state->data, &w)) return false;\n        bool ok = false;\n",
            string(&w.name),
            w.struct_name,
            w.prefix
        );
        // The handlers by name, then the calls with values its parts wire, by
        // their written form.
        let plain = w.handlers.iter().map(|(handler, function)| (handler, function, String::new()));
        let calls = w.calls.iter().map(|(call, function, values)| (call, function, values.iter().map(|v| format!(", {v}")).collect()));
        for (i, (handler, function, values)) in plain.chain(calls).enumerate() {
            let keyword = if i == 0 { "if" } else { "else if" };
            let _ = writeln!(dispatch, "        {keyword} (strcmp(handler, {}) == 0) ok = {function}(db, ui, &w{values});", string(handler));
        }
        let _ = write!(
            dispatch,
            "        else return clarity_fail(CLARITY_INVALID, \"%s has no handler %s\", state->window, handler);\n        if (!ok) return false;\n        *out = clarity_ui_reply(ui, state->window, {}_json(&w));\n        return true;\n    }}\n",
            w.prefix
        );
    }
    for a in &apps {
        for (handler, function) in &a.handlers {
            let _ = write!(
                dispatch,
                "    // The app's handlers run from any window, on the app's own data.\n    if (strcmp(handler, {}) == 0) {{\n        {} app = {{0}};\n        if (!{}_load(db, &app) || !{function}(db, ui, &app)) return false;\n        *out = clarity_ui_reply(ui, state->window, state->data);\n        return true;\n    }}\n",
                string(handler),
                a.struct_name,
                a.prefix
            );
        }
    }
    // The handlers an answer runs, with the values written for them and the answer (DESIGN 5.14).
    let mut answers = String::new();
    for w in windows.iter().filter(|w| !w.answers.is_empty()) {
        let _ = write!(
            answers,
            "    if (strcmp(state->window, {}) == 0) {{\n        {} w = {{0}};\n        if (!{}_from_json(state->data, &w)) return false;\n",
            string(&w.name),
            w.struct_name,
            w.prefix
        );
        for (handler, function, values) in &w.answers {
            let mut decode = String::new();
            let mut passed = String::new();
            for (i, ty) in values.iter().enumerate() {
                let _ = writeln!(decode, "            const cJSON* a{i} = cJSON_GetArrayItem(values, {i});");
                if let check::TypeInfo::Record(entity) = ty {
                    let p = prefix(entity);
                    let _ = write!(
                        decode,
                        "            {entity} v{i} = {{0}};\n            // A record chosen by its id is read; one written for the handler comes as it was.\n            if (cJSON_IsNumber(a{i}) ? !{p}_get(db, (int64_t)a{i}->valuedouble, &v{i}) : !{p}_from_json(a{i}, &v{i})) return false;\n"
                    );
                } else {
                    let _ = writeln!(decode, "            cJSON* box{i} = cJSON_CreateObject();\n            cJSON_AddItemReferenceToObject(box{i}, \"value\", (cJSON*)a{i});");
                    let read = |getter: &str, ty: &str, empty: &str| format!("            {ty} v{i} = {empty};\n            if (!clarity_json_get_{getter}(box{i}, \"value\", &v{i})) return false;\n");
                    decode.push_str(&match ty {
                        check::TypeInfo::Integer | check::TypeInfo::Duration => read("integer", "int64_t", "0"),
                        check::TypeInfo::Decimal | check::TypeInfo::Money => read("decimal", "ClarityDecimal", "{0}"),
                        check::TypeInfo::Bool => read("bool", "bool", "false"),
                        check::TypeInfo::Date => read("date", "ClarityDate", "{0}"),
                        check::TypeInfo::DateTime => read("date_time", "ClarityDateTime", "{0}"),
                        check::TypeInfo::Enum(e) => format!(
                            "            const char* name{i} = NULL;\n            if (!clarity_json_get_text(box{i}, \"value\", &name{i})) return false;\n            {e} v{i} = {}_from(name{i});\n",
                            prefix(e)
                        ),
                        _ => read("text", "const char*", "\"\""),
                    });
                }
                let _ = write!(passed, "{}", if matches!(ty, check::TypeInfo::Record(_)) { format!(", &v{i}") } else { format!(", v{i}") });
            }
            let _ = write!(
                answers,
                "        if (strcmp(handler, {}) == 0) {{\n            if (cJSON_GetArraySize(values) < {}) return clarity_fail(CLARITY_INVALID, \"%s takes more values than the answer gave\", handler);\n{decode}            if (!{function}(db, ui, &w{passed})) return false;\n            *out = clarity_ui_reply(ui, state->window, {}_json(&w));\n            return true;\n        }}\n",
                string(handler),
                values.len(),
                w.prefix
            );
        }
        answers.push_str("    }\n");
    }
    let mut options = String::new();
    for entity in project.stored_entities() {
        let name = &entity.name.name;
        let p = prefix(name);
        let shown = entity
            .fields
            .iter()
            .find(|f| matches!(f.ty, FieldType::Text { .. } | FieldType::Email))
            .map_or_else(|| "clarity_format(\"#%lld\", (long long)all.items[i].id)".to_string(), |f| format!("all.items[i].{}", ident(&f.name.name)));
        let _ = write!(
            options,
            "    if (strcmp(entity, {}) == 0) {{\n        {} all = {{0}};\n        if (!{p}_all(db, &all)) return false;\n        for (size_t i = 0; i < all.count; i++) clarity_add_option(*out, all.items[i].id, {shown});\n    }}\n",
            string(name),
            names::list_type(name)
        );
    }
    let mut pictures = String::new();
    for (e, f) in crate::picture_fields(project) {
        let _ = writeln!(
            pictures,
            "    if (strcmp(entity, {}) == 0 && strcmp(field, {}) == 0) return clarity_picture(db, &{}_entity, id, {}, out);",
            string(&e.name.name),
            string(&f.name.name),
            prefix(&e.name.name),
            string(e.column_of(&f.name.name))
        );
    }
    let ready = string(&format!("{}: the databases are ready.", names::pascal(&settings.name)));
    let title = string(&clarity_project::title(settings));
    // An engine whose file does not fit its declaration stops the application at start.
    let check_engines = if crate::engines(project).is_empty() {
        String::new()
    } else {
        "    if (!engines_check()) {\n        fprintf(stderr, \"%s\\n\", clarity_error()->message);\n        return 1;\n    }\n    clarity_scratch_reset();\n".to_string()
    };
    format!(
        r#"{HEADER}
#include <stdio.h>
#include <string.h>

#include "app.h"
#include "page.h"
#include "schema.h"
#include "shell/shell.h"

/// The database of each data source: its name, its kind and where it is.
static const ClaritySource databases[] = {{
{sources}
}};

/// The state of `window` when it opens: its data loaded, with `with` filled in by name.
static bool open_window(ClarityDb* db, const char* window, const cJSON* with, ClarityWindowState** out) {{
{open}    return clarity_fail(CLARITY_INVALID, "there is no window %s", window);
}}

/// The handler of a window's own event, or NULL.
static const char* handler_of(const char* window, const char* event) {{
    (void)window;
    (void)event;
{events}    return NULL;
}}

/// Runs a handler on a window's state.
static bool dispatch(ClarityDb* db, const ClarityWindowState* state, const char* handler, ClarityReply** out) {{
    ClarityUi* ui = clarity_ui(state);
    (void)db;
    (void)ui;
    (void)out;
{dispatch}    return clarity_fail(CLARITY_INVALID, "%s has no handler %s", state->window, handler);
}}

/// Runs the handler the answer to a question goes to (DESIGN 5.14), with
/// the values written for it and the answer last.
static bool answer(ClarityDb* db, const ClarityWindowState* state, const char* handler, const cJSON* values, ClarityReply** out) {{
    ClarityUi* ui = clarity_ui(state);
    (void)db;
    (void)ui;
    (void)values;
    (void)out;
{answers}    return clarity_fail(CLARITY_INVALID, "%s has no handler %s to answer", state->window, handler);
}}

/// The records a reference field of `entity` can point at.
static bool options(ClarityDb* db, const char* entity, cJSON** out) {{
    (void)db;
    (void)entity;
    *out = cJSON_CreateArray();
{options}    return true;
}}

/// The picture of an image field of a record.
static bool picture(ClarityDb* db, const char* entity, int64_t id, const char* field, ClarityBytes* out) {{
    (void)db;
    (void)id;
    (void)out;
{pictures}    return clarity_fail(CLARITY_INVALID, "%s has no picture %s", entity, field);
}}

/// Draws the canvases of the window `reply` shows anew, each by its draw
/// handler on an empty drawing (conformance/drawing.json).
static bool redraw(ClarityDb* db, ClarityReply* reply) {{
{redraws}    (void)db;
    (void)reply;
    return true;
}}

/// What the shell asks of the application's windows.
static const ClarityWindows windows = {{open_window, handler_of, dispatch, options, picture, redraw, answer}};

/// Says what went wrong, and ends the program.
static int failed(ClarityDb* db) {{
    fprintf(stderr, "%s\n", clarity_error()->message);
    clarity_db_close(db);
    return 1;
}}

int main(int argc, char** argv) {{
{check_engines}    ClarityDb* db = NULL;
    if (!clarity_db_open(databases, sizeof databases / sizeof databases[0], &db)) return failed(db);
    size_t count = 0;
    const SourceSteps* sources = schema_sources(&count);
    for (size_t i = 0; i < count; i++)
        if (!clarity_migrate(db, sources[i].source, sources[i].steps, sources[i].count, NULL)) return failed(db);
{stores}
    clarity_scratch_reset();
    // --check opens and migrates the databases without windows, for builds and scripts.
    for (int i = 1; i < argc; i++) {{
        if (strcmp(argv[i], "--check") == 0) {{
            puts({ready});
            clarity_db_close(db);
            return 0;
        }}
    }}
    ClarityShellOptions options = {{{name}, {title}, {main}, page_model(), page_html(), db, &windows, {width}, {height}}};
    int status = clarity_shell_run(&options);
    clarity_db_close(db);
    return status;
}}
"#,
        sources = sources.join("\n"),
        stores = stores.join("\n"),
        name = string(program),
        main = string(main_window),
        // The desktop window opens at the main window's size.
        width = crate::window_size(project, main_window).0,
        height = crate::window_size(project, main_window).1
    )
}
