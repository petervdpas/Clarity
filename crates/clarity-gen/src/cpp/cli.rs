fn said(text: &Option<Said>) -> String {
    match text {
        Some(Said::Key(key)) => format!("std::optional<std::string>(clarity::Text::key({}).show())", string(key)),
        Some(Said::Plain(text)) => format!("std::optional<std::string>({})", string(text)),
        None => "std::nullopt".to_string(),
    }
}

fn kind(word: &str) -> &'static str {
    match word {
        "integer" => "integer",
        "decimal" => "decimal",
        "money" => "money",
        "date" => "date",
        "datetime" => "datetime",
        "duration" => "duration",
        "enum" => "enumeration",
        "bool" => "boolean",
        _ => "text",
    }
}

fn some(text: &Option<String>) -> String {
    text.as_ref().map_or("std::nullopt".to_string(), |t| format!("std::optional<std::string>({})", string(t)))
}

fn param(p: &ParamSpec) -> String {
    let values: Vec<String> = p.values.iter().map(|v| string(v)).collect();
    format!(
        "clarity::cli::Param{{{}, clarity::cli::Kind::{}, {{{}}}, {}, {}, {}, {}, {}}}",
        string(&p.name),
        kind(p.kind),
        values.join(", "),
        some(&p.default),
        some(&p.min),
        some(&p.max),
        p.required,
        said(&p.help)
    )
}

fn command(c: &CommandSpec) -> String {
    let line: Vec<String> = c.line.iter().map(|w| string(w)).collect();
    let arguments: Vec<String> = c.arguments.iter().map(param).collect();
    let options: Vec<String> = c.options.iter().map(param).collect();
    format!("            clarity::cli::Command{{{{{}}}, {}, {{{}}}, {{{}}}}},\n", line.join(", "), said(&c.help), arguments.join(", "), options.join(", "))
}

/// A value of the command line as the type code holds it.
fn typed(p: &ParamSpec, at: usize) -> String {
    let value = format!("values[{at}]");
    match &p.ty {
        TypeInfo::Integer | TypeInfo::Duration => format!("clarity::cli::integer({value})"),
        TypeInfo::Decimal | TypeInfo::Money => format!("clarity::cli::decimal({value})"),
        TypeInfo::Date => format!("clarity::cli::date({value})"),
        TypeInfo::DateTime => format!("clarity::cli::date_time({value})"),
        TypeInfo::Bool => format!("clarity::cli::boolean({value})"),
        TypeInfo::Enum(name) => format!("{}(clarity::cli::text({value}))", model::from_name(name)),
        _ => format!("clarity::cli::text({value})"),
    }
}

fn cmake_lists(program: &str, target: &str, engines: bool, http: bool) -> String {
    let engine = if engines { " clarity_engine" } else { "" };
    let http = if http { " clarity_http" } else { "" };
    format!(
        "# Generated by Clarity. Do not edit: change the project in Clarity instead.
#
# Configure and build with one command (CMake 3.25 or newer):
#   cmake --workflow --preset debug      (or release)
# The program is then build/debug/{program}. See README.md for what to install.
cmake_minimum_required(VERSION 3.25)
project({target} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

include(clarity-runtime/clarity.cmake)

file(GLOB PROGRAM_SOURCES CONFIGURE_DEPENDS src/*.cpp src/modules/*.cpp)
add_executable({target} ${{PROGRAM_SOURCES}})
set_target_properties({target} PROPERTIES OUTPUT_NAME {program})
target_include_directories({target} PRIVATE src)
target_link_libraries({target} PRIVATE clarity{engine}{http})
"
    )
}

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "C++")?;
    if let Some((name, _, _)) = databases.iter().find(|(_, sql, _)| *sql != Sql::Sqlite) {
        return Err(vec![format!("data source '{name}' is a server database; the C++ backend stores records in SQLite for now")]);
    }
    // The namespace and the settings' folder are the desktop program's; the program is named as typed.
    let space = super::program_name(settings);
    let program = crate::commands::program_name(settings);
    let types = check::types(&project.files);
    let engines = !crate::engines(project).is_empty();
    let mut files = vec![text("CMakeLists.txt", cmake_lists(&program, &space, engines, project.calls_out())), text("CMakePresets.json", PRESETS.to_string())];
    // The runtime without the shell: no window, no webview.
    let engine_files = ENGINE_FILES.iter().chain(&crate::c::WASM3_FILES).filter(|_| engines);
    let http_files = super::HTTP_FILES.iter().filter(|_| project.calls_out());
    for (path, body) in RUNTIME_FILES.iter().chain(engine_files).chain(http_files) {
        files.push(text(&format!("clarity-runtime/{path}"), body.to_string()));
    }
    let (records_h, records_cpp) = model::emit(project);
    files.push(text("src/records.hpp", namespaced(&space, &format!("#pragma once\n\n#include <optional>\n#include <string>\n#include <vector>\n\n#include <nlohmann/json.hpp>\n\n#include \"clarity/db.hpp\"\n#include \"clarity/sql.hpp\"\n#include \"clarity/json_read.hpp\"\n{}", if project.calls_out() { "#include \"http/http.hpp\"\n" } else { "" }), &records_h)));
    files.push(text("src/records.cpp", namespaced(&space, "#include \"records.hpp\"\n", &records_cpp)));

    let mut errors = Vec::new();
    let mut declarations = String::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        for decl in file.functions.iter().chain(&logic::events(file)) {
            let _ = writeln!(declarations, "{};", logic::signature(project, decl));
        }
        for command in &file.commands {
            let _ = writeln!(declarations, "{};", logic::command_signature(project, command));
        }
        declarations.push_str(&logic::engine_declarations(project, file));
        let mut body = String::new();
        match logic::emit(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_commands(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        let kept = file.engines.iter().any(|e| e.body.is_some() && e.state != clarity_spec::code::EngineState::None);
        let includes = if kept { "#include <map>\n#include <memory>\n#include <mutex>\n\n#include \"../app.hpp\"\n" } else { "#include \"../app.hpp\"\n" };
        files.push(text(&format!("src/modules/{}.cpp", snake(&m.name)), namespaced(&space, includes, &body)));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let engines_include = if engines { "#include \"engines.hpp\"\n" } else { "" };
    files.push(text(
        "src/app.hpp",
        namespaced(&space, &format!("#pragma once\n\n#include <nlohmann/json.hpp>\n\n#include \"clarity/cli.hpp\"\n#include \"clarity/code.hpp\"\n{engines_include}#include \"records.hpp\"\n"), &declarations),
    ));
    if engines {
        let (header, source) = engines_cpp(project);
        files.push(text("src/engines.hpp", namespaced(&space, "#pragma once\n\n#include \"engine/engine.hpp\"\n", &header)));
        files.push(text("src/engines.cpp", namespaced(&space, "#include <iterator>\n\n#include \"engines.hpp\"\n", &source)));
    }
    files.push(text("src/schema.hpp", namespaced(&space, "#pragma once\n\n#include <string>\n#include <vector>\n\n#include \"clarity/db.hpp\"\n", SCHEMA_HPP)));
    files.push(text("src/schema.cpp", schema_cpp(project, &space, &owned)?));
    files.push(text("src/main.cpp", main_cpp(project, settings, &space, &databases)));
    files.push(text(
        "README.md",
        format!(
            "# {title}: the command line\n\nGenerated by Clarity from the project {project}: the command-line program `{program}`, in C++. Do not edit these files; change the project in Clarity and generate it again.\n\n## Build and run\n\nIn this folder, build the program with\n\n    cmake --workflow --preset release\n\nwhich writes `build/release/{program}`. Run `{program} --help` to see its commands.\n",
            title = clarity_project::title(settings),
            project = settings.name,
        ),
    ));
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

fn main_cpp(project: &Project, settings: &Settings, space: &str, databases: &[(String, Sql, String)]) -> String {
    let commands = crate::commands::commands(project);
    let sources: Vec<String> = databases.iter().map(|(name, _, at)| format!("{{{}, clarity::Dialect::Sqlite, {}}}", string(name), string(at))).collect();
    let stores: Vec<String> = settings.filestores.iter().map(|s| format!("{{{}, {}}}", string(&s.name), string(&s.location))).collect();
    let languages: Vec<String> = project.translations.keys().map(|l| string(l)).collect();
    let base = project.locale.language.clone().unwrap_or_else(|| "en".to_string());
    let listed: String = commands.iter().map(command).collect();
    let kept = project.files.iter().flat_map(|f| &f.entities).find(|e| e.settings);
    let (kept_fn, start, keep, settings_arg) = match kept {
        Some(entity) => {
            let name = &entity.name.name;
            let language = entity
                .fields
                .iter()
                .find(|f| f.ty == FieldType::Language)
                .map(|f| format!("        if (!settings.{field}.empty()) clarity::set_language(settings.{field});\n", field = ident(&f.name.name)))
                .unwrap_or_default();
            (
                format!("/// The settings kept, each one that still fits; the others have their default.\n{name} kept_settings() {{\n    nlohmann::json values = {name}{{}};\n    const nlohmann::json kept = clarity::read_settings(PROGRAM);\n    for (const auto& [key, value] : kept.items()) {{\n        if (!values.contains(key)) continue;\n        auto tried = values;\n        tried[key] = value;\n        try {{\n            (void)tried.get<{name}>();\n            values = tried;\n        }} catch (const std::exception&) {{\n        }}\n    }}\n    return values.get<{name}>();\n}}\n\n"),
                format!("        auto settings = {space}::kept_settings();\n        const nlohmann::json before = settings;\n{language}"),
                format!("        // A command that changed a setting keeps it, as a window does.\n        nlohmann::json after = settings;\n        if (after != before) {{\n            after.erase(\"id\");\n            clarity::keep_settings({space}::PROGRAM, after);\n        }}\n"),
                "settings, ",
            )
        }
        None => (String::new(), String::new(), String::new(), ""),
    };
    let mut dispatch = String::new();
    for (i, c) in commands.iter().enumerate() {
        let values: Vec<String> = c.arguments.iter().chain(&c.options).enumerate().map(|(at, p)| typed(p, at)).collect();
        let args: String = values.iter().map(|v| format!(", {v}")).collect();
        let _ = writeln!(dispatch, "                case {i}:\n                    return {space}::{}(db, cli{}{args});", logic::command_function(c.decl), if settings_arg.is_empty() { "" } else { ", settings" });
    }
    let settings_include = if kept.is_some() { "#include \"clarity/settings.hpp\"\n" } else { "" };
    format!(
        "{HEADER}
#include <cstdlib>
#include <iostream>

#include \"app.hpp\"
#include \"clarity/text.hpp\"
{settings_include}#include \"schema.hpp\"

namespace {space} {{

/// The desktop program's name, which names the folder the person's
/// settings are kept in: both programs share them.
const std::string PROGRAM = {folder};

/// The database of each data source: its name, its kind and where it is.
const std::vector<clarity::Source> databases{{{sources}}};

/// The folder of each file store.
const std::vector<std::pair<std::string, std::string>> stores{{{stores}}};

/// The texts the program shows, in every language the project has.
const std::string& texts() {{
    static const std::string text = [] {{
{texts}    }}();
    return text;
}}

{kept_fn}/// The program and its commands, as the command line reads them.
clarity::cli::Program program() {{
    return clarity::cli::Program{{
        {name},
        {help},
        {{
{listed}        }},
    }};
}}

}}  // namespace {space}

int main(int argc, char** argv) {{
    try {{
        clarity::load_translations({space}::texts());
        const char* locale = std::getenv(\"LC_ALL\");
        if (!locale || !*locale) locale = std::getenv(\"LC_MESSAGES\");
        if (!locale || !*locale) locale = std::getenv(\"LANG\");
        clarity::set_language(clarity::cli::pick_language(locale ? locale : \"\", {{{languages}}}, {base}));
{start}        clarity::Db db({space}::databases);
        for (const auto& s : {space}::sources()) db.migrate_source(s.source, s.steps);
        for (const auto& [name, at] : {space}::stores) db.add_store(name, at);
        const int code = clarity::cli::run({space}::program(), argc, argv, [&](clarity::cli::Session& cli, size_t command, const std::vector<std::optional<std::string>>& values) {{
            switch (command) {{
{dispatch}            }}
            return 2;
        }});
{keep}        return code;
    }} catch (const std::exception& e) {{
        std::cerr << e.what() << \"\\n\";
        return 1;
    }}
}}
",
        folder = string(space),
        sources = sources.join(", "),
        stores = stores.join(", "),
        texts = indent_lines(&long_text(&crate::commands::texts_json(project)), 1),
        name = string(&crate::commands::program_name(settings)),
        help = said(&crate::commands::program_help(project)),
        languages = languages.join(", "),
        base = string(&base),
    )
}
