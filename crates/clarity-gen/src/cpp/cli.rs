//! The C++ command-line program (DESIGN 5.20): a CMake project of its own
//! in `out/cli`, on the runtime without the shell and its webview, with the
//! project's records, actions and commands, and a main that reads the
//! command line and runs the command it names.

use std::fmt::Write as _;

use clarity_project::Settings;
