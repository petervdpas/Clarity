/// The steps of every database Clarity owns, as SQL per data source.
fn schema_cpp(project: &Project, program: &str, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut body = String::from("const std::vector<SourceSteps>& sources() {\n    static const std::vector<SourceSteps> all{\n");
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        let _ = writeln!(body, "        {{{}, {{", string(source));
        for (i, (title, statements)) in steps.iter().enumerate() {
            let _ = writeln!(body, "            // {}: {title}\n            {{", i + 1);
            for statement in statements {
                let _ = writeln!(body, "                {},", string(statement));
            }
            body.push_str("            },\n");
        }
        body.push_str("        }},\n");
    }
    body.push_str("    };\n    return all;\n}\n");
    if !errors.is_empty() {
        return Err(errors);
    }
    Ok(namespaced(program, "#include \"schema.hpp\"\n", &body))
}

