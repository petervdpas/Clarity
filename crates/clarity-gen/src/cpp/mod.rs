pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "C++")?;
    if let Some((name, sql, _)) = databases.iter().find(|(_, sql, _)| *sql != Sql::Sqlite) {
        return Err(vec![format!(
            "data source '{name}' is a {} database; the C++ backend stores records in SQLite for now",
            match sql {
                Sql::Postgres => "PostgreSQL",
                Sql::Mysql => "MySQL",
                _ => "SQL Server",
            }
        )]);
    }
    let program = program_name(settings);
    let types = check::types(&project.files);
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let engines = !crate::engines(project).is_empty();
    let mut files = vec![
        text("CMakeLists.txt", cmake_lists(&program, engines, !crate::parts::native_parts(project).is_empty(), project.calls_out()) + &crate::libraries::cmake_lines(project, &program)),
        text("CMakePresets.json", PRESETS.to_string()),
    ];
    files.extend(crate::parts::out_files(project, &[]));
    let engine_files = ENGINE_FILES.iter().chain(&crate::c::WASM3_FILES).filter(|_| engines);
    let http_files = HTTP_FILES.iter().filter(|_| project.calls_out());
    for (path, body) in RUNTIME_FILES.iter().chain(&SHELL_FILES).chain(engine_files).chain(http_files) {
        files.push(text(&format!("clarity-runtime/{path}"), body.to_string()));
    }

    let (records_h, records_cpp) = model::emit(project);
    // Each library's header, so every module calls it (DESIGN 5.21).
    let library_includes: String = crate::libraries::libraries(project).iter().map(|l| format!("#include \"clarity/{}.hpp\"\n", l.name.name)).collect();
    // The HTTP client, for code that calls out (DESIGN 5.23).
    let http_include = if project.calls_out() { "#include \"http/http.hpp\"\n" } else { "" };
    files.push(text("src/records.hpp", namespaced(&program, &format!("#pragma once\n\n#include <optional>\n#include <string>\n#include <vector>\n\n#include <nlohmann/json.hpp>\n\n#include \"clarity/db.hpp\"\n#include \"clarity/sql.hpp\"\n#include \"clarity/json_read.hpp\"\n{http_include}{library_includes}"), &records_h)));
    for library in crate::libraries::libraries(project) {
        let n = &library.name.name;
        let own = crate::libraries::own_file(library, true);
        files.extend(crate::libraries::adapter_files(project, n, &own));
        files.push(text(&format!("{}/{own}", crate::libraries::folder(n)), crate::libraries::c_header(library, true)));
    }
    files.push(text("src/records.cpp", namespaced(&program, "#include \"records.hpp\"\n", &records_cpp)));

    let mut errors = Vec::new();
    let mut declarations = String::new();
    let mut windows = String::new();
    let mut owners = Vec::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        for decl in file.functions.iter().chain(&logic::events(file)) {
            let _ = writeln!(declarations, "{};", logic::signature(project, decl));
        }
        declarations.push_str(&logic::engine_declarations(project, file));
        let mut body = String::new();
        match logic::emit(project, file, &file_types) {
            Ok(code) => body.push_str(&code),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types) {
            Ok((header, code, mut found)) => {
                windows.push_str(&header);
                body.push_str(&code);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        // An engine written in Clarity with state keeps each instance's values in a map behind a lock.
        let kept = file.engines.iter().any(|e| e.body.is_some() && e.state != clarity_spec::code::EngineState::None);
        let includes = if kept { "#include <map>\n#include <memory>\n#include <mutex>\n\n#include \"../app.hpp\"\n" } else { "#include \"../app.hpp\"\n" };
        files.push(text(&format!("src/modules/{}.cpp", snake(&m.name)), namespaced(&program, includes, &body)));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let app = format!("{declarations}\n{windows}");
    let engines_include = if engines { "#include \"engines.hpp\"\n" } else { "" };
    files.push(text(
        "src/app.hpp",
        namespaced(&program, &format!("#pragma once\n\n#include <nlohmann/json.hpp>\n\n#include \"clarity/code.hpp\"\n#include \"clarity/ui.hpp\"\n{engines_include}#include \"records.hpp\"\n"), &app),
    ));
    if engines {
        let (header, source) = engines_cpp(project);
        files.push(text("src/engines.hpp", namespaced(&program, "#pragma once\n\n#include \"engine/engine.hpp\"\n", &header)));
        files.push(text("src/engines.cpp", namespaced(&program, "#include <iterator>\n\n#include \"engines.hpp\"\n", &source)));
    }
    files.push(text("src/schema.hpp", namespaced(&program, "#pragma once\n\n#include <string>\n#include <vector>\n\n#include \"clarity/db.hpp\"\n", SCHEMA_HPP)));
    files.push(text("src/schema.cpp", schema_cpp(project, &program, &owned)?));
    files.push(text("src/page.cpp", page_cpp(project, &program)));
    files.push(text("src/main.cpp", main_cpp(project, settings, &program, &databases, &owners, &main_window)));
    Ok(files)
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project.apps().find_map(|a| a.main.as_ref().map(|m| m.name.clone())).or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

fn text(path: &str, body: String) -> OutFile {
    OutFile { path: path.to_string(), text: body, bytes: None }
}

/// A source file: the header line, its includes, and its code in the program's namespace.
fn namespaced(program: &str, includes: &str, body: &str) -> String {
    format!("{HEADER}\n{includes}\nnamespace {program} {{\n\n{}\n}}  // namespace {program}\n", body.trim_end())
}

/// The engines of the application (DESIGN 5.11): each file as bytes in the
/// program, loaded once on first use, and `check`, which loads every one so
/// an engine whose file does not fit stops the application at start.
/// Returns the header and the source, both in namespace `engines`.
fn engines_cpp(project: &Project) -> (String, String) {
    let mut header = String::from("namespace engines {\n\n");
    let mut source = String::from("namespace engines {\n\n");
    let mut checks = String::new();
    for engine in crate::engines(project) {
        let var = snake(&engine.name.name);
        let bytes = project.engines.as_deref().unwrap_or_default().iter().find(|f| f.name == engine.file).map(|f| f.bytes.as_slice()).unwrap_or_default();
        let rows: Vec<String> = bytes.chunks(20).map(|row| row.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ")).collect();
        let functions: Vec<String> = engine.functions.iter().map(|f| string(&f.name.name)).collect();
        let _ = write!(header, "/// Engine {}, from {}.\nconst clarity::Engine& {var}();\n\n", engine.name.name, engine.file);
        let _ = write!(
            source,
            "/// Engine {name}, from {file}.\nconst unsigned char {var}_wasm[] = {{\n    {rows}\n}};\n\nconst clarity::Engine& {var}() {{\n    static const clarity::Engine engine = clarity::Engine::load({quoted}, std::vector<uint8_t>(std::begin({var}_wasm), std::end({var}_wasm)), {{{{{functions}}}, {{{uses}}}, clarity::EngineLimits{{{seconds}, {megabytes}}}, {state}, {opens}}});\n    return engine;\n}}\n\n",
            name = engine.name.name,
            file = engine.file,
            rows = rows.join(",\n    "),
            quoted = string(&engine.name.name),
            functions = functions.join(", "),
            uses = engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            seconds = engine.seconds(),
            megabytes = engine.megabytes(),
            state = match engine.state {
                clarity_spec::code::EngineState::None => "clarity::EngineState::none",
                clarity_spec::code::EngineState::App => "clarity::EngineState::per_app",
                clarity_spec::code::EngineState::Window => "clarity::EngineState::per_window",
            },
            opens = engine.opens,
        );
        let _ = writeln!(checks, "    {var}();");
    }
    header.push_str("/// Loads every engine, so one whose file does not fit stops the application at start.\nvoid check();\n\n}  // namespace engines\n");
    let _ = write!(source, "void check() {{\n{checks}}}\n\n}}  // namespace engines\n");
    (header, source)
}

fn cmake_lists(program: &str, engines: bool, parts: bool, http: bool) -> String {
    let engine = if engines { " clarity_engine" } else { "" };
    let http = if http { " clarity_http" } else { "" };
    // The native custom parts (DESIGN 6.5), built beside the program, which loads them.
    let parts = if parts { "\n# The custom parts drawn by native libraries, which the program loads.\nadd_subdirectory(parts)\n" } else { "" };
    format!(
        "# Generated by Clarity. Do not edit: change the project in Clarity instead.
#
# Configure and build with one command (CMake 3.25 or newer):
#   cmake --workflow --preset debug      (or release)
# The program is then build/debug/{program}. See README.md for what to install.
cmake_minimum_required(VERSION 3.25)
project({program} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

include(clarity-runtime/clarity.cmake)

file(GLOB PROGRAM_SOURCES CONFIGURE_DEPENDS src/*.cpp src/modules/*.cpp)
add_executable({program} ${{PROGRAM_SOURCES}})
target_include_directories({program} PRIVATE src)
target_link_libraries({program} PRIVATE clarity clarity_shell{engine}{http})
{parts}"
    )
}

