/// The runtime package the program stands on, and the one its records are observable with.
const RUNTIME_PACKAGE: &str = "Clarity.Runtime";
const MVVM: (&str, &str) = ("CommunityToolkit.Mvvm", "8.4.2");

fn said(text: &Option<Said>) -> String {
    match text {
        Some(Said::Key(key)) => format!("CliLanguage.Show(Clarity.Runtime.Text.Of({}))", string(key)),
        Some(Said::Plain(text)) => string(text),
        None => "null".to_string(),
    }
}

fn kind(word: &str) -> &'static str {
    match word {
        "integer" => "Integer",
        "decimal" => "Decimal",
        "money" => "Money",
        "date" => "Date",
        "datetime" => "DateTime",
        "duration" => "Duration",
        "enum" => "Enum",
        "bool" => "Bool",
        _ => "Text",
    }
}

fn param(p: &ParamSpec) -> String {
    let mut init = Vec::new();
    if !p.values.is_empty() {
        init.push(format!("Values = [{}]", p.values.iter().map(|v| string(v)).collect::<Vec<_>>().join(", ")));
    }
    for (name, value) in [("Default", &p.default), ("Min", &p.min), ("Max", &p.max)] {
        if let Some(value) = value {
            init.push(format!("{name} = {}", string(value)));
        }
    }
    if p.required {
        init.push("Required = true".to_string());
    }
    if p.help.is_some() {
        init.push(format!("Help = {}", said(&p.help)));
    }
    let init = if init.is_empty() { String::new() } else { format!(" {{ {} }}", init.join(", ")) };
    format!("new CliParam({}, CliKind.{}){init}", string(&p.name), kind(p.kind))
}

fn command(c: &CommandSpec) -> String {
    let line: Vec<String> = c.line.iter().map(|w| string(w)).collect();
    let arguments: Vec<String> = c.arguments.iter().map(param).collect();
    let options: Vec<String> = c.options.iter().map(param).collect();
    format!("            new CliCommand([{}], {}, [{}], [{}]),\n", line.join(", "), said(&c.help), arguments.join(", "), options.join(", "))
}

/// A value of the command line as the type code holds it.
fn typed(p: &ParamSpec, at: usize) -> String {
    let value = format!("values[{at}]");
    match &p.ty {
        TypeInfo::Integer | TypeInfo::Duration => format!("Cli.Long({value})"),
        TypeInfo::Decimal | TypeInfo::Money => format!("Cli.Decimal({value})"),
        TypeInfo::Date => format!("Cli.Date({value})"),
        TypeInfo::DateTime => format!("Cli.Moment({value})"),
        TypeInfo::Bool => format!("Cli.Bool({value})"),
        TypeInfo::Enum(name) => format!("Cli.Enum<{name}>({value})"),
        _ => format!("Cli.Text({value})"),
    }
}

#[allow(clippy::too_many_arguments)]
fn csproj(name: &str, program: &str, drivers: &[&Driver], engines: bool, pictures: bool, formats: bool, auth: bool, agents: bool) -> String {
    let version = runtime_version();
    let packages: Vec<&str> = std::iter::once(RUNTIME_PACKAGE)
        .chain(pictures.then_some(super::IMAGE_PACKAGE))
        .chain(formats.then_some(super::FORMATS_PACKAGE))
        .chain(auth.then_some(super::AUTH_PACKAGE))
        .chain(agents.then_some(super::APP_MCP_PACKAGE))
        .chain(drivers.iter().map(|s| s.package))
        .chain(engines.then_some(ENGINES_PACKAGE))
        .collect();
    let references: String = packages.iter().map(|p| format!("    <PackageReference Include=\"{p}\" Version=\"{version}\" />\n")).collect();
    let projects: String = packages.iter().map(|p| format!("    <ProjectReference Include=\"$(ClarityRuntime)/{p}/{p}.csproj\" />\n")).collect();
    let mut resources = if engines { "  <ItemGroup>\n    <EmbeddedResource Include=\"Engines/*.wasm\" LogicalName=\"Engines/%(Filename)%(Extension)\" />\n  </ItemGroup>\n".to_string() } else { String::new() };
    // The commands agents may call, as the MCP service lists them (docs/ledger/app-mcp.md).
    if agents {
        resources.push_str("  <ItemGroup>\n    <EmbeddedResource Include=\"tools.json\" LogicalName=\"tools.json\" />\n  </ItemGroup>\n");
    }
    format!(
        "<!-- Generated by Clarity. Do not edit: change the project in Clarity instead. -->
<Project Sdk=\"Microsoft.NET.Sdk\">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>{TARGET_FRAMEWORK}</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <RootNamespace>{name}</RootNamespace>
    <AssemblyName>{program}</AssemblyName>
    <!-- Where Clarity's runtime projects are, to build on them instead of its
         packages: dotnet build -p:ClarityRuntime=<folder>, or the environment
         variable CLARITY_RUNTIME. Empty: the packages. -->
    <ClarityRuntime Condition=\"'$(ClarityRuntime)' == ''\">$(CLARITY_RUNTIME)</ClarityRuntime>
  </PropertyGroup>
  <ItemGroup>
    <PackageReference Include=\"{mvvm}\" Version=\"{mvvm_version}\" />
  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' == ''\">
{references}  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' != ''\">
{projects}  </ItemGroup>
{resources}</Project>
",
        mvvm = MVVM.0,
        mvvm_version = MVVM.1,
    )
}

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let project = &crate::with_secret_settings(project, &crate::settings_program(settings));
    let (databases, owned) = crate::databases(project, settings)?;
    let databases = crate::with_secret_locations(databases, &crate::settings_program(settings));
    let name = super::project_name(settings);
    let program = crate::commands::program_name(settings);
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let texts = texts::Texts::of(project);
    let drivers: Vec<&Driver> = DRIVERS
        .iter()
        // A data source that is a file is kept in an in-memory SQLite table.
        .filter(|s| databases.iter().any(|(_, sql, _)| *sql == s.sql) || (s.sql == crate::ddl::Sql::Sqlite && !crate::file_sources(project, settings).unwrap_or_default().is_empty()))
        .collect();
    let engines = !crate::engines(project).is_empty();
    let mut files = vec![text(&format!("{name}.csproj"), csproj(&name, &program, &drivers, engines, crate::uses_picture_functions(project), crate::carries_formats(project, settings), crate::carries_auth(project), crate::agent_tools::offers_agents(project)))];
    if crate::agent_tools::offers_agents(project) {
        files.push(text("tools.json", crate::agent_tools::tool_list_file(project, settings)));
    }
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let settings_usings = if file.entities.iter().any(|e| e.settings) { "using System.Globalization;\nusing System.Text.Json.Nodes;\n" } else { "" };
        let mut code = format!("{HEADER}\n{settings_usings}using Clarity.Runtime;\nusing CommunityToolkit.Mvvm.ComponentModel;\n\nnamespace {name};\n\n");
        code.push_str(&model::emit(project, file, &name, &crate::settings_program(settings), &texts, true));
        match logic::emit(project, file, &file_types) {
            Ok(methods) => code.push_str(&methods),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_commands(project, file, &file_types) {
            Ok(commands) => code.push_str(&commands),
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("Modules/{}.cs", pascal(&module.name)), code.trim_end().to_string() + "\n"));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("Schema.cs", super::schema_cs(project, &name, &owned)?));
    if engines {
        files.extend(crate::engine_files(project, "Engines"));
        files.push(text("Engines.cs", super::engines_cs(project, &name)));
    }
    // The texts, as the desktop program has them, shown in the program's language.
    files.push(text("Texts.cs", texts.class(project, &name)));
    files.push(text("Texts.resx", texts.base_resx(project)));
    let default = clarity_spec::translations::default_language(project);
    for (language, values) in project.translations.iter().filter(|(l, _)| **l != default) {
        files.push(text(&format!("Texts.{language}.resx"), texts.language_resx(values)));
    }
    files.push(text("Locale.cs", locale_cs(project, &name)));
    files.push(text("Program.cs", program_cs(project, settings, &name, &databases, &drivers, engines)));
    files.push(text(
        "README.md",
        format!(
            "# {title}: the command line\n\nGenerated by Clarity from the project {project}: the command-line program `{program}`, in C#. Do not edit these files; change the project in Clarity and generate it again.\n\n## Build and run\n\nIn this folder, build the program with\n\n    dotnet build -c Release\n\nwhich writes `bin/Release/{TARGET_FRAMEWORK}/{program}`. Run `{program} --help` to see its commands.\n",
            title = clarity_project::title(settings),
            project = settings.name,
        ),
    ));
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

/// What the generated code shows texts through, as the desktop program's
/// Locale does: the command line's language, from the runtime.
fn locale_cs(project: &Project, name: &str) -> String {
    let enums: Vec<&str> = project.files.iter().flat_map(|f| &f.enums).map(|e| e.name.name.as_str()).collect();
    let named: String = enums.iter().map(|e| format!("        {lit} => Enum.TryParse<{e}>(value, out var v) ? Of(v) : value,\n", lit = string(e))).collect();
    format!(
        "{HEADER}
using Clarity.Runtime;

namespace {name};

/// <summary>Texts in the language the command line shows, as the desktop program's Locale gives them.</summary>
static class Locale
{{
    public static string Show(Text text) => CliLanguage.Show(text);
    public static string Translate(string keyOrText) => CliLanguage.Translate(keyOrText);
    public static string Translate(string key, string fallback) => CliLanguage.Translate(key, fallback);
}}

public static partial class Labels
{{
    /// <summary>The label of an enum value by the enum's name, for text with slots.</summary>
    public static string Named(string enumName, string value) => enumName switch
    {{
{named}        _ => value,
    }};
}}
"
    )
}

/// What a C# program runs its commands with, as code: their description
/// (`listed`, for `Described()`), how a command's settings start and are
/// kept, the setting that names the language, and the dispatch by command
/// number. The command-line program and the desktop's commands for agents both use them.
pub(crate) struct CommandParts {
    pub listed: String,
    pub start: &'static str,
    pub language: String,
    pub keep: &'static str,
    pub dispatch: String,
}

pub(crate) fn command_parts(project: &Project) -> CommandParts {
    let commands = crate::commands::commands(project);
    let listed: String = commands.iter().map(command).collect();
    let kept = project.files.iter().find_map(|f| f.entities.iter().find(|e| e.settings));
    let (start, language, keep) = match kept {
        Some(entity) => (
            "        Settings.Start();\n        var before = Settings.Current.ToJson().ToJsonString();\n",
            entity.fields.iter().find(|f| f.ty == FieldType::Language).map_or("null".to_string(), |f| format!("Settings.Current.{}", pascal(&f.name.name))),
            "        // A command that changed a setting keeps it, as a window does.\n        if (Settings.Current.ToJson().ToJsonString() != before)\n            Settings.Keep();\n",
        ),
        None => ("", "null".to_string(), ""),
    };
    let mut dispatch = String::new();
    for (i, c) in commands.iter().enumerate() {
        let values: Vec<String> = c.arguments.iter().chain(&c.options).enumerate().map(|(at, p)| typed(p, at)).collect();
        let args: String = values.iter().map(|v| format!(", {v}")).collect();
        dispatch.push_str(&format!("                {i} => Logic.{}(db, cli{args}),\n", logic::command_method(c.decl)));
    }
    CommandParts { listed, start, language, keep, dispatch }
}

/// The desktop program's commands for AI agents (docs/ledger/app-mcp.md),
/// `AgentCommands.cs`: what the app offers Clarity.UI, a command line run on
/// its databases as the command line runs it, and `<program> mcp` without a window.
pub(crate) fn agents_desktop(project: &Project, settings: &Settings, name: &str) -> String {
    // The open app's settings are the ones it works with, and they keep themselves as they change.
    let CommandParts { listed, dispatch, .. } = command_parts(project);
    let (start, keep) = ("", "");
    let tools = crate::agent_tools::tool_list_file(project, settings);
    format!(
        "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n/// <summary>The commands AI agents call while the app runs (docs/ledger/app-mcp.md): each runs as\n/// the command line runs it, on the screen's thread, once Clarity.UI asked the person to allow it.</summary>\npublic static class AgentCommands\n{{\n    /// <summary>The commands agents may call, as the MCP service lists them.</summary>\n    const string Tools = \"\"\"\"\"\n{tools}\n\"\"\"\"\";\n\n    /// <summary>The commands, as the command line reads them.</summary>\n    static CliProgram Described() => new(\n        {program},\n        {help},\n        [\n{listed}        ], Agents: true);\n\n    /// <summary>Runs command <paramref name=\"command\"/> with its values on the app's databases, as the command line does.</summary>\n    static int Run(Db db, CliSession cli, int command, IReadOnlyList<string?> values)\n    {{\n{start}        var code = command switch\n        {{\n{dispatch}                _ => 2,\n        }};\n{keep}        return code;\n    }}\n\n    /// <summary>What the app offers agents.</summary>\n    static Agents Offered() => new(Tools, {app}, {settings_name}, {version});\n\n    /// <summary>Clarity.UI asks the running app about agents through these, on <paramref name=\"db\"/>.</summary>\n    public static void Install(Db db)\n    {{\n        Agents.Desktop.Offered = Offered();\n        Agents.Desktop.Call = (line, ask) => Agents.RunCall(Described(), line, ask, (cli, command, values) => Run(db, cli, command, values));\n    }}\n\n    /// <summary><c>&lt;program&gt; mcp</c>: the commands without a window, forwarded to the running app when\n    /// one answers, else served as the closed app.</summary>\n    public static int Mcp(Db db, string[] args) => Clarity.AppMcp.AgentService.RunProgram(Described(), Offered(), args, (cli, command, values) => Run(db, cli, command, values));\n}}\n",
        program = string(&crate::commands::program_name(settings)),
        help = said(&crate::commands::program_help(project)),
        app = string(&clarity_project::title(settings)),
        settings_name = string(&crate::settings_program(settings)),
        version = string(settings.version.as_deref().unwrap_or("")),
        tools = tools.trim_end(),
    )
}

fn program_cs(project: &Project, settings: &Settings, name: &str, databases: &[(String, crate::ddl::Sql, String)], drivers: &[&Driver], engines: bool) -> String {
    let check_engines = if engines { "        try\n        {\n            Engines.Check();\n        }\n        catch (EngineException e)\n        {\n            Console.Error.WriteLine(e.Message);\n            return 1;\n        }\n" } else { "" };
    let turned_on: String = drivers.iter().map(|s| format!("        {}.Use();\n", s.class)).collect();
    let stores = crate::fixed_stores(settings).iter().map(|s| format!("({}, {})", string(&s.name), string(&s.location))).collect::<Vec<_>>().join(", ");
    // A store whose folder is a folder setting follows the person's settings.
    let program_name = crate::settings_program(settings);
    let folder_stores: String = crate::folder_stores(project, settings)
        .iter()
        .map(|(name, setting, default)| format!("        db.AddStoreSetting({}, {}, {}, {});\n", string(name), string(&program_name), string(setting), string(default)))
        .chain(crate::file_sources(project, settings).unwrap_or_default().iter().map(|f| format!("        Clarity.Formats.FileSources.AddFile(db, new Clarity.Formats.FileSource({}, {}, {}, {}, {}, {}, {}, {}));\n", string(&f.name), string(&f.format), string(&f.path), string(&f.options), string(&f.table), string(&f.key), string(&f.fields), f.readonly)))
        .chain(super::add_signin(project, settings))
        .collect();

    let databases = databases.iter().map(|(source, sql, at)| format!("({}, {}, {})", string(source), dialect(*sql), string(at))).collect::<Vec<_>>().join(", ");
    let currency = settings.currency.as_deref().map_or("null".to_string(), string);
    let CommandParts { listed, start, language, keep, dispatch } = command_parts(project);
    // The command line signs in before a command runs when people sign in on it (step 4):
    // `--user` and `--token` are the sign-in's, not the command's.
    let cli_signin = crate::signin::signin_plan(project).is_some_and(|p| p.targets.iter().any(|t| t == "cli"));
    let (read_signin, signs_in) = if cli_signin {
        (
            "        var signin = CliSignin.FromArgs(args);\n        args = WithoutSignin(args);\n",
            "            db.SigninCli(signin, () => Clarity.Runtime.Signin.ReadPassword(CliLanguage.Translate(\"cliPassword\", \"Password\") + \": \"));\n",
        )
    } else {
        ("", "")
    };
    let without_signin = if cli_signin {
        "\n    /// <summary>The command line without the sign-in's <c>--user</c> and <c>--token</c> and their values.</summary>\n    static string[] WithoutSignin(string[] args)\n    {\n        var end = Array.IndexOf(args, \"--\");\n        var kept = new List<string>();\n        for (var i = 0; i < args.Length; i++)\n        {\n            if ((end < 0 || i < end) && args[i] is \"--user\" or \"--token\")\n            {\n                i++;\n                continue;\n            }\n            kept.Add(args[i]);\n        }\n        return [.. kept];\n    }\n"
    } else {
        ""
    };
    // Commands for agents: `mcp` serves them through Clarity.AppMcp (docs/ledger/app-mcp.md).
    let (tools_fn, run_program) = if crate::agent_tools::offers_agents(project) {
        (
            "    /// <summary>The commands agents may call, as the MCP service lists them.</summary>\n    static string Tools()\n    {\n        using var stream = typeof(Program).Assembly.GetManifestResourceStream(\"tools.json\")!;\n        return new StreamReader(stream).ReadToEnd();\n    }\n\n".to_string(),
            format!(
                "Clarity.AppMcp.AgentService.RunProgram(Described(), new Agents(Tools(), {}, {}, {}), args, ",
                string(&clarity_project::title(settings)),
                string(&crate::settings_program(settings)),
                string(settings.version.as_deref().unwrap_or(""))
            ),
        )
    } else {
        (String::new(), "Cli.RunProgram(Described(), args, ".to_string())
    };
    format!(
        "{HEADER}
using Clarity.Runtime;

namespace {name};

public static class Program
{{
    /// <summary>The database of each data source: its name, its kind and where it is.</summary>
    static readonly (string, Dialect, string)[] Databases = [{databases}];

    /// <summary>The folder of each file store.</summary>
    static readonly (string, string)[] Stores = [{stores}];

    /// <summary>Opens every database and applies the migration steps it has not had yet.</summary>
    static Db OpenDatabases()
    {{
{turned_on}        var db = Db.Connect(Databases);
        foreach (var (source, steps) in Schema.Sources)
            db.MigrateSource(source, steps);
        foreach (var (store, at) in Stores)
            db.AddStore(store, at);
{folder_stores}        return db;
    }}
{without_signin}
    /// <summary>The program and its commands, as the command line reads them.</summary>
{tools_fn}    static CliProgram Described() => new(
        {program},
        {help},
        [
{listed}        ]{agents_arg});

    public static int Main(string[] args)
    {{
{check_engines}{start}{read_signin}        CliLanguage.Start(Texts.BaseLanguage, Texts.Languages, {currency}, Texts.In, Labels.Named, {language});
        Db db;
        try
        {{
            db = OpenDatabases();
        }}
        catch (Exception e) when (e is ClarityException or IOException)
        {{
            Console.Error.WriteLine(e.Message);
            return 1;
        }}
        using var opened = db;
        var code = {run_program}(cli, command, values) =>
        {{
{signs_in}            return command switch
            {{
{dispatch}                _ => 2,
            }};
        }});
{keep}        return code;
    }}
}}
",
        program = string(&crate::commands::program_name(settings)),
        help = said(&crate::commands::program_help(project)),
        agents_arg = if crate::agent_tools::offers_agents(project) { ", Agents: true" } else { "" },
    )
}
