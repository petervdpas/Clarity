/// The first line of every generated C# file.
const HEADER: &str = "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n";

/// The runtime's shared settings, which hold the version of its packages.
const RUNTIME_PROPS: &str = include_str!("../../../../runtimes/csharp/Directory.Build.props");

/// The version of the runtime's packages a project references: the one the
/// runtime in this repository is (all its packages share it).
pub fn runtime_version() -> &'static str {
    let start = RUNTIME_PROPS.find("<Version>").expect("Directory.Build.props sets a Version") + "<Version>".len();
    let end = RUNTIME_PROPS[start..].find("</Version>").expect("the Version is closed");
    RUNTIME_PROPS[start..start + end].trim()
}

/// The package a desktop program draws its windows with: Clarity.UI in the
/// system's own window, and through it Clarity.Ui and Clarity.Runtime (DESIGN 7.9).
const DESKTOP_PACKAGE: &str = "Clarity.Ui.Desktop";

/// What a kind of database brings into a project: the runtime's package of
/// its driver (with the client it stands on), and the class whose Use() turns
/// the driver on. A program served to a browser carries none: its server does.
struct Driver {
    sql: Sql,
    /// The class whose Use() turns the driver on, like `PostgreSql`.
    class: &'static str,
    package: &'static str,
}

const DRIVERS: [Driver; 4] = [
    Driver { sql: Sql::Sqlite, class: "Sqlite", package: "Clarity.Runtime.Sqlite" },
    Driver { sql: Sql::Postgres, class: "PostgreSql", package: "Clarity.Runtime.PostgreSql" },
    Driver { sql: Sql::Mysql, class: "MySql", package: "Clarity.Runtime.MySql" },
    Driver { sql: Sql::Mssql, class: "SqlServer", package: "Clarity.Runtime.SqlServer" },
];

/// The .NET the generated project targets.
pub const TARGET_FRAMEWORK: &str = "net10.0";

/// The name of the generated project, its namespace and its program.
pub fn project_name(settings: &Settings) -> String {
    pascal(&settings.name)
}

pub use cli::generate as generate_cli;

/// The program of the project: the desktop program, or with the web target
/// alone the web application (DESIGN 7.6).
pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    if settings.stack.has(clarity_project::Target::Web) {
        return Err(vec!["C#'s web target on Clarity.UI is not generated yet (DESIGN 7.9, G7d); use the desktop target".to_string()]);
    }
    generate_desktop(project, settings, DESKTOP_PACKAGE)
}

/// The desktop program, its windows drawn by the package `ui`.
fn generate_desktop(project: &Project, settings: &Settings, ui: &str) -> Result<Vec<OutFile>, Vec<String>> {
    let project = &crate::with_secret_settings(project, &crate::settings_program(settings));
    let (databases, owned) = crate::databases(project, settings)?;
    let databases = crate::with_secret_locations(databases, &crate::settings_program(settings));
    if main_window(project).is_none() {
        return Err(vec!["the project has no window to start with".to_string()]);
    }
    let name = project_name(settings);
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let texts = texts::Texts::of(project);
    let drivers: Vec<&Driver> = DRIVERS.iter().filter(|s| databases.iter().any(|(_, sql, _)| *sql == s.sql)).collect();
    let engines = !crate::engines(project).is_empty();
    // Engines beside the screen run in the application's process too, through the same package.
    let screen_engines = !crate::screen_engines(project).is_empty();
    // Custom parts become Clarity.UI's custom controls, in C# (DESIGN 7.9).
    if let Some(part) = parts::dotnet_parts(project).first() {
        return Err(vec![format!("custom part {} is not generated yet: custom parts on C# come with Clarity.UI's custom controls (DESIGN 7.9)", part.name.name)]);
    }
    let mut files = vec![text(&format!("{name}.csproj"), csproj(&name, ui, &drivers, project.resources.as_ref().is_some_and(|r| !r.files.is_empty() || !r.markdown.is_empty()), engines || screen_engines, library_references(project)))];
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        // The settings read and keep JSON, numbers and dates written the same everywhere.
        let settings_usings = if file.entities.iter().any(|e| e.settings) { "using System.Globalization;\nusing System.Text.Json.Nodes;\n" } else { "" };
        let mut code = format!("{HEADER}\n{settings_usings}using Clarity.Runtime;\nusing CommunityToolkit.Mvvm.ComponentModel;\n\nnamespace {name};\n\n");
        code.push_str(&model::emit(project, file, &name, &crate::settings_program(settings), &texts, false));
        match logic::emit(project, file, &file_types) {
            Ok(methods) => code.push_str(&methods),
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("Modules/{}.cs", pascal(&module.name)), code.trim_end().to_string() + "\n"));
        for page in &file.pages {
            match windows::emit(project, page, &file_types, &name, &texts) {
                Ok(mut window) => files.append(&mut window),
                Err(mut problems) => errors.append(&mut problems),
            }
        }
    }
    // The app's `on unconnected` (DESIGN 5.27) runs on a window of its own that
    // is never shown, made of the app's frame and code: its ViewModel alone.
    if let Some((app, handler)) = crate::unconnected(project).and_then(|u| u.handler)
        && let Some(file) = project.files.iter().find(|f| f.apps.iter().any(|a| a.name.name == app))
    {
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let host = unconnected_host(project);
        match windows::emit(project, &host, &file_types, &name, &texts) {
            Ok(window) => files.extend(window),
            Err(mut problems) => errors.append(&mut problems),
        }
        let reason = if crate::unconnected_takes_reason(project, &app, &handler) { "reason" } else { "" };
        files.push(text(
            &format!("Windows/{}Run.cs", host.name.name),
            format!(
                "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\npublic sealed partial class {}ViewModel\n{{\n    /// <summary>Runs the app's <c>on unconnected</c>, with why the databases did not open.</summary>\n    public void Unconnected(Unconnecting unconnecting) => RunUnconnected(unconnecting, reason => On{}({reason}));\n}}\n",
                host.name.name,
                pascal(&handler)
            ),
        ));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("Schema.cs", schema_cs(project, &name, &owned)?));
    files.push(text("Program.cs", program_cs(project, &name, &databases, &drivers, settings, engines)));
    if engines {
        files.extend(crate::engine_files(project, "Engines"));
        files.push(text("Engines.cs", engines_cs(project, &name)));
    }
    if screen_engines {
        files.extend(crate::screen_engine_files(project, "Engines"));
        files.push(text("ScreenEngines.cs", screen_engines_cs(project, &name)));
    }
    // The libraries: each adapter, and the half generated from its declaration (DESIGN 5.21).
    for library in crate::libraries::libraries(project) {
        let n = &library.name.name;
        let own = crate::libraries::own_file(library, false);
        files.extend(crate::libraries::adapter_files(project, n, &own));
        files.push(text(&format!("{}/{own}", crate::libraries::folder(n)), crate::libraries::csharp_half(project, library)));
    }
    // The windows and the app frames as markup, which Clarity.UI draws (DESIGN 7.8, 7.9).
    for file in crate::web_windows::window_files(project).into_iter().chain(crate::web_windows::app_files(project)) {
        let path = file.path.replace("ui/windows/", "Windows/").replace("ui/apps/", "Apps/");
        files.push(OutFile { path, ..file });
    }
    files.push(text("Labels.cs", labels_cs(project, &name)));
    if !clarity_spec::icons::used(project).is_empty() {
        files.push(text("Icons.cs", icons_cs(project, &name)));
    }
    // The default language's texts, and each other language's.
    files.push(text("Texts.cs", texts.class(project, &name)));
    files.push(text("Texts.resx", texts.base_resx(project)));
    let default = clarity_spec::translations::default_language(project);
    for (language, values) in project.translations.iter().filter(|(l, _)| **l != default) {
        files.push(text(&format!("Texts.{language}.resx"), texts.language_resx(values)));
    }
    // The themes offered, as Clarity resolves them for light and dark mode (DESIGN 7.9).
    files.extend(themes::theme_files(project, &name));
    files.extend(crate::web::resource_files(project, "resources"));
    Ok(files)
}

fn text(path: &str, body: String) -> OutFile {
    OutFile {
        path: path.to_string(),
        text: body,
        bytes: None,
    }
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project
        .apps()
        .find_map(|a| a.main.as_ref().map(|m| m.name.clone()))
        .or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

/// The project file. It references the runtime's packages: `ui` (Clarity.Ui.Desktop)
/// and the driver of each kind of database the data sources are. With the
/// property `ClarityRuntime` (or the environment variable CLARITY_RUNTIME) set
/// to the runtime's folder (runtimes/csharp in Clarity's repository), it
/// references the runtime's own projects there instead, for working on them.
fn csproj(name: &str, ui: &str, drivers: &[&Driver], carried: bool, engines: bool, dotnet: String) -> String {
    let version = runtime_version();
    // Engines need Wasmtime, which only an application with an engine carries.
    let packages: Vec<&str> = std::iter::once(ui).chain(drivers.iter().map(|s| s.package)).chain(engines.then_some(ENGINES_PACKAGE)).collect();
    let references: String = packages.iter().map(|p| format!("    <PackageReference Include=\"{p}\" Version=\"{version}\" />\n")).collect();
    let projects: String = packages.iter().map(|p| format!("    <ProjectReference Include=\"$(ClarityRuntime)/{p}/{p}.csproj\" />\n")).collect();
    // The files of the project's resources folder, embedded.
    let mut resources = if carried { "  <ItemGroup>\n    <EmbeddedResource Include=\"resources/**\" LogicalName=\"resources/%(RecursiveDir)%(Filename)%(Extension)\" />\n  </ItemGroup>\n".to_string() } else { String::new() };
    // The engines' files, embedded under their names.
    if engines {
        resources.push_str("  <ItemGroup>\n    <EmbeddedResource Include=\"Engines/*.wasm\" LogicalName=\"Engines/%(Filename)%(Extension)\" />\n  </ItemGroup>\n");
    }
    // The libraries' packages and assemblies.
    resources.push_str(&dotnet);
    format!(
        "<!-- Generated by Clarity. Do not edit: change the project in Clarity instead. -->
<Project Sdk=\"Microsoft.NET.Sdk\">
  <PropertyGroup>
    <OutputType>WinExe</OutputType>
    <TargetFramework>{TARGET_FRAMEWORK}</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <RootNamespace>{name}</RootNamespace>
    <AssemblyName>{name}</AssemblyName>
    <!-- Where Clarity's runtime projects are, to build on them instead of its
         packages: dotnet build -p:ClarityRuntime=<folder>, or the environment
         variable CLARITY_RUNTIME. Empty: the packages. -->
    <ClarityRuntime Condition=\"'$(ClarityRuntime)' == ''\">$(CLARITY_RUNTIME)</ClarityRuntime>
  </PropertyGroup>
  <ItemGroup>
    <!-- The windows and app frames as markup, and the themes, which Clarity.UI draws (DESIGN 7.9). -->
    <EmbeddedResource Include=\"Windows/*.cxaml\" LogicalName=\"Windows/%(Filename)%(Extension)\" />
    <EmbeddedResource Include=\"Apps/*.cxaml\" LogicalName=\"Apps/%(Filename)%(Extension)\" />
    <EmbeddedResource Include=\"Themes/*.json\" LogicalName=\"Themes/%(Filename)%(Extension)\" />
  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' == ''\">
{references}  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' != ''\">
{projects}  </ItemGroup>
{resources}</Project>
"
    )
}

/// The libraries' packages and assemblies, in an item group (DESIGN 5.21).
fn library_references(project: &Project) -> String {
    let lines = crate::libraries::csharp_references(project);
    if lines.is_empty() { lines } else { format!("  <ItemGroup>\n{lines}  </ItemGroup>\n") }
}

/// The runtime's name for a database kind.
fn dialect(sql: Sql) -> &'static str {
    match sql {
        Sql::Sqlite => "Dialect.Sqlite",
        Sql::Postgres => "Dialect.Postgres",
        Sql::Mysql => "Dialect.Mysql",
        Sql::Mssql => "Dialect.Mssql",
    }
}

/// The steps of every database Clarity owns, as SQL per data source.
fn schema_cs(project: &Project, name: &str, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut out = format!(
        "{HEADER}
namespace {name};

public static class Schema
{{
    /// <summary>
    /// The migration steps per data source, in order, each a list of
    /// statements. Each database remembers how many steps it has applied, and
    /// applies the rest when the application starts.
    /// </summary>
    public static readonly (string Source, string[][] Steps)[] Sources =
    [
"
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        out.push_str(&format!("        ({},\n        [\n", string(source)));
        for (i, (title, statements)) in steps.iter().enumerate() {
            out.push_str(&format!("            // {}: {title}\n            [\n", i + 1));
            for statement in statements {
                out.push_str(&format!("                {},\n", verbatim(statement)));
            }
            out.push_str("            ],\n");
        }
        out.push_str("        ]),\n");
    }
    out.push_str("    ];\n}\n");
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}

/// The program: it opens the database of every data source, brings Clarity's
/// own up to date, and starts the windows; `--check` stops after the databases.
/// The package that hosts engines (DESIGN 5.11).
const ENGINES_PACKAGE: &str = "Clarity.Runtime.Engines";

/// The engines of the application (DESIGN 5.11): each loaded once from its
/// embedded file, and every one checked when the application starts.
fn engines_cs(project: &Project, name: &str) -> String {
    let mut members = String::new();
    let mut checks = String::new();
    for engine in crate::engines(project) {
        let member = pascal(&engine.name.name);
        let functions: Vec<String> = engine.functions.iter().map(|f| string(&f.name.name)).collect();
        members.push_str(&format!(
            "    static readonly Lazy<Engine> {field} = new(() => Engine.Load({}, Read({}), new EngineDeclaration([{}], [{}], new EngineLimits({}, {}), {}, {})));\n\n    /// <summary>Engine {}, from {}.</summary>\n    public static Engine {member} => {field}.Value;\n\n",
            string(&engine.name.name),
            string(&engine.file),
            functions.join(", "),
            engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            engine.seconds(),
            engine.megabytes(),
            match engine.state {
                clarity_spec::code::EngineState::None => "EngineState.None",
                clarity_spec::code::EngineState::App => "EngineState.PerApp",
                clarity_spec::code::EngineState::Window => "EngineState.PerWindow",
            },
            engine.opens,
            engine.name.name,
            engine.file,
            field = format!("_{}", camel(&engine.name.name)),
        ));
        checks.push_str(&format!("        _ = {member};\n"));
    }
    format!(
        "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n/// <summary>The engines of the application: each loaded once from its file, every one checked when the application starts.</summary>\npublic static class Engines\n{{\n{members}    /// <summary>Loads every engine, so one whose file does not fit stops the application at start.</summary>\n    public static void Check()\n    {{\n{checks}    }}\n\n    static byte[] Read(string file)\n    {{\n        using var stream = typeof(Engines).Assembly.GetManifestResourceStream(\"Engines/\" + file) ?? throw new EngineException($\"the engine file {{file}} is missing\");\n        using var bytes = new MemoryStream();\n        stream.CopyTo(bytes);\n        return bytes.ToArray();\n    }}\n}}\n"
    )
}

/// The engines beside the screen (DESIGN 5.12): for each, what makes a new
/// instance for a canvas that runs it, from its embedded file.
fn screen_engines_cs(project: &Project, name: &str) -> String {
    let mut members = String::new();
    for engine in crate::screen_engines(project) {
        members.push_str(&format!(
            "    /// <summary>Engine {engine_name} beside the screen, from {file}: a new instance for each canvas that runs it.</summary>\n    public static readonly Func<IFrames> {member} = () => InBrowser is {{ }} load\n        ? load({name}, Read({file_text}), [{uses}], {opens}, {seconds}, {megabytes})\n        : ScreenEngine.Load({name}, Read({file_text}), [{uses}], {opens}, new EngineLimits({seconds}, {megabytes}));\n\n",
            name = string(&engine.name.name),
            file_text = string(&engine.file),
            uses = engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            opens = engine.opens,
            seconds = engine.seconds(),
            megabytes = engine.megabytes(),
            engine_name = engine.name.name,
            file = engine.file,
            member = pascal(&engine.name.name),
        ));
    }
    format!(
        "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n/// <summary>The engines beside the screen, which the canvases that run them draw with.</summary>\npublic static class ScreenEngines\n{{\n    /// <summary>How a browser loads an engine beside the screen, where Wasmtime cannot run (DESIGN 7.6): its name, file, services, on open and limits; none on the desktop.</summary>\n    public static Func<string, byte[], string[], bool, long, long, IFrames>? InBrowser {{ get; set; }}\n\n{members}    static byte[] Read(string file)\n    {{\n        using var stream = typeof(ScreenEngines).Assembly.GetManifestResourceStream(\"Engines/\" + file) ?? throw new EngineException($\"the engine file {{file}} is missing\");\n        using var bytes = new MemoryStream();\n        stream.CopyTo(bytes);\n        return bytes.ToArray();\n    }}\n}}\n"
    )
}

/// An engine whose file does not fit its declaration stops the application at start.
fn check_engines(engines: bool) -> &'static str {
    if engines {
        "        try\n        {\n            Engines.Check();\n        }\n        catch (EngineException e)\n        {\n            Console.Error.WriteLine(e.Message);\n            return 1;\n        }\n"
    } else {
        ""
    }
}

/// The databases of the data sources and the file stores, and `method`, which opens them.
fn opening(project: &Project, databases: &[(String, Sql, String)], drivers: &[&Driver], settings: &Settings, method: &str) -> String {
    // Each kind of database, turned on by its package before the databases open.
    let turned_on: String = drivers.iter().map(|s| format!("        {}.Use();\n", s.class)).collect();
    let stores = crate::fixed_stores(settings).iter().map(|s| format!("({}, {})", string(&s.name), string(&s.location))).collect::<Vec<_>>().join(", ");
    // A store whose folder is a folder setting follows the person's settings.
    let program_name = crate::settings_program(settings);
    let folder_stores: String = crate::folder_stores(project, settings)
        .iter()
        .map(|(name, setting, default)| format!("        db.AddStoreSetting({}, {}, {}, {});\n", string(name), string(&program_name), string(setting), string(default)))
        .collect();
    let databases = databases
        .iter()
        .map(|(source, sql, at)| format!("({}, {}, {})", string(source), dialect(*sql), string(at)))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "    /// <summary>The database of each data source: its name, its kind and where it is.</summary>
    static readonly (string, Dialect, string)[] Sources = [{databases}];

    /// <summary>The folder of each file store, which keeps the pictures of image fields kept as files.</summary>
    static readonly (string, string)[] Stores = [{stores}];

    /// <summary>Opens every database and applies the migration steps it has not had yet.</summary>
    public static Db {method}()
    {{
{turned_on}        var db = Db.Connect(Sources);
        foreach (var (source, steps) in Schema.Sources)
            db.MigrateSource(source, steps);
        foreach (var (name, at) in Stores)
            db.AddStore(name, at);
{folder_stores}        return db;
    }}
"
    )
}

fn program_cs(project: &Project, name: &str, databases: &[(String, Sql, String)], drivers: &[&Driver], settings: &Settings, engines: bool) -> String {
    let check_engines = check_engines(engines);
    let opening = opening(project, databases, drivers, settings, "OpenDatabases");
    let main_window = main_window(project).unwrap_or_default();
    // Engines ask for the language the person picked.
    let engines_language = if engines { "        Clarity.Runtime.Engine.Language = () => Locale.Language?.Name;\n" } else { "" };
    let currency = project.locale.currency.as_deref().map_or_else(|| "null".to_string(), string);
    // The person's settings, after the language and theme they may name (DESIGN 5.17).
    let settings_start = if project.entities().any(|e| e.settings) { "        Settings.Start();\n" } else { "" };
    // The person's keys (DESIGN 5.28).
    let keys_start = if project.keys_editable { format!("        PersonKeys.Start({});\n", string(&crate::settings_program(settings))) } else { String::new() };
    format!(
        "{HEADER}
using Clarity.Runtime;
using Clarity.Ui.Desktop;

namespace {name};

public static class Program
{{
{opening}
    [STAThread]
    public static int Main(string[] args)
    {{
{check_engines}        // `--check` opens and migrates the databases without windows, for builds and scripts.
        if (args.Contains(\"--check\"))
        {{
            using var db = OpenDatabases();
            Console.WriteLine({ready});
            return 0;
        }}
        // The language and theme kept from the last run, or the system's.
        Remembered.Use({application});
        Locale.Start(Texts.BaseLanguage, Texts.Languages, {currency}, Texts.In, Labels.Named);
{engines_language}        AppThemes.Start();
{settings_start}{keys_start}        Db opened;
        try
        {{
            opened = OpenDatabases();
        }}
        catch (Exception e)
        {{
            // The databases did not open (DESIGN 5.27): Clarity.UI's window for it comes with G7d.
            Console.Error.WriteLine(Locale.Show(Unconnecting.Why(e)));
            return 1;
        }}
        using var databases = opened;
        DesktopWindow.Run(new {main_window}ViewModel(databases));
        return 0;
    }}
}}
",
        application = string(name),
        ready = string(&format!("{name}: the databases are ready."))
    )
}

/// The window the app's `on unconnected` runs on: empty, with the app's frame,
/// never shown (DESIGN 5.27).
fn unconnected_host(project: &Project) -> clarity_spec::model::Page {
    use clarity_spec::model::{Frame, Ident, Page, PageKind};
    let taken = |n: &str| project.pages().any(|p| p.name.name == n);
    let name = if taken("AppUnconnected") { "AppUnconnectedStart" } else { "AppUnconnected" };
    Page {
        name: Ident { name: name.to_string(), span: Default::default() },
        kind: PageKind::Window,
        title: None,
        size: None,
        data: Vec::new(),
        columns: 12,
        widgets: Vec::new(),
        frame: Frame::default(),
        handlers: Vec::new(),
        gives: None,
        span: Default::default(),
    }
}

/// The labels of enum values by the enum's name, for text with slots.
fn labels_cs(project: &Project, name: &str) -> String {
    let named: String = project
        .files
        .iter()
        .flat_map(|f| &f.enums)
        .map(|e| format!("        {lit} => Enum.TryParse<{e}>(value, out var v) ? Of(v) : value,\n", lit = string(&e.name.name), e = e.name.name))
        .collect();
    format!(
        "{HEADER}
namespace {name};

public static partial class Labels
{{
    /// <summary>The label of an enum value by the enum's name, for text with slots.</summary>
    public static string Named(string enumName, string value) => enumName switch
    {{
{named}        _ => value,
    }};
}}
"
    )
}

/// The icons the application shows, from Clarity's Lucide set (ISC license):
/// a geometry each in a 24 by 24 box, which a part draws with a round line.
fn icons_cs(project: &Project, namespace: &str) -> String {
    let mut out = format!(
        "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n// The icons are Lucide's (https://lucide.dev), under the ISC license.\n\nnamespace {namespace};\n\n/// <summary>The icons the application shows: an SVG path each in a 24 by 24 box.</summary>\npublic static class Icons\n{{\n"
    );
    for (name, path) in clarity_spec::icons::used(project) {
        out.push_str(&format!("    public const string {} = \"{path}\";\n", windows::icon_member(&name)));
    }
    out.push_str("}\n");
    out
}

/// How a field's values are formatted, as the runtime's `FieldFormat`, for
/// the types that have formats.
pub(super) fn field_format(field: &clarity_spec::model::Field) -> Option<String> {
    let format = field.modifiers.format.as_deref().map(string);
    let (kind, scale) = match &field.ty {
        FieldType::Integer => ("Integer", None),
        FieldType::Decimal { scale, .. } => ("Decimal", Some(*scale)),
        FieldType::Money => ("Money", None),
        FieldType::Date => ("Date", None),
        FieldType::DateTime => ("DateTime", None),
        FieldType::Duration => ("Duration", None),
        _ => return None,
    };
    let mut args = vec![format!("FormatKind.{kind}")];
    match (scale, format) {
        (Some(scale), Some(format)) => args.extend([scale.to_string(), format]),
        (Some(scale), None) => args.push(scale.to_string()),
        (None, Some(format)) => args.extend(["null".to_string(), format]),
        (None, None) => {}
    }
    Some(format!("new FieldFormat({})", args.join(", ")))
}
