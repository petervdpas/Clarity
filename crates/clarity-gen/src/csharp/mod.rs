/// The facts of every field of every entity, which Clarity.UI's parts read
/// beside the values (DESIGN 7.9): `Fields.All["Order.total"]`, keyed by the
/// entity's type name and the field as Clarity writes it.
fn fields_cs(project: &Project, name: &str) -> String {
    use clarity_spec::model::Literal;
    let literal = |value: &Option<Literal>| match value {
        Some(Literal::Number(v) | Literal::Str(v) | Literal::Ident(v)) => string(v),
        Some(Literal::Bool(b)) => string(&b.to_string()),
        None => "null".to_string(),
    };
    let mut lines = String::new();
    for entity in project.entities().chain(project.records()) {
        let parent = tree_parent(entity).map_or("null".to_string(), |p| string(p));
        for field in &entity.fields {
            let refers = match &field.ty {
                FieldType::Ref { entity } => string(&entity.name),
                _ => "null".to_string(),
            };
            // A color field says so, for the parts that show a swatch beside its value.
            let color = if matches!(field.ty, FieldType::Color) { ", Color: true" } else { "" };
            lines.push_str(&format!(
                "        [{key}] = new({label}, {format}, Required: {required}, Min: {min}, Max: {max}, Refers: {refers}, Parent: {parent}{color}),\n",
                key = string(&format!("{}.{}", entity.name.name, field.name.name)),
                label = string(&field.label),
                format = field_format(field).unwrap_or_else(|| "null".to_string()),
                required = field.modifiers.required,
                min = literal(&field.modifiers.min),
                max = literal(&field.modifiers.max),
            ));
        }
    }
    format!(
        "{HEADER}
using Clarity.Runtime;

namespace {name};

/// <summary>The facts of every field of every entity, keyed \"Entity.field\": its label, format, whether it is required, its range, what it refers to, for records that make a tree the field naming a record's parent, and whether it holds a color.</summary>
public static class Fields
{{
    public static readonly IReadOnlyDictionary<string, FieldFacts> All = new Dictionary<string, FieldFacts>
    {{
{lines}    }};
}}
"
    )
}

/// The field naming a record's parent, for an entity whose records make a
/// tree: one with a list of its own kind (what a tree's `children` names),
/// arranged through its one reference to its own kind.
pub(crate) fn tree_parent(entity: &clarity_spec::model::Entity) -> Option<&str> {
    let own = |e: &clarity_spec::model::Ident| e.name == entity.name.name;
    let has_list = entity.fields.iter().any(|f| matches!(&f.ty, FieldType::List { item } if own(item)));
    let mut parents = entity.fields.iter().filter(|f| matches!(&f.ty, FieldType::Ref { entity } if own(entity)));
    match (has_list, parents.next(), parents.next()) {
        (true, Some(parent), None) => Some(&parent.name.name),
        _ => None,
    }
}

/// The icons the application shows, from Clarity's Lucide set (ISC license):
/// a geometry each in a 24 by 24 box, which a part draws with a round line.
fn icons_cs(project: &Project, namespace: &str) -> String {
    let mut out = format!(
        "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n// The icons are Lucide's (https://lucide.dev), under the ISC license.\n\nnamespace {namespace};\n\n/// <summary>The icons the application shows: an SVG path each in a 24 by 24 box.</summary>\npublic static class Icons\n{{\n"
    );
    for (name, path) in clarity_spec::icons::used(project) {
        out.push_str(&format!("    public const string {} = \"{path}\";\n", windows::icon_member(&name)));
    }
    out.push_str("}\n");
    out
}

/// How a field's values are formatted, as the runtime's `FieldFormat`, for
/// the types that have formats.
pub(super) fn field_format(field: &clarity_spec::model::Field) -> Option<String> {
    let format = field.modifiers.format.as_deref().map(string);
    let (kind, scale) = match &field.ty {
        FieldType::Integer => ("Integer", None),
        FieldType::Decimal { .. } => ("Decimal", field.ty.shown_scale()),
        FieldType::Money => ("Money", None),
        FieldType::Date => ("Date", None),
        FieldType::DateTime => ("DateTime", None),
        FieldType::Duration => ("Duration", None),
        _ => return None,
    };
    let mut args = vec![format!("FormatKind.{kind}")];
    match (scale, format) {
        (Some(scale), Some(format)) => args.extend([scale.to_string(), format]),
        (Some(scale), None) => args.push(scale.to_string()),
        (None, Some(format)) => args.extend(["null".to_string(), format]),
        (None, None) => {}
    }
    Some(format!("new FieldFormat({})", args.join(", ")))
}
