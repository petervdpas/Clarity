/// The first line of every generated C# file.
const HEADER: &str = "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n";

/// The runtime's shared settings, which hold the version of its packages.
const RUNTIME_PROPS: &str = include_str!("../../../../runtimes/csharp/Directory.Build.props");

/// The version of the runtime's packages a project references: the one the
/// runtime in this repository is (all its packages share it).
pub fn runtime_version() -> &'static str {
    let start = RUNTIME_PROPS.find("<Version>").expect("Directory.Build.props sets a Version") + "<Version>".len();
    let end = RUNTIME_PROPS[start..].find("</Version>").expect("the Version is closed");
    RUNTIME_PROPS[start..start + end].trim()
}

/// The package everything a project needs comes with: the windows, and
/// through it Clarity.Runtime with SQLite.
const UI_PACKAGE: &str = "Clarity.Avalonia";

/// What a server database brings into a project: the runtime's package of
/// its driver (with the client it stands on), and the class whose Use() turns
/// the driver on.
struct Server {
    sql: Sql,
    /// The class whose Use() turns the driver on, like `PostgreSql`.
    class: &'static str,
    package: &'static str,
}

const SERVERS: [Server; 3] = [
    Server { sql: Sql::Postgres, class: "PostgreSql", package: "Clarity.Runtime.PostgreSql" },
    Server { sql: Sql::Mysql, class: "MySql", package: "Clarity.Runtime.MySql" },
    Server { sql: Sql::Mssql, class: "SqlServer", package: "Clarity.Runtime.SqlServer" },
];

/// The application's styles, with a line where the style classes of its themes go.
const APP_AXAML: &str = include_str!("App.axaml");

/// The .NET the generated project targets.
pub const TARGET_FRAMEWORK: &str = "net10.0";

/// The name of the generated project, its namespace and its program.
pub fn project_name(settings: &Settings) -> String {
    pascal(&settings.name)
}

pub use cli::generate as generate_cli;

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "C#")?;
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let name = project_name(settings);
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let texts = texts::Texts::of(project);
    let servers: Vec<&Server> = SERVERS.iter().filter(|s| databases.iter().any(|(_, sql, _)| *sql == s.sql)).collect();
    let engines = !crate::engines(project).is_empty();
    let mut files = vec![text(&format!("{name}.csproj"), csproj(&name, &servers, project.resources.as_ref().is_some_and(|r| !r.files.is_empty() || !r.markdown.is_empty()), engines))];
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        // The settings read and keep JSON, numbers and dates written the same everywhere.
        let settings_usings = if file.entities.iter().any(|e| e.settings) { "using System.Globalization;\nusing System.Text.Json.Nodes;\nusing Avalonia.Threading;\n" } else { "" };
        let mut code = format!("{HEADER}\n{settings_usings}using Clarity.Avalonia;\nusing Clarity.Runtime;\nusing CommunityToolkit.Mvvm.ComponentModel;\n\nnamespace {name};\n\n");
        code.push_str(&model::emit(project, file, &name, &texts, false));
        match logic::emit(project, file, &file_types) {
            Ok(methods) => code.push_str(&methods),
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("Modules/{}.cs", pascal(&module.name)), code.trim_end().to_string() + "\n"));
        for page in &file.pages {
            match windows::emit(project, page, &file_types, &name, &texts) {
                Ok(mut window) => files.append(&mut window),
                Err(mut problems) => errors.append(&mut problems),
            }
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("Schema.cs", schema_cs(project, &name, &owned)?));
    files.push(text("Program.cs", program_cs(&name, &databases, &servers, settings, engines)));
    if engines {
        files.extend(crate::engine_files(project, "Engines"));
        files.push(text("Engines.cs", engines_cs(project, &name)));
    }
    files.push(text("App.axaml.cs", app_cs(project, &name, &main_window)));
    files.push(text("Views.cs", views_cs(project, &name)));
    files.push(text("Shown.cs", shown_cs(project, &name)));
    if !clarity_spec::icons::used(project).is_empty() {
        files.push(text("Icons.cs", icons_cs(project, &name)));
    }
    // The default language's texts, and each other language's.
    files.push(text("Texts.cs", texts.class(project, &name)));
    files.push(text("Texts.resx", texts.base_resx(project)));
    let default = clarity_spec::translations::default_language(project);
    for (language, values) in project.translations.iter().filter(|(l, _)| **l != default) {
        files.push(text(&format!("Texts.{language}.resx"), texts.language_resx(values)));
    }
    // The themes offered, each merged with Clarity's own; without any, Clarity's own.
    let built_in = clarity_spec::themes::built_in();
    let mut offered: Vec<&ThemeDecl> =
        project.themes.iter().filter_map(|n| project.files.iter().flat_map(|f| &f.themes).find(|t| t.name.name == *n)).collect();
    if offered.is_empty() {
        offered.push(&built_in);
    }
    let styles = themes::style_properties(&offered);
    for theme in &offered {
        files.push(text(&themes::theme_path(theme), themes::theme_axaml(theme, &styles)));
    }
    files.push(text("AppThemes.cs", themes::app_themes(&offered, &name)));
    files.extend(crate::web::resource_files(project, "resources"));
    files.push(text("App.axaml", APP_AXAML.replace("{namespace}", &name).replace("    <!-- {styles} -->\n", &themes::style_classes(&styles))));
    Ok(files)
}

fn text(path: &str, body: String) -> OutFile {
    OutFile {
        path: path.to_string(),
        text: body,
        bytes: None,
    }
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project
        .apps()
        .find_map(|a| a.main.as_ref().map(|m| m.name.clone()))
        .or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

/// The project file. It references the runtime's packages: Clarity.Avalonia
/// and the driver of each server database the data sources are. With the
/// property `ClarityRuntime` (or the environment variable CLARITY_RUNTIME) set
/// to the runtime's folder (runtimes/csharp in Clarity's repository), it
/// references the runtime's own projects there instead, for working on them.
fn csproj(name: &str, servers: &[&Server], carried: bool, engines: bool) -> String {
    let version = runtime_version();
    // Engines need Wasmtime, which only an application with an engine carries.
    let packages: Vec<&str> = std::iter::once(UI_PACKAGE).chain(servers.iter().map(|s| s.package)).chain(engines.then_some(ENGINES_PACKAGE)).collect();
    let references: String = packages.iter().map(|p| format!("    <PackageReference Include=\"{p}\" Version=\"{version}\" />\n")).collect();
    let projects: String = packages.iter().map(|p| format!("    <ProjectReference Include=\"$(ClarityRuntime)/{p}/{p}.csproj\" />\n")).collect();
    // The files of the project's resources folder, embedded.
    let mut resources = if carried { "  <ItemGroup>\n    <AvaloniaResource Include=\"resources/**\" />\n  </ItemGroup>\n".to_string() } else { String::new() };
    // The engines' files, embedded under their names.
    if engines {
        resources.push_str("  <ItemGroup>\n    <EmbeddedResource Include=\"Engines/*.wasm\" LogicalName=\"Engines/%(Filename)%(Extension)\" />\n  </ItemGroup>\n");
    }
    format!(
        "<!-- Generated by Clarity. Do not edit: change the project in Clarity instead. -->
<Project Sdk=\"Microsoft.NET.Sdk\">
  <PropertyGroup>
    <OutputType>WinExe</OutputType>
    <TargetFramework>{TARGET_FRAMEWORK}</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <RootNamespace>{name}</RootNamespace>
    <AssemblyName>{name}</AssemblyName>
    <AvaloniaUseCompiledBindingsByDefault>true</AvaloniaUseCompiledBindingsByDefault>
    <!-- Where Clarity's runtime projects are, to build on them instead of its
         packages: dotnet build -p:ClarityRuntime=<folder>, or the environment
         variable CLARITY_RUNTIME. Empty: the packages. -->
    <ClarityRuntime Condition=\"'$(ClarityRuntime)' == ''\">$(CLARITY_RUNTIME)</ClarityRuntime>
  </PropertyGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' == ''\">
{references}  </ItemGroup>
  <ItemGroup Condition=\"'$(ClarityRuntime)' != ''\">
{projects}  </ItemGroup>
{resources}</Project>
"
    )
}

/// The runtime's name for a database kind.
fn dialect(sql: Sql) -> &'static str {
    match sql {
        Sql::Sqlite => "Dialect.Sqlite",
        Sql::Postgres => "Dialect.Postgres",
        Sql::Mysql => "Dialect.Mysql",
        Sql::Mssql => "Dialect.Mssql",
    }
}

/// The steps of every database Clarity owns, as SQL per data source.
fn schema_cs(project: &Project, name: &str, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut out = format!(
        "{HEADER}
namespace {name};

public static class Schema
{{
    /// <summary>
    /// The migration steps per data source, in order, each a list of
    /// statements. Each database remembers how many steps it has applied, and
    /// applies the rest when the application starts.
    /// </summary>
    public static readonly (string Source, string[][] Steps)[] Sources =
    [
"
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        out.push_str(&format!("        ({},\n        [\n", string(source)));
        for (i, (title, statements)) in steps.iter().enumerate() {
            out.push_str(&format!("            // {}: {title}\n            [\n", i + 1));
            for statement in statements {
                out.push_str(&format!("                {},\n", verbatim(statement)));
            }
            out.push_str("            ],\n");
        }
        out.push_str("        ]),\n");
    }
    out.push_str("    ];\n}\n");
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}

/// The program: it opens the database of every data source, brings Clarity's
/// own up to date, and starts the windows; `--check` stops after the databases.
/// The package that hosts engines (DESIGN 5.11).
const ENGINES_PACKAGE: &str = "Clarity.Runtime.Engines";

/// The engines of the application (DESIGN 5.11): each loaded once from its
/// embedded file, and every one checked when the application starts.
fn engines_cs(project: &Project, name: &str) -> String {
    let mut members = String::new();
    let mut checks = String::new();
    for engine in crate::engines(project) {
        let member = pascal(&engine.name.name);
        let functions: Vec<String> = engine.functions.iter().map(|f| string(&f.name.name)).collect();
        members.push_str(&format!(
            "    static readonly Lazy<Engine> {field} = new(() => Engine.Load({}, Read({}), new EngineDeclaration([{}], [{}], new EngineLimits({}, {}), {}, {})));\n\n    /// <summary>Engine {}, from {}.</summary>\n    public static Engine {member} => {field}.Value;\n\n",
            string(&engine.name.name),
            string(&engine.file),
            functions.join(", "),
            engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            engine.seconds(),
            engine.megabytes(),
            match engine.state {
                clarity_spec::code::EngineState::None => "EngineState.None",
                clarity_spec::code::EngineState::App => "EngineState.PerApp",
                clarity_spec::code::EngineState::Window => "EngineState.PerWindow",
            },
            engine.opens,
            engine.name.name,
            engine.file,
            field = format!("_{}", camel(&engine.name.name)),
        ));
        checks.push_str(&format!("        _ = {member};\n"));
    }
    format!(
        "{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n/// <summary>The engines of the application: each loaded once from its file, every one checked when the application starts.</summary>\npublic static class Engines\n{{\n{members}    /// <summary>Loads every engine, so one whose file does not fit stops the application at start.</summary>\n    public static void Check()\n    {{\n{checks}    }}\n\n    static byte[] Read(string file)\n    {{\n        using var stream = typeof(Engines).Assembly.GetManifestResourceStream(\"Engines/\" + file) ?? throw new EngineException($\"the engine file {{file}} is missing\");\n        using var bytes = new MemoryStream();\n        stream.CopyTo(bytes);\n        return bytes.ToArray();\n    }}\n}}\n"
    )
}

fn program_cs(name: &str, databases: &[(String, Sql, String)], servers: &[&Server], settings: &Settings, engines: bool) -> String {
    // An engine whose file does not fit its declaration stops the application at start.
    let check_engines = if engines {
        "        try\n        {\n            Engines.Check();\n        }\n        catch (EngineException e)\n        {\n            Console.Error.WriteLine(e.Message);\n            return 1;\n        }\n"
    } else {
        ""
    };
    // The server databases, each turned on by its package before the databases open.
    let turned_on: String = servers.iter().map(|s| format!("        {}.Use();\n", s.class)).collect();
    let stores = settings.filestores.iter().map(|s| format!("({}, {})", string(&s.name), string(&s.location))).collect::<Vec<_>>().join(", ");
    let databases = databases
        .iter()
        .map(|(source, sql, at)| format!("({}, {}, {})", string(source), dialect(*sql), string(at)))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "{HEADER}
using Avalonia;
using Clarity.Runtime;

namespace {name};

public static class Program
{{
    /// <summary>The database of each data source: its name, its kind and where it is.</summary>
    static readonly (string, Dialect, string)[] Databases = [{databases}];

    /// <summary>The folder of each file store, which keeps the pictures of image fields kept as files.</summary>
    static readonly (string, string)[] Stores = [{stores}];

    /// <summary>Opens every database and applies the migration steps it has not had yet.</summary>
    public static Db OpenDatabases()
    {{
{turned_on}        var db = Db.Connect(Databases);
        foreach (var (source, steps) in Schema.Sources)
            db.MigrateSource(source, steps);
        foreach (var (name, at) in Stores)
            db.AddStore(name, at);
        return db;
    }}

    [STAThread]
    public static int Main(string[] args)
    {{
{check_engines}        // `--check` opens and migrates the databases without windows, for builds and scripts.
        if (args.Contains(\"--check\"))
        {{
            using var db = OpenDatabases();
            Console.WriteLine({ready});
            return 0;
        }}
        return BuildAvaloniaApp().StartWithClassicDesktopLifetime(args);
    }}

    public static AppBuilder BuildAvaloniaApp() => AppBuilder.Configure<App>().UsePlatformDetect().LogToTrace();
}}
",
        ready = string(&format!("{name}: the databases are ready."))
    )
}

/// The application: it starts in the language and theme kept from the last
/// run (or the system's), opens the databases and shows the main window.
fn app_cs(project: &Project, name: &str, main_window: &str) -> String {
    // Engines ask for the language the person picked.
    let engines_language = if !crate::engines(project).is_empty() {
        "            Clarity.Runtime.Engine.Language = () => Locale.Language?.Name;\n"
    } else {
        ""
    };
    let currency = project.locale.currency.as_deref().map_or_else(|| "null".to_string(), string);
    let application = string(name);
    // The person's settings, after the language and theme they may name (DESIGN 5.17).
    let settings_start = if project.entities().any(|e| e.settings) { "            Settings.Start();\n" } else { "" };
    format!(
        "{HEADER}
using Avalonia;
using Avalonia.Controls;
using Avalonia.Controls.ApplicationLifetimes;
using Avalonia.Markup.Xaml;
using Clarity.Avalonia;

namespace {name};

public partial class App : Application
{{
    public override void Initialize() => AvaloniaXamlLoader.Load(this);

    public override void OnFrameworkInitializationCompleted()
    {{
        if (ApplicationLifetime is IClassicDesktopStyleApplicationLifetime desktop)
        {{
            Remembered.Use({application});
            Locale.Start(Texts.BaseLanguage, Texts.Languages, {currency}, Texts.In, Labels.Named);
{engines_language}            Themes.Start(AppThemes.Offered);
{settings_start}            var db = Program.OpenDatabases();
            desktop.Exit += (_, _) => db.Dispose();
            desktop.ShutdownMode = ShutdownMode.OnMainWindowClose;
            desktop.MainWindow = Shell.Start(new {main_window}ViewModel(db), Views.Create, TimeSpan.FromMilliseconds({MESSAGE_MS}));
        }}
        base.OnFrameworkInitializationCompleted();
    }}
}}
"
    )
}

/// The view of each window's ViewModel, for the shell.
fn views_cs(project: &Project, name: &str) -> String {
    let arms: String = project
        .pages()
        .map(|p| format!("        {page}ViewModel vm => new {page}View {{ DataContext = vm }},\n", page = p.name.name))
        .collect();
    format!(
        "{HEADER}
using Avalonia.Controls;
using Clarity.Avalonia;

namespace {name};

public static class Views
{{
    /// <summary>The view that shows <paramref name=\"model\"/>.</summary>
    public static Control Create(WindowViewModel model) => model switch
    {{
{arms}        _ => throw new ArgumentException($\"no view shows {{model.GetType().Name}}\"),
    }};
}}
"
    )
}

/// How values show in text and tables: enums by their labels, values of
/// fields with a format in the person's format (a converter per field), and
/// how number inputs read what is typed.
fn shown_cs(project: &Project, name: &str) -> String {
    let enums: Vec<&str> = project.files.iter().flat_map(|f| &f.enums).map(|e| e.name.name.as_str()).collect();
    let arms: String = enums.iter().map(|e| format!("        {e} v => Labels.Of(v),\n")).collect();
    let named: String = enums
        .iter()
        .map(|e| format!("        {lit} => Enum.TryParse<{e}>(value, out var v) ? Of(v) : value,\n", lit = string(e)))
        .collect();
    let mut shown = String::new();
    let mut edit = String::new();
    for entity in project.files.iter().flat_map(|f| &f.entities) {
        for field in &entity.fields {
            let Some(format) = field_format(field) else { continue };
            let member = format!("{}{}", entity.name.name, pascal(&field.name.name));
            shown.push_str(&format!("\n    /// <summary>{}.{}</summary>\n    public static readonly FormatConverter {member} = new({format});\n", entity.name.name, field.name.name));
            if matches!(field.ty, FieldType::Integer | FieldType::Decimal { .. } | FieldType::Money | FieldType::Duration) {
                edit.push_str(&format!("\n    /// <summary>{}.{}</summary>\n    public static readonly FieldFormat {member} = {format};\n", entity.name.name, field.name.name));
            }
        }
    }
    format!(
        "{HEADER}
using Avalonia.Data.Converters;
using Avalonia.Media.Imaging;
using Avalonia.Platform;
using Clarity.Avalonia;
using Clarity.Runtime;

namespace {name};

/// <summary>Values as text in the person's language and format.</summary>
public static class Shown
{{
    /// <summary>A value as text: an enum by its label, the rest as the runtime shows it.</summary>
    public static readonly ShownConverter Converter = new(value => value switch
    {{
{arms}        _ => null,
    }});

    /// <summary>A link's address (conformance/small-parts.json): an email address to write to, one with a scheme as it is, else none.</summary>
    public static readonly IValueConverter Address = new FuncValueConverter<string?, Uri?>(value =>
    {{
        var text = value?.Trim() ?? \"\";
        if (text.Length == 0)
            return null;
        var address = text.Contains('@') && !text.Contains(':') ? $\"mailto:{{text}}\" : text;
        return Uri.TryCreate(address, UriKind.Absolute, out var uri) ? uri : null;
    }});

    /// <summary>A picture of the resources by its name, as a key gives it in the language shown.</summary>
    public static readonly IValueConverter Picture = new FuncValueConverter<string?, Bitmap?>(name =>
        string.IsNullOrEmpty(name) ? null : new Bitmap(AssetLoader.Open(new Uri($\"avares://{{typeof(Shown).Assembly.GetName().Name}}/resources/{{name}}\"))));
{shown}}}

/// <summary>How number inputs show their value and read what is typed: the field's kind and format.</summary>
public static class Edit
{{{edit}}}

public static partial class Labels
{{
    /// <summary>The label of an enum value by the enum's name, for text with slots.</summary>
    public static string Named(string enumName, string value) => enumName switch
    {{
{named}        _ => value,
    }};
}}
"
    )
}

/// How a field's values are formatted, as the runtime's `FieldFormat`, for
/// the types that have formats.
fn field_format(field: &clarity_spec::model::Field) -> Option<String> {
    let format = field.modifiers.format.as_deref().map(string);
    let (kind, scale) = match &field.ty {
        FieldType::Integer => ("Integer", None),
        FieldType::Decimal { scale, .. } => ("Decimal", Some(*scale)),
        FieldType::Money => ("Money", None),
        FieldType::Date => ("Date", None),
        FieldType::DateTime => ("DateTime", None),
        FieldType::Duration => ("Duration", None),
        _ => return None,
    };
    let mut args = vec![format!("FormatKind.{kind}")];
    match (scale, format) {
        (Some(scale), Some(format)) => args.extend([scale.to_string(), format]),
        (Some(scale), None) => args.push(scale.to_string()),
        (None, Some(format)) => args.extend(["null".to_string(), format]),
        (None, None) => {}
    }
    Some(format!("new FieldFormat({})", args.join(", ")))
}

/// The icons the application shows, from Clarity's Lucide set (ISC license):
/// a geometry each in a 24 by 24 box, which a part draws with a round line.
fn icons_cs(project: &Project, namespace: &str) -> String {
    let mut out = format!(
        "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n// The icons are Lucide's (https://lucide.dev), under the ISC license.\n\nusing Avalonia.Media;\n\nnamespace {namespace};\n\n/// <summary>The icons the application shows: a path each in a 24 by 24 box.</summary>\npublic static class Icons\n{{\n"
    );
    for (name, path) in clarity_spec::icons::used(project) {
        out.push_str(&format!("    public static Geometry {} {{ get; }} = Geometry.Parse(\"{path}\");\n", windows::icon_member(&name)));
    }
    out.push_str("}\n");
    out
}
