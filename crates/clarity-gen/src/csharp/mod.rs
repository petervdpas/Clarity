//! The C# backend (G2a): one C# file per Clarity module with its enums,
//! records, functions, actions and data events; the migration steps of every
//! database; and the C# runtime copied in, so `out/` builds with `dotnet
//! build` on its own. Windows come with Avalonia in G2b.

mod logic;
mod model;
mod names;

use clarity_project::Settings;
use clarity_spec::Project;
use clarity_spec::code::check;

use crate::OutFile;
use crate::ddl::Sql;
use crate::schema;
use names::{pascal, string, verbatim};

/// The first line of every generated C# file.
const HEADER: &str = "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n";

/// The C# runtime, copied into every generated project.
const RUNTIME_FILES: [(&str, &str); 9] = [
    ("Clarity.Runtime/Db.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Db.cs")),
    ("Clarity.Runtime/Dialect.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Dialect.cs")),
    ("Clarity.Runtime/Errors.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Errors.cs")),
    ("Clarity.Runtime/Query.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Query.cs")),
    ("Clarity.Runtime/Record.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Record.cs")),
    ("Clarity.Runtime/Sql.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Sql.cs")),
    ("Clarity.Runtime/SqliteDriver.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/SqliteDriver.cs")),
    ("Clarity.Runtime/Store.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Store.cs")),
    ("Clarity.Runtime/Text.cs", include_str!("../../../../runtimes/csharp/Clarity.Runtime/Text.cs")),
];

/// The runtime's own project file, whose packages the application takes over.
const RUNTIME_PROJECT: &str = include_str!("../../../../runtimes/csharp/Clarity.Runtime/Clarity.Runtime.csproj");

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "C#")?;
    let name = pascal(&settings.name);
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let mut files = vec![text(&format!("{name}.csproj"), csproj(&name))];
    files.extend(RUNTIME_FILES.iter().map(|(path, body)| text(path, (*body).into())));
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let mut code = format!("{HEADER}\nusing Clarity.Runtime;\n\nnamespace {name};\n\n");
        code.push_str(&model::emit(project, file));
        match logic::emit(project, file, &file_types) {
            Ok(methods) => code.push_str(&methods),
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("{}.cs", pascal(&module.name)), code.trim_end().to_string() + "\n"));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("Schema.cs", schema_cs(project, &name, &owned)?));
    files.push(text("Program.cs", program_cs(&name, &databases)));
    Ok(files)
}

fn text(path: &str, body: String) -> OutFile {
    OutFile {
        path: path.to_string(),
        text: body,
        bytes: None,
    }
}

/// The project file, with the runtime's packages at the versions it is tested with.
fn csproj(name: &str) -> String {
    let packages: String = RUNTIME_PROJECT
        .lines()
        .filter(|l| l.trim_start().starts_with("<PackageReference "))
        .map(|l| format!("    {}\n", l.trim()))
        .collect();
    format!(
        "<!-- Generated by Clarity. Do not edit: change the project in Clarity instead. -->
<Project Sdk=\"Microsoft.NET.Sdk\">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <RootNamespace>{name}</RootNamespace>
    <AssemblyName>{name}</AssemblyName>
  </PropertyGroup>
  <ItemGroup>
{packages}  </ItemGroup>
</Project>
"
    )
}

/// The runtime's name for a database kind.
fn dialect(sql: Sql) -> &'static str {
    match sql {
        Sql::Sqlite => "Dialect.Sqlite",
        Sql::Postgres => "Dialect.Postgres",
        Sql::Mysql => "Dialect.Mysql",
        Sql::Mssql => "Dialect.Mssql",
    }
}

/// The steps of every database Clarity owns, as SQL per data source.
fn schema_cs(project: &Project, name: &str, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut out = format!(
        "{HEADER}
namespace {name};

public static class Schema
{{
    /// <summary>
    /// The migration steps per data source, in order, each a list of
    /// statements. Each database remembers how many steps it has applied, and
    /// applies the rest when the application starts.
    /// </summary>
    public static readonly (string Source, string[][] Steps)[] Sources =
    [
"
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        out.push_str(&format!("        ({},\n        [\n", string(source)));
        for (i, (title, statements)) in steps.iter().enumerate() {
            out.push_str(&format!("            // {}: {title}\n            [\n", i + 1));
            for statement in statements {
                out.push_str(&format!("                {},\n", verbatim(statement)));
            }
            out.push_str("            ],\n");
        }
        out.push_str("        ]),\n");
    }
    out.push_str("    ];\n}\n");
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}

/// The program: it opens the database of every data source and brings
/// Clarity's own up to date.
fn program_cs(name: &str, databases: &[(String, Sql, String)]) -> String {
    let databases = databases
        .iter()
        .map(|(source, sql, at)| format!("({}, {}, {})", string(source), dialect(*sql), string(at)))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "{HEADER}
using Clarity.Runtime;

namespace {name};

public static class Program
{{
    /// <summary>The database of each data source: its name, its kind and where it is.</summary>
    static readonly (string, Dialect, string)[] Databases = [{databases}];

    /// <summary>Opens every database and applies the migration steps it has not had yet.</summary>
    public static Db OpenDatabases()
    {{
        var db = Db.Connect(Databases);
        foreach (var (source, steps) in Schema.Sources)
            db.MigrateSource(source, steps);
        return db;
    }}

    public static void Main()
    {{
        using var db = OpenDatabases();
        Console.WriteLine({ready});
    }}
}}
",
        ready = string(&format!("{name}: the databases are ready. Windows come with the Avalonia frontend."))
    )
}
