//! Custom parts drawn by a .NET library (DESIGN 5.19 and 6.5): an Avalonia
//! control from a NuGet package or a DLL, shown through the developer's
//! adapter, `parts/<Name>/<Name>.cs`, half of a partial class whose other
//! half is generated here from the part's declaration. A value, property or
//! hear the adapter does not show is a compile error, so an adapter that no
//! longer fits its declaration says so.

use std::fmt::Write;

use clarity_spec::Project;
use clarity_spec::code::{Param, PartDecl, PartLibrary};

use super::names::{pascal, string, value_type};

/// The namespace adapters and their generated halves are in.
pub const NAMESPACE: &str = "ClarityParts";

/// The project's parts drawn by .NET libraries.
pub fn dotnet_parts(project: &Project) -> Vec<&PartDecl> {
    project.files.iter().flat_map(|f| &f.parts).filter(|p| matches!(p.library, Some(PartLibrary::Nuget { .. } | PartLibrary::Dll { .. }))).collect()
}

fn ty(project: &Project, param: &clarity_spec::code::TypeRef) -> String {
    value_type(&crate::type_ref_info(project, param))
}

fn params(project: &Project, list: &[Param]) -> String {
    list.iter().map(|p| format!("{} {}", ty(project, &p.ty), super::names::camel(&p.name.name))).collect::<Vec<_>>().join(", ")
}

/// What the adapter shows, as the partial methods it writes: `ShowValue`,
/// `Show<Property>` and `On<Hear>`.
fn shows(project: &Project, part: &PartDecl) -> Vec<String> {
    let mut out = Vec::new();
    if let Some(binds) = &part.binds {
        out.push(format!("ShowValue({} value)", ty(project, binds)));
    }
    for property in &part.properties {
        out.push(format!("Show{}({} {})", pascal(&property.name.name), ty(project, &property.ty), super::names::camel(&property.name.name)));
    }
    for hear in &part.hears {
        out.push(format!("On{}({})", pascal(&hear.name.name), params(project, &hear.params)));
    }
    out
}

/// `Parts/<Name>.g.cs`: the generated half.
pub fn generated_half(project: &Project, part: &PartDecl) -> String {
    let n = &part.name.name;
    let mut out = format!(
        "// Generated by Clarity from custom part {n} (DESIGN 5.19). Do not edit: the\n// adapter beside it, {n}.cs, is yours; it writes the methods below.\n\n#nullable enable\n\nusing Clarity.Avalonia;\n\nnamespace {NAMESPACE};\n\npublic partial class {n} : DotNetPart\n{{\n"
    );
    for show in shows(project, part) {
        let _ = writeln!(out, "    private partial void {show};");
    }
    for tell in &part.tells {
        let names: Vec<String> = tell.params.iter().map(|p| super::names::camel(&p.name.name)).collect();
        let values = if names.is_empty() { String::new() } else { format!(", {}", names.join(", ")) };
        let _ = write!(out, "\n    /// <summary>Tells {}: its handler runs with these values.</summary>\n    protected void {}({}) => Tell({}{values});\n", tell.name.name, pascal(&tell.name.name), params(project, &tell.params), string(&tell.name.name));
    }
    if let Some(binds) = &part.binds {
        let _ = write!(out, "\n    /// <summary>The person changed the value: what the part binds takes it.</summary>\n    protected void Changed({} value) => ChangeValue(value);\n", ty(project, binds));
    }
    out.push_str("\n    protected override void Set(string name, object? value)\n    {\n        switch (name)\n        {\n");
    if let Some(binds) = &part.binds {
        let _ = writeln!(out, "            case \"value\":\n                ShowValue(As<{}>(value));\n                break;", ty(project, binds));
    }
    for property in &part.properties {
        let _ = writeln!(out, "            case {}:\n                Show{}(As<{}>(value));\n                break;", string(&property.name.name), pascal(&property.name.name), ty(project, &property.ty));
    }
    out.push_str("        }\n    }\n\n    protected override void Hear(string hear, object?[] values)\n    {\n        switch (hear)\n        {\n");
    for hear in &part.hears {
        let args: Vec<String> = hear.params.iter().enumerate().map(|(i, p)| format!("As<{}>(values.ElementAtOrDefault({i}))", ty(project, &p.ty))).collect();
        let _ = writeln!(out, "            case {}:\n                On{}({});\n                break;", string(&hear.name.name), pascal(&hear.name.name), args.join(", "));
    }
    out.push_str("        }\n    }\n}\n");
    out
}

/// The adapter a newly declared .NET part gets: it shows a placeholder and
/// writes every method the generated half asks for.
pub fn adapter_starter(project: &Project, part: &PartDecl) -> String {
    let n = &part.name.name;
    let library = match &part.library {
        Some(PartLibrary::Nuget { package, .. }) => format!("the {package} package"),
        Some(PartLibrary::Dll { file }) => file.clone(),
        _ => "its library".to_string(),
    };
    let mut out = format!(
        "// Custom part {n}: shows the control of {library} in the window. Keep the\n// methods the generated half ({n}.g.cs) asks for; they follow the part's\n// declaration. Call a tell, such as {}, to run its handler.\n\nusing Avalonia.Controls;\n\nnamespace {NAMESPACE};\n\npublic partial class {n}\n{{\n    // Stands in for the library's control until it is made here.\n    readonly TextBlock shown = new() {{ Text = {} }};\n\n    public {n}()\n    {{\n        Content = shown;\n    }}\n",
        part.tells.first().map_or("Changed(value)".to_string(), |t| format!("{}(...)", pascal(&t.name.name))),
        string(n)
    );
    for show in shows(project, part) {
        let body = if show.starts_with("ShowValue(") { " => shown.Text = value?.ToString() ?? \"\";".to_string() } else { "\n    {\n    }".to_string() };
        let _ = write!(out, "\n    private partial void {show}{body}\n");
    }
    out.push_str("}\n");
    out
}

/// The project file's lines for the .NET parts: each package, and each
/// assembly beside its adapter.
pub fn references(project: &Project) -> String {
    let mut out = String::new();
    for part in dotnet_parts(project) {
        match &part.library {
            Some(PartLibrary::Nuget { package, version }) => {
                let _ = writeln!(out, "    <PackageReference Include=\"{package}\" Version=\"{version}\" />");
            }
            Some(PartLibrary::Dll { file }) => {
                let name = std::path::Path::new(file).file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
                let stem = name.strip_suffix(".dll").unwrap_or(&name).to_string();
                let _ = writeln!(out, "    <Reference Include=\"{stem}\" HintPath=\"parts/{}/{name}\" />", part.name.name);
            }
            _ => {}
        }
    }
    if out.is_empty() { out } else { format!("  <ItemGroup>\n{out}  </ItemGroup>\n") }
}
