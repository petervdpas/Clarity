//! Custom parts on C# (DESIGN 5.19, 6.5, 7.9): a part declared with a .NET
//! library (a NuGet package or a DLL) is a custom control of Clarity.UI, a
//! class deriving from Clarity.UI's `CustomPart` that draws itself in its
//! place. It is a partial class in `parts/<Name>/`: the developer's adapter
//! (`<Name>.cs`) draws it with the library and passes values to it and from
//! it; the half generated here from the declaration (`<Name>.g.cs`) names it
//! for the windows that place it (`[PartKind("Name")]`), turns what the
//! window sets and code tells it into typed calls the adapter must write
//! (`ShowValue`, `Show<Property>`, `On<Hear>`), and gives the adapter a
//! method per tell and `Changed(value)`. A value, property or hear the
//! adapter does not show is a compile error, so an adapter that no longer
//! fits its declaration says so.

use std::fmt::Write;

use clarity_spec::Project;
use clarity_spec::code::{Param, PartDecl, PartLibrary};

use super::names::{camel, pascal, string, value_type};

/// The namespace adapters and their generated halves are in.
pub const NAMESPACE: &str = "ClarityParts";

/// The project's parts drawn by .NET libraries.
pub fn dotnet_parts(project: &Project) -> Vec<&PartDecl> {
    project.files.iter().flat_map(|f| &f.parts).filter(|p| matches!(p.library, Some(PartLibrary::Nuget { .. } | PartLibrary::Dll { .. }))).collect()
}

fn ty(project: &Project, param: &clarity_spec::code::TypeRef) -> String {
    value_type(&crate::type_ref_info(project, param))
}

fn params(project: &Project, list: &[Param]) -> String {
    list.iter().map(|p| format!("{} {}", ty(project, &p.ty), camel(&p.name.name))).collect::<Vec<_>>().join(", ")
}

/// What the adapter shows, as the partial methods it writes: `ShowValue`,
/// `Show<Property>` and `On<Hear>`.
fn shows(project: &Project, part: &PartDecl) -> Vec<String> {
    let mut out = Vec::new();
    if let Some(binds) = &part.binds {
        out.push(format!("ShowValue({} value)", ty(project, binds)));
    }
    for property in &part.properties {
        out.push(format!("Show{}({} {})", pascal(&property.name.name), ty(project, &property.ty), camel(&property.name.name)));
    }
    for hear in &part.hears {
        out.push(format!("On{}({})", pascal(&hear.name.name), params(project, &hear.params)));
    }
    out
}

/// The library a part's control comes from, in words.
fn library_words(part: &PartDecl) -> String {
    match &part.library {
        Some(PartLibrary::Nuget { package, .. }) => format!("the {package} package"),
        Some(PartLibrary::Dll { file }) => file.clone(),
        _ => "its library".to_string(),
    }
}

/// `parts/<Name>/<Name>.g.cs`: the generated half.
pub fn generated_half(project: &Project, part: &PartDecl) -> String {
    let n = &part.name.name;
    let mut out = format!(
        "// Generated by Clarity from custom part {n} (DESIGN 5.19, 7.9). Do not edit:\n// the adapter beside it, {n}.cs, is yours; it writes the methods below.\n\n#nullable enable\n\nusing Clarity.Ui;\n\nnamespace {NAMESPACE};\n\n/// <summary>Custom part {n}, a control of Clarity.UI: a window that places it finds it by its name.</summary>\n[PartKind({})]\npublic partial class {n} : CustomPart\n{{\n",
        string(n)
    );
    for show in shows(project, part) {
        let _ = writeln!(out, "    private partial void {show};");
    }
    for tell in &part.tells {
        let names: Vec<String> = tell.params.iter().map(|p| camel(&p.name.name)).collect();
        let values = if names.is_empty() { String::new() } else { format!(", {}", names.join(", ")) };
        let _ = write!(
            out,
            "\n    /// <summary>Tells {}: the handler wired to it runs with these values.</summary>\n    protected void {}({}) => Tell({}{values});\n",
            tell.name.name,
            pascal(&tell.name.name),
            params(project, &tell.params),
            string(&tell.name.name)
        );
    }
    if let Some(binds) = &part.binds {
        let _ = write!(out, "\n    /// <summary>The person changed the value: what the part binds takes it, and its change handler runs.</summary>\n    protected void Changed({} value) => ChangeValue(value);\n", ty(project, binds));
    }
    let mut sets = String::new();
    if let Some(binds) = &part.binds {
        let _ = writeln!(sets, "            case \"value\":\n                ShowValue(As<{}>(value));\n                break;", ty(project, binds));
    }
    for property in &part.properties {
        let _ = writeln!(sets, "            case {}:\n                Show{}(As<{}>(value));\n                break;", string(&property.name.name), pascal(&property.name.name), ty(project, &property.ty));
    }
    out.push_str(&method("protected override void Set(string name, object? value)", "name", &sets));
    let mut hears = String::new();
    for hear in &part.hears {
        let args: Vec<String> = hear.params.iter().enumerate().map(|(i, p)| format!("As<{}>(values.ElementAtOrDefault({i}))", ty(project, &p.ty))).collect();
        let _ = writeln!(hears, "            case {}:\n                On{}({});\n                break;", string(&hear.name.name), pascal(&hear.name.name), args.join(", "));
    }
    out.push_str(&method("protected override void Hear(string hear, object?[] values)", "hear", &hears));
    out.push_str("}\n");
    out
}

/// A method that switches on `on` over `cases`; empty without cases, as C# warns of an empty switch.
fn method(signature: &str, on: &str, cases: &str) -> String {
    if cases.is_empty() {
        format!("\n    {signature}\n    {{\n    }}\n")
    } else {
        format!("\n    {signature}\n    {{\n        switch ({on})\n        {{\n{cases}        }}\n    }}\n")
    }
}

/// The adapter a newly declared .NET part gets: a control that draws its
/// value in a frame, and every method the generated half asks for.
pub fn adapter_starter(project: &Project, part: &PartDecl) -> String {
    let n = &part.name.name;
    let tell = part.tells.first().map_or_else(|| "Changed(value)".to_string(), |t| format!("{}(...)", pascal(&t.name.name)));
    let mut out = format!(
        "// Custom part {n}: a control of Clarity.UI that shows the work of\n// {library} in its place in the window. It draws itself (Draw) and\n// takes the pointer and keys as any element does (OnClick, OnKey). Keep the\n// methods the generated half ({n}.g.cs) asks for; they follow the part's\n// declaration. Call a tell, such as {tell}, to run its handler.\n\nusing Clarity.Ui;\n\nnamespace {NAMESPACE};\n\npublic partial class {n}\n{{\n    // What it shows until it draws the library's work.\n    string shown = {};\n\n    public override void Draw(Painter painter)\n    {{\n        var look = painter.Look;\n        painter.Stroke(Bounds, look.Color(\"border\"), look.Border, look.Radius(\"input\"));\n        painter.Text(shown, Bounds.Inset(8), look.Color(\"text\"), look.Size(\"text\"));\n    }}\n",
        string(n),
        library = library_words(part),
    );
    for show in shows(project, part) {
        let body = if show.starts_with("ShowValue(") { "\n    {\n        shown = $\"{value}\";\n        Invalidate();\n    }".to_string() } else { "\n    {\n    }".to_string() };
        let _ = write!(out, "\n    private partial void {show}{body}\n");
    }
    out.push_str("}\n");
    out
}

/// The project file's lines for the .NET parts: each package, and each
/// assembly beside its adapter.
pub fn references(project: &Project) -> String {
    let mut out = String::new();
    for part in dotnet_parts(project) {
        match &part.library {
            Some(PartLibrary::Nuget { package, version }) => {
                let _ = writeln!(out, "    <PackageReference Include=\"{package}\" Version=\"{version}\" />");
            }
            Some(PartLibrary::Dll { file }) => {
                let name = std::path::Path::new(file).file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
                let stem = name.strip_suffix(".dll").unwrap_or(&name).to_string();
                let _ = writeln!(out, "    <Reference Include=\"{stem}\" HintPath=\"parts/{}/{name}\" />", part.name.name);
            }
            _ => {}
        }
    }
    if out.is_empty() { out } else { format!("  <ItemGroup>\n{out}  </ItemGroup>\n") }
}

/// The files of the .NET parts in the generated project: each part's own
/// files (its adapter, a DLL), and the half generated from its declaration.
pub fn files(project: &Project) -> Vec<crate::OutFile> {
    let mut files = Vec::new();
    for part in dotnet_parts(project) {
        let n = &part.name.name;
        let half = format!("{n}.g.cs");
        for file in project.part_files.iter().flatten().filter(|f| f.part == *n && f.path != half) {
            files.push(crate::OutFile { path: format!("parts/{n}/{}", file.path), text: String::new(), bytes: Some(file.bytes.clone().into()) });
        }
        files.push(crate::OutFile { path: format!("parts/{n}/{half}"), text: generated_half(project, part), bytes: None });
    }
    files
}

/// Types of Clarity.UI that are gone (the drawing and browser assemblies
/// before Clarity.UI was one library), which an adapter may still name.
const REMOVED_TYPES: [&str; 5] = ["CustomPlace", "PartSpec", "WindowMarkup", "ShapedText", "PartKinds"];

/// Members of the old CustomPart an adapter may still override.
const REMOVED_OVERRIDES: [&str; 2] = ["Arrange", "Made"];

/// Namespaces that are gone.
const REMOVED_NAMESPACES: [&str; 2] = ["Clarity.Ui.Browser", "Clarity.Ui.Drawing"];

/// What a .NET part's adapter lacks of `<Name>.g.cs`, or still uses that
/// Clarity.UI no longer has, read from its code without building it.
pub fn code_mismatches(project: &Project) -> Vec<String> {
    use crate::part_code::{Lang, after, before, find_word, sources, uses_name};
    let mut found = Vec::new();
    for p in dotnet_parts(project) {
        let n = &p.name.name;
        let half = format!("{n}.g.cs");
        let code = sources(project, p, Lang::CSharp, |path| path.ends_with(".cs") && path != half);
        if code.is_empty() {
            continue;
        }
        for show in shows(project, p) {
            let name = crate::part_code::first_word(&show);
            let written = code.iter().any(|s| find_word(&s.code, name).into_iter().any(|at| before(&s.code, at).ends_with("void") && after(&s.code, at + name.len()).starts_with('(')));
            if !written {
                found.push(format!("custom part {n}: its adapter {n}.cs does not write {name}, which {half} asks: write private partial void {show} {{ .. }}"));
            }
        }
        for name in REMOVED_TYPES {
            if let Some((k, at)) = uses_name(&code, name) {
                found.push(format!("custom part {n}: {} uses {name}, which Clarity.UI no longer has: a part is a CustomPart that draws itself (Draw)", code[k].at(at)));
            }
        }
        for source in &code {
            for name in REMOVED_OVERRIDES {
                let line_of = |at: usize| source.code[..at].rsplit('\n').next().unwrap_or_default().to_string();
                if let Some(at) = find_word(&source.code, name).into_iter().find(|&at| !find_word(&line_of(at), "override").is_empty() && after(&source.code, at + name.len()).starts_with('(')) {
                    found.push(format!("custom part {n}: {} overrides {name}, which CustomPart no longer has: Clarity.UI places the part (Bounds)", source.at(at)));
                }
            }
            for space in REMOVED_NAMESPACES {
                // `Clarity.Ui.Browser`, spaces between its names or not, and not a longer name.
                let names = |at: usize| {
                    let flat: String = source.code[at..].chars().filter(|c| !c.is_whitespace()).take(space.len() + 1).collect();
                    flat.starts_with(space) && !flat[space.len()..].starts_with(crate::part_code::is_ident)
                };
                if let Some(at) = find_word(&source.code, "Clarity").into_iter().find(|&at| names(at)) {
                    found.push(format!("custom part {n}: {} names {space}, which Clarity.UI no longer has: write using Clarity.Ui;", source.at(at)));
                }
            }
        }
    }
    found
}
