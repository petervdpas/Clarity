/// Whether the desktop program remembers a sign-in (`remember N days`), in the secret store.
fn remembers(project: &Project) -> bool {
    crate::signin::signin_plan(project).is_some_and(|p| p.remember_seconds.is_some())
}

/// The lines of openDatabases that name the people of the program after its
/// databases opened (Db.AddSignin); none without a `signin` block.
pub(crate) fn add_signin(project: &Project, settings: &Settings) -> String {
    let Some(plan) = crate::signin::signin_plan(project) else { return String::new() };
    let list = |items: &[String]| items.iter().map(|i| string(i)).collect::<Vec<_>>().join(", ");
    let source = if plan.source == project.default_source() { String::new() } else { format!("Source: {}, ", string(&plan.source)) };
    // `remember N days`: how long the desktop program keeps a sign-in; left out without the line.
    let mut remember = plan.remember_seconds.map(|seconds| format!(", RememberSeconds: {seconds}")).unwrap_or_default();
    // `when asked`: remembered only when the sign-in part's box is ticked; left out otherwise.
    if plan.remember_asks {
        remember.push_str(", RememberAsks: true");
    }
    let strategies = plan.strategies.iter().map(|(name, columns)| format!("{{Name: {}, Columns: []string{{{}}}}}", string(name), list(columns))).collect::<Vec<_>>().join(", ");
    // The program's name, under which the secret store keeps the remembered sign-in.
    let program = string(&crate::settings_program(settings));
    format!(
        "\tif err := db.AddSignin(clarity.SigninSource{{Program: {program}, {source}Table: {}, Key: {}, Page: {}, Targets: []string{{{}}}, Strategies: []clarity.SigninStrategy{{{strategies}}}, SessionSeconds: {}, Tries: {}, TriesSeconds: {}{remember}}}, authCall); err != nil {{\n\t\tdb.Close()\n\t\treturn nil, err\n\t}}\n",
        string(&plan.table),
        string(&plan.key),
        string(&plan.page),
        list(&plan.targets),
        plan.session_seconds,
        plan.tries,
        plan.tries_seconds
    )
}

