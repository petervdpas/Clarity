/// The groups of the runtime's packages a program imports, by the names
/// modules.txt records them under: the base always; the desktop window,
/// secret settings (DESIGN 5.27), engines (DESIGN 5.11) and each server
/// database only when the program uses them.
fn groups(project: &Project, servers: &[&Server], desktop: bool) -> Vec<&'static str> {
    let mut groups = vec!["base"];
    if desktop {
        groups.push("desktop");
    }
    if !project.secret_settings().is_empty() {
        groups.push("secrets");
    }
    if !crate::engines(project).is_empty() {
        groups.push("engine");
    }
    groups.extend(servers.iter().map(|s| s.package));
    groups
}

/// The recorded lines of `kind` (require or sum) of the groups.
fn recorded<'a>(groups: &'a [&str], kind: &'a str) -> impl Iterator<Item = &'static str> + 'a {
    MODULES.lines().filter_map(move |line| {
        let mut words = line.splitn(3, ' ');
        let (group, k, rest) = (words.next()?, words.next()?, words.next()?);
        (k == kind && groups.contains(&group)).then_some(rest)
    })
}

/// Whether version `a` is newer than `b`: by their numbers, then the rest.
fn newer(a: &str, b: &str) -> bool {
    let key = |v: &str| {
        let v = v.trim_start_matches('v');
        let (numbers, rest) = v.split_once('-').unwrap_or((v, ""));
        (numbers.split('.').map(|n| n.parse::<u64>().unwrap_or(0)).collect::<Vec<_>>(), rest.is_empty(), rest.to_string())
    };
    key(a) > key(b)
}

/// The module file: the runtime module, and the requirements of its
/// package groups the program imports, each at the newest version a group
/// needs; those the code imports itself (`direct`) first, the rest marked
/// indirect, as go mod tidy writes them.
fn go_mod(module: &str, groups: &[&str], direct: &[&str]) -> String {
    let go = RUNTIME_MOD.lines().find(|l| l.starts_with("go ")).unwrap_or("go 1.25");
    let mut requirements: Vec<(&str, &str)> = Vec::new();
    for line in recorded(groups, "require") {
        let Some((m, v)) = line.split_once(' ') else { continue };
        match requirements.iter_mut().find(|(have, _)| *have == m) {
            Some(found) if newer(v, found.1) => found.1 = v,
            Some(_) => {}
            None => requirements.push((m, v)),
        }
    }
    requirements.push((RUNTIME_MODULE, runtime_version()));
    requirements.sort();
    // One requirement stands on its own line, as go mod tidy writes it; more go in a block.
    let block = |lines: Vec<String>| match lines.as_slice() {
        [] => String::new(),
        [one] => format!("\nrequire {}", one.trim_start()),
        _ => format!("\nrequire (\n{})\n", lines.concat()),
    };
    let first = block(requirements.iter().filter(|(m, _)| direct.contains(m)).map(|(m, v)| format!("\t{m} {v}\n")).collect());
    let second = block(requirements.iter().filter(|(m, _)| !direct.contains(m)).map(|(m, v)| format!("\t{m} {v} // indirect\n")).collect());
    format!("// Code generated by Clarity. DO NOT EDIT: change the project in Clarity instead.\nmodule {module}\n\n{go}\n{first}{second}")
}

/// The sums of the modules of the package groups the program imports, and
/// those of the runtime module itself once its version is published.
fn go_sum(groups: &[&str]) -> String {
    let runtime = format!("{RUNTIME_MODULE} {} ", runtime_version());
    let own = format!("{RUNTIME_MODULE} {}/go.mod ", runtime_version());
    let published = RUNTIME_PUBLISHED.lines().filter(|l| l.starts_with(&runtime) || l.starts_with(&own));
    let mut lines: Vec<&str> = recorded(groups, "sum").chain(published).collect();
    lines.sort();
    lines.dedup();
    lines.iter().map(|l| format!("{l}\n")).collect()
}

/// A Go file of package main: its body and the imports it uses, as Go
/// refuses an import that is not used.
fn go_file(body: &str) -> String {
    go_file_with(body, &[])
}

/// As `go_file`, with the libraries the body may call (DESIGN 5.21): their
/// package's name in the code, and its module.
pub(crate) fn go_file_with(body: &str, libraries: &[(String, String)]) -> String {
    let mut imports = Vec::new();
    if body.contains("slices.") {
        imports.push("\t\"slices\"\n".to_string());
    }
    if body.contains("sync.") {
        imports.push("\t\"sync\"\n".to_string());
    }
    // In the order gofmt keeps: by path.
    let mut third = Vec::new();
    if body.contains("clarity.") {
        third.push(format!("\t\"{RUNTIME_MODULE}/clarity\"\n"));
    }
    if body.contains("decimal.") {
        third.push("\t\"github.com/shopspring/decimal\"\n".to_string());
    }
    for (alias, module) in libraries {
        if body.contains(&format!("{alias}.")) {
            third.push(format!("\t{alias} \"{module}\"\n"));
        }
    }
    third.sort_by_key(|line| line.split('"').nth(1).unwrap_or_default().to_string());
    let mut block = imports.concat();
    if !imports.is_empty() && !third.is_empty() {
        block.push('\n');
    }
    block.push_str(&third.concat());
    let imports = if block.is_empty() { String::new() } else { format!("import (\n{block})\n\n") };
    let body = body.trim_end();
    if body.is_empty() {
        return format!("{HEADER}\npackage main\n");
    }
    format!("{HEADER}\npackage main\n\n{imports}{body}\n")
}

/// The libraries' packages as the code names them (`wordslib`), with their modules.
fn library_imports(project: &Project) -> Vec<(String, String)> {
    crate::libraries::libraries(project)
        .into_iter()
        .map(|l| (format!("{}lib", crate::libraries::go_package(&l.name.name)), crate::libraries::go_module(project, &l.name.name)))
        .collect()
}

/// The runtime's name for a database kind.
fn dialect(sql: Sql) -> &'static str {
    match sql {
        Sql::Sqlite => "clarity.Sqlite",
        Sql::Postgres => "clarity.Postgres",
        Sql::Mysql => "clarity.Mysql",
        Sql::Mssql => "clarity.Mssql",
    }
}

/// A statement as a Go raw string, or a quoted one when it holds a backquote.
fn raw(text: &str) -> String {
    if text.contains('`') { string(text) } else { format!("`{text}`") }
}

/// The steps of every database Clarity owns, as SQL per data source.
fn schema_go(project: &Project, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut body = String::from(
        "// SourceSteps are the migration steps of one data source, in order, each a\n// list of statements. Each database remembers how many steps it has applied,\n// and applies the rest when the application starts.\ntype SourceSteps struct {\n\tSource string\n\tSteps  [][]string\n}\n\n// Sources are the steps of every database Clarity owns.\nvar Sources = []SourceSteps{\n",
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        body.push_str(&format!("\t{{{}, [][]string{{\n", string(source)));
        for (i, (title, statements)) in steps.iter().enumerate() {
            body.push_str(&format!("\t\t// {}: {title}\n", i + 1));
            // A step with nothing to do on this database (SQL Server keeps
            // no search index) closes on the line it opens, as gofmt writes it.
            if statements.is_empty() {
                body.push_str("\t\t{},\n");
                continue;
            }
            body.push_str("\t\t{\n");
            for statement in statements {
                body.push_str(&format!("\t\t\t{},\n", raw(statement)));
            }
            body.push_str("\t\t},\n");
        }
        body.push_str("\t}},\n");
    }
    body.push_str("}\n");
    // Empty lists close on the line they open, as gofmt writes them.
    let body = body.replace("[][]string{\n\t}}", "[][]string{}}").replace("[]SourceSteps{\n}", "[]SourceSteps{}");
    if errors.is_empty() { Ok(go_file(&body)) } else { Err(errors) }
}

/// The program: it opens the database of every data source, brings
/// Clarity's own up to date, and shows the main window in the shell; the
/// shell asks the program's `windows` for their data and handlers.
/// `--check` stops after the databases.
fn main_go(project: &Project, settings: &Settings, databases: &[(String, Sql, String)], servers: &[&Server], owners: &[logic::Owner], main_window: &str) -> String {
    // The program's custom parts, for the part host (DESIGN 5.19).
    let register_parts = if parts::go_parts(project).is_empty() { "" } else { "\tregisterParts()\n" };
    // The runtime's packages and Wails, by path as gofmt keeps them; a server
    // database's package turns its driver on when it is imported.
    let mut imports: Vec<(String, String)> = vec![(format!("{RUNTIME_MODULE}/clarity"), String::new()), (format!("{RUNTIME_MODULE}/shell"), String::new())];
    // The desktop window and its Wails service; a program served to a browser alone has neither.
    let desktop = has_desktop(settings);
    if desktop {
        imports.push((format!("{RUNTIME_MODULE}/desktop"), String::new()));
        imports.push(("github.com/wailsapp/wails/v3/pkg/application".to_string(), String::new()));
    }
    let bind = if desktop {
        "// Clarity is the service the renderer calls, as main.Clarity.Invoke.\ntype Clarity struct {\n\t*shell.Service\n}\n\n// bind makes the Wails service of the shell's service.\nfunc bind(s *shell.Service) application.Service {\n\treturn application.NewService(&Clarity{s})\n}\n\n"
    } else {
        ""
    };
    imports.extend(servers.iter().map(|s| (format!("{RUNTIME_MODULE}/{}", s.package), "_ ".to_string())));
    // Secret settings (DESIGN 5.27): the system's protected store, set before anything reads a setting.
    let use_secrets = if project.secret_settings().is_empty() {
        ""
    } else {
        imports.push((format!("{RUNTIME_MODULE}/secrets"), String::new()));
        "\t// The secret settings are kept in the system's protected store (DESIGN 5.27).\n\tclarity.Secrets = secrets.System{}\n"
    };
    // A decimal value a click gives is written into the dispatch.
    if owners.iter().flat_map(|o| &o.calls).flat_map(|(_, _, values)| values).any(|v| v.starts_with("decimal.")) {
        imports.push(("github.com/shopspring/decimal".to_string(), String::new()));
    }
    imports.sort();
    let imports: String = imports.iter().map(|(path, name)| format!("\t{name}\"{path}\"\n")).collect();
    let sources = databases
        .iter()
        .map(|(name, sql, at)| format!("{{Name: {}, Dialect: {}, At: {}}}", string(name), dialect(*sql), string(at)))
        .collect::<Vec<_>>()
        .join(", ");
    let ready = string(&format!("{}: the databases are ready.", pascal(&settings.name)));
    // The web target (DESIGN 7.3): a server, by itself or with `--serve` beside the desktop window.
    let run = "\tif err := desktop.Run(options, bind); err != nil {\n\t\tfmt.Fprintln(os.Stderr, err)\n\t\tos.Exit(1)\n\t}\n";
    // Where it listens: the project's port, unless started with --address or CLARITY_ADDRESS.
    let serve = format!(
        "\tif err := shell.Serve(options, shell.Address(os.Args[1:], {})); err != nil {{\n\t\tfmt.Fprintln(os.Stderr, err)\n\t\tos.Exit(1)\n\t}}\n",
        string(&clarity_project::serve_address(settings))
    );
    let serve = serve.as_str();
    let targets = &settings.stack.targets;
    let serve = match (targets.contains(&clarity_project::Target::Web), targets.contains(&clarity_project::Target::Desktop)) {
        (true, false) => serve.to_string(),
        (true, true) => format!("\t// --serve runs it as a web server, for a browser, in place of its window.\n\tif slices.Contains(os.Args[1:], \"--serve\") {{\n\t{}\t\treturn\n\t}}\n{run}", serve.replace("\n\t", "\n\t\t")),
        _ => run.to_string(),
    };
    // An engine whose file does not fit its declaration stops the application at start.
    let check_engines = if crate::engines(project).is_empty() {
        String::new()
    } else {
        "\tif err := checkEngines(); err != nil {\n\t\tfmt.Fprintln(os.Stderr, err)\n\t\tos.Exit(1)\n\t}\n".to_string()
    };
    let stores = settings.filestores.iter().map(|s| format!("{}: {}", string(&s.name), string(&s.location))).collect::<Vec<_>>().join(", ");
    let cases: String = crate::picture_fields(project)
        .iter()
        .map(|(e, f)| {
            format!(
                "\tcase {}:\n\t\treturn clarity.PictureOf[{}](db, id, {})\n",
                string(&format!("{}.{}", e.name.name, f.name.name)),
                e.name.name,
                string(e.column_of(&f.name.name))
            )
        })
        .collect();
    let pictures = if cases.is_empty() { String::new() } else { format!("\tswitch entity + \".\" + field {{\n{cases}\t}}\n") };
    let windows: Vec<&logic::Owner> = owners.iter().filter(|o| !o.is_app).collect();
    let apps: Vec<&logic::Owner> = owners.iter().filter(|o| o.is_app).collect();

    let mut open = String::new();
    for w in &windows {
        open.push_str(&format!(
            "\tcase {}:\n\t\tw, err := load{}(db)\n\t\tif err != nil {{\n\t\t\treturn clarity.WindowState{{}}, err\n\t\t}}\n\t\treturn clarity.Opened(window, w, with)\n",
            string(&w.name),
            w.struct_name
        ));
    }
    let mut events = String::new();
    for w in windows.iter().filter(|w| !w.events.is_empty()) {
        events.push_str(&format!("\tcase {}:\n\t\tswitch event {{\n", string(&w.name)));
        for (event, handler) in &w.events {
            events.push_str(&format!("\t\tcase {}:\n\t\t\treturn {}, true\n", string(event), string(handler)));
        }
        events.push_str("\t\t}\n");
    }
    let mut app_events = String::new();
    for (event, handler) in apps.iter().flat_map(|a| &a.events) {
        app_events.push_str(&format!("\tcase {}:\n\t\treturn {}, true\n", string(event), string(handler)));
    }
    // Each window that has canvases to draw.
    let mut redraws = String::new();
    for w in windows.iter().filter(|w| !w.draws.is_empty()) {
        let draws: String = w
            .draws
            .iter()
            .map(|(canvas, method)| format!("\t\tui.BeginDrawing({})\n\t\tif err := w.{method}(db, ui); err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n", string(canvas)))
            .collect();
        redraws.push_str(&format!(
            "\tcase {}:\n\t\tw := &{}{{}}\n\t\tif err := reply.State.Decode(w); err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n\t\tui := clarity.NewUi(reply.State)\n{draws}\t\tdrawn, err := ui.Reply(reply.State.Window, w)\n\t\tif err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n\t\treply.State.Parts = drawn.State.Parts\n",
            string(&w.name),
            w.struct_name
        ));
    }
    let mut dispatch = String::new();
    for w in windows.iter().filter(|w| !w.handlers.is_empty() || !w.calls.is_empty()) {
        dispatch.push_str(&format!("\tcase {}:\n\t\tswitch handler {{\n", string(&w.name)));
        for (handler, method) in &w.handlers {
            dispatch.push_str(&format!(
                "\t\tcase {}:\n\t\t\tw := &{}{{}}\n\t\t\tif err := state.Decode(w); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\tif err := w.{method}(db, ui); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\treturn ui.Reply(state.Window, w)\n",
                string(handler),
                w.struct_name
            ));
        }
        // The calls with values its parts wire, by their written form.
        for (call, method, values) in &w.calls {
            let values: String = values.iter().map(|v| format!(", {v}")).collect();
            dispatch.push_str(&format!(
                "\t\tcase {}:\n\t\t\tw := &{}{{}}\n\t\t\tif err := state.Decode(w); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\tif err := w.{method}(db, ui{values}); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\treturn ui.Reply(state.Window, w)\n",
                string(call),
                w.struct_name
            ));
        }
        dispatch.push_str("\t\t}\n");
    }
    // The handlers an answer runs, with the values written for them and the answer (DESIGN 5.14).
    let mut answers = String::new();
    for w in windows.iter().filter(|w| !w.answers.is_empty()) {
        answers.push_str(&format!("\tcase {}:\n\t\tswitch handler {{\n", string(&w.name)));
        for (handler, method, values) in &w.answers {
            let mut decode = String::new();
            let mut passed = String::new();
            for (i, value) in values.iter().enumerate() {
                let (call, pass) = match value {
                    logic::AnswerValue::Record(entity) => (format!("clarity.AnswerRecord[{entity}](db, values[{i}])"), format!("&v{i}")),
                    logic::AnswerValue::Value(ty) => (format!("clarity.Answer[{ty}](values[{i}])"), format!("v{i}")),
                };
                decode.push_str(&format!("\t\t\tv{i}, err := {call}\n\t\t\tif err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n"));
                passed.push_str(&format!(", {pass}"));
            }
            answers.push_str(&format!(
                "\t\tcase {}:\n\t\t\tif len(values) < {} {{\n\t\t\t\treturn clarity.Reply{{}}, &clarity.InvalidError{{What: handler + \" takes more values than the answer gave\"}}\n\t\t\t}}\n\t\t\tw := &{}{{}}\n\t\t\tif err := state.Decode(w); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n{decode}\t\t\tif err := w.{method}(db, ui{passed}); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\treturn ui.Reply(state.Window, w)\n",
                string(handler),
                values.len(),
                w.struct_name
            ));
        }
        answers.push_str("\t\t}\n");
    }
    // The app's `on unconnected` runs with why the databases did not open, on
    // empty app data: there are no records to load (DESIGN 5.27).
    let unconnected = crate::unconnected(project);
    if let Some((app, handler)) = unconnected.as_ref().and_then(|u| u.handler.clone())
        && let Some(a) = apps.iter().find(|a| a.name == app)
    {
        let (decode, passed) = if crate::unconnected_takes_reason(project, &app, &handler) {
            ("\t\t\treason, err := clarity.Answer[string](values[0])\n\t\t\tif err != nil {\n\t\t\t\treturn clarity.Reply{}, err\n\t\t\t}\n", ", reason")
        } else {
            ("", "")
        };
        answers.push_str(&format!(
            "\tcase \"\":\n\t\tswitch handler {{\n\t\tcase {}:\n\t\t\tif len(values) < 1 {{\n\t\t\t\treturn clarity.Reply{{}}, &clarity.InvalidError{{What: handler + \" takes why the databases did not open\"}}\n\t\t\t}}\n\t\t\tapp := &{}{{}}\n{decode}\t\t\tif err := app.{}(db, ui{passed}); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\treturn ui.Reply(state.Window, state.Data)\n\t\t}}\n",
            string(&handler),
            a.struct_name,
            names::local(&handler)
        ));
    }
    let (unconnected_open, unconnected_options) = match &unconnected {
        None => (String::new(), String::new()),
        Some(u) => (
            format!(
                "\t// The databases did not open (DESIGN 5.27): the windows work on an empty one in\n\t// memory, and the screen shows what keeps the connection first.\n\tvar unconnected *shell.Unconnected\n\tif err != nil && !slices.Contains(os.Args[1:], \"--check\") {{\n\t\tunconnected = &shell.Unconnected{{Handler: {}, Window: {}, Problem: clarity.UnconnectedReason(err)}}\n\t\tdb, err = clarity.Memory()\n\t}}\n",
                string(u.handler.as_ref().map(|(_, h)| h.as_str()).unwrap_or_default()),
                string(u.window.as_deref().unwrap_or_default())
            ),
            ", Unconnected: unconnected, Connect: openDatabases".to_string(),
        ),
    };
    let mut app_dispatch = String::new();
    for a in &apps {
        for (handler, method) in &a.handlers {
            app_dispatch.push_str(&format!(
                "\tcase {}:\n\t\tapp, err := load{}(db)\n\t\tif err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n\t\tif err := app.{method}(db, ui); err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n\t\treturn ui.Reply(state.Window, state.Data)\n",
                string(handler),
                a.struct_name
            ));
        }
    }
    let needs = crate::dropdown_needs(project);
    let mut values = String::new();
    for (entity, field) in &needs.typed {
        values.push_str(&format!(
            "\tcase {} + \".\" + {}:\n\t\trows, err := clarity.All[{entity}](db)\n\t\tif err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n\t\tfor _, r := range rows {{\n\t\t\tvalues = append(values, r.{})\n\t\t}}\n",
            string(entity),
            string(field),
            names::field(field)
        ));
    }
    let mut options = String::new();
    for entity in project.stored_entities() {
        let name = &entity.name.name;
        let shown = entity
            .fields
            .iter()
            .find(|f| matches!(f.ty, FieldType::Text { .. } | FieldType::Email))
            .map_or_else(|| "fmt.Sprintf(\"#%d\", r.ID)".to_string(), |f| format!("r.{}", names::field(&f.name.name)));
        options.push_str(&format!(
            "\tcase {}:\n\t\trows, err := clarity.All[{name}](db)\n\t\tif err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n\t\tfor _, r := range rows {{\n\t\t\toptions = append(options, clarity.RefOption{{ID: r.ID, Text: {shown}{fields}}})\n\t\t}}\n",
            string(name),
            // The fields a search dropdown shows of each record.
            fields = match needs.shown.get(name).filter(|f| !f.is_empty()) {
                Some(shown) => format!(", Fields: map[string]any{{{}}}", shown.iter().map(|f| format!("{}: r.{}", string(f), names::field(f))).collect::<Vec<_>>().join(", ")),
                None => String::new(),
            }
        ));
    }
    let title = string(&clarity_project::title(settings));
    // The desktop window opens at the main window's size.
    let (width, height) = crate::window_size(project, main_window);
    let main_window = string(main_window);
    // The settings and secrets are kept under the program's own name, alike on every stack.
    let program_text = string(&crate::settings_program(settings));
    // Without a handler anywhere, Dispatch has no use for the screen.
    let new_ui = if dispatch.is_empty() && app_dispatch.is_empty() { "" } else { "\tui := clarity.NewUi(state)\n" };
    format!(
        "{HEADER}
package main

import (
\t\"embed\"
\t\"encoding/json\"
\t\"fmt\"
\t\"io/fs\"
\t\"os\"
\t\"slices\"

{imports})

// renderer is the web renderer every web stack ships, with the themes.
//
//go:embed ui
var renderer embed.FS

// model is the windows, frame and data dictionary the renderer draws from.
//
//go:embed model.json
var model []byte

// databases is the database of each data source: its name, its kind and where it is.
var databases = []clarity.Source{{{sources}}}

// stores is the folder of each file store, which keeps the pictures of image
// fields kept as files.
var stores = map[string]string{{{stores}}}

// openDatabases opens every database and applies the migration steps it has not had yet.
func openDatabases() (*clarity.Db, error) {{
\tdb, err := clarity.Connect(databases...)
\tif err != nil {{
\t\treturn nil, err
\t}}
\tfor _, s := range Sources {{
\t\tif _, err := db.MigrateSource(s.Source, s.Steps); err != nil {{
\t\t\tdb.Close()
\t\t\treturn nil, err
\t\t}}
\t}}
\tfor name, at := range stores {{
\t\tif err := db.AddStore(name, at); err != nil {{
\t\t\tdb.Close()
\t\t\treturn nil, err
\t\t}}
\t}}
\treturn db, nil
}}

{bind}// windows is what the shell asks of the application's windows.
type windows struct{{}}

// Open is the state of window when it opens, with with filled in.
func (windows) Open(db *clarity.Db, window string, with map[string]any) (clarity.WindowState, error) {{
\tswitch window {{
{open}\t}}
\treturn clarity.WindowState{{}}, &clarity.InvalidError{{What: \"there is no window \" + window}}
}}

// Handler is the handler of a window's or the app's own event, if it has one.
func (windows) Handler(window, event string) (string, bool) {{
\tswitch window {{
{events}\t}}
\t// The app's own events run whatever window is given.
\tswitch event {{
{app_events}\t}}
\treturn \"\", false
}}

// Dispatch runs a handler on a window's state.
func (windows) Dispatch(db *clarity.Db, state clarity.WindowState, handler string) (clarity.Reply, error) {{
{new_ui}\tswitch state.Window {{
{dispatch}\t}}
\t// The app's handlers run from any window, on the app's own data.
\tswitch handler {{
{app_dispatch}\t}}
\treturn clarity.Reply{{}}, &clarity.InvalidError{{What: state.Window + \" has no handler \" + handler}}
}}

// Answer runs the handler the answer to a question goes to (DESIGN 5.14),
// with the values written for it and the answer last.
func (windows) Answer(db *clarity.Db, state clarity.WindowState, handler string, values []json.RawMessage) (clarity.Reply, error) {{
\tui := clarity.NewUi(state)
\t_ = ui
\tswitch state.Window {{
{answers}\t}}
\treturn clarity.Reply{{}}, &clarity.InvalidError{{What: state.Window + \" has no handler \" + handler + \" to answer\"}}
}}

// Redraw draws the canvases of the window a reply shows anew, each by its
// draw handler on an empty drawing (conformance/drawing.json).
func (windows) Redraw(db *clarity.Db, reply clarity.Reply) (clarity.Reply, error) {{
\tswitch reply.State.Window {{
{redraws}\t}}
\treturn reply, nil
}}

// Options are the records a reference field of entity can point at.
func (windows) Options(db *clarity.Db, entity string) ([]clarity.RefOption, error) {{
\toptions := []clarity.RefOption{{}}
\tswitch entity {{
{options}\t}}
\treturn options, nil
}}

// Values are the values a text field already has, which a typed dropdown offers.
func (windows) Values(db *clarity.Db, entity, field string) ([]string, error) {{
\tvalues := []string{{}}
\tswitch entity + \".\" + field {{
{values}\t}}
\treturn values, nil
}}

// Picture is the picture of an image field of a record; nil when it has none.
func (windows) Picture(db *clarity.Db, entity string, id int64, field string) ([]byte, error) {{
{pictures}\treturn nil, &clarity.InvalidError{{What: entity + \" has no picture \" + field}}
}}

func main() {{
{use_secrets}{check_engines}\tdb, err := openDatabases()
{unconnected_open}\tif err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(1)
\t}}
\tdefer db.Close()
\t// --check opens and migrates the databases without windows, for builds and scripts.
\tif slices.Contains(os.Args[1:], \"--check\") {{
\t\tfmt.Println({ready})
\t\treturn
\t}}
\tassets, err := fs.Sub(renderer, \"ui\")
\tif err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(1)
\t}}
{register_parts}\toptions := shell.Options{{Name: {program_text}, Title: {title}, Main: {main_window}, Width: {width}, Height: {height}, Model: model, Assets: assets, Db: db, Windows: windows{{}}{unconnected_options}}}
{serve}}}
"
    )
}

/// Whether the program has a desktop window: a program served to a browser
/// alone (the web target) has none.
fn has_desktop(settings: &Settings) -> bool {
    settings.stack.targets.contains(&clarity_project::Target::Desktop)
}
