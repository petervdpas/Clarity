/// The first line of every generated Go file, as Go marks generated code.
const HEADER: &str = "// Code generated by Clarity. DO NOT EDIT: change the project in Clarity instead.\n";

/// Clarity's Go runtime module.
pub const RUNTIME_MODULE: &str = "github.com/petervdpas/Clarity/runtimes/go";

/// The runtime's version constant, which names the version a module requires.
const RUNTIME_VERSION_GO: &str = include_str!("../../../../runtimes/go/clarity/version.go");

/// The version of the runtime module a generated module requires: the one
/// the runtime in this repository is (clarity.Version).
pub fn runtime_version() -> &'static str {
    let start = RUNTIME_VERSION_GO.find("const Version = \"").expect("version.go sets Version") + "const Version = \"".len();
    let end = RUNTIME_VERSION_GO[start..].find('"').expect("the Version is closed");
    &RUNTIME_VERSION_GO[start..start + end]
}

/// The sums of each published version of the runtime module, recorded when
/// it is published, so a generated go.sum holds them.
const RUNTIME_PUBLISHED: &str = include_str!("runtime.sum");

/// A server database's package in the runtime module, and the modules only
/// it needs: a module that no driver of the application uses is left out of
/// its go.mod and go.sum. go_build's `go mod tidy -diff` keeps these lists true.
struct Server {
    sql: Sql,
    /// The package that turns the driver on when it is imported.
    package: &'static str,
}


const SERVERS: [Server; 3] = [
    Server {
        sql: Sql::Postgres,
        package: "postgresql",
    },
    Server {
        sql: Sql::Mysql,
        package: "mysql",
    },
    Server {
        sql: Sql::Mssql,
        package: "sqlserver",
    },
];

/// The runtime's module file, whose requirements the application takes over.
const RUNTIME_MOD: &str = include_str!("../../../../runtimes/go/go.mod");
/// The modules each group of the runtime's packages needs, with their sums,
/// as go mod tidy picks them (recorded by a go_build test).
const MODULES: &str = include_str!("modules.txt");

/// The name of the generated module and program.
pub fn module_name(settings: &Settings) -> String {
    names::module(&settings.name)
}

pub use cli::generate as generate_cli;

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let module = module_name(settings);
    let project = &crate::with_secret_settings(project, &crate::settings_program(settings));
    let (databases, owned) = crate::databases(project, settings)?;
    let databases = crate::with_secret_locations(databases, &crate::settings_program(settings));
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let servers: Vec<&Server> = SERVERS.iter().filter(|s| databases.iter().any(|(_, sql, _)| *sql == s.sql)).collect();
    let engines = crate::engines(project);
    // A program served to a browser alone links nothing of the desktop toolkit.
    let desktop = has_desktop(settings);
    let groups = groups(project, &servers, desktop);
    let mut files = vec![text("model.json", crate::web::model_json(project))];
    files.extend(crate::web::renderer_files(project));
    let mut owners = Vec::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let mut body = model::emit(project, file);
        match logic::emit(project, file, &file_types) {
            Ok(functions) => body.push_str(&functions),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types) {
            Ok((windows, mut found)) => {
                body.push_str(&windows);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("{}_module.go", names::module(&m.name)), go_file_with(&body, &library_imports(project))));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("schema.go", schema_go(project, &owned)?));
    if !engines.is_empty() {
        files.extend(crate::engine_files(project, "engines"));
        files.push(text("engines.go", engines_go(project)));
    }
    // Each library's module, its function types written from its declaration (DESIGN 5.21).
    for library in crate::libraries::libraries(project) {
        let n = &library.name.name;
        let own = crate::libraries::own_file(library, false);
        files.extend(crate::libraries::adapter_files(project, n, &own));
        files.push(text(&format!("{}/{own}", crate::libraries::folder(n)), crate::libraries::go_interface(library)));
    }
    // Each custom part's module, its interface written from its declaration, and the glue that makes it.
    let go_parts = parts::go_parts(project);
    for (part, folder) in &go_parts {
        let n = &part.name.name;
        let into = parts::out_folder(folder);
        for file in project.part_files.iter().flatten().filter(|f| f.part == *n && f.path != "clarity.go") {
            files.push(OutFile { path: format!("{into}/{}", file.path), text: String::new(), bytes: Some(file.bytes.clone().into()) });
        }
        files.push(text(&format!("{into}/clarity.go"), parts::interface(part, folder)));
    }
    if !go_parts.is_empty() {
        files.push(text("parts.go", parts::glue(project)));
    }
    files.push(text("main.go", main_go(project, settings, &databases, &servers, &owners, &main_window)));
    // The modules the code imports itself, which go.mod lists as direct.
    let mut direct = vec![RUNTIME_MODULE];
    if desktop {
        direct.push("github.com/wailsapp/wails/v3");
    }
    if files.iter().any(|f| f.path.ends_with(".go") && f.text.contains("\t\"github.com/shopspring/decimal\"\n")) {
        direct.push("github.com/shopspring/decimal");
    }
    let mut go_mod_text = go_mod(&module, &groups, &direct);
    // Each library is a module of its own beside the program's, as each part is (DESIGN 5.21).
    let required: Vec<String> = go_mod_text.lines().filter_map(|l| l.trim().split_whitespace().next().map(String::from)).collect();
    let mut library_sums = String::new();
    for library in crate::libraries::libraries(project) {
        let n = &library.name.name;
        let path = crate::libraries::go_module(project, n);
        let mut lines = format!("\t{path} v0.0.0\n");
        for (module, version) in crate::libraries::go_requirements(project, n) {
            if !required.contains(&module) {
                lines.push_str(&format!("\t{module} {version} // indirect\n"));
            }
        }
        go_mod_text.push_str(&format!("\nrequire (\n{lines})\n\nreplace {path} => ./{}\n", crate::libraries::folder(n)));
        library_sums.push_str(&crate::libraries::go_sums(project, n));
    }
    // Each part is a module of its own beside the program's; what it requires, and its sums, the program's too.
    let mut part_sums = String::new();
    for (part, folder) in &go_parts {
        let path = parts::module_of(project, &part.name.name, folder);
        let mut lines = format!("\t{path} v0.0.0\n");
        for (module, version) in parts::requirements_of(project, &part.name.name) {
            lines.push_str(&format!("\t{module} {version} // indirect\n"));
        }
        go_mod_text.push_str(&format!("\nrequire (\n{lines})\n\nreplace {path} => ./{}\n", parts::out_folder(folder)));
        part_sums.push_str(&parts::sums_of(project, &part.name.name));
    }
    files.push(text("go.mod", go_mod_text));
    files.push(text("go.sum", go_sum(&groups) + &part_sums + &library_sums));
    Ok(files)
}

/// The modules only engines need, which an application without an engine
/// leaves out of its go.mod and go.sum.
/// The engines of the application (DESIGN 5.11): each embedded, loaded once,
/// and checked when the application starts; a typed function for each of
/// their functions, which code calls like any call that can fail.
fn engines_go(project: &Project) -> String {
    let mut body = String::new();
    let mut checks = String::new();
    for engine in crate::engines(project) {
        let var = names::local(&engine.name.name);
        let names: Vec<String> = engine.functions.iter().map(|f| string(&f.name.name)).collect();
        body.push_str(&format!(
            "//go:embed engines/{file}\nvar {var}Wasm []byte\n\n// {var} is engine {name}, from {file}.\nvar {var} = sync.OnceValues(func() (*engine.Engine, error) {{\n\treturn engine.Load({}, {var}Wasm, engine.Declaration{{Functions: []string{{{}}}, Uses: []string{{{uses}}}, Limits: engine.Limits{{Seconds: {seconds}, Megabytes: {megabytes}}}, State: {state}, Opens: {opens}}})\n}})\n\n",
            string(&engine.name.name),
            names.join(", "),
            uses = engine.uses.iter().map(|u| string(&u.name)).collect::<Vec<_>>().join(", "),
            seconds = engine.seconds(),
            megabytes = engine.megabytes(),
            state = match engine.state {
                clarity_spec::code::EngineState::None => "engine.NoState",
                clarity_spec::code::EngineState::App => "engine.PerApp",
                clarity_spec::code::EngineState::Window => "engine.PerWindow",
            },
            opens = engine.opens,
            file = engine.file,
            name = engine.name.name
        ));
        checks.push_str(&format!("\tif _, err := {var}(); err != nil {{\n\t\treturn err\n\t}}\n"));
        // An engine with state per window is called in a window: its wrappers take the window's number.
        let per_window = engine.state == clarity_spec::code::EngineState::Window;
        for function in &engine.functions {
            let window = per_window.then(|| "window uint64".to_string());
            let params: Vec<String> =
                window.into_iter().chain(function.params.iter().map(|p| format!("{} {}", names::local(&p.name.name), names::value_type(&logic::type_ref_info(project, &p.ty))))).collect();
            let args: Vec<String> = per_window
                .then(|| "window".to_string())
                .into_iter()
                .chain(std::iter::once(string(&function.name.name)))
                .chain(function.params.iter().map(|p| names::local(&p.name.name)))
                .collect();
            let call = if per_window { "CallIn" } else { "Call" };
            let returns = function.returns.as_ref().map_or("any".to_string(), |r| names::value_type(&logic::type_ref_info(project, r)));
            body.push_str(&format!(
                "// {wrapper} calls {name}.{f}.\nfunc {wrapper}({}) ({returns}, error) {{\n\te, err := {var}()\n\tif err != nil {{\n\t\tvar none {returns}\n\t\treturn none, err\n\t}}\n\treturn engine.As[{returns}](e.{call}({}))\n}}\n\n",
                params.join(", "),
                args.join(", "),
                wrapper = engine_function(&engine.name.name, &function.name.name),
                name = engine.name.name,
                f = function.name.name,
            ));
        }
    }
    let decimal = if body.contains("decimal.") { "\n\t\"github.com/shopspring/decimal\"" } else { "" };
    format!(
        "// Code generated by Clarity. DO NOT EDIT: change the project in Clarity instead.\n\npackage main\n\nimport (\n\t_ \"embed\"\n\t\"sync\"\n\n\t\"{RUNTIME_MODULE}/engine\"{decimal}\n)\n\n{body}// checkEngines loads every engine, so one whose file does not fit stops the application at start.\nfunc checkEngines() error {{\n{checks}\treturn nil\n}}\n"
    )
}

/// The Go function code calls for a function of an engine: `pricingAdd`.
pub fn engine_function(engine: &str, function: &str) -> String {
    format!("{}{}", names::local(engine), names::pascal(function))
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project.apps().find_map(|a| a.main.as_ref().map(|m| m.name.clone())).or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

