/// Lines indented by two tabs, as a case of main.go's switches holds them.
fn indent2(lines: &str) -> String {
    lines.lines().map(|l| format!("\t\t{l}\n")).collect()
}

/// The lines that refuse a handler a frame's command with `allow when` runs
/// (docs/APP-CAPABILITIES-PLAN.md step 4), at `pad`; none without one.
fn handler_allow(owner: &logic::Owner, handler: &str, pad: &str) -> String {
    owner
        .handler_allows
        .iter()
        .filter(|(h, _)| h == handler)
        .map(|(_, function)| format!("{pad}if err := {function}(db); err != nil {{\n{pad}\treturn clarity.Reply{{}}, err\n{pad}}}\n"))
        .collect()
}

/// The files of a desktop program on Clarity.UI (DESIGN 7.9), in ui/: the
/// windows and app frames as `.cxaml` (the same markup the other stacks
/// read), the themes the project offers as Clarity resolves them, and the
/// project's resources. The program embeds them.
fn clarity_files(project: &Project) -> Vec<OutFile> {
    let mut files: Vec<OutFile> = crate::web_windows::window_files(project).into_iter().chain(crate::web_windows::app_files(project)).collect();
    files.extend(crate::csharp::themes::resolved_files(project, "ui/themes"));
    files.extend(crate::web::resource_files(project, "ui/resources"));
    files
}

/// Whether the program has a desktop window: a program served to a browser
/// alone (the web target) has none.
fn has_desktop(settings: &Settings) -> bool {
    settings.stack.targets.contains(&clarity_project::Target::Desktop)
}
