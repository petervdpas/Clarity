/// The first line of every generated Go file, as Go marks generated code.
const HEADER: &str = "// Code generated by Clarity. DO NOT EDIT: change the project in Clarity instead.\n";

/// Clarity's Go runtime module.
pub const RUNTIME_MODULE: &str = "github.com/petervdpas/Clarity/runtimes/go";

/// The runtime's version constant, which names the version a module requires.
const RUNTIME_VERSION_GO: &str = include_str!("../../../../runtimes/go/clarity/version.go");

/// The version of the runtime module a generated module requires: the one
/// the runtime in this repository is (clarity.Version).
pub fn runtime_version() -> &'static str {
    let start = RUNTIME_VERSION_GO.find("const Version = \"").expect("version.go sets Version") + "const Version = \"".len();
    let end = RUNTIME_VERSION_GO[start..].find('"').expect("the Version is closed");
    &RUNTIME_VERSION_GO[start..start + end]
}

/// The sums of each published version of the runtime module, recorded when
/// it is published, so a generated go.sum holds them.
const RUNTIME_PUBLISHED: &str = include_str!("runtime.sum");

/// A server database's package in the runtime module, and the modules only
/// it needs: a module that no driver of the application uses is left out of
/// its go.mod and go.sum. go_build's `go mod tidy -diff` keeps these lists true.
struct Server {
    sql: Sql,
    /// The package that turns the driver on when it is imported.
    package: &'static str,
    modules: &'static [&'static str],
}

const SERVERS: [Server; 3] = [
    Server {
        sql: Sql::Postgres,
        package: "postgresql",
        modules: &[
            "github.com/jackc/pgpassfile",
            "github.com/jackc/pgservicefile",
            "github.com/jackc/pgx/v5",
            "github.com/jackc/puddle/v2",
            "golang.org/x/sync",
        ],
    },
    Server {
        sql: Sql::Mysql,
        package: "mysql",
        modules: &["filippo.io/edwards25519", "github.com/go-sql-driver/mysql"],
    },
    Server {
        sql: Sql::Mssql,
        package: "sqlserver",
        modules: &["github.com/golang-sql/civil", "github.com/golang-sql/sqlexp", "github.com/microsoft/go-mssqldb"],
    },
];

/// The runtime's module file, whose requirements the application takes over.
const RUNTIME_MOD: &str = include_str!("../../../../runtimes/go/go.mod");
const RUNTIME_SUM: &str = include_str!("../../../../runtimes/go/go.sum");

/// The name of the generated module and program.
pub fn module_name(settings: &Settings) -> String {
    names::module(&settings.name)
}

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let (databases, owned) = crate::databases(project, settings, "Go")?;
    let module = module_name(settings);
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let (servers, unused): (Vec<&Server>, Vec<&Server>) = SERVERS.iter().partition(|s| databases.iter().any(|(_, sql, _)| *sql == s.sql));
    let left_out: Vec<&str> = unused.iter().flat_map(|s| s.modules.iter().copied()).filter(|m| !servers.iter().any(|s| s.modules.contains(m))).collect();
    let mut files = vec![text("model.json", crate::web::model_json(project))];
    files.extend(crate::web::renderer_files(project));
    let mut owners = Vec::new();
    for file in &project.files {
        let Some(m) = &file.module else { continue };
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let mut body = model::emit(project, file);
        match logic::emit(project, file, &file_types) {
            Ok(functions) => body.push_str(&functions),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types) {
            Ok((windows, mut found)) => {
                body.push_str(&windows);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("{}_module.go", names::module(&m.name)), go_file(&body)));
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("schema.go", schema_go(project, &owned)?));
    files.push(text("main.go", main_go(project, settings, &module, &databases, &servers, &owners, &main_window)));
    // The modules the code imports itself, which go.mod lists as direct.
    let mut direct = vec![RUNTIME_MODULE, "github.com/wailsapp/wails/v3"];
    if files.iter().any(|f| f.path.ends_with(".go") && f.text.contains("\t\"github.com/shopspring/decimal\"\n")) {
        direct.push("github.com/shopspring/decimal");
    }
    files.push(text("go.mod", go_mod(&module, &left_out, &direct)));
    files.push(text("go.sum", go_sum(&left_out)));
    Ok(files)
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project.apps().find_map(|a| a.main.as_ref().map(|m| m.name.clone())).or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

fn text(path: &str, body: String) -> OutFile {
    OutFile {
        path: path.to_string(),
        text: body,
        bytes: None,
    }
}

/// The module file: the runtime module, and its requirements at the
/// versions it is tested with, without the modules left out; those the code
/// imports itself (`direct`) first, the rest marked indirect, as go mod tidy
/// writes them.
fn go_mod(module: &str, left_out: &[&str], direct: &[&str]) -> String {
    let go = RUNTIME_MOD.lines().find(|l| l.starts_with("go ")).unwrap_or("go 1.25");
    let mut requirements: Vec<(&str, &str)> = RUNTIME_MOD
        .lines()
        .map(str::trim)
        .filter(|l| l.contains(' ') && !l.starts_with("//") && !l.starts_with("module ") && !l.starts_with("go ") && !l.starts_with("require"))
        .filter_map(|l| {
            let mut words = l.split_whitespace();
            Some((words.next()?, words.next()?))
        })
        .filter(|(m, _)| !left_out.contains(m))
        .collect();
    requirements.push((RUNTIME_MODULE, runtime_version()));
    requirements.sort();
    let block = |lines: Vec<String>| if lines.is_empty() { String::new() } else { format!("\nrequire (\n{})\n", lines.concat()) };
    let first = block(requirements.iter().filter(|(m, _)| direct.contains(m)).map(|(m, v)| format!("\t{m} {v}\n")).collect());
    let second = block(requirements.iter().filter(|(m, _)| !direct.contains(m)).map(|(m, v)| format!("\t{m} {v} // indirect\n")).collect());
    format!("// Code generated by Clarity. DO NOT EDIT: change the project in Clarity instead.\nmodule {module}\n\n{go}\n{first}{second}")
}

/// The sums of the runtime's modules, without the modules left out, and
/// those of the runtime module itself once its version is published.
fn go_sum(left_out: &[&str]) -> String {
    let runtime = format!("{RUNTIME_MODULE} {} ", runtime_version());
    let own = format!("{RUNTIME_MODULE} {}/go.mod ", runtime_version());
    let published = RUNTIME_PUBLISHED.lines().filter(|l| l.starts_with(&runtime) || l.starts_with(&own));
    let mut lines: Vec<&str> = RUNTIME_SUM.lines().filter(|l| !left_out.contains(&module_of(l))).chain(published).collect();
    lines.sort();
    lines.iter().map(|l| format!("{l}\n")).collect()
}

/// The module a requirement or sum line is about.
fn module_of(line: &str) -> &str {
    line.split_whitespace().next().unwrap_or("")
}

/// A Go file of package main: its body and the imports it uses, as Go
/// refuses an import that is not used.
fn go_file(body: &str) -> String {
    let mut imports = Vec::new();
    if body.contains("slices.") {
        imports.push("\t\"slices\"\n".to_string());
    }
    // In the order gofmt keeps: by path.
    let mut third = Vec::new();
    if body.contains("clarity.") {
        third.push(format!("\t\"{RUNTIME_MODULE}/clarity\"\n"));
    }
    if body.contains("decimal.") {
        third.push("\t\"github.com/shopspring/decimal\"\n".to_string());
    }
    let mut block = imports.concat();
    if !imports.is_empty() && !third.is_empty() {
        block.push('\n');
    }
    block.push_str(&third.concat());
    let imports = if block.is_empty() { String::new() } else { format!("import (\n{block})\n\n") };
    let body = body.trim_end();
    if body.is_empty() {
        return format!("{HEADER}\npackage main\n");
    }
    format!("{HEADER}\npackage main\n\n{imports}{body}\n")
}

/// The runtime's name for a database kind.
fn dialect(sql: Sql) -> &'static str {
    match sql {
        Sql::Sqlite => "clarity.Sqlite",
        Sql::Postgres => "clarity.Postgres",
        Sql::Mysql => "clarity.Mysql",
        Sql::Mssql => "clarity.Mssql",
    }
}

/// A statement as a Go raw string, or a quoted one when it holds a backquote.
fn raw(text: &str) -> String {
    if text.contains('`') { string(text) } else { format!("`{text}`") }
}

/// The steps of every database Clarity owns, as SQL per data source.
fn schema_go(project: &Project, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut body = String::from(
        "// SourceSteps are the migration steps of one data source, in order, each a\n// list of statements. Each database remembers how many steps it has applied,\n// and applies the rest when the application starts.\ntype SourceSteps struct {\n\tSource string\n\tSteps  [][]string\n}\n\n// Sources are the steps of every database Clarity owns.\nvar Sources = []SourceSteps{\n",
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        body.push_str(&format!("\t{{{}, [][]string{{\n", string(source)));
        for (i, (title, statements)) in steps.iter().enumerate() {
            body.push_str(&format!("\t\t// {}: {title}\n\t\t{{\n", i + 1));
            for statement in statements {
                body.push_str(&format!("\t\t\t{},\n", raw(statement)));
            }
            body.push_str("\t\t},\n");
        }
        body.push_str("\t}},\n");
    }
    body.push_str("}\n");
    if errors.is_empty() { Ok(go_file(&body)) } else { Err(errors) }
}

/// The program: it opens the database of every data source, brings
/// Clarity's own up to date, and shows the main window in the shell; the
/// shell asks the program's `windows` for their data and handlers.
/// `--check` stops after the databases.
fn main_go(project: &Project, settings: &Settings, module: &str, databases: &[(String, Sql, String)], servers: &[&Server], owners: &[logic::Owner], main_window: &str) -> String {
    // The runtime's packages and Wails, by path as gofmt keeps them; a server
    // database's package turns its driver on when it is imported.
    let mut imports: Vec<(String, String)> = vec![
        (format!("{RUNTIME_MODULE}/clarity"), String::new()),
        (format!("{RUNTIME_MODULE}/shell"), String::new()),
        ("github.com/wailsapp/wails/v3/pkg/application".to_string(), String::new()),
    ];
    imports.extend(servers.iter().map(|s| (format!("{RUNTIME_MODULE}/{}", s.package), "_ ".to_string())));
    // A decimal value a click gives is written into the dispatch.
    if owners.iter().flat_map(|o| &o.calls).flat_map(|(_, _, values)| values).any(|v| v.starts_with("decimal.")) {
        imports.push(("github.com/shopspring/decimal".to_string(), String::new()));
    }
    imports.sort();
    let imports: String = imports.iter().map(|(path, name)| format!("\t{name}\"{path}\"\n")).collect();
    let sources = databases
        .iter()
        .map(|(name, sql, at)| format!("{{Name: {}, Dialect: {}, At: {}}}", string(name), dialect(*sql), string(at)))
        .collect::<Vec<_>>()
        .join(", ");
    let ready = string(&format!("{}: the databases are ready.", pascal(&settings.name)));
    let stores = settings.filestores.iter().map(|s| format!("{}: {}", string(&s.name), string(&s.location))).collect::<Vec<_>>().join(", ");
    let cases: String = crate::picture_fields(project)
        .iter()
        .map(|(e, f)| {
            format!(
                "\tcase {}:\n\t\treturn clarity.PictureOf[{}](db, id, {})\n",
                string(&format!("{}.{}", e.name.name, f.name.name)),
                e.name.name,
                string(e.column_of(&f.name.name))
            )
        })
        .collect();
    let pictures = if cases.is_empty() { String::new() } else { format!("\tswitch entity + \".\" + field {{\n{cases}\t}}\n") };
    let windows: Vec<&logic::Owner> = owners.iter().filter(|o| !o.is_app).collect();
    let apps: Vec<&logic::Owner> = owners.iter().filter(|o| o.is_app).collect();

    let mut open = String::new();
    for w in &windows {
        open.push_str(&format!(
            "\tcase {}:\n\t\tw, err := load{}(db)\n\t\tif err != nil {{\n\t\t\treturn clarity.WindowState{{}}, err\n\t\t}}\n\t\treturn clarity.Opened(window, w, with)\n",
            string(&w.name),
            w.struct_name
        ));
    }
    let mut events = String::new();
    for w in windows.iter().filter(|w| !w.events.is_empty()) {
        events.push_str(&format!("\tcase {}:\n\t\tswitch event {{\n", string(&w.name)));
        for (event, handler) in &w.events {
            events.push_str(&format!("\t\tcase {}:\n\t\t\treturn {}, true\n", string(event), string(handler)));
        }
        events.push_str("\t\t}\n");
    }
    let mut app_events = String::new();
    for (event, handler) in apps.iter().flat_map(|a| &a.events) {
        app_events.push_str(&format!("\tcase {}:\n\t\treturn {}, true\n", string(event), string(handler)));
    }
    let mut dispatch = String::new();
    for w in windows.iter().filter(|w| !w.handlers.is_empty() || !w.calls.is_empty()) {
        dispatch.push_str(&format!("\tcase {}:\n\t\tswitch handler {{\n", string(&w.name)));
        for (handler, method) in &w.handlers {
            dispatch.push_str(&format!(
                "\t\tcase {}:\n\t\t\tw := &{}{{}}\n\t\t\tif err := state.Decode(w); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\tif err := w.{method}(db, ui); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\treturn ui.Reply(state.Window, w)\n",
                string(handler),
                w.struct_name
            ));
        }
        // The calls with values its parts wire, by their written form.
        for (call, method, values) in &w.calls {
            let values: String = values.iter().map(|v| format!(", {v}")).collect();
            dispatch.push_str(&format!(
                "\t\tcase {}:\n\t\t\tw := &{}{{}}\n\t\t\tif err := state.Decode(w); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\tif err := w.{method}(db, ui{values}); err != nil {{\n\t\t\t\treturn clarity.Reply{{}}, err\n\t\t\t}}\n\t\t\treturn ui.Reply(state.Window, w)\n",
                string(call),
                w.struct_name
            ));
        }
        dispatch.push_str("\t\t}\n");
    }
    let mut app_dispatch = String::new();
    for a in &apps {
        for (handler, method) in &a.handlers {
            app_dispatch.push_str(&format!(
                "\tcase {}:\n\t\tapp, err := load{}(db)\n\t\tif err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n\t\tif err := app.{method}(db, ui); err != nil {{\n\t\t\treturn clarity.Reply{{}}, err\n\t\t}}\n\t\treturn ui.Reply(state.Window, state.Data)\n",
                string(handler),
                a.struct_name
            ));
        }
    }
    let mut options = String::new();
    for entity in project.entities() {
        let name = &entity.name.name;
        let shown = entity
            .fields
            .iter()
            .find(|f| matches!(f.ty, FieldType::Text { .. } | FieldType::Email))
            .map_or_else(|| "fmt.Sprintf(\"#%d\", r.ID)".to_string(), |f| format!("r.{}", names::field(&f.name.name)));
        options.push_str(&format!(
            "\tcase {}:\n\t\trows, err := clarity.All[{name}](db)\n\t\tif err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n\t\tfor _, r := range rows {{\n\t\t\toptions = append(options, clarity.RefOption{{ID: r.ID, Text: {shown}}})\n\t\t}}\n",
            string(name)
        ));
    }
    let title = string(&clarity_project::title(settings));
    // The desktop window opens at the main window's size.
    let (width, height) = crate::window_size(project, main_window);
    let main_window = string(main_window);
    let module_text = string(module);
    format!(
        "{HEADER}
package main

import (
\t\"embed\"
\t\"fmt\"
\t\"io/fs\"
\t\"os\"
\t\"slices\"

{imports})

// renderer is the web renderer every web stack ships, with the themes.
//
//go:embed ui
var renderer embed.FS

// model is the windows, frame and data dictionary the renderer draws from.
//
//go:embed model.json
var model []byte

// databases is the database of each data source: its name, its kind and where it is.
var databases = []clarity.Source{{{sources}}}

// stores is the folder of each file store, which keeps the pictures of image
// fields kept as files.
var stores = map[string]string{{{stores}}}

// openDatabases opens every database and applies the migration steps it has not had yet.
func openDatabases() (*clarity.Db, error) {{
\tdb, err := clarity.Connect(databases...)
\tif err != nil {{
\t\treturn nil, err
\t}}
\tfor _, s := range Sources {{
\t\tif _, err := db.MigrateSource(s.Source, s.Steps); err != nil {{
\t\t\tdb.Close()
\t\t\treturn nil, err
\t\t}}
\t}}
\tfor name, at := range stores {{
\t\tif err := db.AddStore(name, at); err != nil {{
\t\t\tdb.Close()
\t\t\treturn nil, err
\t\t}}
\t}}
\treturn db, nil
}}

// Clarity is the service the renderer calls, as main.Clarity.Invoke.
type Clarity struct {{
\t*shell.Service
}}

// bind makes the Wails service of the shell's service.
func bind(s *shell.Service) application.Service {{
\treturn application.NewService(&Clarity{{s}})
}}

// windows is what the shell asks of the application's windows.
type windows struct{{}}

// Open is the state of window when it opens, with with filled in.
func (windows) Open(db *clarity.Db, window string, with map[string]any) (clarity.WindowState, error) {{
\tswitch window {{
{open}\t}}
\treturn clarity.WindowState{{}}, &clarity.InvalidError{{What: \"there is no window \" + window}}
}}

// Handler is the handler of a window's or the app's own event, if it has one.
func (windows) Handler(window, event string) (string, bool) {{
\tswitch window {{
{events}\t}}
\t// The app's own events run whatever window is given.
\tswitch event {{
{app_events}\t}}
\treturn \"\", false
}}

// Dispatch runs a handler on a window's state.
func (windows) Dispatch(db *clarity.Db, state clarity.WindowState, handler string) (clarity.Reply, error) {{
\tui := clarity.NewUi(state)
\tswitch state.Window {{
{dispatch}\t}}
\t// The app's handlers run from any window, on the app's own data.
\tswitch handler {{
{app_dispatch}\t}}
\treturn clarity.Reply{{}}, &clarity.InvalidError{{What: state.Window + \" has no handler \" + handler}}
}}

// Options are the records a reference field of entity can point at.
func (windows) Options(db *clarity.Db, entity string) ([]clarity.RefOption, error) {{
\toptions := []clarity.RefOption{{}}
\tswitch entity {{
{options}\t}}
\treturn options, nil
}}

// Picture is the picture of an image field of a record; nil when it has none.
func (windows) Picture(db *clarity.Db, entity string, id int64, field string) ([]byte, error) {{
{pictures}\treturn nil, &clarity.InvalidError{{What: entity + \" has no picture \" + field}}
}}

func main() {{
\tdb, err := openDatabases()
\tif err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(1)
\t}}
\tdefer db.Close()
\t// --check opens and migrates the databases without windows, for builds and scripts.
\tif slices.Contains(os.Args[1:], \"--check\") {{
\t\tfmt.Println({ready})
\t\treturn
\t}}
\tassets, err := fs.Sub(renderer, \"ui\")
\tif err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(1)
\t}}
\tif err := shell.Run(shell.Options{{Name: {module_text}, Title: {title}, Main: {main_window}, Width: {width}, Height: {height}, Model: model, Assets: assets, Db: db, Windows: windows{{}}}}, bind); err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(1)
\t}}
}}
"
    )
}
