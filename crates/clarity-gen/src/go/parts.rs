//! Custom parts written in Go (DESIGN 5.19 and 6.5): a part is a Go package
//! with its own module (`go "parts/arena"`), which implements the interface
//! Clarity writes from the declaration into its `clarity.go`. That file is all
//! the package needs of Clarity: the interface, the window it draws in and
//! its typed tells. The program's glue makes each kind of part for the
//! runtime's part host, and its go.mod points at the part's module.

use std::fmt::Write;

use clarity_spec::Project;
use clarity_spec::code::{Param, PartDecl, PartLibrary, TypeRef, TypeRefKind};

/// The project's parts written in Go, each with its folder.
pub fn go_parts(project: &Project) -> Vec<(&PartDecl, &str)> {
    project
        .files
        .iter()
        .flat_map(|f| &f.parts)
        .filter_map(|p| match &p.library {
            Some(PartLibrary::Go { folder }) => Some((p, folder.as_str())),
            _ => None,
        })
        .collect()
}

/// The Go package name of a part's folder: its last name, as Go writes it.
pub fn package(folder: &str) -> String {
    let base = folder.trim_end_matches('/').rsplit('/').next().unwrap_or(folder);
    let mut out: String = base.chars().filter(|c| c.is_ascii_alphanumeric()).collect::<String>().to_lowercase();
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'p');
    }
    out
}

/// A value of `ty` as the part's Go takes it: a whole number, a bool, or
/// text in its plain form (a decimal, money, a date, an enum value).
fn go_type(ty: &TypeRef) -> &'static str {
    match ty.kind {
        TypeRefKind::Integer | TypeRefKind::Duration => "int64",
        TypeRefKind::Bool => "bool",
        _ => "string",
    }
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map(|c| c.to_ascii_uppercase().to_string() + chars.as_str()).unwrap_or_default()
}

fn params(list: &[Param]) -> String {
    list.iter().map(|p| format!("{} {}", p.name.name, go_type(&p.ty))).collect::<Vec<_>>().join(", ")
}

/// The methods the part's type has, in the interface.
fn methods(part: &PartDecl) -> Vec<String> {
    let mut out = vec!["Resize(width, height int)".to_string(), "Frame()".into(), "SetEnabled(enabled bool)".into()];
    if let Some(binds) = &part.binds {
        out.push(format!("SetValue(value {})", go_type(binds)));
    }
    for property in &part.properties {
        out.push(format!("Set{}({} {})", pascal(&property.name.name), property.name.name, go_type(&property.ty)));
    }
    for hear in &part.hears {
        out.push(format!("{}({})", pascal(&hear.name.name), params(&hear.params)));
    }
    out
}

/// `clarity.go` in the part's folder: what its package implements and calls.
pub fn interface(part: &PartDecl, folder: &str) -> String {
    let n = &part.name.name;
    let pkg = package(folder);
    let mut out = format!(
        "// Code generated by Clarity from custom part {n} (DESIGN 5.19); DO NOT EDIT.
// It is written again when the declaration changes; the rest of the package
// is yours. Every method is called on the part host's goroutine, one at a
// time; the part is made there and lives there.

package {pkg}

import \"unsafe\"

// Window is the native window the part draws in: on Linux an X11 window, on
// the part host's own X11 connection.
type Window struct {{
\tXID     uint64
\tDisplay unsafe.Pointer
\tScreen  int
}}

// Part is what part {n} does. The package's New makes one:
//
//\tfunc New(window Window, width, height int, host Host) Part
type Part interface {{
"
    );
    for method in methods(part) {
        let _ = writeln!(out, "\t{method}");
    }
    let _ = write!(
        out,
        "}}\n\n// Host is where part {n} tells what happened.\ntype Host struct {{\n\ttell func(tell string, values []any)\n}}\n\n// NewHost is made by the program for each part it shows.\nfunc NewHost(tell func(tell string, values []any)) Host {{ return Host{{tell: tell}} }}\n"
    );
    if let Some(binds) = &part.binds {
        let _ = write!(out, "\n// Changed says the person changed the value: what it binds takes it, and on change runs.\nfunc (h Host) Changed(value {}) {{ h.tell(\"change\", []any{{value}}) }}\n", go_type(binds));
    }
    for tell in &part.tells {
        let names: Vec<&str> = tell.params.iter().map(|p| p.name.name.as_str()).collect();
        let _ = write!(out, "\n// {} tells {}: its handler runs with these values.\nfunc (h Host) {}({}) {{ h.tell({:?}, []any{{{}}}) }}\n", pascal(&tell.name.name), tell.name.name, pascal(&tell.name.name), params(&tell.params), tell.name.name, names.join(", "));
    }
    out
}

/// What declaring a Go part writes into its folder: its module, which
/// builds and keeps the part's values, drawing nothing yet.
pub fn starter(part: &PartDecl) -> Vec<(String, String)> {
    let Some(PartLibrary::Go { folder }) = &part.library else { return Vec::new() };
    let n = &part.name.name;
    let pkg = package(folder);
    let module = format!("module clarity.parts/{pkg}\n\ngo 1.24\n");
    let mut fields = vec!["\thost    Host".to_string(), "\twindow  Window".into(), "\twidth   int".into(), "\theight  int".into(), "\tenabled bool".into()];
    if let Some(binds) = &part.binds {
        fields.push(format!("\tvalue   {}", go_type(binds)));
    }
    for property in &part.properties {
        fields.push(format!("\t{} {}", property.name.name, go_type(&property.ty)));
    }
    let mut code = format!(
        "// Custom part {n}: draws in the native window Clarity gives it. Keep the
// methods of Part (clarity.go), which follow the part's declaration.
package {pkg}

type part struct {{
{}
}}

// New makes the part in window, width by height pixels.
func New(window Window, width, height int, host Host) Part {{
\treturn &part{{host: host, window: window, width: width, height: height, enabled: true}}
}}

func (p *part) Resize(width, height int) {{ p.width, p.height = width, height }}

// Frame comes about 60 times a second while the part shows: draw here, and read the mouse and keys.
func (p *part) Frame() {{}}

func (p *part) SetEnabled(enabled bool) {{ p.enabled = enabled }}
",
        fields.join("\n")
    );
    if let Some(binds) = &part.binds {
        let _ = write!(code, "\nfunc (p *part) SetValue(value {}) {{ p.value = value }}\n", go_type(binds));
    }
    for property in &part.properties {
        let name = &property.name.name;
        let _ = write!(code, "\nfunc (p *part) Set{}({name} {}) {{ p.{name} = {name} }}\n", pascal(name), go_type(&property.ty));
    }
    for hear in &part.hears {
        let _ = write!(code, "\nfunc (p *part) {}({}) {{}}\n", pascal(&hear.name.name), params(&hear.params));
    }
    vec![("go.mod".into(), module), (format!("{pkg}.go"), code), ("clarity.go".into(), interface(part, folder))]
}

/// The module path of a part, as its go.mod gives it.
pub fn module_of(project: &Project, part: &str, folder: &str) -> String {
    project
        .part_files
        .iter()
        .flatten()
        .find(|f| f.part == part && f.path == "go.mod")
        .and_then(|f| String::from_utf8_lossy(&f.bytes).lines().find_map(|l| l.trim().strip_prefix("module ").map(|m| m.trim().to_string())))
        .unwrap_or_else(|| format!("clarity.parts/{}", package(folder)))
}

fn file_text(project: &Project, part: &str, path: &str) -> String {
    project.part_files.iter().flatten().find(|f| f.part == part && f.path == path).map(|f| String::from_utf8_lossy(&f.bytes).into_owned()).unwrap_or_default()
}

/// What a part's module requires, as its go.mod lists it.
pub fn requirements_of(project: &Project, part: &str) -> Vec<(String, String)> {
    let text = file_text(project, part, "go.mod");
    let mut out = Vec::new();
    let mut block = false;
    for line in text.lines() {
        let line = line.split("//").next().unwrap_or("").trim();
        if line == "require (" {
            block = true;
            continue;
        }
        if block && line == ")" {
            block = false;
            continue;
        }
        let spec = if block { Some(line) } else { line.strip_prefix("require ") };
        if let Some(spec) = spec {
            let mut words = spec.split_whitespace();
            if let (Some(module), Some(version)) = (words.next(), words.next()) {
                out.push((module.to_string(), version.to_string()));
            }
        }
    }
    out
}

/// A part module's sums, which the program's go.sum carries.
pub fn sums_of(project: &Project, part: &str) -> String {
    file_text(project, part, "go.sum")
}

/// Where a part's module is in the program's folder.
pub fn out_folder(folder: &str) -> String {
    format!("parts/{}", package(folder))
}

/// `parts.go` of the program: each part made for the part host, with its
/// values, hears and tells passed to and from its package.
pub fn glue(project: &Project) -> String {
    let mut imports = String::new();
    let mut code = String::new();
    let mut registers = String::new();
    for (part, folder) in go_parts(project) {
        let n = &part.name.name;
        let pkg = package(folder);
        let alias = format!("{pkg}part");
        let _ = writeln!(imports, "\t{alias} {:?}", module_of(project, n, folder));
        let read = |ty: &TypeRef, raw: &str| match go_type(ty) {
            "string" => format!("parts.Text({raw})"),
            other => format!("parts.Read[{other}]({raw})"),
        };
        let mut sets = String::new();
        if let Some(binds) = &part.binds {
            let _ = writeln!(sets, "\tcase \"value\":\n\t\tg.part.SetValue({})", read(binds, "value"));
        }
        for property in &part.properties {
            let _ = writeln!(sets, "\tcase {:?}:\n\t\tg.part.Set{}({})", property.name.name, pascal(&property.name.name), read(&property.ty, "value"));
        }
        let mut hears = String::new();
        for hear in &part.hears {
            let args: Vec<String> = hear.params.iter().enumerate().map(|(i, p)| read(&p.ty, &format!("parts.At(values, {i})"))).collect();
            let _ = writeln!(hears, "\tcase {:?}:\n\t\tg.part.{}({})", hear.name.name, pascal(&hear.name.name), args.join(", "));
        }
        let glue = format!("{pkg}Glue");
        let _ = write!(
            code,
            "
// {glue} runs custom part {n} for the part host.
type {glue} struct{{ part {alias}.Part }}

func (g {glue}) Resize(width, height int) {{ g.part.Resize(width, height) }}
func (g {glue}) Frame()                   {{ g.part.Frame() }}

func (g {glue}) Set(name string, value json.RawMessage) {{
\tswitch name {{
\tcase \"enabled\":
\t\tg.part.SetEnabled(parts.Read[bool](value))
{sets}\t}}
}}

func (g {glue}) Hear(name string, values []json.RawMessage) {{
\tswitch name {{
{hears}\t}}
}}
"
        );
        let _ = write!(
            registers,
            "\tparts.Register({n:?}, func(window parts.Window, width, height int, host parts.Host) parts.Part {{\n\t\tw := {alias}.Window{{XID: window.XID, Display: window.Display, Screen: window.Screen}}\n\t\treturn {glue}{{{alias}.New(w, width, height, {alias}.NewHost(func(tell string, values []any) {{ host.Tell(tell, values...) }}))}}\n\t}})\n"
        );
    }
    format!(
        "// Code generated by Clarity. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"encoding/json\"\n\n\t\"github.com/petervdpas/Clarity/runtimes/go/parts\"\n{imports})\n{code}\n// registerParts tells the part host about every kind of part the program has.\nfunc registerParts() {{\n{registers}}}\n"
    )
}
