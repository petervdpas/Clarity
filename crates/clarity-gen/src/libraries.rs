//! External libraries (DESIGN 5.21): a library declared in Clarity, written
//! in the project's own language by its adapter in `libraries/<Name>/`, which
//! calls the language's package. Per language, Clarity writes the file that
//! types the declared functions (the adapter must fit it, or the build
//! fails), a starter adapter, and how the program calls it.

use std::fmt::Write;

use clarity_spec::Project;
use clarity_spec::code::{EngineFunction, LibraryDecl, LibrarySource, TypeRef, TypeRefKind};

/// The project's libraries.
pub fn libraries(project: &Project) -> Vec<&LibraryDecl> {
    project.files.iter().flat_map(|f| &f.libraries).collect()
}

/// The library named `name`.
pub fn library<'a>(project: &'a Project, name: &str) -> Option<&'a LibraryDecl> {
    libraries(project).into_iter().find(|l| l.name.name == name)
}

/// Where a library's adapter is in the program's folder.
pub fn folder(name: &str) -> String {
    clarity_spec::native::library_folder(name)
}

fn file_text(project: &Project, library: &str, path: &str) -> String {
    project.part_files.iter().flatten().find(|f| f.part == library && f.path == path).map(|f| String::from_utf8_lossy(&f.bytes).into_owned()).unwrap_or_default()
}

/// The adapter's files as the project has them, for the program's folder,
/// without the file Clarity writes.
pub fn adapter_files(project: &Project, library: &str, own: &str) -> Vec<crate::OutFile> {
    project
        .part_files
        .iter()
        .flatten()
        .filter(|f| f.part == library && f.path != own)
        .map(|f| crate::OutFile { path: format!("{}/{}", folder(library), f.path), text: String::new(), bytes: Some(f.bytes.clone().into()) })
        .collect()
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map(|c| c.to_ascii_uppercase().to_string() + chars.as_str()).unwrap_or_default()
}

// -- C# -------------------------------------------------------------------

/// The namespace of C# adapters.
pub const CSHARP_NAMESPACE: &str = "ClarityLibraries";

fn csharp_type(project: &Project, ty: Option<&TypeRef>) -> String {
    match ty {
        None => "void".into(),
        Some(ty) => crate::csharp::value_type_of(&crate::type_ref_info(project, ty)),
    }
}

fn csharp_signature(project: &Project, f: &EngineFunction) -> String {
    let params: Vec<String> = f.params.iter().map(|p| format!("{} {}", csharp_type(project, Some(&p.ty)), p.name.name)).collect();
    format!("public static partial {} {}({})", csharp_type(project, f.returns.as_ref()), pascal(&f.name.name), params.join(", "))
}

/// `libraries/Words/Words.g.cs`: the functions the adapter writes.
pub fn csharp_half(project: &Project, library: &LibraryDecl) -> String {
    let n = &library.name.name;
    let mut out = format!("// Generated by Clarity from library {n} (DESIGN 5.21). Do not edit: the\n// adapter beside it, {n}.cs, is yours; it writes the functions below.\n\n#nullable enable\n\nnamespace {CSHARP_NAMESPACE};\n\npublic static partial class {n}\n{{\n");
    for f in &library.functions {
        let _ = writeln!(out, "    {};", csharp_signature(project, f));
    }
    out.push_str("}\n");
    out
}

fn csharp_empty(project: &Project, ty: Option<&TypeRef>) -> &'static str {
    match ty.map(|t| crate::type_ref_info(project, t)) {
        None => "",
        Some(clarity_spec::code::check::TypeInfo::Text) => "\"\"",
        Some(clarity_spec::code::check::TypeInfo::Bool) => "false",
        Some(clarity_spec::code::check::TypeInfo::Integer | clarity_spec::code::check::TypeInfo::Duration) => "0",
        Some(clarity_spec::code::check::TypeInfo::Decimal | clarity_spec::code::check::TypeInfo::Money) => "0m",
        _ => "default",
    }
}

/// The adapter a newly declared C# library gets.
pub fn csharp_starter(project: &Project, library: &LibraryDecl) -> String {
    let n = &library.name.name;
    let package = match &library.source {
        Some(LibrarySource::Nuget { package, .. }) => format!("the {package} package"),
        Some(LibrarySource::Dll { file }) => file.clone(),
        _ => "its library".into(),
    };
    let mut out = format!("// Library {n}: what Clarity's code calls, written with {package}.\n// Keep the functions of {n}.g.cs, which follow the library's declaration.\n\nnamespace {CSHARP_NAMESPACE};\n\npublic static partial class {n}\n{{\n");
    for f in &library.functions {
        let empty = csharp_empty(project, f.returns.as_ref());
        let body = if empty.is_empty() { " { }".to_string() } else { format!(" => {empty};") };
        let _ = writeln!(out, "    {}{body}", csharp_signature(project, f));
    }
    out.push_str("}\n");
    out
}

/// The project file's lines for the libraries' packages and assemblies.
pub fn csharp_references(project: &Project) -> String {
    let mut out = String::new();
    for library in libraries(project) {
        match &library.source {
            Some(LibrarySource::Nuget { package, version }) => {
                let _ = writeln!(out, "    <PackageReference Include=\"{package}\" Version=\"{version}\" />");
            }
            Some(LibrarySource::Dll { file }) => {
                let name = std::path::Path::new(file).file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
                let stem = name.strip_suffix(".dll").unwrap_or(&name).to_string();
                let _ = writeln!(out, "    <Reference Include=\"{stem}\" HintPath=\"{}/{name}\" />", folder(&library.name.name));
            }
            _ => {}
        }
    }
    out
}

// -- Rust -----------------------------------------------------------------

fn rust_type(ty: Option<&TypeRef>) -> &'static str {
    match ty.map(|t| &t.kind) {
        None => "()",
        Some(TypeRefKind::Integer | TypeRefKind::Duration) => "i64",
        Some(TypeRefKind::Bool) => "bool",
        Some(TypeRefKind::Decimal | TypeRefKind::Money) => "rust_decimal::Decimal",
        Some(TypeRefKind::Date) => "Option<chrono::NaiveDate>",
        Some(TypeRefKind::DateTime) => "Option<chrono::NaiveDateTime>",
        _ => "String",
    }
}

fn rust_signature(f: &EngineFunction) -> String {
    let params: Vec<String> = f.params.iter().map(|p| format!("{}: {}", snake(&p.name.name), rust_type(Some(&p.ty)))).collect();
    format!("fn {}({}) -> {}", snake(&f.name.name), params.join(", "), rust_type(f.returns.as_ref()))
}

/// `libraries/Words/src/clarity.rs`: the trait the crate's `Words` implements.
pub fn rust_interface(library: &LibraryDecl) -> String {
    let n = &library.name.name;
    let mut out = format!("//! Library {n} (DESIGN 5.21): the trait the crate's `{n}` implements. Written by\n//! Clarity from the library's declaration, and written again when it changes;\n//! the rest of the crate is yours.\n\n/// What Clarity's code calls of library {n}.\npub trait {n}Library {{\n");
    for f in &library.functions {
        let _ = writeln!(out, "    {};", rust_signature(f));
    }
    out.push_str("}\n");
    out
}

/// What declaring a Rust library writes: its crate, depending on the declared crate.
pub fn rust_starter(library: &LibraryDecl) -> Vec<(String, String)> {
    let n = &library.name.name;
    let package = format!("{}_library", snake(n));
    let mut deps = String::new();
    if let Some(LibrarySource::Crate { name, version }) = &library.source {
        let _ = writeln!(deps, "{name} = \"{version}\"");
    }
    let kinds: Vec<&TypeRefKind> = library.functions.iter().flat_map(|f| f.params.iter().map(|p| &p.ty.kind).chain(f.returns.as_ref().map(|r| &r.kind))).collect();
    if kinds.iter().any(|k| matches!(k, TypeRefKind::Decimal | TypeRefKind::Money)) {
        deps.push_str("rust_decimal = \"1\"\n");
    }
    if kinds.iter().any(|k| matches!(k, TypeRefKind::Date | TypeRefKind::DateTime)) {
        deps.push_str("chrono = \"0.4\"\n");
    }
    let cargo = format!("# Library {n}: what Clarity's code calls, written with its crate.\n[package]\nname = \"{package}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\n{deps}");
    let mut lib = format!("//! Library {n}: what Clarity's code calls. Keep the functions of\n//! `{n}Library` (src/clarity.rs), which follow the library's declaration.\n\nmod clarity;\npub use clarity::*;\n\npub struct {n};\n\nimpl {n}Library for {n} {{\n");
    for f in &library.functions {
        let names: Vec<String> = f.params.iter().map(|p| snake(&p.name.name)).collect();
        let quiet = if names.is_empty() { String::new() } else { format!("let _ = ({});\n        ", names.join(", ")) };
        let _ = writeln!(lib, "    {} {{\n        {quiet}Default::default()\n    }}", rust_signature(f));
    }
    lib.push_str("}\n");
    vec![("Cargo.toml".into(), cargo), ("src/lib.rs".into(), lib), ("src/clarity.rs".into(), rust_interface(library))]
}

/// The crate's package name, as its Cargo.toml gives it.
pub fn rust_package(project: &Project, library: &str) -> String {
    file_text(project, library, "Cargo.toml")
        .lines()
        .find_map(|l| {
            let (key, value) = l.split_once('=')?;
            (key.trim() == "name").then(|| value.trim().trim_matches('"').to_string())
        })
        .unwrap_or_else(|| format!("{}_library", snake(library)))
}

/// How Rust code calls a library function.
pub fn rust_call(project: &Project, library: &str, function: &str) -> String {
    let package = rust_package(project, library).replace('-', "_");
    format!("<{package}::{library} as {package}::{library}Library>::{}", snake(function))
}

// -- Go -------------------------------------------------------------------

/// The Go package name of a library: its name in lower case.
pub fn go_package(library: &str) -> String {
    library.to_lowercase()
}

fn go_type(ty: Option<&TypeRef>) -> &'static str {
    match ty.map(|t| &t.kind) {
        None => "",
        Some(TypeRefKind::Integer | TypeRefKind::Duration) => "int64",
        Some(TypeRefKind::Bool) => "bool",
        Some(TypeRefKind::Decimal | TypeRefKind::Money) => "decimal.Decimal",
        Some(TypeRefKind::Date) => "*clarity.Date",
        Some(TypeRefKind::DateTime) => "*clarity.DateTime",
        _ => "string",
    }
}

fn go_func_type(f: &EngineFunction) -> String {
    let params: Vec<&str> = f.params.iter().map(|p| go_type(Some(&p.ty))).collect();
    let returns = go_type(f.returns.as_ref());
    format!("func({}){}", params.join(", "), if returns.is_empty() { String::new() } else { format!(" {returns}") })
}

fn go_imports(library: &LibraryDecl) -> (bool, bool) {
    let kinds: Vec<&TypeRefKind> = library.functions.iter().flat_map(|f| f.params.iter().map(|p| &p.ty.kind).chain(f.returns.as_ref().map(|r| &r.kind))).collect();
    (
        kinds.iter().any(|k| matches!(k, TypeRefKind::Decimal | TypeRefKind::Money)),
        kinds.iter().any(|k| matches!(k, TypeRefKind::Date | TypeRefKind::DateTime)),
    )
}

fn go_import_block(library: &LibraryDecl) -> String {
    let (decimals, dates) = go_imports(library);
    let mut lines = Vec::new();
    if dates {
        lines.push("\t\"github.com/petervdpas/Clarity/runtimes/go/clarity\"");
    }
    if decimals {
        lines.push("\t\"github.com/shopspring/decimal\"");
    }
    if lines.is_empty() { String::new() } else { format!("import (\n{}\n)\n\n", lines.join("\n")) }
}

/// `libraries/Words/clarity.go`: each declared function's type, which the package's must have.
pub fn go_interface(library: &LibraryDecl) -> String {
    let n = &library.name.name;
    let pkg = go_package(n);
    let mut out = format!("// Code generated by Clarity from library {n} (DESIGN 5.21); DO NOT EDIT.\n// The package's functions must have these types; the rest of the package is yours.\n\npackage {pkg}\n\n{}", go_import_block(library));
    out.push_str("// The functions Clarity's code calls, each of its declared type.\nvar _ = []any{\n");
    for f in &library.functions {
        let _ = writeln!(out, "\t({})({}),", go_func_type(f), pascal(&f.name.name));
    }
    out.push_str("}\n");
    out
}

/// What declaring a Go library writes: its module, requiring the declared module.
pub fn go_starter(library: &LibraryDecl, runtime_version: &str) -> Vec<(String, String)> {
    let n = &library.name.name;
    let pkg = go_package(n);
    let (decimals, dates) = go_imports(library);
    let mut requires = String::new();
    if let Some(LibrarySource::Go { module, version }) = &library.source {
        let _ = writeln!(requires, "\t{module} {version}");
    }
    if dates {
        let _ = writeln!(requires, "\tgithub.com/petervdpas/Clarity/runtimes/go {runtime_version}");
    }
    if decimals {
        requires.push_str("\tgithub.com/shopspring/decimal v1.4.0\n");
    }
    let module = format!("module clarity.libraries/{pkg}\n\ngo 1.24\n{}", if requires.is_empty() { String::new() } else { format!("\nrequire (\n{requires})\n") });
    let mut code = format!("// Library {n}: what Clarity's code calls. Keep the functions of clarity.go,\n// which follow the library's declaration.\npackage {pkg}\n\n{}", go_import_block(library));
    for f in &library.functions {
        let params: Vec<String> = f.params.iter().map(|p| format!("{} {}", p.name.name, go_type(Some(&p.ty)))).collect();
        let returns = go_type(f.returns.as_ref());
        let body = match returns {
            "" => String::new(),
            "int64" => "\treturn 0\n".into(),
            "bool" => "\treturn false\n".into(),
            "string" => "\treturn \"\"\n".into(),
            "decimal.Decimal" => "\treturn decimal.Zero\n".into(),
            _ => "\treturn nil\n".into(),
        };
        let _ = write!(code, "\n// {} is called by Clarity's code as {n}.{}.\nfunc {}({}){} {{\n{body}}}\n", pascal(&f.name.name), f.name.name, pascal(&f.name.name), params.join(", "), if returns.is_empty() { String::new() } else { format!(" {returns}") });
    }
    vec![("go.mod".into(), module), (format!("{pkg}.go"), code), ("clarity.go".into(), go_interface(library))]
}

/// The module path of a Go library, as its go.mod gives it.
pub fn go_module(project: &Project, library: &str) -> String {
    file_text(project, library, "go.mod")
        .lines()
        .find_map(|l| l.trim().strip_prefix("module ").map(|m| m.trim().to_string()))
        .unwrap_or_else(|| format!("clarity.libraries/{}", go_package(library)))
}

/// What a Go library's module requires, as its go.mod lists it.
pub fn go_requirements(project: &Project, library: &str) -> Vec<(String, String)> {
    let text = file_text(project, library, "go.mod");
    let mut out = Vec::new();
    let mut block = false;
    for line in text.lines() {
        let line = line.split("//").next().unwrap_or("").trim();
        if line == "require (" {
            block = true;
            continue;
        }
        if block && line == ")" {
            block = false;
            continue;
        }
        let spec = if block { Some(line) } else { line.strip_prefix("require ") };
        if let Some(spec) = spec {
            let mut words = spec.split_whitespace();
            if let (Some(module), Some(version)) = (words.next(), words.next()) {
                out.push((module.to_string(), version.to_string()));
            }
        }
    }
    out
}

/// A Go library module's sums.
pub fn go_sums(project: &Project, library: &str) -> String {
    file_text(project, library, "go.sum")
}

// -- C and C++ ------------------------------------------------------------

fn c_type(ty: Option<&TypeRef>, cpp: bool) -> &'static str {
    match (ty.map(|t| &t.kind), cpp) {
        (None, _) => "void",
        (Some(TypeRefKind::Integer | TypeRefKind::Duration), _) => "int64_t",
        (Some(TypeRefKind::Bool), _) => "bool",
        (Some(TypeRefKind::Decimal | TypeRefKind::Money), true) => "clarity::Decimal",
        (Some(TypeRefKind::Decimal | TypeRefKind::Money), false) => "ClarityDecimal",
        (Some(TypeRefKind::Date), true) => "std::optional<clarity::Date>",
        (Some(TypeRefKind::Date), false) => "ClarityDate",
        (Some(TypeRefKind::DateTime), true) => "std::optional<clarity::DateTime>",
        (Some(TypeRefKind::DateTime), false) => "ClarityDateTime",
        (Some(_), true) => "std::string",
        (Some(_), false) => "const char*",
    }
}

/// The C function a library function is: `Words_spell`.
pub fn c_function(library: &str, function: &str) -> String {
    format!("{library}_{function}")
}

fn c_signature(library: &str, f: &EngineFunction, cpp: bool) -> String {
    let params: Vec<String> = f.params.iter().map(|p| format!("{} {}", c_type(Some(&p.ty), cpp), p.name.name)).collect();
    let params = if params.is_empty() && !cpp { "void".to_string() } else { params.join(", ") };
    let name = if cpp { f.name.name.clone() } else { c_function(library, &f.name.name) };
    format!("{} {name}({params})", c_type(f.returns.as_ref(), cpp))
}

/// `libraries/Words/clarity/Words.h` (C) or `.hpp` (C++): the functions the adapter writes.
pub fn c_header(library: &LibraryDecl, cpp: bool) -> String {
    let n = &library.name.name;
    let mut out = format!("// Library {n} (DESIGN 5.21): the functions its adapter writes. Written by\n// Clarity from the library's declaration, and written again when it changes;\n// the files beside this folder are yours.\n\n#pragma once\n\n");
    if cpp {
        out.push_str("#include <cstdint>\n#include <optional>\n#include <string>\n\n#include \"clarity/decimal.hpp\"\n#include \"clarity/text.hpp\"\n\n");
        let _ = writeln!(out, "namespace {n} {{\n");
        for f in &library.functions {
            let _ = writeln!(out, "{};", c_signature(n, f, true));
        }
        let _ = writeln!(out, "\n}}  // namespace {n}");
    } else {
        out.push_str("#include <stdbool.h>\n#include <stdint.h>\n\n#include \"clarity/decimal.h\"\n#include \"clarity/text.h\"\n\n");
        out.push_str("// Text a function gives lives as long as the command that called it: make it\n// with clarity_copy or clarity_format, or give a literal.\n");
        for f in &library.functions {
            let _ = writeln!(out, "{};", c_signature(n, f, false));
        }
    }
    out
}

/// What declaring a C or C++ library writes: its CMake target and the adapter.
pub fn c_starter(library: &LibraryDecl, cpp: bool) -> Vec<(String, String)> {
    let n = &library.name.name;
    let package = match &library.source {
        Some(LibrarySource::Cmake { package }) => package.clone(),
        _ => "Package".into(),
    };
    let (language, extension, header) = if cpp { ("CXX", "cpp", "hpp") } else { ("C", "c", "h") };
    let cmake = format!(
        "# Library {n}: what Clarity's code calls, built into the program. The target\n# keeps the library's name and links Clarity's runtime for its types.\nadd_library({n} STATIC {n}.{extension})\ntarget_include_directories({n} PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}})\ntarget_link_libraries({n} PUBLIC clarity)\n\n# The library it calls, as CMake finds it:\n# find_package({package} REQUIRED)\n# target_link_libraries({n} PRIVATE <its targets>)\n"
    );
    let _ = language;
    let mut code = format!("// Library {n}: what Clarity's code calls. Keep the functions of\n// clarity/{n}.{header}, which follow the library's declaration.\n\n#include \"clarity/{n}.{header}\"\n");
    if cpp {
        let _ = writeln!(code, "\nnamespace {n} {{");
    }
    for f in &library.functions {
        let names: Vec<String> = f.params.iter().map(|p| format!("(void){};", p.name.name)).collect();
        let empty = match c_type(f.returns.as_ref(), cpp) {
            "void" => String::new(),
            "int64_t" => " return 0;".into(),
            "bool" => " return false;".into(),
            "const char*" => " return \"\";".into(),
            "std::string" => " return {};".into(),
            other if cpp => format!(" return {other}{{}};"),
            other => format!(" return ({other}){{0}};"),
        };
        let _ = writeln!(code, "\n{} {{\n    {}{empty}\n}}", c_signature(n, f, cpp), names.join(" "));
    }
    if cpp {
        let _ = writeln!(code, "\n}}  // namespace {n}");
    }
    vec![("CMakeLists.txt".into(), cmake), (format!("{n}.{extension}"), code), (format!("clarity/{n}.{header}"), c_header(library, cpp))]
}

/// The lines a C or C++ program's CMake project ends with: each library
/// built, and linked into the program.
pub fn cmake_lines(project: &Project, program: &str) -> String {
    let mut out = String::new();
    for library in libraries(project) {
        let n = &library.name.name;
        let _ = write!(out, "\n# Library {n} (DESIGN 5.21), which the program's code calls.\nadd_subdirectory({})\ntarget_link_libraries({program} PRIVATE {n})\n", folder(n));
    }
    out
}

/// The file of a library's adapter folder that is Clarity's, by the project's language.
pub fn own_file(library: &LibraryDecl, cpp: bool) -> String {
    let n = &library.name.name;
    match &library.source {
        Some(LibrarySource::Nuget { .. } | LibrarySource::Dll { .. }) => format!("{n}.g.cs"),
        Some(LibrarySource::Crate { .. }) => "src/clarity.rs".into(),
        Some(LibrarySource::Go { .. }) => "clarity.go".into(),
        _ => format!("clarity/{n}.{}", if cpp { "hpp" } else { "h" }),
    }
}

/// What declaring a library writes into its folder, by its language;
/// `cpp` says a CMake library is for C++.
pub fn starter(project: &Project, library: &LibraryDecl, cpp: bool, go_runtime: &str) -> Vec<(String, String)> {
    match &library.source {
        Some(LibrarySource::Nuget { .. } | LibrarySource::Dll { .. }) => vec![(format!("{}.cs", library.name.name), csharp_starter(project, library))],
        Some(LibrarySource::Crate { .. }) => rust_starter(library),
        Some(LibrarySource::Go { .. }) => go_starter(library, go_runtime),
        Some(LibrarySource::Cmake { .. }) => c_starter(library, cpp),
        None => Vec::new(),
    }
}
