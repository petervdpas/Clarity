//! The README.md of every generated project (P3): what the project is, the
//! tools its stack needs and where to get them (the words of `tools`), how
//! to build and run it without Clarity, and where its data is. A project can
//! so be built on a machine without Clarity, or where Clarity found its
//! tools missing.

use clarity_project::{Backend, Settings, SourceKind};

use crate::tools;

/// A connection as the project file can write it for each server database.
fn example(kind: SourceKind) -> &'static str {
    match kind {
        SourceKind::Postgres => "postgres://user:password@host:5432/database",
        SourceKind::Mysql => "mysql://user:password@host:3306/database",
        SourceKind::Mssql => "server=tcp:host,1433;database=name;user=sa;password=...;TrustServerCertificate=true",
        _ => "",
    }
}

fn kind_label(kind: SourceKind) -> &'static str {
    clarity_project::catalog().sources.iter().find(|s| s.id == kind).map_or("database", |s| s.label)
}

/// The commands that build and run a project of `backend`, in its folder.
fn commands(settings: &Settings) -> (String, String) {
    match settings.stack.backend {
        Backend::Rust => ("cargo build --release".into(), "cargo run".into()),
        Backend::Csharp => ("dotnet build -c Release".into(), "dotnet run".into()),
        Backend::Go => {
            let name = crate::go::module_name(settings);
            (format!("go build -trimpath -ldflags=\"-s -w\" -o bin/{name} ."), "go run .".into())
        }
        _ => (String::new(), String::new()),
    }
}

/// The README of `project`: a C or C++ build links libcurl when its code
/// calls web APIs, and a Rust build with custom parts optimizes their
/// dependencies in a debug build too.
pub fn readme(settings: &Settings, project: &clarity_spec::Project) -> String {
    let calls_out = project.calls_out();
    let backend = settings.stack.backend;
    // Every program draws with Clarity.UI, a web program's in the browser (round B of DESIGN 7.9).
    let stack = tools::stack_name(backend, settings.stack.ui);
    let mut out = format!(
        "# {title}\n\nGenerated by Clarity from the project {name}: {stack}. Do not edit these files; change the project in Clarity and generate it again.\n",
        title = clarity_project::title(settings),
        name = settings.name,
    );

    out.push_str("\n## What you need\n\n");
    // Rust's desktop program links Clarity.UI's ready-made library, or with `ui crate` takes the crate
    // clarity-ui; its web program serves the library's browser files.
    let rust_desktop = backend == Backend::Rust && settings.stack.has(clarity_project::Target::Desktop);
    let clarity_ui = rust_desktop && !crate::rust_links_library(settings);
    let rust_library = rust_desktop && crate::rust_links_library(settings);
    for need in tools::requirements(backend) {
        out.push_str(&format!("- {need}\n"));
    }
    if calls_out && matches!(backend, Backend::C | Backend::Cpp) {
        out.push_str(&format!("- {}\n", tools::LIBCURL));
    }
    out.push_str("\nClarity looks for these itself (`clarity tools`, and Build tools on the Project tab); this list is for building the project without it.\n");
    if backend == Backend::Csharp {
        out.push_str(&format!(
            "\nClarity's runtime comes as NuGet packages ({} {}, and the driver of each kind of database), which the first build fetches from nuget.org. To build on the runtime's own projects instead, while working on them, name their folder in Clarity's repository:\n\n    dotnet build -p:ClarityRuntime=<Clarity>/runtimes/csharp\n\nor set the environment variable `CLARITY_RUNTIME` to it. A desktop program built so needs the native Clarity.UI library built first (`cargo build -p clarity-ui-ffi` in Clarity's repository); the build puts it next to the program.\n",
            // A desktop program takes the desktop's package; one served to browsers alone the server's (DESIGN 7.6).
            if crate::windowed_target(settings) == clarity_project::Target::Desktop { "Clarity.Ui" } else { "Clarity.Ui.Server" },
            crate::csharp::runtime_version()
        ));
    }
    if backend == Backend::Cpp && settings.stack.has(clarity_project::Target::Desktop) {
        // The desktop program links Clarity.UI's library (DESIGN 7.9), from the folder CLARITY_UI names.
        out.push_str(&format!("\nThe desktop program draws with Clarity.UI, one library with a C interface. CMake finds it in the folder the environment variable `CLARITY_UI` names (or `cmake -DCLARITY_UI=<folder>`): `include/clarity_ui.h` and, in `lib/`, the library for the system (`libclarity_ui.so` on Linux, `libclarity_ui.dylib` on macOS, `clarity_ui.dll` with its import library on Windows). {} In Clarity's repository the library is built with `cargo build --release -p clarity-ui-ffi` (into `target/release`, the header in `runtimes/rust-ui-ffi/include`). Each build copies the library next to the program, where the program finds it when it runs; copy it along with the program.\n", cmake_fetches()));
    }
    if rust_library {
        // As Go, C and C++ link it (DESIGN 7.9): build.rs takes it from the folder CLARITY_UI names.
        out.push_str(&format!("\nThe desktop program draws with Clarity.UI's ready-made library, which it links through its C interface as Go, C and C++ programs do, so the build compiles no Skia. `build.rs` takes it from the folder the environment variable `CLARITY_UI` names: `include/clarity_ui.h` and, in `lib/`, the library for the system (`libclarity_ui.so` on Linux, `libclarity_ui.dylib` on macOS, `clarity_ui.dll` with `clarity_ui.dll.lib` on Windows), with Clarity.Audio and Clarity.Video beside it when the program plays songs or videos. Clarity's build names the folder; to build without Clarity take the archive for the system, {}, from the release {} (`<system>` is one of {}), check it against the release's `SHA256SUMS`, unpack it and set `CLARITY_UI` to the folder it holds. Each build copies the libraries next to the program, where it finds them (else in that folder): ship them along with it. In Clarity's repository `clarity libraries` rebuilds them from the source. Writing `ui crate` in the project file builds Clarity.UI from source instead, as a Rust custom part needs.\n", archive(), release_page(), SYSTEMS));
    }
    if clarity_ui {
        out.push_str(&format!(
            "\nClarity's runtime and Clarity.UI come as the crates clarity-runtime ({}) and clarity-ui ({}), which the first build fetches from crates.io; clarity-ui's first build also downloads Skia's prebuilt library for the system. To build on the crates in Clarity's repository instead, while working on them, set the environment variable `CLARITY_RUNTIME` to `<Clarity>/runtimes/rust` when Clarity generates the project: it writes `.cargo/config.toml` in this folder, which says\n\n    [patch.crates-io]\n    clarity-runtime = {{ path = \"<Clarity>/runtimes/rust\" }}\n    clarity-ui = {{ path = \"<Clarity>/runtimes/rust-ui\" }}\n\nThe file can also be written by hand. Clarity keeps .cargo when it writes the project again; remove it to build on the published crates.\n",
            crate::rust::runtime_version(),
            crate::rust::ui_version()
        ));
    } else if backend == Backend::Rust {
        out.push_str(&format!(
            "\nClarity's runtime comes as the crate clarity-runtime ({}), with a feature for each database the project uses, which the first build fetches from crates.io. To build on the runtime in Clarity's repository instead, while working on it, set the environment variable `CLARITY_RUNTIME` to `<Clarity>/runtimes/rust` when Clarity generates the project: it writes `.cargo/config.toml` in this folder, which says\n\n    [patch.crates-io]\n    clarity-runtime = {{ path = \"<Clarity>/runtimes/rust\" }}\n\nThe file can also be written by hand. Clarity keeps .cargo when it writes the project again; remove it to build on the published crate.\n",
            crate::rust::runtime_version()
        ));
    }
    if backend == Backend::Go && settings.stack.has(clarity_project::Target::Desktop) {
        // The desktop program calls Clarity.UI's library through cgo (DESIGN 7.9), from the folder CLARITY_UI names.
        out.push_str(&format!("\nThe desktop program draws with Clarity.UI, one library with a C interface, which the program calls through cgo. It comes from the folder the environment variable `CLARITY_UI` names: `include/clarity_ui.h` and, in `lib/`, the library for the system (`libclarity_ui.so` on Linux, `libclarity_ui.dylib` on macOS, `clarity_ui.dll` on Windows). Clarity's build hands it to cgo, and without `CLARITY_UI` takes the library Clarity carries (or fetches it). cgo downloads nothing, so to build without Clarity take the archive for the system, {}, from the release {} (`<system>` is one of {}), check it against the release's `SHA256SUMS`, unpack it and set `CLARITY_UI` to the folder it holds. Then, on Linux:\n\n    export CGO_CFLAGS=\"-I$CLARITY_UI/include\"\n    export CGO_LDFLAGS=\"-L$CLARITY_UI/lib -Wl,-rpath,\\$ORIGIN -Wl,-rpath,$CLARITY_UI/lib\"\n\n(on macOS `@executable_path` in place of `$ORIGIN`; on Windows `-L` alone). The program finds the library beside it, else in that folder: ship it beside the program (on Windows it must be there, or on `PATH`). In Clarity's repository the library is built with `cargo build --release -p clarity-ui-ffi` (into `target/release`, the header in `runtimes/rust-ui-ffi/include`).\n", archive(), release_page(), SYSTEMS));
    }
    if matches!(backend, Backend::Rust | Backend::Go | Backend::C | Backend::Cpp) && settings.stack.has(clarity_project::Target::Web) {
        // The web program serves Clarity.UI in the browser (round B of DESIGN 7.9).
        let serve = if settings.stack.has(clarity_project::Target::Desktop) { " Started with `--serve`, the program serves instead of opening its window." } else { "" };
        out.push_str(&format!(
            "\nThe web program serves Clarity.UI in the browser: `browser/` holds the page, the program's files (`clarity/files.json`, its windows, themes and model, and `clarity/resources/`) and Clarity.UI's browser files (`clarity-ui.js`, `clarity-ui.wasm`, `clarity-ui-worker.js`, `clarity-ui-page.js`), which Clarity copies in when it writes the program: the folder the environment variable `CLARITY_UI_BROWSER` names, else the files Clarity carries, else the archive `{}` of the release {}. The program carries them all; it listens at `--address host:port`, else the environment's `CLARITY_ADDRESS`, else `{}`, and a browser that opens it runs the windows there while the program answers each of their calls.{serve}\n",
            crate::clarity_ui::archive_name(crate::clarity_ui::version(), crate::clarity_ui::BROWSER),
            release_page(),
            clarity_project::serve_address(settings),
        ));
    }
    if backend == Backend::Go {
        out.push_str(&format!(
            "\nClarity's runtime comes as the Go module {module} ({}), with a package for each server database the project uses, which the first build fetches. To build on the runtime in Clarity's repository instead, while working on it, make a workspace next to this module:\n\n    go work init .\n    go work edit -replace {module}=<Clarity>/runtimes/go\n\nClarity keeps go.work when it writes the module again; remove it to build on the published module.\n",
            crate::go::runtime_version(),
            module = crate::go::RUNTIME_MODULE,
        ));
    }

    if backend == Backend::C && settings.stack.has(clarity_project::Target::Desktop) {
        out.push_str(&format!("\nThe windows are drawn by Clarity.UI's library (`clarity_ui`), which the build takes from the folder the environment variable `CLARITY_UI` names (or `cmake -DCLARITY_UI=<folder>`): `include/clarity_ui.h`, and in `lib/` the library for the system (`libclarity_ui.so` on Linux, `libclarity_ui.dylib` on macOS, `clarity_ui.dll` with its import library on Windows). {} Each build copies the library next to the program, where the program finds it, so ship the two together.\n", cmake_fetches()));
    }

    let (build, run) = commands(settings);
    if !build.is_empty() {
        out.push_str("\n## Build and run\n\n");
        out.push_str(&format!("In this folder, build the program with\n\n    {build}\n\n"));
        if let Some(toolchain) = crate::toolchain(settings, true) {
            out.push_str(&format!("which writes `{}`. ", toolchain.program.display()));
        }
        out.push_str(&format!("To try it while you work, build a debug program and start it with\n\n    {run}\n"));
        if backend == Backend::Rust && (settings.stack.has(clarity_project::Target::Desktop) || !crate::rust::parts::crate_parts(project).is_empty()) {
            out.push_str("\nThe debug program builds its dependencies optimized, as Clarity.UI, which draws its windows, and the custom parts' crates and what they use (a game engine, say), so the windows run at speed while the program's own code stays quick to build: Cargo.toml says so under `[profile.dev.package.\"*\"]`.\n");
        }
    }

    out.push_str("\n## Data\n\n");
    for source in &settings.datasources {
        let owner = if source.external { "an existing database Clarity does not change" } else { "migrated by the program when it starts" };
        match (source.kind, source.url.strip_prefix("env:")) {
            (SourceKind::Rest, _) => out.push_str(&format!("- `{}`: the web API at {}\n", source.name, source.url)),
            (kind, Some(variable)) => out.push_str(&format!(
                "- `{}`: a {} database, {owner}. Set the environment variable `{variable}` to its connection, like `{}`.\n",
                source.name,
                kind_label(kind),
                example(kind)
            )),
            (SourceKind::Sqlite, None) if source.url.starts_with("data:") => {
                // A database the project keeps beside it: in the person's folder for application data
                // (conformance/data-folder.json); Clarity's Run names the project's data folder.
                let kept = &source.url["data:".len()..];
                let written = project.sources.iter().find(|s| s.name == source.name).map(|s| s.address.as_str()).filter(|a| !a.is_empty()).unwrap_or(kept);
                out.push_str(&format!(
                    "- `{}`: an SQLite file, {owner}, kept in the person's folder for application data: `~/.local/share/{kept}` on Linux (`$XDG_DATA_HOME` when set), `~/Library/Application Support/{kept}` on macOS, `%APPDATA%\\{}` on Windows. Run in Clarity, it is the project's `{written}`.",
                    source.name,
                    kept.replace('/', "\\")
                ));
                out.push_str(" Set the environment variable `CLARITY_DATA` to a folder to open it there instead, under its own file name.\n");
            }
            (SourceKind::Sqlite, None) => {
                // The path as the project file gives it. A relative one is in the project's folder, where the
                // program opens it whatever folder it starts in (clarity_project::build_settings made it whole);
                // only a program generated from settings that were not built takes it from where it starts.
                let written = project.sources.iter().find(|s| s.name == source.name).map(|s| s.address.as_str()).filter(|a| !a.is_empty()).unwrap_or(&source.url);
                let relative = !std::path::Path::new(written).is_absolute();
                let place = match (relative, std::path::Path::new(&source.url).is_absolute()) {
                    (true, true) => format!(" in the project's folder, {owner}."),
                    (true, false) => format!(", {owner}; a relative path is taken from the folder the program starts in."),
                    (false, _) => format!(", {owner}."),
                };
                out.push_str(&format!("- `{}`: the SQLite file `{written}`{place}", source.name));
                // Every runtime opens an SQLite file in the folder CLARITY_DATA names, when it is set.
                out.push_str(" Set the environment variable `CLARITY_DATA` to a folder to open it there instead, under its own file name.");
                out.push('\n');
            }
            (kind, None) => out.push_str(&format!("- `{}`: a {} database at `{}`, {owner}.\n", source.name, kind_label(kind), source.url)),
        }
    }
    for store in &settings.filestores {
        match store.location.strip_prefix("env:") {
            Some(variable) => out.push_str(&format!(
                "- `{}`: a file store of pictures. Set the environment variable `{variable}` to its folder.\n",
                store.name
            )),
            None => out.push_str(&format!(
                "- `{}`: the file store of pictures in the folder `{}`; a relative path is taken from the folder the program starts in.\n",
                store.name, store.location
            )),
        }
    }
    out
}

/// The systems the library's release has an archive for.
const SYSTEMS: &str = "`linux-x64`, `linux-arm64`, `win-x64`, `win-arm64`, `osx-x64`, `osx-arm64`";

/// The archive of Clarity.UI's library this project is generated for, by name.
fn archive() -> String {
    format!("`{}`", crate::clarity_ui::archive_name(crate::clarity_ui::version(), "<system>"))
}

/// The release page of that library version.
fn release_page() -> String {
    crate::clarity_ui::release_page(crate::clarity_ui::version())
}

/// What a C or C++ build does without CLARITY_UI (clarity_ui.cmake).
fn cmake_fetches() -> String {
    format!(
        "Without it, the build downloads the archive for the system, {}, from the release {} (`<system>` is one of {}), checks it against the release's `SHA256SUMS` and unpacks it into the build folder; Clarity's own build names the library Clarity carries (or fetches it once into the person's cache folder).",
        archive(),
        release_page(),
        SYSTEMS
    )
}
