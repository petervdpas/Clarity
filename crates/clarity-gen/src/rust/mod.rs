/// The project's people as the runtime's signin source takes them (docs/APP-CAPABILITIES-PLAN.md
/// step 4), its remembered sign-in kept under the program's name (main's `PROGRAM`).
pub(crate) fn signin_source(plan: &crate::signin::SigninPlan) -> String {
    let texts = |items: &[String]| items.iter().map(|t| format!("{t:?}.into()")).collect::<Vec<_>>().join(", ");
    let strategies: Vec<String> = plan.strategies.iter().map(|(name, columns)| format!("clarity_runtime::signin::SigninStrategy {{ name: {name:?}.into(), columns: vec![{}] }}", texts(columns))).collect();
    format!(
        "clarity_runtime::signin::SigninSource {{ source: {:?}.into(), table: {:?}.into(), key: {:?}.into(), page: {:?}.into(), targets: vec![{}], strategies: vec![{}], session_seconds: {}, tries: {}, tries_seconds: {}, program: PROGRAM.into(), remember_seconds: {:?}, remember_asks: {} }}",
        plan.source,
        plan.table,
        plan.key,
        plan.page,
        texts(&plan.targets),
        strategies.join(", "),
        plan.session_seconds,
        plan.tries,
        plan.tries_seconds,
        plan.remember_seconds,
        plan.remember_asks
    )
}

fn raw(text: &str) -> String {
    let mut hashes = "#".to_string();
    while text.contains(&format!("\"{hashes}")) {
        hashes.push('#');
    }
    format!("r{hashes}\"{text}\"{hashes}")
}

/// The steps of every database of the application, as SQL per data source.
fn schema_rs(project: &Project, sources: &[(String, Sql)]) -> Result<String, Vec<String>> {
    let mut out = format!(
        "{HEADER}
/// The migration steps per data source, in order, each a list of
/// statements. Each database remembers how many steps it has applied, and
/// applies the rest when the application starts.
pub const SOURCES: &[(&str, &[&[&str]])] = &[
"
    );
    let mut errors = Vec::new();
    for (source, sql) in sources {
        let steps = match schema::steps(project, source, *sql) {
            Ok(steps) => steps,
            Err(mut problems) => {
                errors.append(&mut problems);
                continue;
            }
        };
        out.push_str(&format!("    ({source:?}, &[\n"));
        for (i, (title, statements)) in steps.iter().enumerate() {
            out.push_str(&format!("        // {}: {title}\n        &[\n", i + 1));
            for statement in statements {
                out.push_str(&format!("            {},\n", raw(statement)));
            }
            out.push_str("        ],\n");
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}

/// main as a web server (DESIGN 7.3, round B of 7.9): the browser files,
/// embedded in the program, and the page's wire, answered by the program
/// (`clarity_runtime::wire::answer`).
fn serve_main(address: &str, served: &[String]) -> String {
    // The browser files, in the program itself.
    let arms: String = served.iter().map(|path| format!("            {path:?} => Some(include_bytes!(\"../browser/{path}\").to_vec()),\n")).collect();
    format!(
        "    let files = |path: &str| -> Option<Vec<u8>> {{\n        match path {{\n{arms}            _ => None,\n        }}\n    }};\n    let args: Vec<String> = std::env::args().collect();\n    if let Err(err) = clarity_runtime::serve::serve(PROGRAM, &clarity_runtime::serve::address(&args, {address:?}), &files, &|command, args| clarity_runtime::wire::answer(&app, command, args)) {{\n        eprintln!(\"{{PROGRAM}}: {{err}}\");\n        std::process::exit(1);\n    }}\n"
    )
}

/// Each window's inputs bound to a required field, as the arms of
/// `required_inputs`: the part, the data that holds the record, its table
/// and the field's column (conformance/required.json).
fn required_inputs(project: &Project) -> String {
    use clarity_spec::model::Widget;
    fn walk<'a>(widgets: &'a [Widget], out: &mut Vec<&'a Widget>) {
        for widget in widgets {
            out.push(widget);
            walk(&widget.children, out);
            for page in &widget.pages {
                walk(&page.children, out);
            }
        }
    }
    let mut arms = String::new();
    for page in project.files.iter().flat_map(|f| &f.pages) {
        let mut widgets = Vec::new();
        walk(&page.widgets, &mut widgets);
        for sidebar in &page.frame.sidebars {
            walk(&sidebar.widgets, &mut widgets);
        }
        if let Some(footer) = &page.frame.footer {
            walk(&footer.widgets, &mut widgets);
        }
        let bound: Vec<String> = widgets
            .iter()
            .filter_map(|w| {
                let part = w.props.name.as_deref()?;
                let (data, field) = w.props.bind.as_deref()?.split_once('.')?;
                let entity = project.entity(page.data.iter().find(|d| d.name.name == data)?.entity()?.name.as_str())?;
                let column = entity.column_of(entity.field(field)?.name.name.as_str());
                crate::required_fields(project, entity)
                    .iter()
                    .any(|(c, _)| *c == column)
                    .then(|| format!("Bound {{ part: {part:?}, data: {data:?}, table: {:?}, column: {column:?} }}", entity.table_name()))
            })
            .collect();
        if !bound.is_empty() {
            let _ = writeln!(arms, "        {:?} => &[{}],", page.name.name, bound.join(", "));
        }
    }
    arms
}
