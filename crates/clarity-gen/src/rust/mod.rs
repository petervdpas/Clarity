//! The Rust backend: a Tauri desktop application. One Rust module per
//! Clarity module, the schema as its first migration, the window structs
//! and handlers, and the web renderer as the frontend, on the runtime crate
//! `clarity-runtime` from crates.io with the features of the project's
//! databases. While working on the runtime, `.cargo/config.toml` in the
//! project patches the crate with the runtime in Clarity's repository.

