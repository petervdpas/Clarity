/// The first line of every generated Rust file.
const HEADER: &str = "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n";

/// The runtime, copied into every generated project.
const RUNTIME_FILES: [(&str, &str); 10] = [
    ("clarity-runtime/src/dialect.rs", include_str!("../../../clarity-runtime/src/dialect.rs")),
    ("clarity-runtime/src/mssql.rs", include_str!("../../../clarity-runtime/src/mssql.rs")),
    ("clarity-runtime/src/mysql.rs", include_str!("../../../clarity-runtime/src/mysql.rs")),
    ("clarity-runtime/src/postgres.rs", include_str!("../../../clarity-runtime/src/postgres.rs")),
    ("clarity-runtime/src/sqlite.rs", include_str!("../../../clarity-runtime/src/sqlite.rs")),
    ("clarity-runtime/src/store.rs", include_str!("../../../clarity-runtime/src/store.rs")),
    ("clarity-runtime/src/lib.rs", include_str!("../../../clarity-runtime/src/lib.rs")),
    ("clarity-runtime/src/query.rs", include_str!("../../../clarity-runtime/src/query.rs")),
    ("clarity-runtime/src/sql.rs", include_str!("../../../clarity-runtime/src/sql.rs")),
    ("clarity-runtime/src/ui.rs", include_str!("../../../clarity-runtime/src/ui.rs")),
];

/// The application icon until a project sets its own.
const ICON: &[u8] = include_bytes!("../../assets/icon.png");

/// The frontend, built from the designer's renderer (`npm run build:runtime`).
const UI_FILES: [(&str, &str); 3] = [
    ("ui/index.html", include_str!("../../ui/runtime.html")),
    ("ui/runtime.js", include_str!("../../ui/runtime.js")),
    ("ui/runtime.css", include_str!("../../ui/runtime.css")),
];

/// The runtime's own manifest, with every database driver as a feature.
const RUNTIME_MANIFEST: &str = include_str!("../../../clarity-runtime/Cargo.toml");

/// The runtime's manifest as a generated project has it: on its own rather
/// than in Clarity's workspace.
fn runtime_cargo() -> String {
    RUNTIME_MANIFEST
        .replace("edition.workspace = true", "edition = \"2024\"")
        .replace("version.workspace = true", "version = \"0.1.0\"")
        .replace("license.workspace = true\n", "")
}

/// Lints that generated code does not follow, because names come from the
/// project as the developer wrote them.
const ALLOW: &str = "#![allow(non_camel_case_types, non_snake_case, unused_parens, unused_mut, unused_variables, unused_imports, dead_code, unreachable_code, clippy::all)]\n";

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let crate_name = crate_name(settings);
    if settings.datasources.is_empty() {
        return Err(vec!["the project needs a data source to store its records".to_string()]);
    }
    // A database for every data source that holds entities.
    let mut databases: Vec<(String, Sql, String)> = Vec::new();
    for source in &settings.datasources {
        if project.entities_in(&source.name).next().is_none() {
            continue;
        }
        let Some(sql) = Sql::of(source.kind) else {
            return Err(vec![format!(
                "data source '{}' is a web API; the Rust backend stores records in SQL databases only for now",
                source.name
            )]);
        };
        if source.url.starts_with("keychain:") {
            return Err(vec![format!(
                "data source '{}': a generated application reads its connection from 'env:NAME' for now, not from the keychain",
                source.name
            )]);
        }
        databases.push((source.name.clone(), sql, source.url.clone()));
    }
    // Steps only for the databases Clarity owns; external ones are opened as
    // they are.
    let owned: Vec<(String, Sql)> = databases
        .iter()
        .filter(|(name, _, _)| settings.datasources.iter().any(|s| s.name == *name && !s.external))
        .map(|(name, sql, _)| (name.clone(), *sql))
        .collect();
    let mut features: Vec<&str> = databases.iter().map(|(_, sql, _)| sql.feature()).collect();
    features.sort();
    features.dedup();
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let mut files = vec![
        text("Cargo.toml", cargo_toml(&crate_name, &features)),
        text("build.rs", format!("{HEADER}\nfn main() {{\n    tauri_build::build()\n}}\n")),
        text("tauri.conf.json", tauri_conf(&clarity_project::title(settings), &crate_name)),
        text("clarity-runtime/Cargo.toml", runtime_cargo()),
        text("src/model.json", model_json(project)),
    ];
    files.extend(RUNTIME_FILES.iter().chain(&UI_FILES).map(|(path, body)| text(path, (*body).into())));
    // A CSS file per theme the application offers, linked from the page so
    // the application can hold the class of the theme it shows.
    let themes: Vec<&clarity_spec::model::ThemeDecl> = project
        .themes
        .iter()
        .filter_map(|name| project.files.iter().flat_map(|f| &f.themes).find(|t| t.name.name == *name))
        .collect();
    // Clarity's own theme first: the base the project's themes change.
    let base = clarity_spec::themes::built_in();
    let links: String = std::iter::once(&base)
        .chain(themes.iter().copied())
        .map(|t| format!("    <link rel=\"stylesheet\" href=\"./{}\">\n", crate::web::theme_file(t)))
        .collect();
    files.push(text(&format!("ui/{}", crate::web::theme_file(&base)), crate::web::base_css()));
    for theme in &themes {
        files.push(text(&format!("ui/{}", crate::web::theme_file(theme)), crate::web::theme_css(theme)));
    }
    if let Some(index) = files.iter_mut().find(|f| f.path == "ui/index.html") {
        index.text = index.text.replace("  </head>", &format!("{links}  </head>"));
    }
    files.push(OutFile {
        path: "icons/icon.png".into(),
        text: String::new(),
        bytes: Some(ICON),
    });

    let mut modules = Vec::new();
    let mut owners: Vec<Owner> = Vec::new();
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let name = snake(&module.name);
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let mut code = format!("{HEADER}\nuse clarity_runtime::sql;\nuse clarity_runtime::ui::*;\nuse clarity_runtime::*;\n");
        for used in &file.uses {
            code.push_str(&format!("use crate::{}::*;\n", snake(&used.name)));
        }
        code.push('\n');
        code.push_str(&model::emit(project, file));
        match logic::emit(project, file, &file_types) {
            Ok(functions) => code.push_str(&functions),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types, &name) {
            Ok((windows, mut found)) => {
                code.push_str(&windows);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("src/{name}.rs"), code.trim_end().to_string() + "\n"));
        modules.push(name);
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.push(text("src/schema.rs", schema::emit(project, &owned)?));
    files.push(text("src/main.rs", main_rs(project, &modules, &owners, &databases, &main_window)));
    Ok(files)
}

fn text(path: &str, body: String) -> OutFile {
    OutFile {
        path: path.to_string(),
        text: body,
        bytes: None,
    }
}

/// The window the application opens with: the app's main window, or the
/// first window of the project.
fn main_window(project: &Project) -> Option<String> {
    project
        .apps()
        .find_map(|a| a.main.as_ref().map(|m| m.name.clone()))
        .or_else(|| project.pages().next().map(|p| p.name.name.clone()))
}

/// The windows, the frame and the data dictionary, for the renderer. File
/// paths are left out: they belong to the machine the project was on.
fn model_json(project: &Project) -> String {
    let mut project = project.clone();
    for file in &mut project.files {
        file.path = std::path::Path::new(&file.path)
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_default();
        file.version = String::new();
    }
    project.diagnostics.clear();
    let mut preview = Preview::new(project);
    preview.samples.clear();
    preview.displays.clear();
    serde_json::to_string(&preview).unwrap_or_default() + "\n"
}

/// The manifest of the application, with the runtime features of the
/// databases its data sources are.
fn cargo_toml(name: &str, features: &[&str]) -> String {
    let features = features.iter().map(|f| format!("{f:?}")).collect::<Vec<_>>().join(", ");
    format!(
        r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
clarity-runtime = {{ path = "clarity-runtime", default-features = false, features = [{features}] }}
serde = {{ version = "1", features = ["derive"] }}
serde_json = "1"
tauri = {{ version = "2", features = [] }}

[build-dependencies]
tauri-build = {{ version = "2", features = [] }}

[workspace]
members = [".", "clarity-runtime"]
"#
    )
}

fn tauri_conf(title: &str, crate_name: &str) -> String {
    let conf = serde_json::json!({
        "$schema": "https://schema.tauri.app/config/2",
        "productName": title,
        "version": "0.1.0",
        "identifier": format!("app.clarity.{}", crate_name.replace('_', "-")),
        "build": { "frontendDist": "ui" },
        "app": {
            "windows": [{ "title": title, "width": 1100, "height": 760 }],
            "security": { "csp": null }
        },
        "bundle": { "active": false }
    });
    serde_json::to_string_pretty(&conf).unwrap_or_default() + "\n"
}

/// The field a reference dropdown shows for a record: its first text field.
fn display_field(entity: &clarity_spec::model::Entity) -> Option<String> {
    entity
        .fields
        .iter()
        .find(|f| matches!(f.ty, FieldType::Text { .. } | FieldType::Email))
        .map(|f| ident(&f.name.name))
}

fn main_rs(project: &Project, modules: &[String], owners: &[Owner], databases: &[(String, Sql, String)], main_window: &str) -> String {
    let databases = databases
        .iter()
        .map(|(name, sql, at)| format!("({name:?}, {}, {at:?})", sql.runtime()))
        .collect::<Vec<_>>()
        .join(", ");
    let mods: String = modules.iter().map(|m| format!("mod {m};\n")).collect();
    let module_of = |name: &str| {
        project
            .files
            .iter()
            .find(|f| f.entities.iter().any(|e| e.name.name == name))
            .and_then(|f| f.module.as_ref())
            .map(|m| snake(&m.name))
            .unwrap_or_default()
    };

    let opens: String = owners
        .iter()
        .filter(|o| !o.is_app)
        .map(|o| {
            format!(
                "        {:?} => to_data(&{}::{}::load(db)?)?,\n",
                o.name, o.module, o.struct_name
            )
        })
        .collect();
    let checks: String = owners
        .iter()
        .filter(|o| !o.is_app)
        .map(|o| {
            format!(
                "        {:?} => {{\n            from_data::<{}::{}>(state.data.clone())?;\n        }}\n",
                o.name, o.module, o.struct_name
            )
        })
        .collect();
    let mut dispatch = String::new();
    for o in owners.iter().filter(|o| !o.is_app) {
        for (handler, function) in &o.handlers {
            dispatch.push_str(&format!(
                "        ({:?}, {:?}) => {{
            let mut w: {m}::{s} = from_data(state.data.clone())?;
            {m}::{function}(db, &mut w, &mut ui)?;
            Ok(ui.reply(&state.window, to_data(&w)?))
        }}
",
                o.name,
                handler,
                m = o.module,
                s = o.struct_name
            ));
        }
    }
    // The app's handlers run from any window, on the app's own data.
    for o in owners.iter().filter(|o| o.is_app) {
        for (handler, function) in &o.handlers {
            dispatch.push_str(&format!(
                "        (_, {:?}) => {{
            let mut app = {m}::{s}::load(db)?;
            {m}::{function}(db, &mut app, &mut ui)?;
            Ok(ui.reply(&state.window, state.data.clone()))
        }}
",
                handler,
                m = o.module,
                s = o.struct_name
            ));
        }
    }
    // Windows by name; the app's start runs whatever window is given.
    let events: String = owners
        .iter()
        .flat_map(|o| {
            o.events.iter().map(move |(event, handler)| {
                let window = if o.is_app { "_".to_string() } else { format!("{:?}", o.name) };
                format!("        ({window}, {event:?}) => Some({handler:?}),\n")
            })
        })
        .collect();
    let options: String = project
        .entities()
        .map(|e| {
            let name = &e.name.name;
            let text = display_field(e).map_or("format!(\"#{}\", r.id)".to_string(), |f| format!("r.{f}.clone()"));
            format!(
                "        {name:?} => db\n            .all::<{}::{name}>()?\n            .into_iter()\n            .map(|r| RefOption {{ id: r.id, text: {text} }})\n            .collect(),\n",
                module_of(name)
            )
        })
        .collect();

    format!(
        r#"{HEADER}{ALLOW}
mod schema;
{mods}
use std::sync::Mutex;

use clarity_runtime::ui::{{RefOption, Reply, Ui, WindowState, from_data, to_data}};
use clarity_runtime::{{Db, Dialect, Error, Result}};
use serde_json::{{Map, Value}};

/// The windows, frame and data dictionary the renderer draws from.
const MODEL: &str = include_str!("model.json");
const MAIN_WINDOW: &str = {main_window:?};
/// The database of each data source: its kind, and its file or connection
/// (`env:NAME` reads it from that environment variable when the
/// application starts).
const DATABASES: &[(&str, Dialect, &str)] = &[{databases}];

struct App(Mutex<Db>);

/// A window's state when it opens, with `with` filled in.
fn open(db: &Db, window: &str, with: Map<String, Value>) -> Result<Reply> {{
    let mut data = match window {{
{opens}        _ => return Err(Error::Invalid(format!("there is no window {{window}}"))),
    }};
    data.extend(with);
    let state = WindowState::new(window, data);
    check(&state)?;
    on_event(db, state, "open")
}}

/// The handler of a window's or the app's own event, if it has one.
fn event_handler(window: &str, event: &str) -> Option<&'static str> {{
    match (window, event) {{
{events}        _ => None,
    }}
}}

/// Runs the handler of an own event (open, close, return, start), or
/// returns the state as it is when there is none.
fn on_event(db: &Db, state: WindowState, event: &str) -> Result<Reply> {{
    match event_handler(&state.window, event) {{
        Some(handler) => dispatch(db, state, handler),
        None => {{
            let data = state.data.clone();
            Ok(Ui::from_state(&state).reply(&state.window, data))
        }}
    }}
}}

/// Fails when the data does not fit the window, such as a wrong `with`.
fn check(state: &WindowState) -> Result<()> {{
    match state.window.as_str() {{
{checks}        _ => {{}}
    }}
    Ok(())
}}

/// Runs a handler on a window's state.
fn dispatch(db: &Db, state: WindowState, handler: &str) -> Result<Reply> {{
    let mut ui = Ui::from_state(&state);
    match (state.window.as_str(), handler) {{
{dispatch}        _ => Err(Error::Invalid(format!("{{}} has no handler {{handler}}", state.window))),
    }}
}}

/// The records a reference field of `entity` can point at.
fn options(db: &Db, entity: &str) -> Result<Vec<RefOption>> {{
    Ok(match entity {{
{options}        _ => Vec::new(),
    }})
}}

/// What a command answers: its result, or what went wrong as the screen
/// shows it. A refusal keeps its slots, so the screen fills them in the
/// format of the person using the application.
type Answer<T> = std::result::Result<T, Value>;

fn locked<T>(app: &App, run: impl FnOnce(&Db) -> Result<T>) -> Answer<T> {{
    let db = app.0.lock().map_err(|_| Value::from("the database is not available"))?;
    run(&db).map_err(|err| match err {{
        Error::Refused(text) => serde_json::to_value(text).unwrap_or_default(),
        other => Value::from(other.to_string()),
    }})
}}

#[tauri::command]
fn start() -> Value {{
    serde_json::json!({{ "model": serde_json::from_str::<Value>(MODEL).unwrap_or(Value::Null), "main": MAIN_WINDOW }})
}}

#[tauri::command]
fn open_window(app: tauri::State<App>, window: String, with: Map<String, Value>) -> Answer<Reply> {{
    locked(&app, |db| open(db, &window, with))
}}

/// Runs a window's `on close` before the screen closes it.
#[tauri::command]
fn close_window(app: tauri::State<App>, state: WindowState) -> Answer<Reply> {{
    locked(&app, |db| on_event(db, state, "close"))
}}

/// Runs a window's `on return` when it is on top again.
#[tauri::command]
fn return_to(app: tauri::State<App>, state: WindowState) -> Answer<Reply> {{
    locked(&app, |db| on_event(db, state, "return"))
}}

/// Runs the app's `on start`, before its main window opens.
#[tauri::command]
fn start_app(app: tauri::State<App>) -> Answer<Reply> {{
    locked(&app, |db| on_event(db, WindowState::new("", Map::new()), "start"))
}}

#[tauri::command]
fn dispatch_event(app: tauri::State<App>, state: WindowState, handler: String) -> Answer<Reply> {{
    locked(&app, |db| dispatch(db, state, &handler))
}}

#[tauri::command]
fn ref_options(app: tauri::State<App>, entity: String) -> Answer<Vec<RefOption>> {{
    locked(&app, |db| options(db, &entity))
}}

#[tauri::command]
fn quit_app(handle: tauri::AppHandle) {{
    handle.exit(0);
}}

fn main() {{
    let mut db = Db::connect(DATABASES).expect("cannot open the databases");
    for (source, steps) in schema::SOURCES {{
        db.migrate_source(source, steps).expect("cannot bring the database up to date");
    }}
    tauri::Builder::default()
        .manage(App(Mutex::new(db)))
        .invoke_handler(tauri::generate_handler![
            start,
            start_app,
            open_window,
            close_window,
            return_to,
            dispatch_event,
            ref_options,
            quit_app
        ])
        .run(tauri::generate_context!())
        .expect("cannot start the application");
}}
"#
    )
}

/// The Cargo package (and program) name of a project.
pub fn crate_name(settings: &Settings) -> String {
    snake(&settings.name)
}

/// The migration steps of data source `source` as the statements a
/// database of `kind` runs, each step with its title; for tools and tests
/// that apply them without building the application.
pub fn migration_sql(project: &Project, source: &str, kind: clarity_project::SourceKind) -> Result<Vec<(String, Vec<String>)>, Vec<String>> {
    let Some(sql) = Sql::of(kind) else {
        return Err(vec![format!("data source '{source}' is not a SQL database")]);
    };
    schema::steps(project, source, sql)
}
