/// The first line of every generated Rust file.
const HEADER: &str = "// Generated by Clarity. Do not edit: change the project in Clarity instead.\n";

/// The runtime crate's manifest, which names its version.
const RUNTIME_MANIFEST: &str = include_str!("../../../../runtimes/rust/Cargo.toml");

/// The version of the runtime crate a generated project requires: the one
/// the runtime in this repository is.
pub fn runtime_version() -> &'static str {
    let start = RUNTIME_MANIFEST.find("\nversion = \"").expect("the runtime's manifest sets its version") + "\nversion = \"".len();
    let end = RUNTIME_MANIFEST[start..].find('"').expect("the version is closed");
    &RUNTIME_MANIFEST[start..start + end]
}

/// The environment variable that, set while Clarity generates a project,
/// names the Rust runtime's folder in Clarity's repository
/// (`<Clarity>/runtimes/rust`), or the C# runtime's beside it as C# wants
/// it, the runtimes folder or the repository.
pub const RUNTIME_VARIABLE: &str = "CLARITY_RUNTIME";

/// `.cargo/config.toml` of a project that builds on the runtime in Clarity's
/// repository (`runtime`). The path is absolute, with `/` between folders (a
/// backslash is an escape in TOML). Fails when `runtime` holds no
/// clarity-runtime crate, saying what to name.
pub fn local_patch(named: &std::path::Path) -> Result<String, String> {
    let wrong = || format!("{RUNTIME_VARIABLE} names {}, which holds no clarity-runtime crate; name the Rust runtime's folder in Clarity's repository, <Clarity>/runtimes/rust", named.display());
    // One variable serves every language: the Rust runtime itself, a runtime beside it (runtimes/csharp), the runtimes folder or the repository.
    let holds = |folder: &std::path::Path| std::fs::read_to_string(folder.join("Cargo.toml")).is_ok_and(|m| m.contains("\nname = \"clarity-runtime\""));
    let candidates = [named.to_path_buf(), named.join("../rust"), named.join("rust"), named.join("runtimes/rust")];
    let runtime = candidates.iter().find(|c| holds(c)).ok_or_else(wrong)?;
    let runtime = runtime.canonicalize().map_err(|_| wrong())?;
    let path = runtime.display().to_string().replace('\\', "/");
    Ok(format!(
        "# Written by Clarity because {RUNTIME_VARIABLE} named the Rust runtime in Clarity's\n# repository when it generated this project: the program builds on the crate\n# there instead of the published one. Remove this folder to build on crates.io.\n\n[patch.crates-io]\nclarity-runtime = {{ path = \"{path}\" }}\n"
    ))
}

/// The patch file when the environment's CLARITY_RUNTIME names the runtime
/// (`local_patch`); none when it is unset or empty.
pub(crate) fn local_patch_file() -> Result<Option<OutFile>, Vec<String>> {
    match std::env::var(RUNTIME_VARIABLE).ok().filter(|v| !v.is_empty()) {
        Some(folder) => local_patch(std::path::Path::new(&folder)).map(|t| Some(text(".cargo/config.toml", t))).map_err(|e| vec![e]),
        None => Ok(None),
    }
}

/// Lints that generated code does not follow, because names come from the
/// project as the developer wrote them.
const ALLOW: &str = "#![allow(non_camel_case_types, non_snake_case, unused_parens, unused_mut, unused_variables, unused_imports, dead_code, unreachable_code, clippy::all)]\n";

pub fn generate(project: &Project, settings: &Settings) -> Result<Vec<OutFile>, Vec<String>> {
    let crate_name = crate_name(settings);
    let project = &crate::with_secret_settings(project, &crate::settings_program(settings));
    let (databases, owned) = crate::databases(project, settings)?;
    let databases = crate::with_secret_locations(databases, &crate::settings_program(settings));
    let mut features: Vec<&str> = databases.iter().map(|(_, sql, _)| sql.feature()).collect();
    // A data source that is a file: an in-memory SQLite table filled through Clarity.Formats.
    if !crate::file_sources(project, settings)?.is_empty() {
        features.extend(["sqlite", "formats"]);
    }
    if !crate::engines(project).is_empty() {
        features.push("engines");
    }
    // Custom parts written in Rust (DESIGN 5.19): the runtime's part host.
    let rust_parts = parts::crate_parts(project);
    let mut mismatches = parts::ui_mismatches(project);
    // What the part's code lacks of Clarity's file, read without building it.
    mismatches.extend(parts::code_mismatches(project));
    if !mismatches.is_empty() {
        return Err(mismatches);
    }
    // `stack rust desktop`: Clarity.UI draws the windows in the program's own process (DESIGN 7.9).
    // `stack rust web`: the program serves Clarity.UI's browser files and answers their wire;
    // with both, `--serve` serves.
    let clarity = settings.stack.has(clarity_project::Target::Desktop);
    let web = settings.stack.has(clarity_project::Target::Web);
    // The desktop links Clarity.UI's ready-made library through the runtime (as Go, C and C++ do).
    if clarity {
        features.push("native-ui");
    }
    let songs = clarity && clarity_spec::resources::plays_songs(project);
    let videos = clarity && clarity_spec::resources::plays_videos(project);
    // The engines beside the screen run in the program, on the runtime's engines (DESIGN 5.12).
    let screen_engines = !crate::screen_engines(project).is_empty();
    if screen_engines {
        features.push("engines");
    }
    // HTTP calls from code (DESIGN 5.23): the runtime's client.
    if project.calls_out() {
        features.push("http");
    }
    // The picture functions of code (docs/IMAGE-PLAN.md): Clarity.Image.
    if crate::uses_picture_functions(project) {
        features.push("pictures");
    }
    // The data formats of code (docs/FORMATS-PLAN.md): Clarity.Formats.
    if crate::carries_formats(project, settings) {
        features.push("formats");
    }
    // Secret settings (DESIGN 5.27): the system's protected store.
    if !project.secret_settings().is_empty() {
        features.push("secrets");
    }
    // Who is using the program (docs/APP-CAPABILITIES-PLAN.md step 4): Clarity.Auth.
    if crate::signin::carries_auth(project) {
        features.push("auth");
    }
    // A sign-in remembered between runs (`remember N days`) is kept in the system's protected store.
    if crate::signin::signin_plan(project).is_some_and(|plan| plan.remember_seconds.is_some()) {
        features.push("secrets");
    }
    // Until the databases open, the windows work on an empty SQLite one in memory.
    if crate::unconnected(project).is_some() {
        features.push("sqlite");
    }
    features.sort();
    features.dedup();
    let Some(main_window) = main_window(project) else {
        return Err(vec!["the project has no window to start with".to_string()]);
    };
    let types = check::types(&project.files);
    let mut errors = Vec::new();
    let mut files = vec![
        text(
            "Cargo.toml",
            cargo_toml(
                &crate_name,
                &features,
                &rust_parts.iter().map(|p| (parts::package_of(project, &p.name.name), p.name.name.clone())).collect::<Vec<_>>(),
                &crate::libraries::libraries(project).iter().map(|l| (crate::libraries::rust_package(project, &l.name.name), l.name.name.clone())).collect::<Vec<_>>(),
            ),
        ),
        text("src/model.json", crate::web::model_json(project)),
    ];
    if clarity {
        // The windows and app frames as markup, the themes and the texts, which Clarity.UI reads (DESIGN 7.9).
        files.extend(clarity_files(project));
    }
    if web {
        // The page and what Clarity.UI draws from in a browser, in browser/; the library's files join them (web_browser).
        files.extend(crate::web_browser::site(project, settings));
    }

    let mut modules = Vec::new();
    let mut owners: Vec<Owner> = Vec::new();
    for file in &project.files {
        let Some(module) = &file.module else { continue };
        let name = snake(&module.name);
        let file_types = types.get(&file.path).cloned().unwrap_or_default();
        let mut code = format!("{HEADER}\nuse clarity_runtime::sql;\nuse clarity_runtime::ui::*;\nuse clarity_runtime::*;\n");
        for used in &file.uses {
            code.push_str(&format!("use super::{}::*;\n", snake(&used.name)));
        }
        code.push('\n');
        code.push_str(&model::emit(project, file));
        match logic::emit(project, file, &file_types) {
            Ok(functions) => code.push_str(&functions),
            Err(mut problems) => errors.append(&mut problems),
        }
        match logic::emit_windows(project, file, &file_types, &format!("modules::{name}")) {
            Ok((windows, mut found)) => {
                code.push_str(&windows);
                owners.append(&mut found);
            }
            Err(mut problems) => errors.append(&mut problems),
        }
        files.push(text(&format!("src/modules/{name}.rs"), code.trim_end().to_string() + "\n"));
        modules.push(name);
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    let declared: String = modules.iter().map(|m| format!("pub mod {m};\n")).collect();
    files.push(text("src/modules.rs", format!("{HEADER}\n{declared}")));
    files.push(text("src/schema.rs", schema_rs(project, &owned)?));
    files.extend(crate::engine_files(project, "engines"));
    if screen_engines {
        files.extend(crate::screen_engine_files(project, "engines"));
    }
    // Each custom part's crate, its interface written from its declaration, and the glue that registers it.
    for part in &rust_parts {
        let n = &part.name.name;
        for file in project.part_files.iter().flatten().filter(|f| f.part == *n && f.path != "src/clarity.rs") {
            files.push(OutFile { path: format!("parts/{n}/{}", file.path), text: String::new(), bytes: Some(file.bytes.clone().into()) });
        }
        files.push(text(&format!("parts/{n}/src/clarity.rs"), parts::ui_interface(part)));
    }
    if !rust_parts.is_empty() {
        files.push(text("src/parts.rs", parts::ui_glue(project)));
    }
    // Each library's crate, its trait written from its declaration (DESIGN 5.21).
    for library in crate::libraries::libraries(project) {
        let n = &library.name.name;
        let own = crate::libraries::own_file(library, false);
        files.extend(crate::libraries::adapter_files(project, n, &own));
        files.push(text(&format!("{}/{own}", crate::libraries::folder(n)), crate::libraries::rust_interface(library)));
    }
    if !crate::engines(project).is_empty() {
        files.push(text("src/engines.rs", engines_rs(project)));
    }
    // The browser files, which the web server serves from the program itself: its own and the library's.
    let mut served: Vec<String> = files.iter().filter_map(|f| f.path.strip_prefix("browser/").map(String::from)).collect();
    if web {
        served.extend(crate::clarity_ui::BROWSER_FILES.iter().map(|f| f.to_string()));
        served.sort();
    }
    let clarity_run = clarity.then(|| clarity_run(project, settings, &files, &main_window, !rust_parts.is_empty(), songs, videos));
    let main_text = main_rs(project, settings, &owners, &databases, &main_window, &served, clarity_run.as_deref());
    // What Clarity.UI's parts read beside the values: the facts of the fields and types (DESIGN 7.9).
    files.push(text("src/facts.rs", facts_rs(project)));
    let main_text = main_text
        .replacen("mod modules;\n", "mod modules;\nmod facts;\n", 1)
        .replacen("impl Program for App {\n", &format!("{}impl Program for App {{\n    fn facts_json(&self) -> Value {{\n        facts::FACTS.to_json()\n    }}\n\n{}", screen_engines_static(project), screen_engine_fn(project)), 1);
    files.push(text("src/main.rs", main_text));
    // Built on the crates in Clarity's repository when CLARITY_RUNTIME names them.
    files.extend(local_patch_file()?);
    // The program file's icon and version on Windows, linked by build.rs (docs/APP-ICON-SPLASH-PLAN.md, docs/VERSION-PLAN.md);
    // on the desktop, build.rs links the ready-made library too.
    let icons = crate::windows_resources::object_files(project, &clarity_project::title(settings), &crate_name, crate::windows_resources::object_path);
    let has_icons = !icons.is_empty();
    files.extend(icons);
    if clarity {
        files.push(text("build.rs", native_build_rs(songs, videos, has_icons)));
    } else if has_icons {
        files.push(text("build.rs", crate::windows_resources::RUST_BUILD.to_string()));
    }
    Ok(files)
}

/// Where the program keeps the engines beside the screen its canvases
/// opened, by number (`clarity_runtime::screen::Instances`). Empty without
/// such engines.
fn screen_engines_static(project: &Project) -> String {
    if crate::screen_engines(project).is_empty() {
        return String::new();
    }
    "/// The engines beside the screen the canvases opened, by number.\nstatic SCREEN_ENGINES: clarity_runtime::screen::Instances = clarity_runtime::screen::Instances::new();\n\n".to_string()
}

/// The program's answer to a canvas that runs an engine beside the screen
/// (DESIGN 5.12): a new instance of it from its file, kept in the program by
/// number, its frames and its end by that number; none for a name it has no
/// engine of. Empty without such engines.
fn screen_engine_fn(project: &Project) -> String {
    let engines = crate::screen_engines(project);
    if engines.is_empty() {
        return String::new();
    }
    let arms: String = engines
        .iter()
        .map(|e| {
            format!(
                "            {name:?} => clarity_runtime::engine::ScreenEngine::load({name:?}, include_bytes!(\"../engines/{file}\"), &[{uses}], {opens}, clarity_runtime::engine::Limits {{ seconds: {seconds}, megabytes: {megabytes} }}),\n",
                name = e.name.name,
                file = e.file,
                uses = e.uses.iter().map(|u| format!("{:?}", u.name)).collect::<Vec<_>>().join(", "),
                opens = e.opens,
                seconds = e.seconds(),
                megabytes = e.megabytes(),
            )
        })
        .collect();
    format!(
        "    fn engine_open(&self, name: &str) -> Option<std::result::Result<u64, String>> {{\n        let made = match name {{\n{arms}            _ => return None,\n        }};\n        Some(made.map(|engine| SCREEN_ENGINES.open(Box::new(engine))))\n    }}\n\n    fn engine_hears(&self, id: u64) -> clarity_runtime::screen::Hears {{\n        SCREEN_ENGINES.hears(id)\n    }}\n\n    fn engine_frame(&self, id: u64, ms: f64, input: Vec<clarity_runtime::screen::ScreenInput>) -> std::result::Result<clarity_runtime::screen::Drawn, String> {{\n        SCREEN_ENGINES.frame(id, ms, &input)\n    }}\n\n    fn engine_close(&self, id: u64) {{\n        SCREEN_ENGINES.close(id)\n    }}\n\n"
    )
}

/// A type as the runtime's facts write it (`clarity_runtime::fields`): a
/// record, entity or enum by its name, a list as `list<Order>`, a reference
/// as `ref<Customer>`, a plain value by its keyword.
fn fact_type(ty: &FieldType) -> String {
    match ty {
        FieldType::Text { .. } => "text".into(),
        FieldType::Integer => "integer".into(),
        FieldType::Decimal { .. } => "decimal".into(),
        FieldType::Money => "money".into(),
        FieldType::Bool => "bool".into(),
        FieldType::Date => "date".into(),
        FieldType::DateTime => "datetime".into(),
        FieldType::Duration => "duration".into(),
        FieldType::Image => "image".into(),
        FieldType::File => "file".into(),
        FieldType::Email => "email".into(),
        FieldType::Url => "url".into(),
        FieldType::Color => "color".into(),
        FieldType::Secret => "secret".into(),
        FieldType::Folder => "folder".into(),
        FieldType::Language => "language".into(),
        FieldType::Theme => "theme".into(),
        FieldType::Id => "id".into(),
        FieldType::Enum { name } => name.name.clone(),
        FieldType::Ref { entity } => format!("ref<{}>", entity.name),
        FieldType::Record { entity } => entity.name.clone(),
        FieldType::List { item } => format!("list<{}>", item.name),
        FieldType::Values { item } => format!("list<{}>", item.word()),
    }
}

/// A type written in code, as [`fact_type`] writes it.
fn code_fact_type(ty: &clarity_spec::code::TypeRef) -> String {
    use clarity_spec::code::TypeRefKind as K;
    match &ty.kind {
        K::Text => "text".into(),
        K::Integer => "integer".into(),
        K::Decimal => "decimal".into(),
        K::Money => "money".into(),
        K::Bool => "bool".into(),
        K::Date => "date".into(),
        K::DateTime => "datetime".into(),
        K::Duration => "duration".into(),
        K::File => "file".into(),
        K::Bytes => "bytes".into(),
        K::Named { name } => name.clone(),
        K::List { item } => format!("list<{item}>"),
    }
}

/// The facts of a program on Clarity.UI (DESIGN 7.9), as the C# program's
/// Fields.cs: each window's values and their types, each entity's and
/// record's fields and theirs, the facts of every entity's field keyed
/// "Entity.field", and each enum's values.
fn facts_rs(project: &Project) -> String {
    use clarity_spec::model::{DataKind, Literal};
    let typed = |pairs: Vec<(String, String)>| -> String { format!("&[{}]", pairs.iter().map(|(n, t)| format!("({n:?}, {t:?})")).collect::<Vec<_>>().join(", ")) };
    let optional = |value: Option<&str>| value.map_or("None".to_string(), |v| format!("Some({v:?})"));
    let literal = |value: &Option<Literal>| match value {
        Some(Literal::Number(v) | Literal::Str(v) | Literal::Ident(v)) => format!("Some({v:?})"),
        Some(Literal::Bool(b)) => format!("Some({:?})", b.to_string()),
        None => "None".to_string(),
    };
    let mut windows = String::new();
    let pages = project.files.iter().flat_map(|f| f.pages.iter().map(|p| (&p.name.name, &p.data)));
    let apps = project.files.iter().flat_map(|f| f.apps.iter().map(|a| (&a.name.name, &a.data)));
    for (name, data) in pages.chain(apps) {
        let values = data
            .iter()
            .map(|d| {
                let ty = match &d.of {
                    DataKind::Record { entity } => entity.name.clone(),
                    DataKind::List { entity } => format!("list<{}>", entity.name),
                    DataKind::Value { ty, .. } => code_fact_type(ty),
                };
                (d.name.name.clone(), ty)
            })
            .collect();
        let _ = writeln!(windows, "        ({name:?}, {}),", typed(values));
    }
    let mut records = String::new();
    let mut fields = String::new();
    for file in &project.files {
        for entity in file.entities.iter().chain(&file.records) {
            let types = entity.fields.iter().map(|f| (f.name.name.clone(), fact_type(&f.ty))).collect();
            let _ = writeln!(records, "        ({:?}, {}),", entity.name.name, typed(types));
        }
    }
    for entity in project.entities().chain(project.records()) {
        let parent = crate::csharp::tree_parent(entity);
        for field in &entity.fields {
            let refers = match &field.ty {
                FieldType::Ref { entity } => Some(entity.name.as_str()),
                _ => None,
            };
            let format = fact_format(field).map_or("None".to_string(), |f| format!("Some({f})"));
            let _ = writeln!(
                fields,
                "        ({key:?}, FieldFacts {{ label: {label:?}, format: {format}, required: {required}, min: {min}, max: {max}, refers: {refers}, parent: {parent}, color: {color} }}),",
                key = format!("{}.{}", entity.name.name, field.name.name),
                label = field.label,
                required = field.modifiers.required,
                min = literal(&field.modifiers.min),
                max = literal(&field.modifiers.max),
                refers = optional(refers),
                parent = optional(parent),
                color = matches!(field.ty, FieldType::Color),
            );
        }
    }
    let enums: String = project
        .enums()
        .map(|e| format!("        ({:?}, &[{}]),\n", e.name.name, e.variants.iter().map(|v| format!("{:?}", v.name.name)).collect::<Vec<_>>().join(", ")))
        .collect();
    format!(
        "{HEADER}\n//! What the program knows of its fields and types, which Clarity.UI's parts\n//! read beside the values: each window's values and their types, each\n//! record's fields and theirs, the facts of every entity's field keyed\n//! \"Entity.field\", and each enum's values.\n\nuse clarity_runtime::fields::{{Facts, FieldFacts, FieldFormat, FormatKind}};\n\npub static FACTS: Facts = Facts {{\n    windows: &[\n{windows}    ],\n    records: &[\n{records}    ],\n    fields: &[\n{fields}    ],\n    enums: &[\n{enums}    ],\n}};\n"
    )
}

/// The facts of [`facts_rs`] as the JSON the library reads (`facts`, DESIGN
/// 7.9, `clarity_runtime::fields::Facts::to_json`), for the languages that
/// answer it through the C interface.
pub(crate) fn facts_json(project: &Project) -> String {
    use clarity_spec::model::{DataKind, Literal};
    use serde_json::{Map, Value, json};
    let literal = |value: &Option<Literal>| match value {
        Some(Literal::Number(v) | Literal::Str(v) | Literal::Ident(v)) => Value::from(v.as_str()),
        Some(Literal::Bool(b)) => Value::from(b.to_string()),
        None => Value::Null,
    };
    let mut windows = Map::new();
    let pages = project.files.iter().flat_map(|f| f.pages.iter().map(|p| (&p.name.name, &p.data)));
    let apps = project.files.iter().flat_map(|f| f.apps.iter().map(|a| (&a.name.name, &a.data)));
    for (name, data) in pages.chain(apps) {
        let values: Map<String, Value> = data
            .iter()
            .map(|d| {
                let ty = match &d.of {
                    DataKind::Record { entity } => entity.name.clone(),
                    DataKind::List { entity } => format!("list<{}>", entity.name),
                    DataKind::Value { ty, .. } => code_fact_type(ty),
                };
                (d.name.name.clone(), Value::from(ty))
            })
            .collect();
        windows.insert(name.clone(), Value::Object(values));
    }
    let mut records = Map::new();
    for file in &project.files {
        for entity in file.entities.iter().chain(&file.records) {
            let types: Map<String, Value> = entity.fields.iter().map(|f| (f.name.name.clone(), Value::from(fact_type(&f.ty)))).collect();
            records.insert(entity.name.name.clone(), Value::Object(types));
        }
    }
    let mut fields = Map::new();
    for entity in project.entities().chain(project.records()) {
        let parent = crate::csharp::tree_parent(entity);
        for field in &entity.fields {
            let refers = match &field.ty {
                FieldType::Ref { entity } => Some(entity.name.as_str()),
                _ => None,
            };
            let format = fact_format_parts(field).map(|(kind, scale)| json!({"kind": kind, "scale": scale, "format": field.modifiers.format}));
            fields.insert(
                format!("{}.{}", entity.name.name, field.name.name),
                json!({
                    "label": field.label,
                    "format": format,
                    "required": field.modifiers.required,
                    "min": literal(&field.modifiers.min),
                    "max": literal(&field.modifiers.max),
                    "refers": refers,
                    "parent": parent,
                    "color": matches!(field.ty, FieldType::Color),
                }),
            );
        }
    }
    let enums: Map<String, Value> = project.enums().map(|e| (e.name.name.clone(), Value::from(e.variants.iter().map(|v| v.name.name.clone()).collect::<Vec<_>>()))).collect();
    json!({"windows": windows, "records": records, "fields": fields, "enums": enums}).to_string()
}

/// A field's format kind as conformance/formats.json names it, and its scale; none for a type without formats.
fn fact_format_parts(field: &clarity_spec::model::Field) -> Option<(&'static str, Option<u32>)> {
    match &field.ty {
        FieldType::Integer => Some(("integer", None)),
        FieldType::Decimal { .. } => Some(("decimal", field.ty.shown_scale())),
        FieldType::Money => Some(("money", None)),
        FieldType::Date => Some(("date", None)),
        FieldType::DateTime => Some(("dateTime", None)),
        FieldType::Duration => Some(("duration", None)),
        _ => None,
    }
}

/// How a field's values are formatted, as the runtime's `FieldFormat`, for
/// the types that have formats.
fn fact_format(field: &clarity_spec::model::Field) -> Option<String> {
    let (kind, scale) = match &field.ty {
        FieldType::Integer => ("Integer", None),
        FieldType::Decimal { .. } => ("Decimal", field.ty.shown_scale()),
        FieldType::Money => ("Money", None),
        FieldType::Date => ("Date", None),
        FieldType::DateTime => ("DateTime", None),
        FieldType::Duration => ("Duration", None),
        _ => return None,
    };
    let scale = scale.map_or("None".to_string(), |s| format!("Some({s})"));
    let format = field.modifiers.format.as_deref().map_or("None".to_string(), |f| format!("Some({f:?})"));
    Some(format!("FieldFormat {{ kind: FormatKind::{kind}, scale: {scale}, format: {format} }}"))
}

