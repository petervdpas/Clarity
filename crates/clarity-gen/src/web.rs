//! The web renderer's share of a project's look: one CSS file per theme
//! (design section 1.5, T1), as a web developer would write it. The
//! application holds the theme's class on its root, and a part holds the
//! class of its style. The designer gets the same CSS for its canvas.

use clarity_spec::model::ThemeDecl;
use clarity_spec::themes::{full_hex, resolve};


/// The renderer's CSS variable for each role a theme can set.
const ROLE_VARIABLES: [(&str, &str); 8] = [
    ("background", "--bg"),
    ("panel", "--panel"),
    ("text", "--text"),
    ("muted", "--text-muted"),
    ("border", "--border"),
    ("accent", "--accent"),
    ("error", "--error"),
    ("warning", "--warning"),
];

/// The file of a theme in the generated application's `ui` folder:
/// `themes/night-owl.css` for the class `theme-night-owl`.
pub fn theme_file(theme: &ThemeDecl) -> String {
    format!("themes/{}.css", theme.class.trim_start_matches("theme-"))
}

/// The CSS variable of a color: a role's own variable, or one of the
/// theme's colors (names are the theme's own, an open set).
fn variable(color: &str) -> String {
    ROLE_VARIABLES
        .iter()
        .find(|(role, _)| *role == color)
        .map_or_else(|| format!("--color-{}", color.replace('_', "-")), |(_, var)| var.to_string())
}

/// A color as a style writes it: a name as its variable, `#abc` in full.
fn color_value(written: &str) -> String {
    if written.starts_with('#') { full_hex(written) } else { format!("var({})", variable(written)) }
}

fn rule(selector: &str, lines: &[String]) -> String {
    let body: String = lines.iter().map(|l| format!("  {l};\n")).collect();
    format!("{selector} {{\n{body}}}\n")
}

/// The CSS file of `theme`. Its colors for light mode go on its class, those
/// that differ in dark mode on its class with `data-scheme="dark"`, and its
/// styles under it as `style-<name>` classes.
pub fn theme_css(theme: &ThemeDecl) -> String {
    let class = format!(".{}", theme.class);
    let light = resolve(theme, false);
    let dark = resolve(theme, true);
    let mut lines: Vec<String> = theme
        .colors
        .iter()
        .filter_map(|c| light.colors.get(&c.name.name).map(|v| format!("{}: {v}", variable(&c.name.name))))
        .collect();
    if let Some(font) = &theme.font {
        lines.push(format!("--font: \"{}\"", font.replace('"', "")));
    }
    if let Some(size) = theme.size {
        lines.push(format!("--font-size: {size}px"));
    }
    if let Some(radius) = theme.radius {
        lines.push(format!("--radius: {radius}px"));
    }
    lines.push("color: var(--text)".into());
    lines.push("background: var(--bg)".into());
    if theme.font.is_some() {
        lines.push("font-family: var(--font)".into());
    }
    if theme.size.is_some() {
        lines.push("font-size: var(--font-size)".into());
    }
    let mut out = format!(
        "/* Generated by Clarity from theme {}. Do not edit: change the theme in Clarity instead. */\n\n",
        theme.name.name
    );
    out.push_str(&rule(&class, &lines));
    let darker: Vec<String> = theme
        .colors
        .iter()
        .filter_map(|c| {
            let name = &c.name.name;
            let value = dark.colors.get(name)?;
            (light.colors.get(name) != Some(value)).then(|| format!("{}: {value}", variable(name)))
        })
        .collect();
    if !darker.is_empty() {
        out.push('\n');
        out.push_str(&rule(&format!("{class}[data-scheme=\"dark\"]"), &darker));
    }
    for style in &theme.styles {
        let mut parts = Vec::new();
        if let Some(background) = &style.background {
            parts.push(format!("background: {}", color_value(background)));
        }
        if let Some(text) = &style.text {
            parts.push(format!("color: {}", color_value(text)));
        }
        match style.border.as_deref() {
            Some("none") => parts.push("border: none".into()),
            Some(border) => parts.push(format!("border-color: {}", color_value(border))),
            None => {}
        }
        out.push('\n');
        out.push_str(&rule(&format!("{class} .{}", style.class), &parts));
    }
    out
}
