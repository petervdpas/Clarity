//! The windows of a web stack as markup (DESIGN 7.8, G6b): one Svelte file
//! per window, `ui/src/windows/Main.svelte`, each part an element of the
//! screen package (`@clarity/ui`) with its options as attributes, written in
//! Clarity's own words, as C# writes each window as AXAML.
//!
//! A part writes only what differs from its kind's defaults (the catalog's
//! `new_props`, which the package reads from `generated/part-defaults.json`),
//! so a window reads like its Clarity.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use clarity_spec::model::{Command, CommandKind, Menu, Page, PageKind, Project, Widget, WidgetPage};
use clarity_spec::widgets::{self, WidgetKind};
use serde_json::Value;

use crate::OutFile;

/// Where the window files go in a generated project's `ui` folder.
pub const WINDOWS_FOLDER: &str = "ui/src/windows";

/// A field of a part's props and the word its attribute is written with,
/// where Clarity writes it differently. Every other field keeps its name.
const WORDS: [(&str, &str); 4] = [
    ("shortcut", "key"),
    ("tabOrder", "taborder"),
    // A tree's `children` field; `children` is what a Svelte element holds.
    ("children", "childList"),
    ("onClick", "opens"),
];

/// Fields written in their own form, not compared with the defaults:
/// the kind (the element), the place (`at`, `span`, `rows`), the handlers
/// (`onclick`), and what the project works out itself.
const OWN_FORM: [&str; 9] = ["kind", "name", "col", "row", "width", "height", "handlers", "made", "undoScope"];

/// The windows and dialogs of the project as markup, one file each.
pub fn window_files(project: &Project) -> Vec<OutFile> {
    project
        .files
        .iter()
        .flat_map(|f| &f.pages)
        .filter(|p| p.kind != PageKind::View)
        .map(|page| OutFile { path: format!("{WINDOWS_FOLDER}/{}.svelte", page.name.name), text: window_markup(page), bytes: None })
        .collect()
}

/// One window as a Svelte file of the screen package's elements.
pub fn window_markup(page: &Page) -> String {
    let mut used = BTreeSet::new();
    let mut body = String::new();
    for widget in drawn(&page.widgets) {
        part(widget, 1, &mut used, &mut body);
    }
    used.insert("Window".to_string());
    let imports = used.into_iter().collect::<Vec<_>>().join(", ");
    format!(
        "<!-- Generated by Clarity from the window {name}. Do not edit: change the window in Clarity instead. -->\n<script lang=\"ts\">\n  import {{ {imports} }} from \"@clarity/ui\";\n</script>\n\n<Window name=\"{name}\">\n{body}</Window>\n",
        name = page.name.name
    )
}

/// The parts the screen draws: a sound and a timer have no place on it.
fn drawn(widgets: &[Widget]) -> impl Iterator<Item = &Widget> {
    widgets.iter().filter(|w| !matches!(w.props.kind, WidgetKind::Sound | WidgetKind::Timer))
}

/// A part's kind as the model names it: `treeTable`, `custom`.
fn kind_name(kind: WidgetKind) -> String {
    serde_json::to_value(kind).ok().and_then(|v| v.as_str().map(str::to_string)).unwrap_or_default()
}

/// A part's element name: its kind in Pascal case, `treeTable` as `TreeTable`.
pub fn element_name(kind: WidgetKind) -> String {
    let word = kind_name(kind);
    let mut chars = word.chars();
    chars.next().map(|c| c.to_ascii_uppercase().to_string() + chars.as_str()).unwrap_or_default()
}

fn part(widget: &Widget, depth: usize, used: &mut BTreeSet<String>, out: &mut String) {
    let pad = "  ".repeat(depth);
    let p = &widget.props;
    let element = element_name(p.kind);
    used.insert(element.clone());
    let attributes = attributes(widget);
    let inner = !widget.children.is_empty() || !widget.pages.is_empty() || widget.menu.is_some();
    if !inner {
        let _ = writeln!(out, "{pad}<{element}{attributes} />");
        return;
    }
    let _ = writeln!(out, "{pad}<{element}{attributes}>");
    if let Some(menu) = &widget.menu {
        menu_element(menu, depth + 1, used, out);
    }
    for child in drawn(&widget.children) {
        part(child, depth + 1, used, out);
    }
    for page in &widget.pages {
        page_element(p.kind, page, depth + 1, used, out);
    }
    let _ = writeln!(out, "{pad}</{element}>");
}

/// A part's menu (DESIGN 5.16): `<Menu>` with an `<Item>` per command.
fn menu_element(menu: &Menu, depth: usize, used: &mut BTreeSet<String>, out: &mut String) {
    let pad = "  ".repeat(depth);
    used.insert("Menu".to_string());
    let name = menu.name.as_ref().map(|n| attribute("name", &Value::String(n.clone()))).unwrap_or_default();
    let _ = writeln!(out, "{pad}<Menu{name}>");
    for item in &menu.items {
        command_element(item, depth + 1, used, out);
    }
    let _ = writeln!(out, "{pad}</Menu>");
}

/// A command of a menu: what differs from a new item, in Clarity's words,
/// and the items of a submenu inside it.
fn command_element(command: &Command, depth: usize, used: &mut BTreeSet<String>, out: &mut String) {
    let pad = "  ".repeat(depth);
    used.insert("Item".to_string());
    let defaults = serde_json::to_value(clarity_spec::frame::new_command(CommandKind::Item, None)).unwrap_or(Value::Null);
    let mut attributes = String::new();
    for (field, value) in in_order(&serde_json::to_string(&command.props).unwrap_or_default()) {
        if defaults.get(&field) == Some(&value) {
            continue;
        }
        let word = match field.as_str() {
            "shortcut" => "key",
            "onClick" => "opens",
            "handler" => "onclick",
            other => other,
        };
        attributes.push_str(&attribute(word, &value));
    }
    if command.items.is_empty() {
        let _ = writeln!(out, "{pad}<Item{attributes} />");
        return;
    }
    let _ = writeln!(out, "{pad}<Item{attributes}>");
    for item in &command.items {
        command_element(item, depth + 1, used, out);
    }
    let _ = writeln!(out, "{pad}</Item>");
}

/// A tab, step, section or pane, with the parts on it.
fn page_element(kind: WidgetKind, page: &WidgetPage, depth: usize, used: &mut BTreeSet<String>, out: &mut String) {
    let pad = "  ".repeat(depth);
    let element = match kind {
        WidgetKind::Steps => "Step",
        WidgetKind::Accordion => "Section",
        WidgetKind::Splitter => "Pane",
        _ => "Tab",
    };
    used.insert(element.to_string());
    let mut attributes = String::new();
    if let Some(title) = &page.title {
        attributes.push_str(&attribute("title", &Value::String(title.clone())));
    }
    if let Some(columns) = page.columns {
        attributes.push_str(&attribute("span", &Value::from(columns)));
    }
    let _ = writeln!(out, "{pad}<{element}{attributes}>");
    for child in drawn(&page.children) {
        part(child, depth + 1, used, out);
    }
    let _ = writeln!(out, "{pad}</{element}>");
}

/// The attributes of a part: its name and place first, then what differs
/// from its kind's defaults, then its handlers.
fn attributes(widget: &Widget) -> String {
    let p = &widget.props;
    let mut out = String::new();
    if let Some(name) = &p.name {
        out.push_str(&attribute("name", &Value::String(name.clone())));
    }
    let _ = write!(out, " at=\"{},{}\"", p.col, p.row);
    out.push_str(&attribute("span", &Value::from(p.width)));
    if p.height > 1 {
        out.push_str(&attribute("rows", &Value::from(p.height)));
    }
    let own = in_order(&serde_json::to_string(p).unwrap_or_default());
    let defaults = serde_json::to_value(widgets::new_props(p.kind, p.col, p.row)).unwrap_or(Value::Null);
    if let Value::Object(defaults) = defaults {
        for (field, value) in &own {
            if OWN_FORM.contains(&field.as_str()) || defaults.get(field) == Some(value) {
                continue;
            }
            let word = WORDS.iter().find(|(f, _)| f == field).map_or(field.as_str(), |(_, w)| w);
            out.push_str(&attribute(word, value));
        }
    }
    for h in &p.handlers {
        out.push_str(&attribute(&format!("on{}", h.event.keyword()), &Value::String(widgets::handler_call(h))));
    }
    out
}

/// The fields of a serialized object in the order they were written, which
/// is the order of the props struct and of a part's line in Clarity.
fn in_order(json: &str) -> Vec<(String, Value)> {
    struct Fields;
    impl<'de> serde::de::Visitor<'de> for Fields {
        type Value = Vec<(String, Value)>;
        fn expecting(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
            f.write_str("an object")
        }
        fn visit_map<A: serde::de::MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
            let mut fields = Vec::new();
            while let Some(entry) = map.next_entry::<String, Value>()? {
                fields.push(entry);
            }
            Ok(fields)
        }
    }
    let mut reader = serde_json::Deserializer::from_str(json);
    serde::Deserializer::deserialize_map(&mut reader, Fields).unwrap_or_default()
}

/// ` word="text"`, ` word` for true, or ` word={value}` for anything else.
fn attribute(word: &str, value: &Value) -> String {
    match value {
        Value::Bool(true) => format!(" {word}"),
        // Plain text as it is; text a Svelte attribute would read otherwise (braces, entities, quotes) as a string expression.
        Value::String(s) if !s.contains(['{', '}', '"', '&', '<', '\n']) => format!(" {word}=\"{s}\""),
        other => format!(" {word}={{{other}}}"),
    }
}

/// A new menu item's defaults as the package's `<Item>` reads them (`command-defaults.json`).
pub fn command_defaults() -> String {
    serde_json::to_string_pretty(&clarity_spec::frame::new_command(CommandKind::Item, None)).unwrap_or_default() + "\n"
}

/// Every kind's defaults as the package's elements read them (`part-defaults.json`).
pub fn part_defaults() -> String {
    let mut all = serde_json::Map::new();
    for info in widgets::catalog() {
        all.insert(kind_name(info.kind), serde_json::to_value(widgets::new_props(info.kind, 1, 1)).unwrap_or(Value::Null));
    }
    serde_json::to_string_pretty(&Value::Object(all)).unwrap_or_default() + "\n"
}

/// The tools a generated screen builds with, at the versions Clarity's own
/// screen is built and tested with (app/package.json; tests/web_windows.rs keeps them equal).
pub const SCREEN_TOOLS: [(&str, &str); 4] = [("svelte", "5.57.2"), ("@tauri-apps/api", "2.12.4"), ("vite", "8.3.4"), ("@sveltejs/vite-plugin-svelte", "7.3.1")];

/// The screen of a web stack's application as a project of its own, in
/// `ui/` (DESIGN 7.8): its windows as markup, Clarity's screen package in
/// `ui/clarity-ui/`, its themes and resources in `ui/public/`, built with
/// Vite (`npm install`, `npm run build`) into `ui/dist/`, which the program
/// serves.
pub fn ui_project(project: &Project, name: &str) -> Vec<OutFile> {
    ui_project_as(project, name, false)
}

/// The screen's project for a program whose webview shows one page and no
/// folder (the C and C++ stacks): the build writes `ui/dist/index.html`
/// with its script, styles, themes and pictures in it, which CMake compiles
/// into the program.
pub fn one_page_project(project: &Project, name: &str) -> Vec<OutFile> {
    ui_project_as(project, name, true)
}

fn ui_project_as(project: &Project, name: &str, one_page: bool) -> Vec<OutFile> {
    let text = |path: &str, body: String| OutFile { path: path.to_string(), text: body, bytes: None };
    let mut files = Vec::new();
    let package = format!(
        "{{\n  \"name\": \"{name}-ui\",\n  \"private\": true,\n  \"type\": \"module\",\n  \"scripts\": {{\n    \"build\": \"vite build\"\n  }},\n  \"dependencies\": {{\n    \"@clarity/ui\": \"file:./clarity-ui\",\n    \"{}\": \"{}\",\n    \"{}\": \"{}\"\n  }},\n  \"devDependencies\": {{\n    \"{}\": \"{}\",\n    \"{}\": \"{}\"\n  }}\n}}\n",
        SCREEN_TOOLS[0].0, SCREEN_TOOLS[0].1, SCREEN_TOOLS[1].0, SCREEN_TOOLS[1].1, SCREEN_TOOLS[2].0, SCREEN_TOOLS[2].1, SCREEN_TOOLS[3].0, SCREEN_TOOLS[3].1
    );
    files.push(text("ui/package.json", package));
    // A webview that shows one page gets the whole screen in index.html (the package's build/onePage.mjs).
    let config = if one_page {
        VITE_CONFIG
            .replace("  plugins: [svelte()],", "  plugins: [svelte(), onePage()],")
            .replace("import { svelte } from \"@sveltejs/vite-plugin-svelte\";\n", "import { svelte } from \"@sveltejs/vite-plugin-svelte\";\nimport { onePage } from \"@clarity/ui/build/onePage.mjs\";\n")
    } else {
        VITE_CONFIG.to_string()
    };
    files.push(text("ui/vite.config.ts", config));
    files.push(text("ui/svelte.config.js", SVELTE_CONFIG.to_string()));
    files.push(text("ui/.gitignore", "# What npm install and npm run build make.\nnode_modules/\ndist/\n".to_string()));
    // Each window that is markup, and the start that hands them to the screen.
    let windows = window_files(project);
    let names: Vec<String> = windows.iter().filter_map(|f| f.path.rsplit('/').next()?.strip_suffix(".svelte").map(str::to_string)).collect();
    let mut main = String::from("// Generated by Clarity: the application's screen, its windows as markup.\nimport { startScreen } from \"@clarity/ui/host/start.ts\";\n");
    for n in &names {
        let _ = writeln!(main, "import {n} from \"./windows/{n}.svelte\";");
    }
    let _ = writeln!(main, "\nstartScreen({{ {} }});", names.join(", "));
    files.push(text("ui/src/main.ts", main));
    files.extend(windows);
    // The themes and resources the page links, as they are, in public/.
    let mut links = String::new();
    for file in crate::web::screen_assets(project) {
        let Some(rest) = file.path.strip_prefix("ui/") else { continue };
        if rest.starts_with("themes/") {
            let _ = writeln!(links, "    <link rel=\"stylesheet\" href=\"./{rest}\">");
        }
        if rest.starts_with("themes/") || rest.starts_with("resources/") {
            files.push(OutFile { path: format!("ui/public/{rest}"), ..file });
        }
    }
    files.push(text("ui/index.html", format!("<!doctype html>\n<html lang=\"en\">\n  <head>\n    <meta charset=\"UTF-8\" />\n    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\" />\n    <title></title>\n{links}  </head>\n  <body>\n    <div id=\"app\"></div>\n    <script type=\"module\" src=\"/src/main.ts\"></script>\n  </body>\n</html>\n")));
    files.extend(crate::screen_package::files().iter().map(|(path, body)| text(&format!("ui/clarity-ui/{path}"), (*body).to_string())));
    files
}

/// The files `npm run build` writes into `ui/dist/`, by their path there:
/// the page, its one script and style sheet, and what `ui/public/` holds.
pub fn dist_files(project: &Project) -> Vec<String> {
    let mut files: Vec<String> = ["index.html", "runtime.js", "runtime.css"].map(String::from).to_vec();
    files.extend(ui_project(project, "").into_iter().filter_map(|f| f.path.strip_prefix("ui/public/").map(String::from)));
    files
}

const VITE_CONFIG: &str = "// Generated by Clarity: builds the application's screen into dist/, which\n// the program serves, with Clarity's screen package (clarity-ui/).\nimport { defineConfig } from \"vite\";\nimport { svelte } from \"@sveltejs/vite-plugin-svelte\";\n\nexport default defineConfig({\n  plugins: [svelte()],\n  base: \"./\",\n  // One copy of each, for the screen package and the windows alike.\n  resolve: { dedupe: [\"svelte\", \"@tauri-apps/api\"] },\n  // The package is Svelte and TypeScript as written, compiled with the windows.\n  optimizeDeps: { exclude: [\"@clarity/ui\"] },\n  build: {\n    outDir: \"dist\",\n    emptyOutDir: true,\n    rollupOptions: {\n      // One script and one style sheet, by the names the program embeds them under.
      output: { entryFileNames: \"runtime.js\", assetFileNames: \"runtime.[ext]\", inlineDynamicImports: true },\n    },\n  },\n});\n";

const SVELTE_CONFIG: &str = "// Generated by Clarity: the windows and the screen package are Svelte with TypeScript.\nimport { vitePreprocess } from \"@sveltejs/vite-plugin-svelte\";\n\nexport default {\n  preprocess: vitePreprocess(),\n};\n";
