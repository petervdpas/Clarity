/// Clarity.AppMcp's library, built in this repository: the folder of its
/// header and the folder of the library, which a program that offers
/// commands to agents links.
fn app_mcp_library() -> (PathBuf, PathBuf) {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap();
    let status = Command::new("cargo").args(["build", "--release", "--quiet", "-p", "clarity-app-mcp-ffi"]).current_dir(&root).env("CARGO_BUILD_JOBS", "2").status().unwrap();
    assert!(status.success());
    (root.join("runtimes/rust-app-mcp-ffi/include"), root.join("target/release"))
}

/// A Clarity.UI folder holding Clarity.AppMcp, as a C or C++ program finds
/// its libraries: include/ and lib/.
fn app_mcp_folder() -> PathBuf {
    let (include, lib) = app_mcp_library();
    let folder = scratch("clarity-ui-app-mcp");
    std::fs::create_dir_all(folder.join("include")).unwrap();
    std::fs::create_dir_all(folder.join("lib")).unwrap();
    std::fs::copy(include.join("clarity_app_mcp.h"), folder.join("include/clarity_app_mcp.h")).unwrap();
    // Every library's header, as a Clarity.UI folder holds them all.
    let runtimes = include.join("../..");
    for header in ["rust-ui-ffi/include/clarity_ui.h", "rust-formats-ffi/include/clarity_formats.h", "rust-auth-ffi/include/clarity_auth.h"] {
        let from = runtimes.join(header);
        std::fs::copy(&from, folder.join("include").join(from.file_name().unwrap())).unwrap();
    }
    for name in ["libclarity_app_mcp.so", "libclarity_app_mcp.dylib", "clarity_app_mcp.dll", "clarity_app_mcp.dll.lib"] {
        if lib.join(name).exists() {
            std::fs::copy(lib.join(name), folder.join("lib").join(name)).unwrap();
        }
    }
    folder
}

/// Where builds go: target/generated in the repository, on disk.
fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/generated").join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// What a run of the program gave: its exit code, standard output and standard error.
fn run(program: &Path, dir: &Path, args: &[&str], input: &str) -> (i32, String, String) {
    let mut child = Command::new(program)
        .args(args)
        .current_dir(dir)
        .env("XDG_CONFIG_HOME", dir.join("config"))
        .env("LANG", "C")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    use std::io::Write;
    child.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
    let out = child.wait_with_output().unwrap();
    (out.status.code().unwrap_or(-1), String::from_utf8_lossy(&out.stdout).into(), String::from_utf8_lossy(&out.stderr).into())
}

/// The commands of a built program, run as a person or a script runs them.
fn the_commands_run(program: &Path, dir: &Path) {
    std::fs::create_dir_all(dir.join("data")).unwrap();
    let (code, out, _) = run(program, dir, &["--help"], "");
    assert_eq!(code, 0);
    assert!(out.starts_with("The shop from the command line\n\nUsage: shop <command> [options]\n"), "{out}");
    assert!(out.contains("  customer add     Adds a customer\n"), "{out}");

    let (code, out, err) = run(program, dir, &["customer", "add", "Ada", "ada@example.org", "--vip", "--limit", "500"], "");
    assert_eq!((code, out.as_str(), err.as_str()), (0, "Added Ada\n", ""));
    assert_eq!(run(program, dir, &["customer", "add", "Bob", "bob@example.org"], "").0, 0);
    let (code, out, _) = run(program, dir, &["customer", "list"], "");
    assert_eq!(code, 0);
    assert_eq!(out, "Name  Email            Kind      Credit limit\nAda   ada@example.org  Business           500\nBob   bob@example.org  Person            1000\n");

    // Wrong command lines end with 2, refusals with 1.
    let (code, _, err) = run(program, dir, &["customer", "add", "Ada", "a@b.c", "--limit", "9000"], "");
    assert_eq!((code, err.lines().next()), (2, Some("--limit is at most 5000")));
    let (code, _, err) = run(program, dir, &["custmer"], "");
    assert_eq!((code, err.lines().next()), (2, Some("There is no command custmer")));
    let (code, _, err) = run(program, dir, &["customer", "remove", "Zed"], "");
    assert_eq!((code, err.as_str()), (1, "There is no customer Zed\n"));
    // Piped, nobody answers: a question without a default ends the program.
    let (code, _, err) = run(program, dir, &["customer", "remove", "Bob"], "Remove\n");
    assert_eq!((code, err.as_str()), (2, "There is nobody to answer: Remove Bob?\n"));

    // A setting set by a command is kept for the next one, and exit gives its code.
    assert_eq!(run(program, dir, &["page", "--size", "50"], "").0, 3);
    let (code, out, _) = run(program, dir, &["page"], "");
    assert_eq!((code, out.as_str()), (0, "50\n"));

    the_agents_call(program, dir);
}

/// What each tool call of `calls` answered, served by `<program> mcp`: its text and whether it is an error.
fn served(program: &Path, dir: &Path, calls: &[(&str, serde_json::Value)]) -> Vec<(String, bool)> {
    let lines: String = calls
        .iter()
        .enumerate()
        .map(|(i, (tool, arguments))| serde_json::json!({ "jsonrpc": "2.0", "id": i, "method": "tools/call", "params": { "name": tool, "arguments": arguments } }).to_string() + "\n")
        .collect();
    let (code, out, err) = run(program, dir, &["mcp"], &lines);
    assert_eq!(code, 0, "{err}");
    out.lines()
        .map(|line| {
            let reply: serde_json::Value = serde_json::from_str(line).unwrap_or_else(|e| panic!("{e}: {line}"));
            let result = &reply["result"];
            (result["content"][0]["text"].as_str().unwrap_or_else(|| panic!("{reply}")).to_string(), result["isError"].as_bool().unwrap())
        })
        .collect()
}

/// The commands for agents of a built program, served over MCP while the
/// app is closed (docs/ledger/app-mcp.md): refused until the person's
/// settings allow them, then run as if typed.
fn the_agents_call(program: &Path, dir: &Path) {
    let (code, help, _) = run(program, dir, &["--help"], "");
    assert_eq!(code, 0);
    assert!(help.contains("\n  mcp              Serves the commands for AI agents over MCP\n"), "the help lists mcp: {help}");
    let add = ("customer-add", serde_json::json!({ "name": "Cy", "email": "cy@example.org" }));
    assert_eq!(served(program, dir, std::slice::from_ref(&add)), [("Shop is not open; open it to allow this.".to_string(), true)]);
    // The person allows agents while the app is closed; the settings the program keeps stay.
    let file = dir.join("config/shop/settings.json");
    let mut kept: serde_json::Map<String, serde_json::Value> = serde_json::from_str(&std::fs::read_to_string(&file).unwrap()).unwrap();
    kept.insert("agentReadsWhileClosed".into(), true.into());
    kept.insert("agentChangesWhileClosed".into(), true.into());
    std::fs::write(&file, serde_json::Value::Object(kept).to_string()).unwrap();
    let answers = served(program, dir, &[add, ("customer-list", serde_json::json!({})), ("customer-remove", serde_json::json!({ "name": "Zed" })), ("customer-remove", serde_json::json!({ "name": "Bob" }))]);
    assert_eq!(answers[0], ("Added Cy".to_string(), false));
    assert!(answers[1].0.starts_with("Name  Email            Kind      Credit limit\n") && answers[1].0.contains("\nCy    cy@example.org   Person            1000"), "{}", answers[1].0);
    assert_eq!(answers[2], ("There is no customer Zed".to_string(), true));
    assert_eq!(answers[3], (String::new(), false), "a client that cannot ask: a yes or no is a no");
    // While the app runs, `mcp` forwards to it: the app answers, and grants each change itself.
    let running = clarity_app_mcp::discovery::file_in(&dir.join("config/shop"));
    let app = clarity_app_mcp::relay::listen("Shop", &running, |lines, _close| {
        while let Some(line) = lines.read() {
            let id = serde_json::from_str::<serde_json::Value>(&line).unwrap()["id"].clone();
            lines.write(&serde_json::json!({ "jsonrpc": "2.0", "id": id, "result": { "content": [{ "type": "text", "text": "from the running app" }], "isError": false } }).to_string());
        }
    })
    .unwrap();
    assert_eq!(served(program, dir, &[("customer-list", serde_json::json!({}))]), [("from the running app".to_string(), false)]);
    drop(app);
    assert!(!running.exists());
    // A setting a command changes keeps the person's switches.
    assert_eq!(run(program, dir, &["page", "--size", "60"], "").0, 3);
    let kept: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&file).unwrap()).unwrap();
    assert_eq!((kept["agentChangesWhileClosed"].clone(), kept["pageSize"].clone()), (serde_json::json!(true), serde_json::json!(60)), "{kept}");
}

