//! Every generated project explains itself in a README.md (P3): what it is,
//! the tools its stack needs and where to get them, and how to build and
//! run it without Clarity, so it can be built on a machine Clarity is not on.

use clarity_gen::generate;
use clarity_project::{Backend, Settings, SourceKind, Ui, starter};
use clarity_spec::load_sources;

const SHOP: &str = "module shop

entity Customer
    name: text(80)

page Card: window
    title \"Customer card\"
    data customer: Customer
";

fn readme(settings: &Settings) -> String {
    let project = load_sources([("shop.clarity", SHOP)]);
    let files = generate(&project, settings).unwrap_or_else(|e| panic!("{e:#?}"));
    files.into_iter().find(|f| f.path == "README.md").expect("a README.md").text
}

fn has(text: &str, expected: &str) {
    assert!(text.contains(expected), "expected\n{expected}\nin\n{text}");
}

#[test]
fn a_rust_project_says_what_it_needs_and_how_to_build_it() {
    let text = readme(&starter("Shop", "shop"));
    assert!(text.starts_with("# Shop\n"), "{text}");
    has(&text, "Generated by Clarity from the project Shop");
    has(&text, "Rust with the web renderer");
    // The same words as Clarity's own check (clarity tools).
    has(&text, "- Rust with cargo, from https://rustup.rs\n");
    has(&text, "- on Linux, the WebKitGTK development files and pkg-config");
    has(&text, "    cargo build --release\n");
    has(&text, "    cargo run\n");
    has(&text, "target/release/shop");
    has(&text, "data/shop.db");
    // The runtime comes from crates.io, or from Clarity's repository while working on it.
    has(&text, &format!("Clarity's runtime comes as the crate clarity-runtime ({})", clarity_gen::rust_runtime_version()));
    has(&text, "    [patch.crates-io]\n    clarity-runtime = { path = \"<Clarity>/runtimes/rust\" }\n");
}

#[test]
fn a_csharp_project_says_what_it_needs_and_how_to_build_it() {
    let mut settings = starter("Shop", "shop");
    settings.stack.backend = Backend::Csharp;
    settings.stack.ui = Ui::Avalonia;
    let text = readme(&settings);
    has(&text, "C# with Avalonia");
    has(&text, "- the .NET 10 SDK, from https://dotnet.microsoft.com/download\n");
    has(&text, "    dotnet build -c Release\n");
    has(&text, "    dotnet run\n");
    has(&text, "bin/Release/net10.0/Shop");
    // The runtime comes from nuget.org, or from its own projects while working on it.
    has(&text, &format!("Clarity's runtime comes as NuGet packages (Clarity.Avalonia.Desktop {},", clarity_gen::csharp_runtime_version()));
    has(&text, "    dotnet build -p:ClarityRuntime=<Clarity>/runtimes/csharp\n");
    // Served to browsers alone, the package without the desktop's own.
    settings.stack.targets = vec![clarity_project::Target::Web];
    let web = readme(&settings);
    has(&web, &format!("Clarity's runtime comes as NuGet packages (Clarity.Avalonia {},", clarity_gen::csharp_runtime_version()));
    // Trimmed and compressed in Release, for putting it online.
    has(&web, "    dotnet build Server -c Release\n    dotnet Server/bin/Release/net10.0/Shop.Server.dll\n");
}

#[test]
fn a_server_database_is_named_by_its_variable() {
    let mut settings = starter("Shop", "shop");
    settings.datasources[0].kind = SourceKind::Postgres;
    settings.datasources[0].url = "env:SHOP_DATABASE".into();
    let text = readme(&settings);
    has(&text, "`SHOP_DATABASE`");
    has(&text, "PostgreSQL");
    has(&text, "postgres://user:password@host:5432/database");
}

#[test]
fn a_go_project_says_what_it_needs_and_how_to_build_it() {
    let mut settings = starter("Shop", "shop");
    settings.stack.backend = Backend::Go;
    let text = readme(&settings);
    has(&text, "Go with the web renderer");
    has(&text, "- Go, from https://go.dev/dl\n");
    has(&text, "    go build -tags production -trimpath -ldflags=\"-s -w\" -o bin/shop .\n");
    has(&text, "    go run .\n");
    // The runtime comes as a Go module, or from Clarity's repository while working on it.
    has(&text, &format!("Clarity's runtime comes as the Go module github.com/petervdpas/Clarity/runtimes/go ({})", clarity_gen::go_runtime_version()));
    has(&text, "    go work init .\n    go work edit -replace github.com/petervdpas/Clarity/runtimes/go=<Clarity>/runtimes/go\n");
}

/// A file store says where its pictures are, and which variable names it.
#[test]
fn a_file_store_says_where_its_pictures_are() {
    let mut settings = starter("Shop", "shop");
    settings.filestores.push(clarity_project::FileStore { name: "photos".into(), location: "env:PHOTO_FOLDER".into() });
    settings.filestores.push(clarity_project::FileStore { name: "scans".into(), location: "scans".into() });
    let text = readme(&settings);
    has(&text, "- `photos`: a file store of pictures. Set the environment variable `PHOTO_FOLDER` to its folder.\n");
    has(&text, "- `scans`: the file store of pictures in the folder `scans`; a relative path is taken from the folder the program starts in.\n");
}
