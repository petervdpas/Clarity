//! Every generated project explains itself in a README.md (P3): what it is,
//! the tools its stack needs and where to get them, and how to build and
//! run it without Clarity, so it can be built on a machine Clarity is not on.

use clarity_gen::generate;
use clarity_project::{Backend, Settings, SourceKind, Ui, starter};
use clarity_spec::load_sources;

const SHOP: &str = "module shop

entity Customer
    name: text(80)

page Card: window
    title \"Customer card\"
    data customer: Customer
";

fn readme(settings: &Settings) -> String {
    let project = load_sources([("shop.clarity", SHOP)]);
    let files = generate(&project, settings).unwrap_or_else(|e| panic!("{e:#?}"));
    files.into_iter().find(|f| f.path == "README.md").expect("a README.md").text
}

fn has(text: &str, expected: &str) {
    assert!(text.contains(expected), "expected\n{expected}\nin\n{text}");
}

#[test]
fn a_rust_project_says_what_it_needs_and_how_to_build_it() {
    let text = readme(&starter("Shop", "shop"));
    assert!(text.starts_with("# Shop\n"), "{text}");
    has(&text, "Generated by Clarity from the project Shop");
    has(&text, "Rust with Clarity.UI");
    // The same words as Clarity's own check (clarity tools); Clarity.UI needs no webview.
    has(&text, "- Rust with cargo, from https://rustup.rs\n");
    assert!(!text.contains("WebKitGTK"), "{text}");
    has(&text, "    cargo build --release\n");
    has(&text, "    cargo run\n");
    has(&text, "target/release/shop");
    has(&text, "data/shop.db");
    // The runtime comes from crates.io, or from Clarity's repository while working on it.
    has(&text, &format!("Clarity's runtime and Clarity.UI come as the crates clarity-runtime ({})", clarity_gen::rust_runtime_version()));
    has(&text, "    [patch.crates-io]\n    clarity-runtime = { path = \"<Clarity>/runtimes/rust\" }\n    clarity-ui = { path = \"<Clarity>/runtimes/rust-ui\" }\n");
    has(&text, "set the environment variable `CLARITY_RUNTIME` to `<Clarity>/runtimes/rust`");
    // A run by hand or in the IDE chooses its data without editing the program.
    has(&text, "Set the environment variable `CLARITY_DATA` to a folder to open it there instead, under its own file name.");
}

#[test]
fn a_csharp_project_says_what_it_needs_and_how_to_build_it() {
    let mut settings = starter("Shop", "shop");
    settings.stack.backend = Backend::Csharp;
    settings.stack.ui = Ui::Clarity;
    let text = readme(&settings);
    has(&text, "C# with Clarity.UI");
    has(&text, "- the .NET 10 SDK, from https://dotnet.microsoft.com/download\n");
    has(&text, "    dotnet build -c Release\n");
    has(&text, "    dotnet run\n");
    has(&text, "bin/Release/net10.0/Shop");
    // The runtime comes from nuget.org, or from its own projects while working on it.
    has(&text, &format!("Clarity's runtime comes as NuGet packages (Clarity.Ui {},", clarity_gen::csharp_runtime_version()));
    has(&text, "    dotnet build -p:ClarityRuntime=<Clarity>/runtimes/csharp\n");
    // A run by hand or in the IDE chooses its data without editing the program.
    has(&text, "Set the environment variable `CLARITY_DATA` to a folder to open it there instead, under its own file name.");
}

#[test]
fn a_server_database_is_named_by_its_variable() {
    let mut settings = starter("Shop", "shop");
    settings.datasources[0].kind = SourceKind::Postgres;
    settings.datasources[0].url = "env:SHOP_DATABASE".into();
    let text = readme(&settings);
    has(&text, "`SHOP_DATABASE`");
    has(&text, "PostgreSQL");
    has(&text, "postgres://user:password@host:5432/database");
}

#[test]
fn a_go_project_says_what_it_needs_and_how_to_build_it() {
    let mut settings = starter("Shop", "shop");
    settings.stack.backend = Backend::Go;
    settings.stack.ui = Ui::Clarity;
    let text = readme(&settings);
    has(&text, "Go with Clarity.UI");
    has(&text, "- Go, from https://go.dev/dl\n");
    assert!(!text.contains("WebKitGTK") && !text.contains("production"), "{text}");
    // Clarity.UI's library comes from the folder CLARITY_UI names, through cgo.
    has(&text, "    export CGO_CFLAGS=\"-I$CLARITY_UI/include\"\n");
    has(&text, "ship it beside the program");
    // cgo downloads nothing: the README says where the release's archive is.
    has(&text, &format!("`clarity-ui-{}-<system>.tar.gz`, from the release https://github.com/petervdpas/Clarity/releases/tag/runtimes/rust-ui-ffi/v{}", clarity_gen::clarity_ui::version(), clarity_gen::clarity_ui::version()));
    has(&text, "    go build -trimpath -ldflags=\"-s -w\" -o bin/shop .\n");
    has(&text, "    go run .\n");
    // The runtime comes as a Go module, or from Clarity's repository while working on it.
    has(&text, &format!("Clarity's runtime comes as the Go module github.com/petervdpas/Clarity/runtimes/go ({})", clarity_gen::go_runtime_version()));
    has(&text, "    go work init .\n    go work edit -replace github.com/petervdpas/Clarity/runtimes/go=<Clarity>/runtimes/go\n");
    // The web program serves the shared web screen, and needs no library.
    settings.stack.targets = vec![clarity_project::Target::Web];
    let web = readme(&settings);
    has(&web, "Go with the web renderer");
    assert!(!web.contains("CGO_CFLAGS"), "{web}");
}

/// Every runtime opens an SQLite file in the folder CLARITY_DATA names, so
/// every stack's README says so.
#[test]
fn every_stack_says_clarity_data_moves_its_sqlite_file() {
    for backend in [Backend::Rust, Backend::Go, Backend::Csharp, Backend::C, Backend::Cpp] {
        let mut settings = starter("Shop", "shop");
        settings.stack.backend = backend;
        settings.stack.ui = Ui::Clarity;
        has(&readme(&settings), "Set the environment variable `CLARITY_DATA` to a folder to open it there instead, under its own file name.");
    }
}

/// A file store says where its pictures are, and which variable names it.
#[test]
fn a_file_store_says_where_its_pictures_are() {
    let mut settings = starter("Shop", "shop");
    settings.filestores.push(clarity_project::FileStore { name: "photos".into(), location: "env:PHOTO_FOLDER".into() });
    settings.filestores.push(clarity_project::FileStore { name: "scans".into(), location: "scans".into() });
    let text = readme(&settings);
    has(&text, "- `photos`: a file store of pictures. Set the environment variable `PHOTO_FOLDER` to its folder.\n");
    has(&text, "- `scans`: the file store of pictures in the folder `scans`; a relative path is taken from the folder the program starts in.\n");
}

/// A built project's SQLite file is opened at the full path of the project's
/// folder, so the README gives the path as the project file writes it and
/// says it is in the project's folder, not the machine's full path with the
/// words that a relative path is taken from the folder the program starts in.
#[test]
fn a_sqlite_file_is_named_as_the_project_writes_it_in_the_projects_folder() {
    let dir = std::env::temp_dir().join("clarity-readme-shop");
    let unbuilt = starter("Shop", "shop");
    let written = unbuilt.datasources[0].url.clone();
    let settings = clarity_project::build_settings(&dir, &unbuilt);
    assert!(std::path::Path::new(&settings.datasources[0].url).is_absolute());
    let mut project = load_sources([("shop.clarity", SHOP)]);
    let mut source = clarity_spec::SourceRef::sql(&unbuilt.datasources[0].name);
    source.address = written.clone();
    project.sources.push(source);
    let files = generate(&project, &settings).unwrap_or_else(|e| panic!("{e:#?}"));
    let text = &files.iter().find(|f| f.path == "README.md").expect("a README.md").text;
    has(text, &format!("the SQLite file `{written}` in the project's folder, migrated by the program when it starts."));
    assert!(!text.contains(&settings.datasources[0].url), "{text}");
    assert!(!text.contains("a relative path is taken from the folder the program starts in"), "{text}");
}
