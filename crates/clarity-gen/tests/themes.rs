//! Themes as the web renderer gets them (T1): one CSS file per theme, a
//! class for the theme on the application and a class per style on parts.

use clarity_gen::generate;
use clarity_project::starter;
use clarity_spec::{load_sources, themes};

const SHOP: &str = "module shop

entity Customer
    name: text(80)

page Card: window
    data customer: Customer
    button \"Save\" name save at 1,1 span 2 style primary

theme Shop
    mode system
    color accent \"#1f6f5c\" dark \"#4fb393\"
    color brand \"#F5C400\"
    font \"Inter\"
    size 14
    radius 4
    part button hover background accent_soft
    style primary background accent, text \"#fff\", border accent, weight bold
    style quiet border none, radius 12
    style loud background brand, text text

theme NightOwl
    mode dark
    color background \"#000000\"
    style primary background accent
";

const SHOP_CSS: &str = "/* Generated by Clarity from theme Shop. Do not edit: change the theme in Clarity instead. */

.clarity-app.theme-shop {
  --accent: #1f6f5c;
  --color-brand: #f5c400;
  --font: \"Inter\";
  --font-size: 14px;
  --radius-input: 4px;
  --radius-button: 4px;
  --radius-panel: 4px;
  --button-hover-bg: var(--accent-soft);
}

.clarity-app.theme-shop[data-scheme=\"dark\"] {
  --accent: #4fb393;
}

.clarity-app.theme-shop .style-primary {
  background: var(--accent);
  color: #ffffff;
  border-color: var(--accent);
  font-weight: 600;
}

.clarity-app.theme-shop .style-quiet {
  border: none;
  border-radius: 12px;
}

.clarity-app.theme-shop .style-loud {
  background: var(--color-brand);
  color: var(--text);
}
";

#[test]
fn a_theme_is_a_css_file_of_its_own() {
    let project = load_sources([("shop.clarity", SHOP)]);
    let shop = &project.files[0].themes[0];
    assert_eq!(clarity_gen::theme_css(shop), SHOP_CSS);
}

#[test]
fn the_application_gets_a_file_per_theme_and_links_them() {
    let mut project = load_sources([("shop.clarity", SHOP)]);
    themes::use_themes(&mut project, &["Shop", "NightOwl"]);
    assert!(project.diagnostics.is_empty(), "{:#?}", project.diagnostics);
    let files = generate(&project, &starter("Shop", "shop")).unwrap();
    let file = |path: &str| files.iter().find(|f| f.path == path).map(|f| f.text.clone()).unwrap_or_else(|| panic!("no {path}"));
    assert_eq!(file("ui/themes/shop.css"), SHOP_CSS);
    assert!(file("ui/themes/night-owl.css").starts_with("/* Generated by Clarity from theme NightOwl."));
    let index = file("ui/index.html");
    assert!(index.contains("<link rel=\"stylesheet\" href=\"./themes/shop.css\">"), "{index}");
    assert!(index.contains("<link rel=\"stylesheet\" href=\"./themes/night-owl.css\">"), "{index}");
}

#[test]
fn only_the_offered_themes_ship() {
    let mut project = load_sources([("shop.clarity", SHOP)]);
    themes::use_themes(&mut project, &["Shop"]);
    let files = generate(&project, &starter("Shop", "shop")).unwrap();
    assert!(files.iter().any(|f| f.path == "ui/themes/shop.css"));
    assert!(!files.iter().any(|f| f.path == "ui/themes/night-owl.css"));
    let index = files.iter().find(|f| f.path == "ui/index.html").unwrap();
    assert!(!index.text.contains("night-owl"), "{}", index.text);
}

#[test]
fn clarity_s_own_theme_is_the_base_every_theme_starts_from() {
    let css = clarity_gen::base_css();
    assert!(css.starts_with("/* Generated by Clarity from theme Clarity."), "{css}");
    for line in [
        ".clarity-app {\n",
        "  --panel-alt: #f6f7f9;\n",
        "  --font: system-ui, -apple-system, \"Segoe UI\", \"Roboto\", sans-serif;\n",
        "  --mono: ui-monospace, \"JetBrains Mono\", \"Cascadia Code\", \"Consolas\", \"Menlo\", \"DejaVu Sans Mono\", \"Noto Sans Mono\", monospace;\n",
        "  --font-size-small: 12px;\n",
        "  --padding: 4px;\n",
        "  --border-width: 1px;\n",
        "  --shadow: 0 6px 18px rgb(0 0 0 / 0.25);\n",
        "  --button-bg: var(--panel-alt);\n",
        "  --button-hover-border: var(--accent);\n",
        "  --header-weight: 600;\n",
        // The base applies the values to the application itself.
        "  color: var(--text);\n",
        "  font-family: var(--font);\n",
        ".clarity-app[data-scheme=\"dark\"] {\n",
        "  --panel-alt: #232832;\n",
        // Native controls (a select, a date picker) draw in the same mode.
        "  color-scheme: light;\n",
        "  color-scheme: dark;\n",
    ] {
        assert!(css.contains(line), "{line:?} not in\n{css}");
    }
}

#[test]
fn every_application_gets_the_base_first() {
    let mut project = load_sources([("shop.clarity", SHOP)]);
    themes::use_themes(&mut project, &["Shop"]);
    let files = generate(&project, &starter("Shop", "shop")).unwrap();
    let base = files.iter().find(|f| f.path == "ui/themes/clarity.css").expect("the base");
    assert_eq!(base.text, clarity_gen::base_css());
    let index = &files.iter().find(|f| f.path == "ui/index.html").unwrap().text;
    let at = |file: &str| index.find(&format!("href=\"./themes/{file}\"")).unwrap_or_else(|| panic!("no {file} in {index}"));
    assert!(at("clarity.css") < at("shop.css"), "{index}");

    // Without a theme, the application still looks as Clarity does.
    let plain = load_sources([("shop.clarity", "module shop\n\nentity Customer\n    name: text(80)\n\npage Card: window\n    data customer: Customer\n")]);
    let files = generate(&plain, &starter("Shop", "shop")).unwrap();
    assert!(files.iter().any(|f| f.path == "ui/themes/clarity.css"));
}

/// A style that sets how its text shows: size, a font of the theme and
/// alignment, which keeps the text an input's padding from the edge.
#[test]
fn a_style_sets_the_size_font_and_alignment_of_its_text() {
    let source = "module calc\n\ntheme Calc\n    style display background \"#c9d8b0\", size 36, font mono, align right\n";
    let project = load_sources([("calc.clarity", source)]);
    assert!(project.diagnostics.is_empty(), "{:#?}", project.diagnostics);
    let css = clarity_gen::theme_css(&project.files[0].themes[0]);
    assert!(
        css.contains(".clarity-app.theme-calc .style-display {\n  background: #c9d8b0;\n  font-size: 36px;\n  font-family: var(--mono);\n  text-align: right;\n  justify-content: flex-end;\n  padding-inline: calc(var(--padding) * 2);\n}\n"),
        "{css}"
    );
}
