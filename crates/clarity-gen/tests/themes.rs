//! Themes as the web renderer gets them (T1): one CSS file per theme, a
//! class for the theme on the application and a class per style on parts.

use clarity_gen::generate;
use clarity_project::starter;
use clarity_spec::{load_sources, themes};

const SHOP: &str = "module shop

entity Customer
    name: text(80)

page Card: window
    data customer: Customer
    button \"Save\" name save at 1,1 span 2 style primary

theme Shop
    mode system
    color accent \"#1f6f5c\" dark \"#4fb393\"
    color brand \"#F5C400\"
    font \"Inter\"
    size 14
    radius 4
    style primary background accent, text \"#fff\", border accent
    style quiet border none
    style loud background brand, text text

theme NightOwl
    mode dark
    color background \"#000000\"
    style primary background accent
";

const SHOP_CSS: &str = "/* Generated by Clarity from theme Shop. Do not edit: change the theme in Clarity instead. */

.theme-shop {
  --accent: #1f6f5c;
  --color-brand: #f5c400;
  --font: \"Inter\";
  --font-size: 14px;
  --radius: 4px;
  color: var(--text);
  background: var(--bg);
  font-family: var(--font);
  font-size: var(--font-size);
}

.theme-shop[data-scheme=\"dark\"] {
  --accent: #4fb393;
}

.theme-shop .style-primary {
  background: var(--accent);
  color: #ffffff;
  border-color: var(--accent);
}

.theme-shop .style-quiet {
  border: none;
}

.theme-shop .style-loud {
  background: var(--color-brand);
  color: var(--text);
}
";

#[test]
fn a_theme_is_a_css_file_of_its_own() {
    let project = load_sources([("shop.clarity", SHOP)]);
    let shop = &project.files[0].themes[0];
    assert_eq!(clarity_gen::theme_css(shop), SHOP_CSS);
}

#[test]
fn the_application_gets_a_file_per_theme_and_links_them() {
    let mut project = load_sources([("shop.clarity", SHOP)]);
    themes::use_themes(&mut project, &["Shop", "NightOwl"]);
    assert!(project.diagnostics.is_empty(), "{:#?}", project.diagnostics);
    let files = generate(&project, &starter("Shop", "shop")).unwrap();
    let file = |path: &str| files.iter().find(|f| f.path == path).map(|f| f.text.clone()).unwrap_or_else(|| panic!("no {path}"));
    assert_eq!(file("ui/themes/shop.css"), SHOP_CSS);
    assert!(file("ui/themes/night-owl.css").starts_with("/* Generated by Clarity from theme NightOwl."));
    let index = file("ui/index.html");
    assert!(index.contains("<link rel=\"stylesheet\" href=\"./themes/shop.css\">"), "{index}");
    assert!(index.contains("<link rel=\"stylesheet\" href=\"./themes/night-owl.css\">"), "{index}");
}

#[test]
fn only_the_offered_themes_ship() {
    let mut project = load_sources([("shop.clarity", SHOP)]);
    themes::use_themes(&mut project, &["Shop"]);
    let files = generate(&project, &starter("Shop", "shop")).unwrap();
    assert!(files.iter().any(|f| f.path == "ui/themes/shop.css"));
    assert!(!files.iter().any(|f| f.path == "ui/themes/night-owl.css"));
    let index = files.iter().find(|f| f.path == "ui/index.html").unwrap();
    assert!(!index.text.contains("night-owl"), "{}", index.text);
}
