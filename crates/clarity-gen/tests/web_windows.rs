//! The windows of a web stack as markup (DESIGN 7.8, G6b): each part an
//! element of the screen package with what differs from its kind's
//! defaults, written in Clarity's own words.

use std::path::Path;

fn calculator() -> clarity_spec::Project {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/calculator");
    clarity_project::load_modules(&dir).unwrap()
}

#[test]
fn the_calculator_s_window_is_markup_in_clarity_s_words() {
    let project = calculator();
    let page = project.files.iter().flat_map(|f| &f.pages).find(|p| p.name.name == "Main").unwrap();
    let markup = clarity_gen::web_windows::window_markup(page);
    for line in [
        "  import { Button, Display, Window } from \"@clarity/ui\";",
        "<Window name=\"Main\">",
        "  <Display name=\"screen\" at=\"1,1\" span=\"4\" rows=\"2\" bind=\"shown\" digits=\"12\" style=\"display\" />",
        "  <Button name=\"clearKey\" at=\"1,3\" span=\"1\" caption=\"@clearKeyCaption\" key=\"Escape\" onclick=\"clear\" />",
        "  <Button name=\"digit7\" at=\"1,4\" span=\"1\" caption=\"7\" key=\"7\" onclick=\"digit(7)\" />",
        "  <Button name=\"equalsKey\" at=\"4,7\" span=\"1\" caption=\"=\" style=\"equals\" key=\"=\" default onclick=\"equals\" />",
        "</Window>",
    ] {
        let line = line.replace("span=\"4\"", "span={4}").replace("span=\"1\"", "span={1}").replace("rows=\"2\"", "rows={2}").replace("digits=\"12\"", "digits={12}");
        assert!(markup.contains(&line), "{line}\nin\n{markup}");
    }
    assert!(markup.starts_with("<!-- Generated by Clarity"), "{markup}");
}

#[test]
fn every_window_of_the_calculator_is_written() {
    let files = clarity_gen::web_windows::window_files(&calculator());
    let paths: Vec<&str> = files.iter().map(|f| f.path.as_str()).collect();
    assert!(paths.contains(&"ui/src/windows/Main.svelte") && paths.contains(&"ui/src/windows/Preferences.svelte"), "{paths:?}");
}

/// The package's elements read each kind's defaults from a file this writes,
/// so Rust's catalog stays the one source of them.
/// `CLARITY_WRITE_DEFAULTS=1 cargo test -p clarity-gen --test web_windows` writes it again.
#[test]
fn the_package_reads_the_catalog_s_defaults() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../runtimes/web/src/generated/part-defaults.json");
    let defaults = clarity_gen::web_windows::part_defaults();
    if std::env::var("CLARITY_WRITE_DEFAULTS").is_ok() {
        std::fs::write(&path, &defaults).unwrap();
    }
    let written = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(written == defaults, "{} is not the catalog's defaults; write it with CLARITY_WRITE_DEFAULTS=1", path.display());
    let path = path.with_file_name("command-defaults.json");
    let defaults = clarity_gen::web_windows::command_defaults();
    if std::env::var("CLARITY_WRITE_DEFAULTS").is_ok() {
        std::fs::write(&path, &defaults).unwrap();
    }
    assert!(std::fs::read_to_string(&path).unwrap_or_default() == defaults, "{} is not a new item's defaults; write it with CLARITY_WRITE_DEFAULTS=1", path.display());
}

/// A generated screen builds with the tools Clarity's own screen is built and tested with.
#[test]
fn a_generated_screen_builds_with_the_ide_s_versions() {
    let app: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../app/package.json")).unwrap()).unwrap();
    for (tool, version) in clarity_gen::web_windows::SCREEN_TOOLS {
        let used = app["dependencies"][tool].as_str().or(app["devDependencies"][tool].as_str()).unwrap_or_default();
        assert_eq!(used.trim_start_matches('^'), version, "{tool}");
    }
}

#[test]
fn the_calculator_s_screen_is_a_project_of_its_own() {
    let files = clarity_gen::web_windows::ui_project(&calculator(), "calculator");
    let file = |path: &str| files.iter().find(|f| f.path == path).unwrap_or_else(|| panic!("no {path}")).text.clone();
    assert!(file("ui/package.json").contains("\"@clarity/ui\": \"file:./clarity-ui\""));
    assert!(file("ui/src/main.ts").contains("startScreen({ Main, Preferences });"));
    assert!(file("ui/index.html").contains("href=\"./themes/calculator.css\""), "{}", file("ui/index.html"));
    assert!(files.iter().any(|f| f.path == "ui/public/themes/calculator.css"));
    assert!(files.iter().any(|f| f.path == "ui/clarity-ui/src/elements/Window.svelte"));
    assert!(files.iter().any(|f| f.path == "ui/src/windows/Main.svelte"));
}
