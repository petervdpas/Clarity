#[test]
fn a_part_is_its_kind_s_defaults_with_what_the_markup_changes() {
    let spec = markup::read(WINDOW).unwrap();
    assert_eq!(vec!["Menu"], spec.frame.iter().map(|e| e.name.as_str()).collect::<Vec<_>>());
    assert_eq!(Some("Main"), spec.name.as_deref());
    let save = &spec.parts[0];
    assert_eq!("button", save.kind);
    assert_eq!(Some("save"), save.name());
    assert_eq!(GridItem::new(3, 2, 4, 1, false), save.place(false));
    assert_eq!(Some("@saveCaption"), save.text("caption"));
    assert_eq!(Some("Ctrl+S"), save.text("shortcut"));
    let calls: Vec<&HandlerCall> = save.on("click").collect();
    assert_eq!(1, calls.len());
    assert_eq!(("digit", 2), (calls[0].handler.as_str(), calls[0].args.len()));
    assert_eq!("\"a, b\"", calls[0].args[1]);
    let note = &spec.parts[1];
    assert_eq!(("textbox", 2, Some("order.note")), (note.kind.as_str(), note.place(false).height, note.text("bind")));
    assert_eq!(None, note.text("placeholder"));
    assert_eq!(Some(&Value::Null), note.json("placeholder"));
    assert_eq!("noteChanged", note.on("change").next().unwrap().written());
    let tabs = &spec.parts[2];
    assert_eq!(vec![Some("One".to_string()), Some("Two".to_string())], tabs.pages.iter().map(|p| p.title.clone()).collect::<Vec<_>>());
    assert_eq!(Some(6), tabs.pages[1].columns);
    assert_eq!("label", tabs.pages[0].children[0].kind);
    assert_eq!(vec!["number", "status"], spec.parts[3].names("columns"));
}

#[test]
fn a_menu_item_reads_its_own_words() {
    let spec = markup::read(WINDOW).unwrap();
    let item = &markup::menu_of(&spec.frame[0]).items[0];
    assert_eq!((Some("Open"), Some("Ctrl+O"), Some("Orders")), (item.text("caption"), item.text("shortcut"), item.text("onClick")));
}

#[test]
fn every_kind_of_the_catalog_reads() {
    let kinds: Vec<&str> = markup::kinds().collect();
    assert!(kinds.len() > 40);
    for kind in kinds {
        let mut tag = kind.to_string();
        tag[..1].make_ascii_uppercase();
        let read = markup::read(&format!("<Window><{tag} at=\"1,1\" /></Window>")).unwrap();
        assert_eq!(kind, read.parts[0].kind);
    }
}

#[test]
fn a_markup_with_an_unknown_part_or_no_well_formed_xml_is_refused() {
    assert!(markup::read("<Window><Gizmo /></Window>").is_err());
    assert!(markup::read("<Window><Button at=\"1,1\"></Window>").is_err());
    assert!(markup::read("<Window><Button at=\"x,1\" /></Window>").is_err());
    assert!(markup::read("").is_err());
}

#[test]
fn a_window_as_the_generator_writes_it_reads() {
    let spec = markup::read(GENERATED).unwrap();
    assert_eq!(Some("Entities"), spec.name.as_deref());
    assert_eq!(12, spec.columns);
    let splitter = &spec.parts[0];
    assert_eq!(("splitter", 13), (splitter.kind.as_str(), splitter.place(false).height));
    assert_eq!(Some(&Value::Null), splitter.json("orientation"));
    assert_eq!(vec![Some(4), None], splitter.pages.iter().map(|p| p.columns).collect::<Vec<_>>());
    let right = &splitter.pages[1].children;
    let table = right.iter().find(|p| p.kind == "table").unwrap();
    assert_eq!(Some(80.0), table.json("widths").and_then(|w| w["mandatory"].as_f64()));
    assert_eq!(vec!["name", "type", "key", "mandatory"], table.names("edit"));
    assert_eq!(Some("columnGrid"), table.text("undoScope"));
    let save = right.iter().find(|p| p.name() == Some("saveEntity")).unwrap();
    assert!(save.flag("default"));
    assert_eq!(Some("Ctrl+S"), save.text("shortcut"));
    let form = right.iter().find(|p| p.kind == "form").unwrap();
    assert_eq!(8, form.children.len());
    assert_eq!(Some("entityName"), form.children[0].text("for"));
}

#[test]
fn the_windows_the_csharp_server_tests_carry_read() {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../csharp/Clarity.Ui.Server.Tests/Windows");
    let mut read = 0;
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "cxaml") {
            let spec = markup::read(&std::fs::read_to_string(&path).unwrap()).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            assert!(!spec.parts.is_empty(), "{}", path.display());
            read += 1;
        }
    }
    // Every window the C# tests carry reads, however many they are.
    assert!(read >= 3, "only {read} windows read");
}

