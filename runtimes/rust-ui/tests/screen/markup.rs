#[test]
fn a_handler_call_is_written_as_every_stack_writes_it() {
    let cases: Value = serde_json::from_str(&std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../conformance/calls.json")).unwrap()).unwrap();
    for case in cases["cases"].as_array().unwrap() {
        let text = case["text"].as_str().unwrap();
        let call = handler_of("click", text);
        assert_eq!(case["handler"].as_str().unwrap(), call.handler);
        assert_eq!(case["args"].as_array().unwrap().len(), call.args.len(), "{text}");
        assert_eq!(text, call.written());
    }
}

#[test]
fn a_kind_not_drawn_yet_says_so_in_its_place() {
    let host = TestHost::new();
    let mut props = serde_json::Map::new();
    for (k, v) in [("col", 1), ("row", 1), ("width", 4), ("height", 1)] {
        props.insert(k.to_string(), Value::from(v));
    }
    let made = parts::make(markup::PartSpec::new("notDrawnYet", props), host.clone());
    let missing = made.as_any().downcast_ref::<MissingPart>().unwrap();
    assert_eq!(None, missing.why);
    assert_eq!("notDrawnYet: not drawn yet", missing.says());
    let mut screen = window_of(r#"<Chart at="1,1" span="4" />"#, host);
    let mut shot = Shot::of(&mut screen, 800, 400, 1.0);
    assert!(shot.any_not(0, 0, 260, 36, screen.look().color("background")));
}

#[test]
fn a_part_that_code_hides_takes_no_pointer() {
    let host = TestHost::new();
    let mut screen = window_of(r#"<Label at="1,1" span="12" name="cpu" caption="CPU" />"#, host.clone());
    screen.resize(800.0, 400.0, 1.0);
    let label = clarity_ui::testing::part_named(&screen, "cpu");
    assert_eq!(Some(label), screen.at(20.0, 10.0));
    host.set_state("cpu", |s| s.visible = Some(false));
    assert_ne!(Some(label), screen.at(20.0, 10.0));
}
